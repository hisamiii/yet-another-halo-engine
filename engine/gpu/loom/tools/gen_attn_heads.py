    outs = accumulate("tail_")
    e("      kernel.barrier<workgroup> scope(workgroup) ordering(acq_rel)")
    e(f"      scf.yield {heads(outs)} : {', '.join([V4H] * 4 * H)}")
    e("    }")
    ys = []
    for i in R:
        ys += [f"%tail_next_max_{i}", f"%tail_next_sum_{i}"] + [f"%tail_next_output{r}_{i}" for r in range(4)]
    e(f"    scf.yield {heads(ys)} : {state_types()}")
    e("  }")
    e("")
