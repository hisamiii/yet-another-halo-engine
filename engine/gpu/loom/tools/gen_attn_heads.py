        e(f"  scf.if %query_valid{r} {{")
        e(f"    %bounded_query_token = index.assume %query_token{r} [lt(%query_token{r}, %token_count)] : index")
        for i in R:
            e(f"    %gate_values_{i} = vector.load %gate_view[%bounded_query_token, %output_channel_{i}] : view<[%token_count]x6144xf32> -> {V4F}")
