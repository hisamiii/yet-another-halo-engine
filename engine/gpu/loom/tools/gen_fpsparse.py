#!/usr/bin/env python3
"""Block-sparse prefill attention (FlashPrefill V2, arXiv 2608.19758) for the kv4 paged f16 pools: block means, block
selection, and the tile lists the KT2 attention (gen_attn_fa FPSPARSE) walks.

Blocks are 128 keys. Per attention layer and chunk:
  yah_fpmean  means of the chunk's blocks (and the previous chunk's: the last layer skips its attention on non-final
              chunks) from the f16 pools into the layer's persistent means [block][1024] (K rows; V row-major).
  yah_fpcopy  the layer's means of every block so far into the pools' extension pages: block j is pooled key cap + j
              (K row cap + j, V^T tile cap / 16 + j / 16, key slot j % 16), so the attention loads it like any key.
  yah_fpsel   per (16-token query block, KV head): scores the prior blocks with the pooled keys over the block's 96 query
              rows (6 heads), E_J = sum_r exp(q_r . kbar_J - M), keeps E_J >= ALPHA max E plus the sink and window
              blocks (the answer tile, the query block holding the chunk's last live token, keeps every block, as LSE),
              and writes the tile list: the kept blocks' 32-key tiles, the chunk's own tiles up to the causal
              limit, then correction tiles of 32 pooled rows with a bit per row (1 = a dropped candidate block, scored
              with a log 128 shift: mean correction).
List layout per (query block, KV head) g = qb * 4 + kvh at g * LS: [0] = tile count n, then (ks, word) pairs from [2];
two pad pairs (0, 0) follow so the attention's one-ahead K / V loads stay in range.
"""

V4H = "vector<4xf16>"
V4 = "vector<4xf32>"
V8H = "vector<8xf16>"
V8 = "vector<8xf32>"
V16H = "vector<16xf16>"
V16 = "vector<16xf32>"

BLK = 128         # keys per block
ALPHA = 0.1       # keep blocks with E_J >= ALPHA max E
SINK = 2          # blocks always kept from the start (256 tokens)
WINDOW = 4        # blocks always kept before the chunk (512 tokens)
LN128 = 4.852030263919617


def ext_pages(cap):
    """Extension pages for the pooled rows of every block of a cap-token context."""
    return -(-(cap // BLK) // 256)


def list_stride(cap, B):
    nb = cap // BLK
    return 2 * (4 * nb + B // 32 + nb // 32 + 4) + 2


def _consts(e, vals):
    for v in vals:
        e(f"  %c{v} = index.constant {v} : index")


def gen_fpmean():
    """yah_fpmean: means of blocks first..nend-1 (grid x = nend - first). Thread t: K columns 4t..4t+3 (KV head t / 64),
    V dims 4 (t % 64)..+3 of KV head t / 64. Bindings: kpool, vpool, ptab, kmean, vmean."""
    L = []
    e = L.append
    e("// GENERATED by tools/gen_fpsparse.py (fpmean) -- edit the generator.")
    e("amdgpu.target<gfx1151> @fps_w32 {subgroup_size = 32}")
    for k in ("capacity", "capx", "first", "nend"):
        e(f"config.decl @yah_fpmean.{k} : %value: index where [range(%value, 0, 1048576)]")
    e("")
    e("kernel.def target(@fps_w32) @yah_fpmean() {")
    e("  %first = config.get @yah_fpmean.first : index")
    e("  %nend = config.get @yah_fpmean.nend : index")
    e("  %c1 = index.constant 1 : index")
    e("  %c256 = index.constant 256 : index")
    e("  %nwg = index.sub %nend, %first : index")
    e("  kernel.launch.config workgroups(%nwg, %c1, %c1) workgroup_size(%c256, %c1, %c1) : index")
    e("} launch(%kpool: buffer, %vpool: buffer, %ptab: buffer, %kmean: buffer, %vmean: buffer) {")
    e("  %base = index.constant 0 : offset")
    _consts(e, (0, 1, 4, 8, 15, 16, 64, 128, 255, 256, 1024, 4096))
    _pool_setup(e, "yah_fpmean")
    e("  %first = config.get @yah_fpmean.first : index")
    e("  %wg = kernel.workgroup.id<x> : index")
    e("  %j = index.add %first, %wg : index")
    e("  %tid = kernel.workitem.id<x> : index")
    e("  %col = index.mul %tid, %c4 : index")           # K / V column of the 1024 (KV head x 256 dims)
    e("  %kvh = index.div %tid, %c64 : index")
    e("  %d0 = index.rem %tid, %c64 : index")
    e("  %d4 = index.mul %d0, %c4 : index")
    # K: rows j * 128 .. + 127 lie in one page
    e("  %row0 = index.mul %j, %c128 : index")
    e("  %lp = index.div %row0, %c256 : index")
    e("  %pg0 = view.load %pt_flat[%lp] : view<[%npx]xi32> -> i32")
    e("  %pgr = index.cast %pg0 : i32 to index")
    e("  %pg = index.assume %pgr [range(%pgr, 0, 65535), lt(%pgr, %npx)] : index")
    e("  %pb = index.mul %pg, %c256 : index")
    e("  %po = index.rem %row0, %c256 : index")
    e("  %prow0 = index.add %pb, %po : index")
    e(f"  %z4 = vector.constant 0.0 : {V4}")
    e(f"  %kacc = scf.for %i = [%c0 to %c128 step %c1](%a = %z4 : {V4}) -> ({V4}) {{")
    e("    %pr = index.add %prow0, %i : index")
    e("    %ka0 = index.mul %pr, %c1024 : index")
    e("    %ka1 = index.add %ka0, %col : index")
    e("    %ka = index.min %ka1, %ktot4 : index")
    e(f"    %kx = vector.load %k_flat[%ka] : view<[%ktot]xf16> -> {V4H}")
    e(f"    %kxf = vector.extf %kx : {V4H} to {V4}")
    e(f"    %an = vector.addf %a, %kxf : {V4}")
    e(f"    scf.yield %an : {V4}")
    e("  }")
    e("  %inv = scalar.constant 0.0078125 : f32")
    e(f"  %inv4 = vector.splat %inv : {V4}")
    e(f"  %km4 = vector.mulf %kacc, %inv4 : {V4}")
    e(f"  %kmh = vector.fptrunc %km4 : {V4} to {V4H}")
    e("  %mo0 = index.mul %j, %c1024 : index")
    e("  %mo1 = index.add %mo0, %col : index")
    e("  %mo = index.min %mo1, %mtot4 : index")
    e(f"  vector.store %kmh, %km_flat[%mo] : {V4H}, view<[%mtot]xf16>")
    # V: tiles 8j .. 8j + 7 (16 keys each, one page), dims d4 .. d4 + 3 of KV head kvh
    e("  %vhb = index.mul %kvh, %vtx : index")
    sums = [None] * 4
    for u in range(8):
        e(f"  %vt{u}c = index.constant {u} : index")
        e(f"  %vt{u}a = index.mul %j, %c8 : index")
        e(f"  %vt{u} = index.add %vt{u}a, %vt{u}c : index")
        e(f"  %vlp{u} = index.div %vt{u}, %c16 : index")
        e(f"  %vpg{u}0 = view.load %pt_flat[%vlp{u}] : view<[%npx]xi32> -> i32")
        e(f"  %vpg{u}r = index.cast %vpg{u}0 : i32 to index")
        e(f"  %vpg{u} = index.assume %vpg{u}r [range(%vpg{u}r, 0, 65535), lt(%vpg{u}r, %npx)] : index")
        e(f"  %vpb{u} = index.mul %vpg{u}, %c16 : index")
        e(f"  %vpo{u} = index.rem %vt{u}, %c16 : index")
        e(f"  %vpt{u} = index.add %vpb{u}, %vpo{u} : index")
        e(f"  %vti{u} = index.add %vhb, %vpt{u} : index")
        e(f"  %vtb{u} = index.mul %vti{u}, %c256 : index")
        for d in range(4):
            e(f"  %vd{u}_{d}c = index.constant {d} : index")
            e(f"  %vd{u}_{d}a = index.add %d4, %vd{u}_{d}c : index")
            e(f"  %vd{u}_{d}b = index.add %vtb{u}, %vd{u}_{d}a : index")
            e(f"  %vd{u}_{d}m = index.mul %vd{u}_{d}b, %c16 : index")
            e(f"  %vd{u}_{d} = index.min %vd{u}_{d}m, %vtot16 : index")
            e(f"  %vx{u}_{d} = vector.load %v_flat[%vd{u}_{d}] : view<[%vtot]xf16> -> {V16H}")
            e(f"  %vxf{u}_{d} = vector.extf %vx{u}_{d} : {V16H} to {V16}")
            e(f"  %zf{u}_{d} = scalar.constant 0.0 : f32")
            e(f"  %vs{u}_{d} = vector.reduce<addf> %vxf{u}_{d}, %zf{u}_{d} : {V16}, f32")
            if sums[d] is None:
                sums[d] = f"%vs{u}_{d}"
            else:
                e(f"  %va{u}_{d} = scalar.addf {sums[d]}, %vs{u}_{d} : f32")
                sums[d] = f"%va{u}_{d}"
    hs = []
    for d in range(4):
        e(f"  %vm{d} = scalar.mulf {sums[d]}, %inv : f32")
        e(f"  %vh{d} = scalar.fptrunc %vm{d} : f32 to f16")
        hs.append(f"%vh{d}")
    e(f"  %vmh = vector.from_elements {', '.join(hs)} : {V4H}")
    e("  %vmo0 = index.mul %kvh, %c256 : index")
    e("  %vmo1 = index.add %vmo0, %d4 : index")
    e("  %vmo2 = index.add %mo0, %vmo1 : index")
    e("  %vmo = index.min %vmo2, %mtot4 : index")
    e(f"  vector.store %vmh, %vm_flat[%vmo] : {V4H}, view<[%mtot]xf16>")
    e("  kernel.return")
    e("}")
    return "\n".join(L) + "\n"


def _pool_setup(e, sym):
    """Pool geometry: base context pages (npages, pcap), extended (npx, pcapx), views of both pools, ptab, the means."""
    e(f"  %cap = config.get @{sym}.capacity : index")
    e(f"  %capx = config.get @{sym}.capx : index")
    e("  %npg0 = index.add %cap, %c255 : index")
    e("  %npages = index.div %npg0, %c256 : index")
    e("  %pcap = index.mul %npages, %c256 : index")
    e("  %npx0 = index.add %capx, %c255 : index")
    e("  %npx = index.div %npx0, %c256 : index")
    e("  %pcapx = index.mul %npx, %c256 : index")
    e("  %ktot = index.mul %pcapx, %c1024 : index")
    e("  %vtx = index.div %pcapx, %c16 : index")           # V^T tiles per KV head (extended pool)
    e("  %vtot0 = index.mul %vtx, %c4096 : index")
    e("  %vtot = index.mul %vtot0, %c4 : index")
    e("  %nbm = index.div %pcap, %c128 : index")
    e("  %mtot = index.mul %nbm, %c1024 : index")
    e("  %ktot4 = index.sub %ktot, %c4 : index")
    e("  %vtot16 = index.sub %vtot, %c16 : index")
    e("  %vtot1 = index.sub %vtot, %c1 : index")
    e("  %mtot4 = index.sub %mtot, %c4 : index")
    e("  %kp_na, %vp_na, %pt_na, %km_na, %vm_na = buffer.assume.noalias %kpool, %vpool, %ptab, %kmean, %vmean : buffer, buffer, buffer, buffer, buffer")
    e("  %k_flat = buffer.view %kp_na[%base] : buffer -> view<[%ktot]xf16>")
    e("  %v_flat = buffer.view %vp_na[%base] : buffer -> view<[%vtot]xf16>")
    e("  %pt_flat = buffer.view %pt_na[%base] : buffer -> view<[%npx]xi32>")
    e("  %km_flat = buffer.view %km_na[%base] : buffer -> view<[%mtot]xf16>")
    e("  %vm_flat = buffer.view %vm_na[%base] : buffer -> view<[%mtot]xf16>")


def gen_fpcopy():
    """yah_fpcopy: the layer's means of blocks 0..nend-1 into the pools' extension (grid x = nend). Block j is pooled key
    pcap + j: K row pcap + j (the host maps extension pages to themselves), V^T tile pcap / 16 + j / 16, slot j % 16.
    Same bindings as yah_fpmean."""
    L = []
    e = L.append
    e("// GENERATED by tools/gen_fpsparse.py (fpcopy) -- edit the generator.")
    e("amdgpu.target<gfx1151> @fps_w32 {subgroup_size = 32}")
    for k in ("capacity", "capx", "nend"):
        e(f"config.decl @yah_fpcopy.{k} : %value: index where [range(%value, 0, 1048576)]")
    e("")
    e("kernel.def target(@fps_w32) @yah_fpcopy() {")
    e("  %nend = config.get @yah_fpcopy.nend : index")
    e("  %c1 = index.constant 1 : index")
    e("  %c256 = index.constant 256 : index")
    e("  kernel.launch.config workgroups(%nend, %c1, %c1) workgroup_size(%c256, %c1, %c1) : index")
    e("} launch(%kpool: buffer, %vpool: buffer, %ptab: buffer, %kmean: buffer, %vmean: buffer) {")
    e("  %base = index.constant 0 : offset")
    _consts(e, (0, 1, 4, 16, 64, 128, 255, 256, 1024, 4096))
    _pool_setup(e, "yah_fpcopy")
    e("  %j = kernel.workgroup.id<x> : index")
    e("  %tid = kernel.workitem.id<x> : index")
    e("  %col = index.mul %tid, %c4 : index")
    e("  %kvh = index.div %tid, %c64 : index")
    e("  %d0 = index.rem %tid, %c64 : index")
    e("  %d4 = index.mul %d0, %c4 : index")
    e("  %mo0 = index.mul %j, %c1024 : index")
    e("  %mo1 = index.add %mo0, %col : index")
    e("  %mo = index.min %mo1, %mtot4 : index")
    e(f"  %kmh = vector.load %km_flat[%mo] : view<[%mtot]xf16> -> {V4H}")
    e(f"  %vmh = vector.load %vm_flat[%mo] : view<[%mtot]xf16> -> {V4H}")
    e("  %kr = index.add %pcap, %j : index")
    e("  %ko0 = index.mul %kr, %c1024 : index")
    e("  %ko1 = index.add %ko0, %col : index")
    e("  %ko = index.min %ko1, %ktot4 : index")
    e(f"  vector.store %kmh, %k_flat[%ko] : {V4H}, view<[%ktot]xf16>")
    e("  %pt16 = index.div %pcap, %c16 : index")
    e("  %jt = index.div %j, %c16 : index")
    e("  %js = index.rem %j, %c16 : index")
    e("  %vt0 = index.add %pt16, %jt : index")
    e("  %vhb = index.mul %kvh, %vtx : index")
    e("  %vt = index.add %vhb, %vt0 : index")
    e("  %vtb = index.mul %vt, %c256 : index")
    for d in range(4):
        e(f"  %vh{d} = vector.extract %vmh[{d}] : {V4H} -> f16")
        e(f"  %vo{d}c = index.constant {d} : index")
        e(f"  %vo{d}a = index.add %d4, %vo{d}c : index")
        e(f"  %vo{d}b = index.add %vtb, %vo{d}a : index")
        e(f"  %vo{d}d = index.mul %vo{d}b, %c16 : index")
        e(f"  %vo{d}e = index.add %vo{d}d, %js : index")
        e(f"  %vo{d} = index.min %vo{d}e, %vtot1 : index")
        e(f"  view.store %vh{d}, %v_flat[%vo{d}] : f16, view<[%vtot]xf16>")
    e("  kernel.return")
    e("}")
    return "\n".join(L) + "\n"


def gen_fpsel(cap, B, alpha=ALPHA):
    """yah_fpsel: the tile lists (module doc). Grid (B / 16 query blocks, 4 KV heads), 256 threads.
    Config: start_pos (the chunk's first token), tpad (pooled key base = the pool's whole-page capacity).
    Bindings: q (f16 [B][6144], q / 16 as the attention reads it), kmean (the layer's [block][1024]), valid (live tokens
    of the chunk), sel (i32 lists)."""
    nbm = cap // BLK
    assert nbm <= 1536, "fpsel: the per-block (m, S) LDS arrays exceed 64 KB past 192K tokens"
    LS = list_stride(cap, B)
    QB = 96 * 256 * 2               # LDS: the query block's 96 rows x 256 dims f16
    LDS = QB + 2 * nbm * 4 + 64
    assert LDS <= 65536
    L = []
    e = L.append
    e("// GENERATED by tools/gen_fpsparse.py (fpsel) -- edit the generator.")
    e("amdgpu.target<gfx1151> @fps_w32 {subgroup_size = 32}")
    for k in ("start_pos", "tpad"):
        e(f"config.decl @yah_fpsel.{k} : %value: index where [range(%value, 0, 1048576)]")
    e("")
    e("kernel.def target(@fps_w32) @yah_fpsel() {")
    e("  %c4 = index.constant 4 : index")
    e(f"  %cnq = index.constant {B // 16} : index")
    e("  %c256 = index.constant 256 : index")
    e("  %c1 = index.constant 1 : index")
    e("  kernel.launch.config workgroups(%cnq, %c4, %c1) workgroup_size(%c256, %c1, %c1) : index")
    e("} launch(%q: buffer, %kmean: buffer, %valid: buffer, %sel: buffer) {")
    e("  %base = index.constant 0 : offset")
    _consts(e, (0, 1, 2, 3, 4, 6, 8, 16, 24, 31, 32, 64, 128, 256, 1024, 6144))
    e("  %start_pos = config.get @yah_fpsel.start_pos : index")
    e("  %tpad = config.get @yah_fpsel.tpad : index")
    e(f"  %qtot = index.constant {B * 6144} : index")
    e(f"  %mtot = index.constant {nbm * 1024} : index")
    e(f"  %ls = index.constant {LS} : index")
    e(f"  %stot = index.constant {LS * (B // 16) * 4} : index")
    e("  %nbp = index.div %start_pos, %c128 : index")
    e(f"  %qtot8 = index.constant {B * 6144 - 8} : index")
    e(f"  %mtot8 = index.constant {nbm * 1024 - 8} : index")
    e(f"  %stot1 = index.constant {LS * (B // 16) * 4 - 1} : index")      # prior blocks (the chunk starts on a block boundary)
    e("  %q_na, %km_na, %sl_na = buffer.assume.noalias %q, %kmean, %sel : buffer, buffer, buffer")
    e("  %q_flat = buffer.view %q_na[%base] : buffer -> view<[%qtot]xf16>")
    e("  %km_flat = buffer.view %km_na[%base] : buffer -> view<[%mtot]xf16>")
    e("  %sl_flat = buffer.view %sl_na[%base] : buffer -> view<[%stot]xi32>")
    e("  %vl_flat = buffer.view %valid[%base] : buffer -> view<1xi32>")
    e("  %nv0 = view.load %vl_flat[%c0] : view<1xi32> -> i32")
    e("  %nv1 = index.cast %nv0 : i32 to index")
    e(f"  %nvB = index.constant {B} : index")
    e("  %nv = index.min %nv1, %nvB : index")
    e(f"  %pb = index.constant {LDS} : offset")
    e("  %pool = buffer.alloca<workgroup> align(16) %pb : buffer")
    e("  %qv = buffer.view %pool[%base] : buffer -> view<96x256xf16>")
    e(f"  %mo_ = index.constant {QB} : offset")
    e(f"  %mv = buffer.view %pool[%mo_] : buffer -> view<{nbm}xf32>")
    e(f"  %so_ = index.constant {QB + nbm * 4} : offset")
    e(f"  %sv = buffer.view %pool[%so_] : buffer -> view<{nbm}xf32>")
    e(f"  %ro_ = index.constant {QB + 2 * nbm * 4} : offset")
    e("  %rv = buffer.view %pool[%ro_] : buffer -> view<16xf32>")
    e("  %qb = kernel.workgroup.id<x> : index")
    e("  %kvh = kernel.workgroup.id<y> : index")
    e("  %tid = kernel.workitem.id<x> : index")
    e("  %wave = index.div %tid, %c32 : index")
    e("  %qs = index.mul %qb, %c16 : index")
    e("  %h0 = index.mul %kvh, %c6 : index")
    e("  %zero = scalar.constant 0.0 : f32")
    e("  %ninf = scalar.constant -3.4028234663852886e+38 : f32")
    e("  %log2e = scalar.constant 1.4426950408889634 : f32")
    e(f"  %zh8 = vector.constant 0.0 : {V8H}")
    # stage Q: row r = token * 6 + head, 32 chunks of 8 dims; dead tokens zero
    for c in range(12):
        e(f"  %sq{c}c = index.constant {256 * c} : index")
        e(f"  %sq{c}i = index.add %tid, %sq{c}c : index")
        e(f"  %sq{c}r = index.div %sq{c}i, %c32 : index")
        e(f"  %sq{c}k = index.rem %sq{c}i, %c32 : index")
        e(f"  %sq{c}d = index.mul %sq{c}k, %c8 : index")
        e(f"  %sq{c}t = index.div %sq{c}r, %c6 : index")
        e(f"  %sq{c}h = index.rem %sq{c}r, %c6 : index")
        e(f"  %sq{c}tk = index.add %qs, %sq{c}t : index")
        e(f"  %sq{c}l = index.cmp ult, %sq{c}tk, %nv : index")
        e(f"  %sq{c}a0 = index.mul %sq{c}tk, %c6144 : index")
        e(f"  %sq{c}hh = index.add %h0, %sq{c}h : index")
        e(f"  %sq{c}a1 = index.mul %sq{c}hh, %c256 : index")
        e(f"  %sq{c}a2 = index.add %sq{c}a0, %sq{c}a1 : index")
        e(f"  %sq{c}a3 = index.add %sq{c}a2, %sq{c}d : index")
        e(f"  %sq{c}a = index.min %sq{c}a3, %qtot8 : index")
        e(f"  %sq{c}v = vector.load %q_flat[%sq{c}a] : view<[%qtot]xf16> -> {V8H}")
        e(f"  %sq{c}z = scf.select %sq{c}l, %sq{c}v, %zh8 : {V8H}")
        e(f"  vector.store %sq{c}z, %qv[%sq{c}r, %sq{c}d] : {V8H}, view<96x256xf16>")
    e("  kernel.barrier<workgroup> scope(workgroup) ordering(acq_rel)")
    # scoring: lane = block J; rows in 4 groups of 24 (f16 dot partials per 8 dims, summed in f32)
    e("  %kvd = index.mul %kvh, %c256 : index")
    e("  %tmax = scf.for %J = [%tid to %nbp step %c256](%tm = %ninf : f32) -> (f32) {")
    e("    %Jb = index.mul %J, %c1024 : index")
    e("    %Jk = index.add %Jb, %kvd : index")
    run_m, run_s = "%ninf", "%zero"
    for g in range(4):
        accs = [f"%g{g}a{r}" for r in range(24)]
        init = ", ".join(f"{a} = %zh8 : {V8H}" for a in accs)
        outs = [f"%g{g}o{r}" for r in range(24)]
        e(f"    {', '.join(outs)} = scf.for %g{g}d8 = [%c0 to %c32 step %c1]({init}) -> ({', '.join([V8H] * 24)}) {{")
        e(f"      %g{g}dd = index.mul %g{g}d8, %c8 : index")
        e(f"      %g{g}ka0 = index.add %Jk, %g{g}dd : index")
        e(f"      %g{g}ka = index.min %g{g}ka0, %mtot8 : index")
        e(f"      %g{g}kx = vector.load %km_flat[%g{g}ka] : view<[%mtot]xf16> -> {V8H}")
        nxt = []
        for r in range(24):
            e(f"      %g{g}qr{r} = index.constant {24 * g + r} : index")
            e(f"      %g{g}qx{r} = vector.load %qv[%g{g}qr{r}, %g{g}dd] : view<96x256xf16> -> {V8H}")
            e(f"      %g{g}qn{r} = vector.fmaf %g{g}qx{r}, %g{g}kx, {accs[r]} : {V8H}")
            nxt.append(f"%g{g}qn{r}")
        e(f"      scf.yield {', '.join(nxt)} : {', '.join([V8H] * 24)}")
        e("    }")
        ss = []
        for r in range(24):
            row = 24 * g + r
            e(f"    %g{g}f{r} = vector.extf {outs[r]} : {V8H} to {V8}")
            e(f"    %g{g}s{r} = vector.reduce<addf> %g{g}f{r}, %zero : {V8}, f32")
            e(f"    %g{g}t{r} = index.constant {row // 6} : index")
            e(f"    %g{g}tk{r} = index.add %qs, %g{g}t{r} : index")
            e(f"    %g{g}l{r} = index.cmp ult, %g{g}tk{r}, %nv : index")
            e(f"    %g{g}x{r} = scf.select %g{g}l{r}, %g{g}s{r}, %ninf : f32")
            ss.append((f"%g{g}x{r}", f"%g{g}l{r}"))
        cur = ss[0][0]
        for r in range(1, 24):
            e(f"    %g{g}m{r} = scalar.maxnumf {cur}, {ss[r][0]} : f32")
            cur = f"%g{g}m{r}"
        e(f"    %g{g}mx = scalar.maxnumf {run_m}, {cur} : f32")
        # rescale the running sum to the new max, add this group's terms
        e(f"    %g{g}rd = scalar.subf {run_m}, %g{g}mx : f32")
        e(f"    %g{g}rl = scalar.mulf %g{g}rd, %log2e : f32")
        e(f"    %g{g}re = scalar.exp2f<afn> %g{g}rl : f32")
        e(f"    %g{g}rs = scalar.mulf {run_s}, %g{g}re : f32")
        acc = f"%g{g}rs"
        for r in range(24):
            x, live = ss[r]
            e(f"    %g{g}d{r} = scalar.subf {x}, %g{g}mx : f32")
            e(f"    %g{g}dl{r} = scalar.mulf %g{g}d{r}, %log2e : f32")
            e(f"    %g{g}p{r} = scalar.exp2f<afn> %g{g}dl{r} : f32")
            e(f"    %g{g}pz{r} = scf.select {live}, %g{g}p{r}, %zero : f32")
            e(f"    %g{g}sa{r} = scalar.addf {acc}, %g{g}pz{r} : f32")
            acc = f"%g{g}sa{r}"
        run_m, run_s = f"%g{g}mx", acc
    e(f"    view.store {run_m}, %mv[%J] : f32, view<{nbm}xf32>")
    e(f"    view.store {run_s}, %sv[%J] : f32, view<{nbm}xf32>")
    e(f"    %tmn = scalar.maxnumf %tm, {run_m} : f32")
    e("    scf.yield %tmn : f32")
    e("  }")

    def wg_max(src, tag):
        """Workgroup max of a per-thread f32 (8 waves) through the 16-float LDS slot."""
        e(f"  %{tag}w = kernel.subgroup.reduce<maxnumf> {src} : f32")
        e(f"  view.store %{tag}w, %rv[%wave] : f32, view<16xf32>")
        e("  kernel.barrier<workgroup> scope(workgroup) ordering(acq_rel)")
        cur = None
        for w in range(8):
            e(f"  %{tag}i{w} = index.constant {w} : index")
            e(f"  %{tag}v{w} = view.load %rv[%{tag}i{w}] : view<16xf32> -> f32")
            if cur is None:
                cur = f"%{tag}v{w}"
            else:
                e(f"  %{tag}m{w} = scalar.maxnumf {cur}, %{tag}v{w} : f32")
                cur = f"%{tag}m{w}"
        e("  kernel.barrier<workgroup> scope(workgroup) ordering(acq_rel)")
        return cur

    M = wg_max("%tmax", "gm")
    # E_J = S_J exp(m_J - M) into the S array; the thread max of E
    e("  %emax = scf.for %J2 = [%tid to %nbp step %c256](%em = %zero : f32) -> (f32) {")
    e(f"    %mJ = view.load %mv[%J2] : view<{nbm}xf32> -> f32")
    e(f"    %sJ = view.load %sv[%J2] : view<{nbm}xf32> -> f32")
    e(f"    %eD = scalar.subf %mJ, {M} : f32")
    e("    %eL = scalar.mulf %eD, %log2e : f32")
    e("    %eX = scalar.exp2f<afn> %eL : f32")
    e("    %eJ = scalar.mulf %sJ, %eX : f32")
    e(f"    view.store %eJ, %sv[%J2] : f32, view<{nbm}xf32>")
    e("    %emn = scalar.maxnumf %em, %eJ : f32")
    e("    scf.yield %emn : f32")
    e("  }")
    EM = wg_max("%emax", "ge")
    e(f"  %alpha = scalar.constant {alpha!r} : f32")
    e(f"  %thr = scalar.mulf {EM}, %alpha : f32")
    # thread 0: the list (kept blocks ascending, the chunk's tiles, correction tiles), then the count and two pad pairs
    e("  %g4 = index.mul %qb, %c4 : index")
    e("  %gi = index.add %g4, %kvh : index")
    e("  %lb0 = index.mul %gi, %ls : index")
    e("  %lb = index.min %lb0, %stot1 : index")
    e("  %lb2 = index.add %lb, %c2 : index")
    e("  %t0 = index.cmp eq, %tid, %c0 : index")
    e(f"  %csink = index.constant {SINK} : index")
    e(f"  %cwin = index.constant {WINDOW} : index")
    e("  %nbw = index.sub %nbp, %cwin : index")
    e("  %onef = scalar.constant 1.0 : f32")
    # answer tile (as LSE): the 16-token block holding the chunk's last live token keeps every block exact
    e("  %qs16 = index.add %qs, %c16 : index")
    e("  %anlo = index.cmp ugt, %nv, %qs : index")
    e("  %anhi = index.cmp ule, %nv, %qs16 : index")
    e("  %ans = scalar.andi %anlo, %anhi : i1")
    e("  scf.if %t0 {")
    # kept blocks: flag 1.0 / 0.0 into the m array (the correction words read it)
    e("    %n1 = scf.for %J3 = [%c0 to %nbp step %c1](%na = %c0 : index) -> (index) {")
    e("      %naA = index.assume %na [range(%na, 0, 1048576)] : index")
    e(f"      %kE = view.load %sv[%J3] : view<{nbm}xf32> -> f32")
    e("      %kT = scalar.cmpf oge, %kE, %thr : f32")
    e("      %kS = index.cmp ult, %J3, %csink : index")
    e("      %kW = index.cmp uge, %J3, %nbw : index")
    e("      %kSW = scalar.ori %kS, %kW : i1")
    e("      %kTA = scalar.ori %kT, %ans : i1")
    e("      %kk = scalar.ori %kTA, %kSW : i1")
    e("      %kf = scf.select %kk, %onef, %zero : f32")
    e(f"      view.store %kf, %mv[%J3] : f32, view<{nbm}xf32>")
    e("      %kks = index.mul %J3, %c128 : index")
    for i in range(4):
        e(f"      %ke{i}c = index.constant {2 * i} : index")
        e(f"      %ke{i}n = index.mul %naA, %c2 : index")
        e(f"      %ke{i}a0 = index.add %lb2, %ke{i}n : index")
        e(f"      %ke{i}a = index.add %ke{i}a0, %ke{i}c : index")
        e(f"      %ke{i}ac = index.min %ke{i}a, %stot1 : index")
        e(f"      %ke{i}o = index.constant {32 * i} : index")
        e(f"      %ke{i}k = index.add %kks, %ke{i}o : index")
        e(f"      %ke{i}ki = index.cast %ke{i}k : index to i32")
        e(f"      view.store %ke{i}ki, %sl_flat[%ke{i}ac] : i32, view<[%stot]xi32>")
    e("      %kn4 = index.add %naA, %c4 : index")
    e("      %kn = scf.select %kk, %kn4, %naA : index")
    e("      scf.yield %kn : index")
    e("    }")
    # the chunk's own tiles up to the causal limit start_pos + qs + 16
    e("    %cv0 = index.add %qs, %c16 : index")
    e("    %cv1 = index.add %cv0, %c31 : index")
    e("    %ncur = index.div %cv1, %c32 : index")
    e("    %n2 = scf.for %ci = [%c0 to %ncur step %c1](%nb = %n1 : index) -> (index) {")
    e("      %nbA = index.assume %nb [range(%nb, 0, 1048576)] : index")
    e("      %cks0 = index.mul %ci, %c32 : index")
    e("      %cks = index.add %start_pos, %cks0 : index")
    e("      %cksi = index.cast %cks : index to i32")
    e("      %cn2 = index.mul %nbA, %c2 : index")
    e("      %ca0 = index.add %lb2, %cn2 : index")
    e("      %ca = index.min %ca0, %stot1 : index")
    e("      view.store %cksi, %sl_flat[%ca] : i32, view<[%stot]xi32>")
    e("      %cn = index.add %nbA, %c1 : index")
    e("      scf.yield %cn : index")
    e("    }")
    # correction tiles: pooled rows 32 jw .. + 31, bit b = block 32 jw + b is a dropped candidate (not sink, not kept)
    e("    %nw0 = index.add %nbp, %c31 : index")
    e("    %nwd = index.div %nw0, %c32 : index")
    e("    %zi = scalar.constant 0 : i32")
    e("    %onei = scalar.constant 1 : i32")
    e("    %n3 = scf.for %jw = [%c0 to %nwd step %c1](%nc = %n2 : index) -> (index) {")
    e("      %ncA = index.assume %nc [range(%nc, 0, 1048576)] : index")
    e("      %jb = index.mul %jw, %c32 : index")
    e("      %wd = scf.for %b = [%c0 to %c32 step %c1](%w = %zi : i32) -> (i32) {")
    e("        %bJ = index.add %jb, %b : index")
    e("        %bin = index.cmp ult, %bJ, %nbp : index")
    e("        %bJc = index.min %bJ, %nbp : index")
    e("        %bJs = index.sub %nbp, %c1 : index")
    e("        %bJr = index.min %bJc, %bJs : index")
    e(f"        %bk = view.load %mv[%bJr] : view<{nbm}xf32> -> f32")
    e("        %bdrop = scalar.cmpf olt, %bk, %onef : f32")
    e("        %bns = index.cmp uge, %bJ, %csink : index")
    e("        %bc0 = scalar.andi %bin, %bdrop : i1")
    e("        %bc = scalar.andi %bc0, %bns : i1")
    e("        %bbi = index.cast %b : index to i32")
    e("        %bbit = scalar.shli %onei, %bbi : i32")
    e("        %bor = scalar.ori %w, %bbit : i32")
    e("        %wn = scf.select %bc, %bor, %w : i32")
    e("        scf.yield %wn : i32")
    e("      }")
    e("      %wks0 = index.add %tpad, %jb : index")
    e("      %wksi = index.cast %wks0 : index to i32")
    e("      %wn2 = index.mul %ncA, %c2 : index")
    e("      %wa0 = index.add %lb2, %wn2 : index")
    e("      %wa = index.min %wa0, %stot1 : index")
    e("      %wa10 = index.add %wa0, %c1 : index")
    e("      %wa1 = index.min %wa10, %stot1 : index")
    e("      view.store %wksi, %sl_flat[%wa] : i32, view<[%stot]xi32>")
    e("      view.store %wd, %sl_flat[%wa1] : i32, view<[%stot]xi32>")
    e("      %wnz = scalar.cmpi ne, %wd, %zi : i32")
    e("      %wn1 = index.add %ncA, %c1 : index")
    e("      %wnn = scf.select %wnz, %wn1, %ncA : index")
    e("      scf.yield %wnn : index")
    e("    }")
    e("    %n3A = index.assume %n3 [range(%n3, 0, 1048576)] : index")
    for p in range(2):   # pad pairs (0, 0)
        e(f"    %pn{p}c = index.constant {p} : index")
        e(f"    %pn{p} = index.add %n3A, %pn{p}c : index")
        e(f"    %pn{p}2 = index.mul %pn{p}, %c2 : index")
        e(f"    %pa{p}0 = index.add %lb2, %pn{p}2 : index")
        e(f"    %pa{p} = index.min %pa{p}0, %stot1 : index")
        e(f"    %pa{p}10 = index.add %pa{p}0, %c1 : index")
        e(f"    %pa{p}1 = index.min %pa{p}10, %stot1 : index")
        e(f"    view.store %zi, %sl_flat[%pa{p}] : i32, view<[%stot]xi32>")
        e(f"    view.store %zi, %sl_flat[%pa{p}1] : i32, view<[%stot]xi32>")
    e("    %n3i = index.cast %n3A : index to i32")
    e("    view.store %n3i, %sl_flat[%lb] : i32, view<[%stot]xi32>")
    e("  }")
    e("  kernel.return")
    e("}")
    return "\n".join(L) + "\n"


