#!/usr/bin/env python3
"""Block-sparse prefill attention (FlashPrefill V2, arXiv 2608.19758) for the kv4 paged sets: block means, block
selection, and the tile lists the KT2 attention (gen_attn_fa FPSPARSE) walks.

Blocks are 128 keys. Per attention layer and chunk:
  yah_fpmean  means of the chunk's blocks (and the previous chunk's: the last layer skips its attention on non-final
              chunks) from the f16 pools into the layer's persistent means [block][1024] (K rows; V row-major).
  yah_fpcopyk / yah_fpcopyv  the layer's means of every block so far, quantized as kv4 into the int4 pools' extension:
              block j is pooled key cap + j (K row cap + j; V^T tile j / 16, key slot j % 16, of a region after the 4
              KV heads), so the attention (on the int4 pools directly) loads it like any key.
  yah_fpsel   per (16-token query block, KV head): scores the prior blocks with the pooled keys over the block's 96 query
              rows (6 heads), E_J = sum_r exp(q_r . kbar_J - M), keeps E_J >= ALPHA max E plus the sink and window
              blocks (the answer tile, the query block holding the prompt's last token, keeps every block, as LSE),
              and writes the tile list: the kept blocks' 32-key tiles, the chunk's own tiles up to the causal
              limit, then correction tiles of 32 pooled rows with a bit per row (1 = a dropped candidate block, scored
              with a log 128 shift: mean correction).
List layout per (query block, KV head) g = qb * 4 + kvh at g * LS: [0] = tile count n, then (ks, word) pairs from [2];
two pad pairs (0, 0) follow so the attention's one-ahead K / V loads stay in range.
"""

V4H = "vector<4xf16>"
V4 = "vector<4xf32>"
V8H = "vector<8xf16>"
V8 = "vector<8xf32>"
V16H = "vector<16xf16>"
V16 = "vector<16xf32>"

BLK = 128         # keys per block
ALPHA = 0.1       # keep blocks with E_J >= ALPHA max E
SINK = 2          # blocks always kept from the start (256 tokens)
WINDOW = 4        # blocks always kept before the chunk (512 tokens)
LN128 = 4.852030263919617


def ext_pages(cap):
    """Extension pages for the pooled rows of every block of a cap-token context."""
    return -(-(cap // BLK) // 256)


def list_stride(cap, B):
    nb = cap // BLK
    return 2 * (4 * nb + B // 32 + nb // 32 + 4) + 2


def _consts(e, vals):
    for v in vals:
        e(f"  %c{v} = index.constant {v} : index")


def gen_fpmean():
    """yah_fpmean: means of blocks first..nend-1 (grid x = nend - first). Thread t: K columns 4t..4t+3 (KV head t / 64),
    V dims 4 (t % 64)..+3 of KV head t / 64. Bindings: kpool, vpool, ptab, kmean, vmean."""
    L = []
    e = L.append
    e("// GENERATED by tools/gen_fpsparse.py (fpmean) -- edit the generator.")
    e("amdgpu.target<gfx1151> @fps_w32 {subgroup_size = 32}")
    for k in ("capacity", "capx", "first", "nend"):
        e(f"config.decl @yah_fpmean.{k} : %value: index where [range(%value, 0, 1048576)]")
    e("")
    e("kernel.def target(@fps_w32) @yah_fpmean() {")
    e("  %first = config.get @yah_fpmean.first : index")
    e("  %nend = config.get @yah_fpmean.nend : index")
    e("  %c1 = index.constant 1 : index")
    e("  %c256 = index.constant 256 : index")
    e("  %nwg = index.sub %nend, %first : index")
    e("  kernel.launch.config workgroups(%nwg, %c1, %c1) workgroup_size(%c256, %c1, %c1) : index")
    e("} launch(%kpool: buffer, %vpool: buffer, %ptab: buffer, %kmean: buffer, %vmean: buffer) {")
    e("  %base = index.constant 0 : offset")
    _consts(e, (0, 1, 4, 8, 15, 16, 64, 128, 255, 256, 1024, 4096))
    _pool_setup(e, "yah_fpmean")
    e("  %first = config.get @yah_fpmean.first : index")
    e("  %wg = kernel.workgroup.id<x> : index")
    e("  %j = index.add %first, %wg : index")
    e("  %tid = kernel.workitem.id<x> : index")
    e("  %col = index.mul %tid, %c4 : index")           # K / V column of the 1024 (KV head x 256 dims)
    e("  %kvh = index.div %tid, %c64 : index")
    e("  %d0 = index.rem %tid, %c64 : index")
    e("  %d4 = index.mul %d0, %c4 : index")
    # K: rows j * 128 .. + 127 lie in one page
    e("  %row0 = index.mul %j, %c128 : index")
    e("  %lp = index.div %row0, %c256 : index")
    e("  %pg0 = view.load %pt_flat[%lp] : view<[%npx]xi32> -> i32")
    e("  %pgr = index.cast %pg0 : i32 to index")
    e("  %pg = index.assume %pgr [range(%pgr, 0, 65535), lt(%pgr, %npx)] : index")
    e("  %pb = index.mul %pg, %c256 : index")
    e("  %po = index.rem %row0, %c256 : index")
    e("  %prow0 = index.add %pb, %po : index")
    e(f"  %z4 = vector.constant 0.0 : {V4}")
    e(f"  %kacc = scf.for %i = [%c0 to %c128 step %c1](%a = %z4 : {V4}) -> ({V4}) {{")
    e("    %pr = index.add %prow0, %i : index")
    e("    %ka0 = index.mul %pr, %c1024 : index")
    e("    %ka1 = index.add %ka0, %col : index")
    e("    %ka = index.min %ka1, %ktot4 : index")
    e(f"    %kx = vector.load %k_flat[%ka] : view<[%ktot]xf16> -> {V4H}")
    e(f"    %kxf = vector.extf %kx : {V4H} to {V4}")
    e(f"    %an = vector.addf %a, %kxf : {V4}")
    e(f"    scf.yield %an : {V4}")
    e("  }")
    e("  %inv = scalar.constant 0.0078125 : f32")
    e(f"  %inv4 = vector.splat %inv : {V4}")
    e(f"  %km4 = vector.mulf %kacc, %inv4 : {V4}")
    e(f"  %kmh = vector.fptrunc %km4 : {V4} to {V4H}")
    e("  %mo0 = index.mul %j, %c1024 : index")
    e("  %mo1 = index.add %mo0, %col : index")
    e("  %mo = index.min %mo1, %mtot4 : index")
    e(f"  vector.store %kmh, %km_flat[%mo] : {V4H}, view<[%mtot]xf16>")
    # V: tiles 8j .. 8j + 7 (16 keys each, one page), dims d4 .. d4 + 3 of KV head kvh
    e("  %vhb = index.mul %kvh, %vtx : index")
    sums = [None] * 4
    for u in range(8):
        e(f"  %vt{u}c = index.constant {u} : index")
        e(f"  %vt{u}a = index.mul %j, %c8 : index")
        e(f"  %vt{u} = index.add %vt{u}a, %vt{u}c : index")
        e(f"  %vlp{u} = index.div %vt{u}, %c16 : index")
        e(f"  %vpg{u}0 = view.load %pt_flat[%vlp{u}] : view<[%npx]xi32> -> i32")
        e(f"  %vpg{u}r = index.cast %vpg{u}0 : i32 to index")
        e(f"  %vpg{u} = index.assume %vpg{u}r [range(%vpg{u}r, 0, 65535), lt(%vpg{u}r, %npx)] : index")
        e(f"  %vpb{u} = index.mul %vpg{u}, %c16 : index")
        e(f"  %vpo{u} = index.rem %vt{u}, %c16 : index")
        e(f"  %vpt{u} = index.add %vpb{u}, %vpo{u} : index")
        e(f"  %vti{u} = index.add %vhb, %vpt{u} : index")
        e(f"  %vtb{u} = index.mul %vti{u}, %c256 : index")
        for d in range(4):
            e(f"  %vd{u}_{d}c = index.constant {d} : index")
            e(f"  %vd{u}_{d}a = index.add %d4, %vd{u}_{d}c : index")
            e(f"  %vd{u}_{d}b = index.add %vtb{u}, %vd{u}_{d}a : index")
            e(f"  %vd{u}_{d}m = index.mul %vd{u}_{d}b, %c16 : index")
            e(f"  %vd{u}_{d} = index.min %vd{u}_{d}m, %vtot16 : index")
            e(f"  %vx{u}_{d} = vector.load %v_flat[%vd{u}_{d}] : view<[%vtot]xf16> -> {V16H}")
            e(f"  %vxf{u}_{d} = vector.extf %vx{u}_{d} : {V16H} to {V16}")
            e(f"  %zf{u}_{d} = scalar.constant 0.0 : f32")
            e(f"  %vs{u}_{d} = vector.reduce<addf> %vxf{u}_{d}, %zf{u}_{d} : {V16}, f32")
            if sums[d] is None:
                sums[d] = f"%vs{u}_{d}"
            else:
                e(f"  %va{u}_{d} = scalar.addf {sums[d]}, %vs{u}_{d} : f32")
                sums[d] = f"%va{u}_{d}"
    hs = []
    for d in range(4):
        e(f"  %vm{d} = scalar.mulf {sums[d]}, %inv : f32")
        e(f"  %vh{d} = scalar.fptrunc %vm{d} : f32 to f16")
        hs.append(f"%vh{d}")
    e(f"  %vmh = vector.from_elements {', '.join(hs)} : {V4H}")
    e("  %vmo0 = index.mul %kvh, %c256 : index")
    e("  %vmo1 = index.add %vmo0, %d4 : index")
    e("  %vmo2 = index.add %mo0, %vmo1 : index")
    e("  %vmo = index.min %vmo2, %mtot4 : index")
    e(f"  vector.store %vmh, %vm_flat[%vmo] : {V4H}, view<[%mtot]xf16>")
    e("  kernel.return")
    e("}")
    return "\n".join(L) + "\n"


def _pool_setup(e, sym):
    """Pool geometry: base context pages (npages, pcap), extended (npx, pcapx), views of both pools, ptab, the means."""
    e(f"  %cap = config.get @{sym}.capacity : index")
    e(f"  %capx = config.get @{sym}.capx : index")
    e("  %npg0 = index.add %cap, %c255 : index")
    e("  %npages = index.div %npg0, %c256 : index")
    e("  %pcap = index.mul %npages, %c256 : index")
    e("  %npx0 = index.add %capx, %c255 : index")
    e("  %npx = index.div %npx0, %c256 : index")
    e("  %pcapx = index.mul %npx, %c256 : index")
    e("  %ktot = index.mul %pcapx, %c1024 : index")
    e("  %vtx = index.div %pcapx, %c16 : index")           # V^T tiles per KV head (extended pool)
    e("  %vtot0 = index.mul %vtx, %c4096 : index")
    e("  %vtot = index.mul %vtot0, %c4 : index")
    e("  %nbm = index.div %pcap, %c128 : index")
    e("  %mtot = index.mul %nbm, %c1024 : index")
    e("  %ktot4 = index.sub %ktot, %c4 : index")
    e("  %vtot16 = index.sub %vtot, %c16 : index")
    e("  %vtot1 = index.sub %vtot, %c1 : index")
    e("  %mtot4 = index.sub %mtot, %c4 : index")
    e("  %kp_na, %vp_na, %pt_na, %km_na, %vm_na = buffer.assume.noalias %kpool, %vpool, %ptab, %kmean, %vmean : buffer, buffer, buffer, buffer, buffer")
    e("  %k_flat = buffer.view %kp_na[%base] : buffer -> view<[%ktot]xf16>")
    e("  %v_flat = buffer.view %vp_na[%base] : buffer -> view<[%vtot]xf16>")
    e("  %pt_flat = buffer.view %pt_na[%base] : buffer -> view<[%npx]xi32>")
    e("  %km_flat = buffer.view %km_na[%base] : buffer -> view<[%mtot]xf16>")
    e("  %vm_flat = buffer.view %vm_na[%base] : buffer -> view<[%mtot]xf16>")


