#!/usr/bin/env python3
"""Generate yah_ssm_conv_kq for the chunked DeltaNet (gen_gdn_chunk CONV16) reading the qkv GEMM's f16 output: the same
ops, roundings and summation orders as yah_ssm_conv_kq_f32.loom with emit_prefill_pp.conv_x16 / conv_n16, so the
output is bit-identical, but one workgroup per (256 channels, TB tokens) instead of per (256 channels, token).

usage: gen_conv_kq.py [out.loom]

Workgroup x < num_key_heads takes the q (lanes 0-127) and k (128-255) channels of key head x, the others 256 v channels;
workgroup y the tokens TB y .. TB y + TB - 1. Lane = channel: its 4 weights and the 3 previous inputs stay in registers,
each token's input is read once (the f32 kernel loaded 4 taps and 3 state values per output). For token t:
    s3 = x[t], s2 = x[t-1], s1 = x[t-2], s0 = x[t-3] (state[c][3], [2], [1] before token 0)
    dot = (s0 w0 + s1 w1) + (s2 w2 + s3 w3), result = dot * (1 / (1 + exp(-dot)))
v channels store f16(result). q / k workgroups keep the TB x 256 results in LDS; wave w takes tokens TB / 8 w ..:
lane l sums elements 4 l .. 4 l + 3 in order (k^2, q^2, k q), then a subgroup add, and lane 0 writes inv_k, q_scale
(1 / sqrt(sum + eps), times 1 / sqrt(128) for q) and k.q to scales [token][head][3] and to LDS; every lane then stores
f16(result * scale) of its channel.
Bindings: x (f16 [batch][qkv_dim]), conv_weights (f32 [qkv_dim][4]), state (f32 [qkv_dim][4]), conv_out
(f16 [batch][qkv_dim]), scales (f32 [batch][num_key_heads][3]).
"""
import sys

import gen_rot

TB = 16   # tokens per workgroup (a multiple of 8, the batch a multiple of TB): 32 kept 3 workgroups per WGP (LDS)
D = 128   # channels per key head


def conv_steps(e, xs):
    """%r_t = silu(dot_t) for the tokens xs (f32 SSA names), window entering the first: %pw1, %pw2, %pw3 = x[-1], x[-2],
    x[-3]; weights %w0 .. %w3."""
    p1, p2, p3 = "%pw1", "%pw2", "%pw3"   # x[t-1], x[t-2], x[t-3]
    for t, x in enumerate(xs):
        s3, s2, s1, s0 = x, p1, p2, p3
        e(f"  %d0_{t} = scalar.mulf {s0}, %w0 : f32")
        e(f"  %d1_{t} = scalar.mulf {s1}, %w1 : f32")
        e(f"  %d2_{t} = scalar.mulf {s2}, %w2 : f32")
        e(f"  %d3_{t} = scalar.mulf {s3}, %w3 : f32")
        e(f"  %sa_{t} = scalar.addf %d0_{t}, %d1_{t} : f32")
        e(f"  %sb_{t} = scalar.addf %d2_{t}, %d3_{t} : f32")
        e(f"  %dot_{t} = scalar.addf %sa_{t}, %sb_{t} : f32")
        e(f"  %ng_{t} = scalar.mulf %dot_{t}, %negone : f32")
        e(f"  %ex_{t} = scalar.expf<afn> %ng_{t} : f32")
        e(f"  %dn_{t} = scalar.addf %one, %ex_{t} : f32")
        e(f"  %sg_{t} = scalar.divf %one, %dn_{t} : f32")
        e(f"  %r_{t} = scalar.mulf %dot_{t}, %sg_{t} : f32")
        p1, p2, p3 = s3, p1, p2


def gen(climit=None, flag=0):
    """climit: only channels < climit (a NPU qkv split; gen_c takes the rest): v workgroups up to it, stores masked.
    flag (the qkv GEMM's gen_gemm_iu4.flag_count): binding cnt after scales, i32 per 128-token tile (zero before the
    GEMM); a workgroup waits for the tiles of its tokens and the 3 before them (gen_rot.flag_wait), so the GEMM runs
    without a graph barrier before this kernel."""
    L = []
    e = L.append
    e("// GENERATED by tools/gen_conv_kq.py -- edit the generator.")
    e("amdgpu.target<gfx1151> @yah_wave32 {subgroup_size = 32}")
    e("")
    e("config.decl @yah_ssm_conv_kq.batch : %value: index where [range(%value, 1, 1048576)]")
    e("config.decl @yah_ssm_conv_kq.qkv_dim : %value: index where [range(%value, 1, 1048576)]")
    e("config.decl @yah_ssm_conv_kq.num_key_heads : %value: index where [range(%value, 1, 4096)]")
    e("")
    e("kernel.def target(@yah_wave32) @yah_ssm_conv_kq() {")
    e("  %unit = index.constant 1 : index")
    e("  %qkv_dim = config.get @yah_ssm_conv_kq.qkv_dim : index")
    e("  %batch = config.get @yah_ssm_conv_kq.batch : index")
    e("  %nkh = config.get @yah_ssm_conv_kq.num_key_heads : index")
    e("  %c256 = index.constant 256 : index")
    e(f"  %ctb = index.constant {TB} : index")
    e(f"  %cqk = index.constant {2 * D} : index")
    e("  %qk_dim = index.mul %nkh, %cqk : index")
    e("  %v_dim = index.sub %qkv_dim, %qk_dim : index")
    if climit:
        e(f"  %climit = index.constant {climit} : index")
        e("  %v_lim = index.sub %climit, %qk_dim : index")
        e("  %c255 = index.constant 255 : index")
        e("  %v_lim255 = index.add %v_lim, %c255 : index")
        e("  %vt = index.div %v_lim255, %c256 : index")
    else:
        e("  %vt = index.div %v_dim, %c256 : index")
    e("  %tiles = index.add %nkh, %vt : index")
    e("  %blocks = index.div %batch, %ctb : index")
    e("  kernel.launch.config workgroups(%tiles, %blocks, %unit) workgroup_size(%c256, %unit, %unit) : index")
    e("} launch(%x: buffer, %weights: buffer, %state: buffer, %out: buffer, %scales: buffer"
      + (", %cnt: buffer" if flag else "") + ") {")
    e("  %base = index.constant 0 : offset")
    for v in (0, 1, 2, 3, 4, 32, 128, 256):
        e(f"  %c{v} = index.constant {v} : index")
    e(f"  %ctb = index.constant {TB} : index")
    e("  %negone = scalar.constant -1.0 : f32")
    e("  %one = scalar.constant 1.0 : f32")
    e("  %zero = scalar.constant 0.0 : f32")
    e("  %epsilon = scalar.constant 0.000001 : f32")
    e("  %batch = config.get @yah_ssm_conv_kq.batch : index")
    e("  %qkv_dim = config.get @yah_ssm_conv_kq.qkv_dim : index")
    e("  %nkh = config.get @yah_ssm_conv_kq.num_key_heads : index")
    e("  %x_total = index.mul %batch, %qkv_dim : index")
    e("  %w_total = index.mul %qkv_dim, %c4 : index")
    e("  %scale_cnt = index.mul %batch, %nkh : index")
    e("  %scale_total = index.mul %scale_cnt, %c3 : index")
    if flag:
        e("  %x_na, %w_na, %st_na, %out_na, %sc_na, %cnt_na = buffer.assume.noalias %x, %weights, %state, %out, %scales, %cnt"
          " : buffer, buffer, buffer, buffer, buffer, buffer")
    else:
        e("  %x_na, %w_na, %st_na, %out_na, %sc_na = buffer.assume.noalias %x, %weights, %state, %out, %scales : buffer, buffer, buffer, buffer, buffer")
    e("  %x_view = buffer.view %x_na[%base] : buffer -> view<[%x_total]xf16>")
    e("  %w_view = buffer.view %w_na[%base] : buffer -> view<[%w_total]xf32>")
    e("  %st_view = buffer.view %st_na[%base] : buffer -> view<[%w_total]xf32>")
    e("  %out_view = buffer.view %out_na[%base] : buffer -> view<[%x_total]xf16>")
    e("  %sc_view = buffer.view %sc_na[%base] : buffer -> view<[%scale_total]xf32>")
    e("  %wg = kernel.workgroup.id<x> : index")
    e("  %blk = kernel.workgroup.id<y> : index")
    e("  %lane = kernel.workitem.id<x> : index")
    e("  %t0 = index.mul %blk, %ctb : index")
    if flag:
        assert gen_rot.FLAG_TT % TB == 0
        e(f"  %fl_tt = index.constant {gen_rot.FLAG_TT} : index")
        e("  %fl_t3 = index.max %t0, %c3 : index")
        e("  %fl_tp = index.sub %fl_t3, %c3 : index")
        e("  %fl_ta = index.div %fl_tp, %fl_tt : index")
        e("  %fl_tb = index.div %t0, %fl_tt : index")
        e("  %fl_n = index.div %batch, %fl_tt : index")
        e("  %fl_cv = buffer.view %cnt_na[%base] : buffer -> view<[%fl_n]xi32>")
        gen_rot.flag_wait(e, "%fl_cv", "view<[%fl_n]xi32>", ["%fl_ta", "%fl_tb"], flag, "%lane")
    # channel map (the f32 kernel's)
    e("  %is_qk = index.cmp ult, %wg, %nkh : index")
    e("  %lane_hi = index.cmp uge, %lane, %c128 : index")
    e("  %lane_lo = index.rem %lane, %c128 : index")
    e("  %qh_base = index.mul %wg, %c128 : index")
    e("  %k_off = index.mul %nkh, %c128 : index")
    e("  %kh_base = index.add %k_off, %qh_base : index")
    e("  %qk_base = scf.select %lane_hi, %kh_base, %qh_base : index")
    e("  %qk_c = index.add %qk_base, %lane_lo : index")
    e("  %v_off = index.mul %k_off, %c2 : index")
    e("  %wg_v0 = index.max %wg, %nkh : index")
    e("  %wg_v = index.sub %wg_v0, %nkh : index")
    e("  %v_wb = index.mul %wg_v, %c256 : index")
    e("  %v_b = index.add %v_off, %v_wb : index")
    e("  %v_c = index.add %v_b, %lane : index")
    e("  %c = scf.select %is_qk, %qk_c, %v_c : index")
    e("  %c4i = index.mul %c, %c4 : index")
    for j in range(4):
        e(f"  %w{j}_off = index.add %c4i, %c{j} : index")
        e(f"  %w{j} = view.load %w_view[%w{j}_off] : view<[%w_total]xf32> -> f32")
    # the 3 inputs before t0: the state ring before token 0, else x (rows clamped, then selected: no branch)
    e("  %first = index.cmp eq, %blk, %c0 : index")
    for j in (1, 2, 3):
        e(f"  %st{j} = view.load %st_view[%w{j}_off] : view<[%w_total]xf32> -> f32")
        e(f"  %tp{j}0 = index.max %t0, %c{j} : index")
        e(f"  %tp{j} = index.sub %tp{j}0, %c{j} : index")
        e(f"  %tp{j}r = index.mul %tp{j}, %qkv_dim : index")
        e(f"  %xp{j}o = index.add %tp{j}r, %c : index")
        e(f"  %xp{j}h = view.load %x_view[%xp{j}o] : view<[%x_total]xf16> -> f16")
        e(f"  %xp{j} = scalar.extf %xp{j}h : f16 to f32")
    # window entering token t0: x[t0-1], x[t0-2], x[t0-3] (state 3, 2, 1 before token 0)
    e("  %pw1 = scf.select %first, %st3, %xp1 : f32")
    e("  %pw2 = scf.select %first, %st2, %xp2 : f32")
    e("  %pw3 = scf.select %first, %st1, %xp3 : f32")
    for t in range(TB):
        e(f"  %ct{t} = index.constant {t} : index")
        e(f"  %tk{t} = index.add %t0, %ct{t} : index")
        e(f"  %tr{t} = index.mul %tk{t}, %qkv_dim : index")
        e(f"  %xo{t} = index.add %tr{t}, %c : index")
        e(f"  %xh{t} = view.load %x_view[%xo{t}] : view<[%x_total]xf16> -> f16")
        e(f"  %x{t} = scalar.extf %xh{t} : f16 to f32")
    e("  %kq_bytes = index.constant " + str(TB * 256 * 4 + TB * 2 * 4) + " : offset")
    e("  %kq_l = buffer.alloca<workgroup> align(16) %kq_bytes : buffer")
    e(f"  %kq_lds = buffer.view %kq_l[%base] : buffer -> view<{TB * 256 + TB * 2}xf32>")
    conv_steps(e, [f"%x{t}" for t in range(TB)])
    # v channels: f16(result)
    e("  %is_v = index.cmp uge, %wg, %nkh : index")
    e("  scf.if %is_v {")
    if climit:
        e(f"    %climit_s = index.constant {climit} : index")
        e("    %in_lim = index.cmp ult, %c, %climit_s : index")
        e("    scf.if %in_lim {")
    for t in range(TB):
        e(f"    %rh{t} = scalar.fptrunc %r_{t} : f32 to f16")
        e(f"    view.store %rh{t}, %out_view[%xo{t}] : f16, view<[%x_total]xf16>")
    if climit:
        e("    }")
    e("  }")
    # q / k: the per-token norms (prep_kq) with the f32 kernel's order, then f16(result * scale)
    e("  scf.if %is_qk {")
    for t in range(TB):
        e(f"    %lo{t} = index.constant {256 * t} : index")
        e(f"    %la{t} = index.add %lo{t}, %lane : index")
        e(f"    view.store %r_{t}, %kq_lds[%la{t}] : f32, view<{TB * 256 + TB * 2}xf32>")
    e("    kernel.barrier<workgroup> scope(workgroup) ordering(acq_rel)")
    e("    %wave = index.div %lane, %c32 : index")
    e("    %wl = index.rem %lane, %c32 : index")
    e("    %wquad = index.mul %wl, %c4 : index")
    e(f"    %ctpw = index.constant {TB // 8} : index")
    e("    %wt0 = index.mul %wave, %ctpw : index")   # wave w takes tokens TB / 8 * w ..
    e(f"    %cscl = index.constant {TB * 256} : index")
    for u in range(TB // 8):
        e(f"    %cu{u} = index.constant {u} : index")
        e(f"    %tu{u} = index.add %wt0, %cu{u} : index")         # token of this wave's step u
        e(f"    %rb{u} = index.mul %tu{u}, %c256 : index")
        e(f"    %eb{u} = index.add %rb{u}, %wquad : index")
        acc = ("%zero", "%zero", "%zero")
        for j in range(4):
            e(f"    %ej{u}_{j}c = index.constant {j} : index")
            e(f"    %ej{u}_{j} = index.add %eb{u}, %ej{u}_{j}c : index")
            e(f"    %ki{u}_{j} = index.add %ej{u}_{j}, %c128 : index")
            e(f"    %kv{u}_{j} = view.load %kq_lds[%ki{u}_{j}] : view<{TB * 256 + TB * 2}xf32> -> f32")
            e(f"    %qv{u}_{j} = view.load %kq_lds[%ej{u}_{j}] : view<{TB * 256 + TB * 2}xf32> -> f32")
            e(f"    %kk{u}_{j} = scalar.mulf %kv{u}_{j}, %kv{u}_{j} : f32")
            e(f"    %qq{u}_{j} = scalar.mulf %qv{u}_{j}, %qv{u}_{j} : f32")
            e(f"    %dq{u}_{j} = scalar.mulf %kv{u}_{j}, %qv{u}_{j} : f32")
            e(f"    %ka{u}_{j} = scalar.addf {acc[0]}, %kk{u}_{j} : f32")
            e(f"    %qa{u}_{j} = scalar.addf {acc[1]}, %qq{u}_{j} : f32")
            e(f"    %da{u}_{j} = scalar.addf {acc[2]}, %dq{u}_{j} : f32")
            acc = (f"%ka{u}_{j}", f"%qa{u}_{j}", f"%da{u}_{j}")
        e(f"    %ks{u} = kernel.subgroup.reduce<addf> {acc[0]} : f32")
        e(f"    %qs{u} = kernel.subgroup.reduce<addf> {acc[1]} : f32")
        e(f"    %kqs{u} = kernel.subgroup.reduce<addf> {acc[2]} : f32")
        e(f"    %l0_{u} = index.cmp ult, %wl, %c1 : index")
        e(f"    scf.if %l0_{u} {{")
        e(f"      %kse{u} = scalar.addf %ks{u}, %epsilon : f32")
        e(f"      %ksr{u} = scalar.sqrtf %kse{u} : f32")
        e(f"      %ik{u} = scalar.divf %one, %ksr{u} : f32")
        e(f"      %qse{u} = scalar.addf %qs{u}, %epsilon : f32")
        e(f"      %qsr{u} = scalar.sqrtf %qse{u} : f32")
        e(f"      %iq{u} = scalar.divf %one, %qsr{u} : f32")
        e(f"      %dim_i{u} = index.cast %c128 : index to i32")
        e(f"      %dim_f{u} = scalar.sitofp %dim_i{u} : i32 to f32")
        e(f"      %dim_r{u} = scalar.sqrtf %dim_f{u} : f32")
        e(f"      %idim{u} = scalar.divf %one, %dim_r{u} : f32")
        e(f"      %qsc{u} = scalar.mulf %iq{u}, %idim{u} : f32")
        e(f"      %tg{u} = index.add %t0, %tu{u} : index")
        e(f"      %sr{u} = index.mul %tg{u}, %nkh : index")
        e(f"      %sh{u} = index.add %sr{u}, %wg : index")
        e(f"      %sb{u} = index.mul %sh{u}, %c3 : index")
        e(f"      %sb1_{u} = index.add %sb{u}, %c1 : index")
        e(f"      %sb2_{u} = index.add %sb{u}, %c2 : index")
        e(f"      view.store %ik{u}, %sc_view[%sb{u}] : f32, view<[%scale_total]xf32>")
        e(f"      view.store %qsc{u}, %sc_view[%sb1_{u}] : f32, view<[%scale_total]xf32>")
        e(f"      view.store %kqs{u}, %sc_view[%sb2_{u}] : f32, view<[%scale_total]xf32>")
        e(f"      %ls{u}0 = index.mul %tu{u}, %c2 : index")
        e(f"      %ls{u} = index.add %cscl, %ls{u}0 : index")
        e(f"      %ls{u}q = index.add %ls{u}, %c1 : index")
        e(f"      view.store %ik{u}, %kq_lds[%ls{u}] : f32, view<{TB * 256 + TB * 2}xf32>")
        e(f"      view.store %qsc{u}, %kq_lds[%ls{u}q] : f32, view<{TB * 256 + TB * 2}xf32>")
        e("    }")
    e("    kernel.barrier<workgroup> scope(workgroup) ordering(acq_rel)")
    for t in range(TB):
        e(f"    %so{t} = index.constant {TB * 256 + 2 * t} : index")
        e(f"    %so{t}q = index.constant {TB * 256 + 2 * t + 1} : index")
        e(f"    %ksv{t} = view.load %kq_lds[%so{t}] : view<{TB * 256 + TB * 2}xf32> -> f32")
        e(f"    %qsv{t} = view.load %kq_lds[%so{t}q] : view<{TB * 256 + TB * 2}xf32> -> f32")
        e(f"    %osc{t} = scf.select %lane_hi, %ksv{t}, %qsv{t} : f32")
        e(f"    %on{t} = scalar.mulf %r_{t}, %osc{t} : f32")
        e(f"    %oh{t} = scalar.fptrunc %on{t} : f32 to f16")
        e(f"    view.store %oh{t}, %out_view[%xo{t}] : f16, view<[%x_total]xf16>")
    e("  }")
    e("  kernel.return")
    e("}")
    return "\n".join(L) + "\n"


def conv_steps_p(e, xs, p):
    """conv_steps for the channel prefix p (gen_p: a lane's q and k channels): %{p}r_t, window %{p}pw1..3, weights
    %{p}w0..3."""
    p1, p2, p3 = f"%{p}pw1", f"%{p}pw2", f"%{p}pw3"
    for t, x in enumerate(xs):
        s3, s2, s1, s0 = x, p1, p2, p3
        q = f"%{p}"
        e(f"    {q}d0_{t} = scalar.mulf {s0}, {q}w0 : f32")
        e(f"    {q}d1_{t} = scalar.mulf {s1}, {q}w1 : f32")
        e(f"    {q}d2_{t} = scalar.mulf {s2}, {q}w2 : f32")
        e(f"    {q}d3_{t} = scalar.mulf {s3}, {q}w3 : f32")
        e(f"    {q}sa_{t} = scalar.addf {q}d0_{t}, {q}d1_{t} : f32")
        e(f"    {q}sb_{t} = scalar.addf {q}d2_{t}, {q}d3_{t} : f32")
        e(f"    {q}dot_{t} = scalar.addf {q}sa_{t}, {q}sb_{t} : f32")
        e(f"    {q}ng_{t} = scalar.mulf {q}dot_{t}, %negone : f32")
        e(f"    {q}ex_{t} = scalar.expf<afn> {q}ng_{t} : f32")
        e(f"    {q}dn_{t} = scalar.addf %one, {q}ex_{t} : f32")
        e(f"    {q}sg_{t} = scalar.divf %one, {q}dn_{t} : f32")
        e(f"    {q}r_{t} = scalar.mulf {q}dot_{t}, {q}sg_{t} : f32")
        p1, p2, p3 = s3, p1, p2


PG = 128  # gen_p workgroups: two rounds of the 256 (key head, token tile) segments
PTB = 4   # gen_p tokens per norm batch (LDS: PTB x 3 x 32 partials + PTB x 2 scales)
PSB = 8   # gen_p tokens per sub-block: the next sub-block's inputs load while this one computes


def gen_p(batch, nkh=16, qkv_dim=10240, G=PG):
    """yah_ssm_conv_kq_p: gen's q / k part (dnvconv: DeltaNet does the v channels) with gen's flag wait, as G
    persistent workgroups of 128 lanes: segment (key head, 128-token tile) i + G k for workgroup i, token tile major.
    Each waits for the flagged qkv GEMM's counters (cnt, one per token tile, gen_gemm_iu4.flag_count(qkv_dim)) of its
    tile and the one before (the window's 3 tokens), then walks its tile PSB tokens at a time, the next PSB tokens'
    inputs loading meanwhile (loop-carried f16), instead of gen's workgroup launch and first loads per 16 tokens.
    Bit-identical to gen.
    Lane l = q channel l and k channel l of the head: the conv as gen; the per-token sums keep gen's order (norm lane j
    sums channels 4 j .. 4 j + 3 in order, then a subgroup add): lane 4 m chains its quad with xor shuffles 1, 2, 3,
    the 32 partials meet in LDS in j order and wave u reduces token u of a PTB-token batch.
    Bindings: as gen with flag (x, conv_weights, state, conv_out, scales, cnt)."""
    import gen_gemm_iu4
    TT = gen_rot.FLAG_TT
    assert batch % TT == 0 and TT % PSB == 0 and PSB % PTB == 0 and PTB <= 4
    need = gen_gemm_iu4.flag_count(qkv_dim)
    tt = batch // TT
    nseg = nkh * tt
    x_total = batch * qkv_dim
    w_total = qkv_dim * 4
    sc_total = batch * nkh * 3
    NL = PTB * 3 * 32 + PTB * 2
    L = []
    e = L.append
    e("// GENERATED by tools/gen_conv_kq.py gen_p -- edit the generator.")
    e("amdgpu.target<gfx1151> @yah_wave32 {subgroup_size = 32}")
    e("")
    # the segment count as the config (emit_hal needs one); the generator fixes it
    e(f"config.decl @yah_ssm_conv_kq_p.items : %value: index where [range(%value, {nseg}, {nseg + 1})]")
    e("")
    e("kernel.def target(@yah_wave32) @yah_ssm_conv_kq_p() {")
    e("  %unit = index.constant 1 : index")
    e(f"  %cg = index.constant {G} : index")
    e(f"  %cd = index.constant {D} : index")
    e("  kernel.launch.config workgroups(%cg, %unit, %unit) workgroup_size(%cd, %unit, %unit) : index")
    e("} launch(%x: buffer, %weights: buffer, %state: buffer, %out: buffer, %scales: buffer, %cnt: buffer) {")
    e("  %base = index.constant 0 : offset")
    for v in (0, 1, 2, 3, 4, 8, 32, 128):
        e(f"  %c{v} = index.constant {v} : index")
    e(f"  %cG = index.constant {G} : index")
    e("  %cns = config.get @yah_ssm_conv_kq_p.items : index")
    e(f"  %qkv_dim = index.constant {qkv_dim} : index")
    e(f"  %nkh = index.constant {nkh} : index")
    e(f"  %clast = index.constant {batch - 1} : index")
    e("  %negone = scalar.constant -1.0 : f32")
    e("  %one = scalar.constant 1.0 : f32")
    e("  %zero = scalar.constant 0.0 : f32")
    e("  %epsilon = scalar.constant 0.000001 : f32")
    e("  %x32 = scalar.constant 32 : i32")
    e("  %x_na, %w_na, %st_na, %out_na, %sc_na, %cnt_na = buffer.assume.noalias %x, %weights, %state, %out, %scales, %cnt"
      " : buffer, buffer, buffer, buffer, buffer, buffer")
    e(f"  %x_view = buffer.view %x_na[%base] : buffer -> view<{x_total}xf16>")
    e(f"  %w_view = buffer.view %w_na[%base] : buffer -> view<{w_total}xf32>")
    e(f"  %st_view = buffer.view %st_na[%base] : buffer -> view<{w_total}xf32>")
    e(f"  %out_view = buffer.view %out_na[%base] : buffer -> view<{x_total}xf16>")
    e(f"  %sc_view = buffer.view %sc_na[%base] : buffer -> view<{sc_total}xf32>")
    FV = f"view<{tt}xi32>"
    e(f"  %cv = buffer.view %cnt_na[%base] : buffer -> {FV}")
    e(f"  %lb = index.constant {NL * 4} : offset")
    e("  %lds = buffer.alloca<workgroup> align(16) %lb : buffer")
    e(f"  %lv = buffer.view %lds[%base] : buffer -> view<{NL}xf32>")
    e("  %lane = kernel.workitem.id<x> : index")
    e("  %wgid = kernel.workgroup.id<x> : index")
    e("  %wave = index.div %lane, %c32 : index")
    e("  %wl = index.rem %lane, %c32 : index")
    e("  %quad = index.rem %wl, %c4 : index")
    e("  %q0 = index.cmp eq, %quad, %c0 : index")
    e("  %wm = index.div %wl, %c4 : index")
    e("  %w8 = index.mul %wave, %c8 : index")
    e("  %pj = index.add %w8, %wm : index")   # norm lane j of this quad: channels 4 j .. 4 j + 3
    e(f"  %need = scalar.constant {need} : i32")
    e(f"  %limit = scalar.constant {gen_rot.FLAG_POLLS} : i32")
    e("  %izero = scalar.constant 0 : i32")
    e("  %ione = scalar.constant 1 : i32")
    e("  scf.for %sg = [%wgid to %cns step %cG] {")
    e("    %tile = index.div %sg, %nkh : index")
    e("    %head = index.rem %sg, %nkh : index")
    e(f"    %ctt = index.constant {TT} : index")
    e("    %ts = index.mul %tile, %ctt : index")
    # the counters of this tile and the one before, one round trip per poll; relaxed polls (an acquire load
    # invalidates the WGP's L0 and its array's L1 at every poll), the barrier's global acquire after them
    e("    %fl_t1 = index.max %tile, %c1 : index")
    e("    %fl_ta = index.sub %fl_t1, %c1 : index")
    idx = ["%fl_ta", "%tile"]
    e("    %fl_w0 = index.cmp ult, %lane, %c32 : index")
    e("    scf.if %fl_w0 {")
    e("      %fl_n, %fl_v = scf.while(%fl_i = %izero : i32, %fl_p = %izero : i32) -> (i32, i32) {")
    for j, ix in enumerate(idx):
        e(f"        %fl_x{j} = view.atomic.load %cv[{ix}] {{ordering = relaxed, scope = device}} : {FV} -> i32")
    e("        %fl_m = scalar.minsi %fl_x0, %fl_x1 : i32")
    e("        %fl_early = scalar.cmpi slt, %fl_m, %need : i32")
    e("        %fl_lt = scalar.cmpi ult, %fl_i, %limit : i32")
    e("        %fl_go = scalar.andi %fl_early, %fl_lt : i1")
    e("        scf.condition %fl_go, %fl_i, %fl_m : i1, i32, i32")
    e("      } do(%fl_j: i32, %fl_y: i32) {")
    e("        %fl_j1 = scalar.addi %fl_j, %ione : i32")
    e("        scf.yield %fl_j1, %fl_y : i32, i32")
    e("      }")
    e("    }")
    e("    kernel.barrier<global> scope(workgroup) ordering(acquire)")
    # channels: q = 128 head + lane, k = 128 (nkh + head) + lane
    e("    %qc0 = index.mul %head, %c128 : index")
    e("    %qc = index.add %qc0, %lane : index")
    e(f"    %ckoff = index.constant {nkh * D} : index")
    e("    %kc = index.add %qc, %ckoff : index")
    e("    %first = index.cmp eq, %tile, %c0 : index")
    chans = (("q", "%qc"), ("k", "%kc"))

    def xload(p, ch, tok, nm, ind="    "):
        e(f"{ind}%{nm}r = index.mul {tok}, %qkv_dim : index")
        e(f"{ind}%{nm}o = index.add %{nm}r, {ch} : index")
        e(f"{ind}%{nm} = view.load %x_view[%{nm}o] : view<{x_total}xf16> -> f16")
    for p, ch in chans:
        e(f"    %{p}c4 = index.mul {ch}, %c4 : index")
        for j in range(4):
            e(f"    %{p}w{j}_off = index.add %{p}c4, %c{j} : index")
            e(f"    %{p}w{j} = view.load %w_view[%{p}w{j}_off] : view<{w_total}xf32> -> f32")
        for j in (1, 2, 3):
            e(f"    %{p}st{j} = view.load %st_view[%{p}w{j}_off] : view<{w_total}xf32> -> f32")
            e(f"    %{p}tp{j}0 = index.max %ts, %c{j} : index")
            e(f"    %{p}tp{j} = index.sub %{p}tp{j}0, %c{j} : index")
            xload(p, ch, f"%{p}tp{j}", f"{p}xp{j}h")
            e(f"    %{p}xp{j} = scalar.extf %{p}xp{j}h : f16 to f32")
        e(f"    %{p}pw1i = scf.select %first, %{p}st3, %{p}xp1 : f32")
        e(f"    %{p}pw2i = scf.select %first, %{p}st2, %{p}xp2 : f32")
        e(f"    %{p}pw3i = scf.select %first, %{p}st1, %{p}xp3 : f32")
        for t in range(PSB):
            e(f"    %{p}i{t}c = index.constant {t} : index")
            e(f"    %{p}i{t}t = index.add %ts, %{p}i{t}c : index")
            xload(p, ch, f"%{p}i{t}t", f"{p}i{t}")
    # the sub-block loop: window (f32) and the prefetched inputs (f16) carried
    carry = [(f"%{p}pw{j}", f"%{p}pw{j}i", "f32") for p, _ in chans for j in (1, 2, 3)]
    carry += [(f"%{p}x{t}h", f"%{p}i{t}", "f16") for p, _ in chans for t in range(PSB)]
    e(f"    %cnsb = index.constant {TT // PSB} : index")
    e("    " + ", ".join(f"%o{i}" for i in range(len(carry))) + " = scf.for %sb = [%c0 to %cnsb step %c1]("
      + ", ".join(f"{a} = {b} : {ty}" for a, b, ty in carry) + ") -> (" + ", ".join(ty for _, _, ty in carry) + ") {")
    e(f"      %csb = index.constant {PSB} : index")
    e("      %sbt = index.mul %sb, %csb : index")
    e("      %t0 = index.add %ts, %sbt : index")
    nxt = []
    for p, ch in chans:
        for t in range(PSB):
            e(f"      %{p}n{t}c = index.constant {PSB + t} : index")
            e(f"      %{p}n{t}u = index.add %t0, %{p}n{t}c : index")
            e(f"      %{p}n{t}t = index.min %{p}n{t}u, %clast : index")   # the last sub-block's: in range, unused
            xload(p, ch, f"%{p}n{t}t", f"{p}n{t}", "      ")
            nxt.append(f"%{p}n{t}")
    for p, ch in chans:
        for t in range(PSB):
            e(f"      %{p}x{t} = scalar.extf %{p}x{t}h : f16 to f32")
            e(f"      %{p}xo{t}c = index.constant {t} : index")
            e(f"      %{p}tk{t} = index.add %t0, %{p}xo{t}c : index")
            e(f"      %{p}tr{t} = index.mul %{p}tk{t}, %qkv_dim : index")
            e(f"      %{p}xo{t} = index.add %{p}tr{t}, {ch} : index")
        body = []
        conv_steps_p(body.append, [f"%{p}x{t}" for t in range(PSB)], p)
        for l in body:
            e("  " + l)
    sc_base = PTB * 3 * 32
    for b in range(PSB // PTB):
        for u in range(PTB):
            t = b * PTB + u
            prods = {}
            e(f"      %kk{t} = scalar.mulf %kr_{t}, %kr_{t} : f32")
            e(f"      %qq{t} = scalar.mulf %qr_{t}, %qr_{t} : f32")
            e(f"      %kq{t} = scalar.mulf %kr_{t}, %qr_{t} : f32")
            for si, nm in enumerate(("kk", "qq", "kq")):
                v = f"%{nm}{t}"
                acc = f"%{nm}a{t}_0"
                e(f"      {acc} = scalar.addf %zero, {v} : f32")
                e(f"      %{nm}b{t} = scalar.bitcast {v} : f32 to i32")
                for k in (1, 2, 3):
                    e(f"      %{nm}k{t}_{k} = scalar.constant {k} : i32")
                    e(f"      %{nm}s{t}_{k}, %{nm}sv{t}_{k} = kernel.subgroup.shuffle<xor> %{nm}b{t}, %{nm}k{t}_{k}, %x32 : i32, i32, i32")
                    e(f"      %{nm}f{t}_{k} = scalar.bitcast %{nm}s{t}_{k} : i32 to f32")
                    e(f"      %{nm}a{t}_{k} = scalar.addf {acc}, %{nm}f{t}_{k} : f32")
                    acc = f"%{nm}a{t}_{k}"
                prods[si] = acc
            e("      scf.if %q0 {")
            for si in range(3):
                e(f"        %po{t}_{si} = index.constant {(u * 3 + si) * 32} : index")
                e(f"        %pa{t}_{si} = index.add %po{t}_{si}, %pj : index")
                e(f"        view.store {prods[si]}, %lv[%pa{t}_{si}] : f32, view<{NL}xf32>")
            e("      }")
        e("      kernel.barrier<workgroup> scope(workgroup) ordering(acq_rel)")
        for u in range(PTB):
            t = b * PTB + u
            e(f"      %cw{t} = index.constant {u} : index")
            e(f"      %isw{t} = index.cmp eq, %wave, %cw{t} : index")
            e(f"      scf.if %isw{t} {{")
            red = []
            for si in range(3):
                e(f"        %ro{t}_{si} = index.constant {(u * 3 + si) * 32} : index")
                e(f"        %ra{t}_{si} = index.add %ro{t}_{si}, %wl : index")
                e(f"        %rv{t}_{si} = view.load %lv[%ra{t}_{si}] : view<{NL}xf32> -> f32")
                e(f"        %rs{t}_{si} = kernel.subgroup.reduce<addf> %rv{t}_{si} : f32")
                red.append(f"%rs{t}_{si}")
            ks, qs, kqs = red
            e(f"        %l0_{t} = index.cmp ult, %wl, %c1 : index")
            e(f"        scf.if %l0_{t} {{")
            e(f"          %kse{t} = scalar.addf {ks}, %epsilon : f32")
            e(f"          %ksr{t} = scalar.sqrtf %kse{t} : f32")
            e(f"          %ik{t} = scalar.divf %one, %ksr{t} : f32")
            e(f"          %qse{t} = scalar.addf {qs}, %epsilon : f32")
            e(f"          %qsr{t} = scalar.sqrtf %qse{t} : f32")
            e(f"          %iq{t} = scalar.divf %one, %qsr{t} : f32")
            e(f"          %dim_i{t} = index.cast %c128 : index to i32")
            e(f"          %dim_f{t} = scalar.sitofp %dim_i{t} : i32 to f32")
            e(f"          %dim_r{t} = scalar.sqrtf %dim_f{t} : f32")
            e(f"          %idim{t} = scalar.divf %one, %dim_r{t} : f32")
            e(f"          %qsc{t} = scalar.mulf %iq{t}, %idim{t} : f32")
            e(f"          %sr{t} = index.mul %qtk{t}, %nkh : index")
            e(f"          %sh{t} = index.add %sr{t}, %head : index")
            e(f"          %sb{t} = index.mul %sh{t}, %c3 : index")
            e(f"          %sb1_{t} = index.add %sb{t}, %c1 : index")
            e(f"          %sb2_{t} = index.add %sb{t}, %c2 : index")
            e(f"          view.store %ik{t}, %sc_view[%sb{t}] : f32, view<{sc_total}xf32>")
            e(f"          view.store %qsc{t}, %sc_view[%sb1_{t}] : f32, view<{sc_total}xf32>")
            e(f"          view.store {kqs}, %sc_view[%sb2_{t}] : f32, view<{sc_total}xf32>")
            e(f"          %ls{t} = index.constant {sc_base + 2 * u} : index")
            e(f"          %ls{t}q = index.constant {sc_base + 2 * u + 1} : index")
            e(f"          view.store %ik{t}, %lv[%ls{t}] : f32, view<{NL}xf32>")
            e(f"          view.store %qsc{t}, %lv[%ls{t}q] : f32, view<{NL}xf32>")
            e("        }")
            e("      }")
        e("      kernel.barrier<workgroup> scope(workgroup) ordering(acq_rel)")
        for u in range(PTB):
            t = b * PTB + u
            e(f"      %so{t} = index.constant {sc_base + 2 * u} : index")
            e(f"      %so{t}q = index.constant {sc_base + 2 * u + 1} : index")
            e(f"      %ksv{t} = view.load %lv[%so{t}] : view<{NL}xf32> -> f32")
            e(f"      %qsv{t} = view.load %lv[%so{t}q] : view<{NL}xf32> -> f32")
            for p, sv in (("q", f"%qsv{t}"), ("k", f"%ksv{t}")):
                e(f"      %{p}on{t} = scalar.mulf %{p}r_{t}, {sv} : f32")
                e(f"      %{p}oh{t} = scalar.fptrunc %{p}on{t} : f32 to f16")
                e(f"      view.store %{p}oh{t}, %out_view[%{p}xo{t}] : f16, view<{x_total}xf16>")
    # window into the next sub-block: its last three inputs
    win = [f"%{p}x{t}" for p, _ in chans for t in (PSB - 1, PSB - 2, PSB - 3)]
    e("      scf.yield " + ", ".join(win + nxt) + " : " + ", ".join(ty for _, _, ty in carry))
    e("    }")
    e("  }")
    e("  kernel.return")
    e("}")
    return "\n".join(L) + "\n"


def tiles(climit, qk_dim=4096):
    """Workgroups along x of gen(climit): the q / k heads (16) and the v channels up to climit."""
    return 16 + (climit - qk_dim + 255) // 256


CW = 160   # gen_c lanes per workgroup: two NPU columns of gen_npu_gemm.TN
TC = 32    # gen_c tokens per workgroup


def gen_c(first, cols, batch, qkv_dim=10240):
    """yah_ssm_conv_kq_c: the conv for the v channels first .. first + cols * TN - 1 of a NPU qkv split, its input
    read straight from the NPU's C. Bit-identical to the f16 unpack (gen_npu_unpack) + gen.
    A workgroup takes CW channels x TC tokens. Staging: lanes take the unpack's work items (8 C columns of one token,
    token fastest, so a wave reads whole 128-byte C blocks), sum the C partials and round to f16 with the unpack's ops,
    into LDS as [token][channel], for the TC tokens and the 8 before them. Then lane = channel: its weights and the
    window in registers, the conv as gen, f16 out.
    Bindings: c (bf16 pairs), conv_weights, state (as gen), conv_out (f16 [batch][qkv_dim])."""
    import gen_npu_gemm as GN
    import gen_npu_unpack as GU
    n = cols * GN.TN
    assert n % CW == 0 and batch % TC == 0 and first >= 4096   # v channels only
    nwords = batch * n * GU.CG // 2
    rows = TC + 8   # LDS rows: tokens t0 - 8 .. t0 + TC - 1
    items = CW // 8   # 8-column items per token row
    L = []
    e = L.append
    e("// GENERATED by tools/gen_conv_kq.py gen_c -- edit the generator.")
    e("amdgpu.target<gfx1151> @yah_wave32 {subgroup_size = 32}")
    e("")
    e("kernel.def target(@yah_wave32) @yah_ssm_conv_kq_c() {")
    e("  %unit = index.constant 1 : index")
    e(f"  %wgx = index.constant {n // CW} : index")
    e(f"  %wgy = index.constant {batch // TC} : index")
    e(f"  %wgsz = index.constant {CW} : index")
    e("  kernel.launch.config workgroups(%wgx, %wgy, %unit) workgroup_size(%wgsz, %unit, %unit) : index")
    e("} launch(%cbuf: buffer, %weights: buffer, %state: buffer, %out: buffer) {")
    e("  %base = index.constant 0 : offset")
    for v in (0, 1, 2, 3, 4, 8):
        e(f"  %c{v} = index.constant {v} : index")
    e("  %c16i = scalar.constant 16 : i32")
    e("  %chii = scalar.constant -65536 : i32")
    e("  %negone = scalar.constant -1.0 : f32")
    e("  %one = scalar.constant 1.0 : f32")
    e(f"  %qkv_dim = index.constant {qkv_dim} : index")
    e(f"  %x_total = index.constant {batch * qkv_dim} : index")
    e(f"  %w_total = index.constant {qkv_dim * 4} : index")
    e(f"  %nc = index.constant {nwords} : index")
    e(f"  %cgs = index.constant {batch * GN.TN} : index")   # C group stride (gen_npu_unpack.load_cg)
    e("  %c_na, %w_na, %st_na, %out_na = buffer.assume.noalias %cbuf, %weights, %state, %out : buffer, buffer, buffer, buffer")
    e("  %cv = buffer.view %c_na[%base] : buffer -> view<[%nc]xi32>")
    e("  %w_view = buffer.view %w_na[%base] : buffer -> view<[%w_total]xf32>")
    e("  %st_view = buffer.view %st_na[%base] : buffer -> view<[%w_total]xf32>")
    e("  %out_view = buffer.view %out_na[%base] : buffer -> view<[%x_total]xf16>")
    e(f"  %xs_bytes = index.constant {rows * CW * 2} : offset")
    e("  %xs_buf = buffer.alloca<workgroup> align(16) %xs_bytes : buffer")
    e(f"  %xs = buffer.view %xs_buf[%base] : buffer -> view<{rows * CW}xf16>")
    e("  %wg = kernel.workgroup.id<x> : index")
    e("  %blk = kernel.workgroup.id<y> : index")
    e("  %lane = kernel.workitem.id<x> : index")
    e(f"  %ctc = index.constant {TC} : index")
    e("  %t0 = index.mul %blk, %ctc : index")
    e(f"  %ccw = index.constant {CW} : index")
    e("  %nc0 = index.mul %wg, %ccw : index")
    # staging: lane = item * 8 + token in its 8-token group; LDS row r holds token t0 - 8 + r (block 0: rows 0-7 hold
    # tokens 0-7 instead, which the window never reads)
    e("  %tr = index.rem %lane, %c8 : index")
    e("  %it = index.div %lane, %c8 : index")
    e("  %itc0 = index.mul %it, %c8 : index")
    e("  %itc = index.add %nc0, %itc0 : index")   # the item's first NPU column
    la = GU.c_lane(e, "cl_", "%itc", batch)
    e(f"  %nel = index.constant {2 * nwords - (GU.CG - 1) * batch * GN.TN - 8} : index")   # last group-0 item start
    e("  %t0m8 = index.max %t0, %c8 : index")
    e("  %tlo = index.sub %t0m8, %c8 : index")
    for g in range(rows // 8):
        p = f"s{g}_"
        e(f"  %{p}o = index.constant {8 * g} : index")
        if g == 0:
            e(f"  %{p}t0 = index.add %tlo, %c0 : index")
        else:
            e(f"  %{p}g = index.constant {8 * (g - 1)} : index")
            e(f"  %{p}t0 = index.add %t0, %{p}g : index")
        e(f"  %{p}tk = index.add %{p}t0, %tr : index")
        tb = GU.c_tok(e, f"{p}k_", f"%{p}tk")
        e(f"  %{p}i0 = index.add {la}, {tb} : index")
        e(f"  %{p}i = index.min %{p}i0, %nel : index")   # in range by construction; for the bound proof
        GU.load_cg(e, f"%{p}v", f"%{p}i")
        e(f"  %{p}h = vector.fptrunc %{p}v : vector<8xf32> to vector<8xf16>")
        e(f"  %{p}r = index.add %tr, %{p}o : index")
        e(f"  %{p}a0 = index.mul %{p}r, %ccw : index")
        e(f"  %{p}a = index.add %{p}a0, %itc0 : index")
        e(f"  vector.store %{p}h, %xs[%{p}a] : vector<8xf16>, view<{rows * CW}xf16>")
    e("  kernel.barrier<workgroup> scope(workgroup) ordering(acq_rel)")
    # conv: lane = channel
    e(f"  %cfirst = index.constant {first} : index")
    e("  %c0a = index.add %cfirst, %nc0 : index")
    e("  %c = index.add %c0a, %lane : index")
    e("  %c4i = index.mul %c, %c4 : index")
    for j in range(4):
        e(f"  %w{j}_off = index.add %c4i, %c{j} : index")
        e(f"  %w{j} = view.load %w_view[%w{j}_off] : view<[%w_total]xf32> -> f32")
    def lds(name, row):
        e(f"  %{name}o = index.constant {row * CW} : index")
        e(f"  %{name}a = index.add %{name}o, %lane : index")
