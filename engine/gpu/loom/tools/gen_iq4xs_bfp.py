#!/usr/bin/env python3
"""Emit the GPU IQ4_XS -> NPU bfp16ebs8 weight decoder: the NPU decoder's exact values and rounding, on the GPU.

Input: IQ4_XS rows [rows][K / 256][136 B] (block_iq4_xs). Output: fragments [rows / 8][K / 8][72 B] (row-major).
Fragment = 8 rows x 8 consecutive k: per row [E u8][8 x int8 m], value = m * 2^(E - 133) (gen_bfp16_encode's format).
w = (d * (ls - 32)) * kvalue is exact in f32 (<= 23 significant bits). E = the f32 exponent field of the row block's
max |w|, + 1 if a rounded mantissa leaves int8 (npu_dec_emit.bfp_hw, the NPU panel's rule); m = roundeven (no clamp
needed after the bump).
One work item per fragment; adjacent items take adjacent k-blocks of one 8-row group, so a wave writes whole lines.
"""
import os
import re
import sys

import gen_bfp16_encode as BE

WG = 256
WAVE_B = 32 * 72   # a wave's fragments: one 2304-aligned run of 2304 B (stream and row-major)
# stream mode: the stores restaged through LDS (restage); KQ_LDS=0: 9 strided 8 B stores a lane, 2-2.4x slower
LDS = os.environ.get("KQ_LDS", "1") == "1"
KVALUES = [-127, -104, -83, -65, -49, -35, -22, -10, 1, 13, 25, 38, 53, 69, 89, 113]


def out_bytes(rows, K, stream=None):
    if stream:
        return BE.layout_bytes("act", 2 * rows, stream["ks"], stream["passes"], stream["tile"])
    return rows // 8 * (K // 8) * 72


def gen(rows, K, stream=None):
    """stream (row 5 swap): dict(ks, passes, tile, up): write the swap's weight stream instead (gen_bfp16_encode act,
    2 rows rows: 32-row block b of this tensor at stream rows 64 b (gate, up 0) or 64 b + 32 (up 1), k ascending)."""
    assert rows % 8 == 0 and K % 256 == 0
    rb = K // 256 * 136
    n = items(rows, K)
    nin, nout = rows * rb, out_bytes(rows, K, stream)
    L = []
    e = L.append
    e(f"// GENERATED by tools/gen_iq4xs_bfp.py (rows={rows} K={K}" + (f" stream={stream}" if stream else "")
      + ") -- edit the generator.")
    e("amdgpu.target<gfx1151> @yah_wave32 {subgroup_size = 32}")
    e("")
    e("kernel.def target(@yah_wave32) @yah_iq4xs_bfp() {")
    e("  %unit = index.constant 1 : index")
    e(f"  %wgs = index.constant {(n + WG - 1) // WG} : index")
    e(f"  %wgsz = index.constant {WG} : index")
    e("  kernel.launch.config workgroups(%wgs, %unit, %unit) workgroup_size(%wgsz, %unit, %unit) : index")
    e("} launch(%w: buffer, %out: buffer) {")
    e("  %base = index.constant 0 : offset")
    e(f"  %nin = index.constant {nin} : index")
    e(f"  %nout = index.constant {nout} : index")
    e("  %w_na, %out_na = buffer.assume.noalias %w, %out : buffer, buffer")
    e("  %wv = buffer.view %w_na[%base] : buffer -> view<[%nin]xi8>")
    e("  %ov = buffer.view %out_na[%base] : buffer -> view<[%nout]xi8>")
    if stream and LDS:
        lds_decl(e, n)
    e("  %wg = kernel.workgroup.id<x> : index")
    e("  %tid = kernel.workitem.id<x> : index")
    e(f"  %cwg = index.constant {WG} : index")
    e("  %item0 = index.mul %wg, %cwg : index")
    e("  %item = index.add %item0, %tid : index")
    L += body(rows, K, stream=stream)
    e("  kernel.return")
    e("}")
    return "\n".join(L) + "\n"


def items(rows, K):
    return rows // 8 * (K // 8)


def frag(e, src, r, s, qw, nsh):
    """Row r: the 8 nibbles of the i32 pair qw (shifted by nsh) -> E' and 8 mantissa sources, appended to src."""
    n = f"{r}"
    sh = [f"%qy{n}_{h}" for h in range(2)]
    for h in range(2):
        e(f"    %qy{n}_{h} = scalar.shrui {qw[h]}, {nsh} : i32")
    e(f"    %nw{n} = vector.from_elements {sh[0]}, {sh[1]} : vector<2xi32>")
    e(f"    %nc{n} = vector.bitcast %nw{n} : vector<2xi32> to vector<8xi8>")
    e(f"    %nb{n} = vector.andi %nc{n}, %m15v : vector<8xi8>")   # (the lookup's index range proof)
    e(f"    %ku{n} = vector.table.lookup %kvt[%nb{n}] : vector<16xi8>, vector<8xi8> -> vector<8xi8>")
    e(f"    %kw{n} = vector.bitcast %ku{n} : vector<8xi8> to vector<2xi32>")
    u, kbs = [], []
    for j in range(8):   # signed kvalue bytes: one v_bfe_i32 each
        if j % 4 == 0:
            e(f"    %kx{n}_{j // 4} = vector.extract %kw{n}[{j // 4}] : vector<2xi32> -> i32")
        e(f"    %kb{n}_{j} = scalar.bitfield.extracts %kx{n}_{j // 4} {{offset = {8 * (j % 4)}, width = 8}} : i32 -> i32")
        e(f"    %u{n}_{j} = scalar.sitofp %kb{n}_{j} : i32 to f32")
        u.append(f"%u{n}_{j}")
        kbs.append(f"%kb{n}_{j}")
    # the codebook is increasing: the extremes of the 8 values are s times the extreme codes
    hi, lo = kbs[0], kbs[0]
    for j in range(1, 8):
        e(f"    %uh{n}_{j} = scalar.maxsi {hi}, {kbs[j]} : i32")
        e(f"    %ul{n}_{j} = scalar.minsi {lo}, {kbs[j]} : i32")
        hi, lo = f"%uh{n}_{j}", f"%ul{n}_{j}"
    e(f"    %khf{n} = scalar.sitofp {hi} : i32 to f32")
    e(f"    %klf{n} = scalar.sitofp {lo} : i32 to f32")
    e(f"    %wh{n} = scalar.mulf {s}, %khf{n} : f32")
    e(f"    %wl{n} = scalar.mulf {s}, %klf{n} : f32")
    e(f"    %ah{n} = scalar.absf %wh{n} : f32")
    e(f"    %al{n} = scalar.absf %wl{n} : f32")
    e(f"    %am{n} = scalar.maxnumf %ah{n}, %al{n} : f32")
    e(f"    %pm{n} = scalar.maxnumf %wh{n}, %wl{n} : f32")
    e(f"    %mb{n} = scalar.bitcast %am{n} : f32 to i32")
    # exponent field of max |w|; an all-zero block has s = 0, so every product below is 0 and E = 0
    e(f"    %E{n} = scalar.bitfield.extractu %mb{n} {{offset = 23, width = 8}} : i32 -> i32")
    e(f"    %ie{n} = scalar.subi %i260, %E{n} : i32")
    e(f"    %ib{n} = scalar.shli %ie{n}, %i23 : i32")
    e(f"    %iq{n} = scalar.bitcast %ib{n} : i32 to f32")          # 2^(133 - E)
    # bfp_hw's bump: the largest value rounds to 128 -> E + 1 (only a positive value can leave int8)
    e(f"    %ps{n} = scalar.mulf %pm{n}, %iq{n} : f32")
    e(f"    %pr{n} = scalar.roundevenf %ps{n} : f32")
    e(f"    %bu{n} = scalar.cmpf ogt, %pr{n}, %f127 : f32")
    e(f"    %Ep{n} = scalar.addi %E{n}, %i1 : i32")
    e(f"    %E1_{n} = scf.select %bu{n}, %Ep{n}, %E{n} : i32")
    e(f"    %je{n} = scalar.subi %i260, %E1_{n} : i32")
    e(f"    %jb{n} = scalar.shli %je{n}, %i23 : i32")
    e(f"    %jq{n} = scalar.bitcast %jb{n} : i32 to f32")
    e(f"    %ss{n} = scalar.mulf {s}, %jq{n} : f32")   # s 2^(133 - E'), exact
    src.append(f"%E1_{n}")
    for j in range(8):   # m = roundeven(kvalue * ss): exact product, one rounding (|m| <= 128 after the bump)
        e(f"    %y{n}_{j} = scalar.fmaf {u[j]}, %ss{n}, %magic : f32")
        e(f"    %yb{n}_{j} = scalar.bitcast %y{n}_{j} : f32 to i32")
        src.append(f"%yb{n}_{j}")


def pack(e, src):
    """72 sources (low bytes) -> 18 words: two byte pairs (v_perm) and their merge."""
    words = []
    for w in range(18):
        a, b, c, d = src[4 * w:4 * w + 4]
        n = f"{w}"
        for nm, x, y in (("pa", a, b), ("pb", c, d)):
            e(f"    %{nm}{n} = vector.from_elements {x}, {y} : vector<2xi32>")
            e(f"    %{nm}c{n} = vector.bitcast %{nm}{n} : vector<2xi32> to vector<8xi8>")
            e(f"    %{nm}s{n} = vector.shuffle<[0, 4, 0, 4, 0, 0, 0, 0]> %{nm}c{n} : vector<8xi8>")
            e(f"    %{nm}w{n} = vector.bitcast %{nm}s{n} : vector<8xi8> to vector<2xi32>")
            e(f"    %{nm}x{n} = vector.extract %{nm}w{n}[0] : vector<2xi32> -> i32")
        e(f"    %pm2_{n} = vector.from_elements %pax{n}, %pbx{n} : vector<2xi32>")
        e(f"    %pmc{n} = vector.bitcast %pm2_{n} : vector<2xi32> to vector<8xi8>")
        e(f"    %pms{n} = vector.shuffle<[0, 1, 4, 5, 0, 0, 0, 0]> %pmc{n} : vector<8xi8>")
        e(f"    %pmw{n} = vector.bitcast %pms{n} : vector<8xi8> to vector<2xi32>")
        e(f"    %o{n} = vector.extract %pmw{n}[0] : vector<2xi32> -> i32")
        words.append(f"%o{n}")
    return words


def st(e, words, base):
    """18 words -> 72 bytes at base: 9 aligned 8-byte stores."""
    for j in range(9):
        n = f"{j}"
        e(f"    %wd{n} = vector.from_elements {words[2 * j]}, {words[2 * j + 1]} : vector<2xi32>")
        e(f"    %w{n} = vector.bitcast %wd{n} : vector<2xi32> to vector<8xi8>")
        e(f"    %wo{n} = index.constant {8 * j} : index")
        e(f"    %wa{n} = index.add {base}, %wo{n} : index")
        e(f"    vector.store %w{n}, %ov[%wa{n}] : vector<8xi8>, view<[%nout]xi8>")


def lds_decl(e, n):
    """The restage's LDS: WG / 32 waves x WAVE_B bytes (n items: all live, for its barrier)."""
    assert n % WG == 0, "the restage's barrier needs every item live"
    e(f"  %lds_bytes = index.constant {WG // 32 * WAVE_B} : offset")
    e("  %lds = buffer.alloca<workgroup> align(16) %lds_bytes : buffer")
    e(f"  %lv = buffer.view %lds[%base] : buffer -> view<{WG // 32 * WAVE_B}xi8>")


def restage(e, words):
    """KQ_LDS=1: the wave's 32 fragments (one 2304-aligned 2304 B run) go to its 2304 B of LDS at the fragment's place in
    the run, then back out as 144 contiguous 16 B chunks (lane l: chunks l + 32 r): whole lines instead of 9 strided
    8 B stores a lane. Global bytes written: exactly the run's, as before."""
    nl = WG // 32 * WAVE_B
    for nm, v in (("rs_cw", WAVE_B), ("rs_c32", 32), ("rs_c16", 16)):
        e(f"    %{nm} = index.constant {v} : index")
    e("    %rs_nl16 = index.sub %nout, %rs_c16 : index")
    e("    %rs_wave = index.div %tid, %rs_c32 : index")
    e("    %rs_lane = index.rem %tid, %rs_c32 : index")
    e("    %rs_wl = index.mul %rs_wave, %rs_cw : index")
    e("    %rs_in = index.rem %frag, %rs_cw : index")
    e("    %rs_gq = index.div %frag, %rs_cw : index")
    e("    %rs_gb = index.mul %rs_gq, %rs_cw : index")          # the run's first byte
    # (assumed, checked by the caller's layout: the fragment starts at 72 i in its run, i < 32; the run lies in out)
    e(f"    %rs_l0x = index.add %rs_wl, %rs_in : index")
    e(f"    %rs_l0 = index.assume %rs_l0x [range(%rs_l0x, 0, {nl - 72})] : index")
    for j in range(9):
        e(f"    %rs_d{j} = vector.from_elements {words[2 * j]}, {words[2 * j + 1]} : vector<2xi32>")
        e(f"    %rs_w{j} = vector.bitcast %rs_d{j} : vector<2xi32> to vector<8xi8>")
        e(f"    %rs_o{j} = index.constant {8 * j} : index")
        e(f"    %rs_a{j} = index.add %rs_l0, %rs_o{j} : index")
        e(f"    vector.store %rs_w{j}, %lv[%rs_a{j}] : vector<8xi8>, view<{nl}xi8>")
    e("    kernel.barrier<workgroup> scope(workgroup) ordering(acq_rel)")
    for r in range(5):
        e(f"    %rs_cr{r} = index.constant {32 * r} : index")
        e(f"    %rs_ch{r} = index.add %rs_lane, %rs_cr{r} : index")
        e(f"    %rs_cb{r} = index.mul %rs_ch{r}, %rs_c16 : index")
        cb = f"%rs_cb{r}"
        if r == 4:   # chunks 128 .. 143: lanes 0 .. 15
            e(f"    %rs_cl = index.constant {WAVE_B} : index")
            e(f"    %rs_ok = index.cmp ult, %rs_cb4, %rs_cl : index")
            # the footprint analysis ignores the guard: the clamp (a no-op for lanes 0 .. 15) keeps the .fp at nout
            e(f"    %rs_cm = index.constant {WAVE_B - 16} : index")
            e(f"    %rs_cb4c = index.min %rs_cb4, %rs_cm : index")
            cb = "%rs_cb4c"
            e("    scf.if %rs_ok {")
        e(f"    %rs_la{r} = index.add %rs_wl, {cb} : index")
        e(f"    %rs_v{r} = vector.load %lv[%rs_la{r}] : view<{nl}xi8> -> vector<16xi8>")
        e(f"    %rs_gx{r} = index.add %rs_gb, {cb} : index")
        e(f"    %rs_ga{r} = index.assume %rs_gx{r} [range(%rs_gx{r}, 0, %rs_nl16)] : index")
        e(f"    vector.store %rs_v{r}, %ov[%rs_ga{r}] : vector<16xi8>, view<[%nout]xi8>")
        if r == 4:
            e("    }")


def prologue(e, rows, K, rb, koff=0, stream=None, blk=136):
    """Work item %item's fragment: %g8 (its 8-row group), %kbi (its k-block), %frag (its first output byte: row-major
    or the swap's stream), opening "scf.if %live" (closed by the caller). Shared by the K-quant decoders."""
    kb = K // 8
    e(f"  %citems = index.constant {items(rows, K)} : index")
    e("  %live = index.cmp ult, %item, %citems : index")
    e("  scf.if %live {")
    for nm, v in (("ckb", kb), ("crb", rb), ("ckoff", koff), ("c8", 8), ("c4", 4), ("c2", 2), ("c32", 32),
                  ("c136", blk), ("c16", 16), ("c72", 72)) + ((("c0i", 0),) if stream else ()):
        e(f"    %{nm} = index.constant {v} : index")
    if stream:   # a lane pair: one k-block's two 8-row halves of a 16-row group (144 contiguous stream bytes)
        e("    %ihf = index.rem %item, %c2 : index")
        e("    %ipr = index.div %item, %c2 : index")
        e("    %g16 = index.div %ipr, %ckb : index")
        e("    %kbi = index.rem %ipr, %ckb : index")
        e("    %g16x = index.mul %g16, %c2 : index")
        e("    %g8 = index.add %g16x, %ihf : index")
    else:
        e("    %g8 = index.div %item, %ckb : index")
        e("    %kbi = index.rem %item, %ckb : index")
    if stream:   # stream row group 8 (g8 / 4) + 4 up + g8 % 4 (a 32-row block's 4 groups), its act offset
        assert sum(stream["ks"]) * stream["passes"] == kb and rows % 32 == 0
        for nm, v in (("s_c2", 2), ("s_c144", 144), ("s_c72", 72), ("s_csub", stream["tile"] // 16),
                      ("s_cpk", sum(stream["ks"])), ("s_cpass", stream["passes"]), ("s_cup", 4 * stream["up"])):
            e(f"    %{nm} = index.constant {v} : index")
        e("    %s_gb = index.div %g8, %c4 : index")
        e("    %s_gr = index.rem %g8, %c4 : index")
        e("    %s_gb8 = index.mul %s_gb, %c8 : index")
        e("    %s_gu = index.add %s_gb8, %s_cup : index")
        e("    %s_g8 = index.add %s_gu, %s_gr : index")
        fr = BE.emit_offset(e, "act", 2 * rows, list(stream["ks"]), stream["passes"], stream["tile"], True,
                            "%s_g8", "%kbi", p="s_", perm=False)
        e(f"    %frag = index.add {fr}, %c0i : index")
    else:
        e("    %frag = index.mul %item, %c72 : index")


def body(rows, K, p="", rstride=None, koff=0, stream=None):
    """The decode of work item %item (views %wv over the rows, %ov over the fragments), names prefixed with p.
    Row r's IQ4_XS blocks start at byte r * rstride + koff (default: K's blocks back to back)."""
    kb = K // 8
    rb = rstride or K // 256 * 136
    L = []
    e = L.append
    prologue(e, rows, K, rb, koff, stream)
    # k-block kbi: super-block kbi / 32, sub-block (kbi % 32) / 4, nibble half (kbi % 4) / 2, byte half kbi % 2
    e("    %sb = index.div %kbi, %c32 : index")
    e("    %kbl = index.rem %kbi, %c32 : index")
    e("    %ib = index.div %kbl, %c4 : index")
    e("    %q4 = index.rem %kbl, %c4 : index")
    e("    %hi = index.div %q4, %c2 : index")
    e("    %bh = index.rem %q4, %c2 : index")
    e("    %sbo = index.mul %sb, %c136 : index")
    e("    %ibo = index.mul %ib, %c16 : index")
    e("    %bho = index.mul %bh, %c8 : index")
    e("    %qo0 = index.add %ibo, %bho : index")
    e("    %qo1 = index.add %qo0, %c8 : index")
    e("    %row0 = index.mul %g8, %c8 : index")
    e("    %rb0 = index.mul %row0, %crb : index")
    e("    %rb1 = index.add %rb0, %ckoff : index")
    e("    %blkb = index.add %rb1, %sbo : index")
    e("    %ib_i = index.cast %ib : index to i32")
    e("    %hi_i = index.cast %hi : index to i32")
    for nm, v in (("i1", 1), ("i2", 2), ("i3", 3), ("i15", 15), ("i16", 16), ("i23", 23), ("i32", 32), ("i260", 260)):
        e(f"    %{nm} = scalar.constant {v} : i32")
    e("    %sh2 = scalar.shli %ib_i, %i1 : i32")
    e("    %sh4 = scalar.shli %ib_i, %i2 : i32")
    e("    %sh16 = scalar.addi %sh2, %i16 : i32")
    e("    %nsh = scalar.shli %hi_i, %i2 : i32")   # 0 (low nibbles) or 4 (high)
    e("    %c15b = scalar.constant 15 : i8")
    e("    %m15v = vector.splat %c15b : vector<8xi8>")
    e("    %f127 = scalar.constant 127.0 : f32")
    # 1.5 * 2^23: x + magic rounds x to the nearest even integer, left in the low mantissa bits (|x| < 2^22)
    e("    %magic = scalar.constant 12582912.0 : f32")
    for i, v in enumerate(KVALUES):
        e(f"    %kv{i} = scalar.constant {v} : i8")
    e("    %kvt = vector.from_elements " + ", ".join(f"%kv{i}" for i in range(16)) + " : vector<16xi8>")
    src = []   # per fragment byte: an i32 whose low byte it is
    for r in range(8):
        e(f"    %ro{r} = index.constant {r * rb} : index")
        e(f"    %blk{r} = index.add %blkb, %ro{r} : index")
        e(f"    %hdr{r} = vector.load %wv[%blk{r}] : view<[%nin]xi8> -> vector<8xi8>")
        e(f"    %hdw{r} = vector.bitcast %hdr{r} : vector<8xi8> to vector<2xi32>")
        e(f"    %hw0_{r} = vector.extract %hdw{r}[0] : vector<2xi32> -> i32")
        e(f"    %hw1_{r} = vector.extract %hdw{r}[1] : vector<2xi32> -> i32")
        e(f"    %d16_{r} = scalar.trunci %hw0_{r} : i32 to i16")
        e(f"    %dh{r} = scalar.bitcast %d16_{r} : i16 to f16")
        e(f"    %d{r} = scalar.extf %dh{r} : f16 to f32")
        e(f"    %slw{r} = scalar.shrui %hw1_{r}, %sh4 : i32")
        e(f"    %scl{r} = scalar.andi %slw{r}, %i15 : i32")
        e(f"    %sha{r} = scalar.shrui %hw0_{r}, %sh16 : i32")
        e(f"    %sch{r} = scalar.andi %sha{r}, %i3 : i32")
        e(f"    %ls{r} = scalar.fmai %sch{r}, %i16, %scl{r} : i32")
        e(f"    %sc{r} = scalar.subi %ls{r}, %i32 : i32")
        e(f"    %scf{r} = scalar.sitofp %sc{r} : i32 to f32")
        e(f"    %s{r} = scalar.mulf %d{r}, %scf{r} : f32")   # d (ls - 32), exact
        e(f"    %qa{r} = index.add %blk{r}, %qo1 : index")
        e(f"    %qb{r} = vector.load %wv[%qa{r}] : view<[%nin]xi8> -> vector<8xi8>")
        e(f"    %qw{r} = vector.bitcast %qb{r} : vector<8xi8> to vector<2xi32>")
        qw = []
        for h in range(2):
            e(f"    %qx{r}_{h} = vector.extract %qw{r}[{h}] : vector<2xi32> -> i32")
            qw.append(f"%qx{r}_{h}")
        frag(e, src, r, f"%s{r}", qw, "%nsh")
    if stream and LDS:
        restage(e, pack(e, src))
    else:
        st(e, pack(e, src), "%frag")
    e("  }")
    return [re.sub(r"%([A-Za-z_]\w*)", lambda m: "%" + p + m.group(1), ln) for ln in L] if p else L


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: gen_iq4xs_bfp.py <rows> <K>")
    sys.stdout.write(gen(int(sys.argv[1]), int(sys.argv[2])))


if __name__ == "__main__":
    main()
