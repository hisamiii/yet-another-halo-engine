    e("  }")
    e("  %Ls, %As = scf.for %s = [%c0 to %np step %c1](%lc = %zf : f32, %ac = %zf : f32) -> (f32, f32) {")
    e("    %r0 = index.mul %s, %cnh : index")
    e("    %r1 = index.add %r0, %hh : index")
    e("    %mi = index.mul %r1, %c2 : index")
