    e("    %an = scalar.fmaf %w, %as, %ac : f32")
    e("    scf.yield %ln, %an : f32, f32")
    e("  }")
    e("  %inv = scalar.divf %one, %Ls : f32")
    e("  %ctx = scalar.mulf %As, %inv : f32")
    e("  %oi0 = index.mul %hh, %c256 : index")
    e("  %oi = index.add %oi0, %t : index")
    e(f"  %g = view.load %gv[%oi] : view<{NH * HD}xf32> -> f32")
