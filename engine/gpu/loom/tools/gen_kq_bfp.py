    if len(sys.argv) != 4:
        sys.exit("usage: gen_kq_bfp.py <Q4_K|Q5_K|Q3_K|IQ3_S|IQ3_XXS|IQ2_XS|IQ2_S> <rows> <K>")
    sys.stdout.write(gen(sys.argv[1], int(sys.argv[2]), int(sys.argv[3])))


