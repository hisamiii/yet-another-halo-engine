#!/usr/bin/env python3
"""Emit the GPU Q4_K / Q5_K / Q3_K / IQ3_S / IQ3_XXS / IQ2_XS / IQ2_S -> NPU bfp16ebs8 weight decoder: the NPU decoder's exact values and rounding, on the GPU
(row 5 swap: the GPU decodes a pair layer's gate / up into the swap's weight stream).

Input: rows [rows][K / 256][144 B] (block_q4_K) or [176 B] (block_q5_K). Output: as gen_iq4xs_bfp (fragments of 8 rows
x 8 k, per row [E u8][8 x int8 m]; row-major, or the swap's stream).
Values: gen_npu_dec.weights() of the gather-free path (Q4_K's "GF" order, the pair layers' form, and Q5_K): per
sub-block T = d sc and M = -dmin m, each split into two bf16 parts (RNE, then the RNE of the remainder); X = 128 + q
(q = nibble + 16 h, h = 0 for Q4_K); in f32, in the NPU kernel's order: w = M0 + M1, + T0 (-128), + T1 (-128), + T0 X,
+ T1 X. Every product is exact (8-bit T part times a <= 8-bit X), so a fused multiply-add rounds as the kernel does.
IQ3_S (110 B blocks): w = d (1 + 2 sc) grid[qs | qh bit << 8][j] (-1)^sign, exact in f32; the 512-word grid
(tables/grid_iq3s.bin, 4 u8 values a word) is a second input buffer, read through the cache.
Q3_K (110 B blocks): w = d (sc - 32) (crumb + 4 hbit - 4), exact in f32.
IQ3_XXS (98 B) / IQ2_XS (74 B) / IQ2_S (82 B): w = d (1 + 2 s) (grid / 4 or / 8)[idx][j] (-1)^sign, exact in f32;
IQ3_XXS / IQ2_XS signs from 7-bit fields f (ksigns(f) = f | parity(f) << 7, the parity by xor folds).
E / m: npu_dec_emit.bfp_hw, as gen_iq4xs_bfp (the exponent of max |w|, + 1 when the largest value rounds to 128).
"""
import os
import sys

import gen_iq4xs_bfp as I

WG = I.WG
BLK = {"Q4_K": 144, "Q5_K": 176, "IQ3_S": 110, "Q3_K": 110, "IQ3_XXS": 98, "IQ2_XS": 74, "IQ2_S": 82}
# grid formats: the grid (tables/grid_<fmt>.bin) is a second input buffer of this many i32 words
GRIDW = {"IQ3_S": 512, "IQ3_XXS": 256, "IQ2_XS": 1024, "IQ2_S": 2048}
LDS = os.environ.get("KQ_LDS", "1") == "1"   # (gen_iq4xs_bfp.restage; KQ_LDS=0: 9 strided 8 B stores a lane)
QS = {"Q4_K": 16, "Q5_K": 48}   # the qs bytes' offset in a block (Q5_K: qh 32 B at 16 first)


def out_bytes(rows, K, stream=None):
    return I.out_bytes(rows, K, stream)


def items(rows, K):
    return I.items(rows, K)


def gen(fmt, rows, K, stream=None):
    assert fmt in BLK and rows % 8 == 0 and K % 256 == 0
    rb = K // 256 * BLK[fmt]
    n = items(rows, K)
    nin, nout = rows * rb, out_bytes(rows, K, stream)
    L = []
    e = L.append
    e(f"// GENERATED by tools/gen_kq_bfp.py ({fmt} rows={rows} K={K}" + (f" stream={stream}" if stream else "")
      + ") -- edit the generator.")
    e("amdgpu.target<gfx1151> @yah_wave32 {subgroup_size = 32}")
    e("")
    e("kernel.def target(@yah_wave32) @yah_kq_bfp() {")
    e("  %unit = index.constant 1 : index")
    e(f"  %wgs = index.constant {(n + WG - 1) // WG} : index")
    e(f"  %wgsz = index.constant {WG} : index")
    e("  kernel.launch.config workgroups(%wgs, %unit, %unit) workgroup_size(%wgsz, %unit, %unit) : index")
    grid = fmt in GRIDW
    e("} launch(%w: buffer, %grid: buffer, %out: buffer) {" if grid else "} launch(%w: buffer, %out: buffer) {")
    e("  %base = index.constant 0 : offset")
    e(f"  %nin = index.constant {nin} : index")
    e(f"  %nout = index.constant {nout} : index")
    if grid:
        e("  %w_na, %grid_na, %out_na = buffer.assume.noalias %w, %grid, %out : buffer, buffer, buffer")
        e(f"  %gv = buffer.view %grid_na[%base] : buffer -> view<{GRIDW[fmt]}xi32>")
    else:
        e("  %w_na, %out_na = buffer.assume.noalias %w, %out : buffer, buffer")
    e("  %wv = buffer.view %w_na[%base] : buffer -> view<[%nin]xi8>")
    e("  %ov = buffer.view %out_na[%base] : buffer -> view<[%nout]xi8>")
    if LDS:
        I.lds_decl(e, n)
    e("  %wg = kernel.workgroup.id<x> : index")
    e("  %tid = kernel.workitem.id<x> : index")
    e(f"  %cwg = index.constant {WG} : index")
    e("  %item0 = index.mul %wg, %cwg : index")
    e("  %item = index.add %item0, %tid : index")
    L += body(fmt, rows, K, stream)
    e("  kernel.return")
    e("}")
    return "\n".join(L) + "\n"


def store(e, src):
    """The fragment's 72 bytes at %frag. (diag KQ_DIAG: "nostore" guards the stores by an impossible E (loads and math
    kept); "storeonly" stores a word of %frag instead of the values (the decode is dead code))"""
    diag = os.environ.get("KQ_DIAG", "")
    if diag == "storeonly":
        e("    %dgf = index.cast %frag : index to i32")
        if LDS:
            I.restage(e, ["%dgf"] * 18)
        else:
            I.st(e, ["%dgf"] * 18, "%frag")
        return
    words = I.pack(e, src)
    if diag == "nostore":
        e("    %dgc = scalar.constant 999 : i32")
        e("    %dg = scalar.cmpi eq, %E1_0, %dgc : i32")
        e("    scf.if %dg {")
        I.st(e, words, "%frag")
        e("    }")
        return
    assert not diag, diag
    if LDS:
        I.restage(e, words)
        return
    I.st(e, words, "%frag")


def rne(e, n, x):
    """f32 x -> its nearest-even bf16 as f32 (npu_dec_emit.bf16_rne), named %{n}."""
    e(f"    %{n}_u = scalar.bitcast {x} : f32 to i32")
    e(f"    %{n}_l = scalar.shrui %{n}_u, %i16 : i32")
    e(f"    %{n}_o = scalar.andi %{n}_l, %i1 : i32")
    e(f"    %{n}_a = scalar.addi %{n}_u, %i7fff : i32")
    e(f"    %{n}_b = scalar.addi %{n}_a, %{n}_o : i32")
    e(f"    %{n}_c = scalar.andi %{n}_b, %ihi : i32")
    e(f"    %{n} = scalar.bitcast %{n}_c : i32 to f32")


def parts2(e, n, x):
    """f32 x -> %{n}0, %{n}1 (gen_npu_dec.parts2: the RNE, then the RNE of the exact remainder)."""
    rne(e, f"{n}0", x)
    e(f"    %{n}r = scalar.subf {x}, %{n}0 : f32")
    rne(e, f"{n}1", f"%{n}r")


def row(e, src, fmt, r):
    """Row r of the fragment: its block at %blk{r}; 1 E source and 8 mantissa sources appended to src."""
    n = f"{r}"
    e(f"    %hdr{n} = vector.load %wv[%blk{n}] : view<[%nin]xi8> -> vector<16xi8>")
    e(f"    %hdw{n} = vector.bitcast %hdr{n} : vector<16xi8> to vector<4xi32>")
    for h in range(4):
        e(f"    %hw{h}_{n} = vector.extract %hdw{n}[{h}] : vector<4xi32> -> i32")
    e(f"    %d16_{n} = scalar.trunci %hw0_{n} : i32 to i16")
    e(f"    %dh{n} = scalar.bitcast %d16_{n} : i16 to f16")
    e(f"    %d{n} = scalar.extf %dh{n} : f16 to f32")
    e(f"    %dmw{n} = scalar.shrui %hw0_{n}, %i16 : i32")
    e(f"    %dm16_{n} = scalar.trunci %dmw{n} : i32 to i16")
    e(f"    %dmh{n} = scalar.bitcast %dm16_{n} : i16 to f16")
    e(f"    %dm{n} = scalar.extf %dmh{n} : f16 to f32")
    # scale bytes s % 4 of words 1..3 (bytes 4 + a, 8 + a, 12 + a); sub-block s < 4: sc = b1 & 63, m = b2 & 63;
    # s >= 4: sc = b3 & 15 | (b1 >> 6) << 4, m = b3 >> 4 | (b2 >> 6) << 4 (picked by the mask %selm: s >= 4)
    for h in (1, 2, 3):
        e(f"    %bs{h}_{n} = scalar.shrui %hw{h}_{n}, %sh8a : i32")
        e(f"    %b{h}_{n} = scalar.andi %bs{h}_{n}, %i255 : i32")
    e(f"    %scl{n} = scalar.andi %b1_{n}, %i63 : i32")
    e(f"    %mnl{n} = scalar.andi %b2_{n}, %i63 : i32")
    e(f"    %t1_{n} = scalar.shrui %b1_{n}, %i6 : i32")
    e(f"    %t1s{n} = scalar.shli %t1_{n}, %i4 : i32")
    e(f"    %b3l{n} = scalar.andi %b3_{n}, %i15 : i32")
    e(f"    %sch{n} = scalar.ori %b3l{n}, %t1s{n} : i32")
    e(f"    %t2_{n} = scalar.shrui %b2_{n}, %i6 : i32")
    e(f"    %t2s{n} = scalar.shli %t2_{n}, %i4 : i32")
    e(f"    %b3h{n} = scalar.shrui %b3_{n}, %i4 : i32")
    e(f"    %mnh{n} = scalar.ori %b3h{n}, %t2s{n} : i32")
    for v in ("sc", "mn"):
        e(f"    %{v}x{n} = scalar.xori %{v}l{n}, %{v}h{n} : i32")
        e(f"    %{v}y{n} = scalar.andi %{v}x{n}, %selm : i32")
        e(f"    %{v}{n} = scalar.xori %{v}l{n}, %{v}y{n} : i32")
    e(f"    %scf{n} = scalar.sitofp %sc{n} : i32 to f32")
    e(f"    %mnf{n} = scalar.sitofp %mn{n} : i32 to f32")
    e(f"    %T{n} = scalar.mulf %d{n}, %scf{n} : f32")         # d sc, exact (11 x 6 bits)
    e(f"    %Mp{n} = scalar.mulf %dm{n}, %mnf{n} : f32")
    e(f"    %M{n} = scalar.negf %Mp{n} : f32")                 # -dmin m, exact
    parts2(e, f"Tp{n}_", f"%T{n}")
    parts2(e, f"Mq{n}_", f"%M{n}")
    e(f"    %qa{n} = index.add %blk{n}, %qso : index")
    e(f"    %qb{n} = vector.load %wv[%qa{n}] : view<[%nin]xi8> -> vector<8xi8>")
    e(f"    %qw{n} = vector.bitcast %qb{n} : vector<8xi8> to vector<2xi32>")
    if fmt == "Q5_K":
        e(f"    %ha{n} = index.add %blk{n}, %qho : index")
        e(f"    %hb{n} = vector.load %wv[%ha{n}] : view<[%nin]xi8> -> vector<8xi8>")
        e(f"    %qhw{n} = vector.bitcast %hb{n} : vector<8xi8> to vector<2xi32>")
    for h in range(2):
        e(f"    %qx{n}_{h} = vector.extract %qw{n}[{h}] : vector<2xi32> -> i32")
        e(f"    %qy{n}_{h} = scalar.shrui %qx{n}_{h}, %nsh : i32")
        if fmt == "Q5_K":
            e(f"    %hx{n}_{h} = vector.extract %qhw{n}[{h}] : vector<2xi32> -> i32")
            e(f"    %hy{n}_{h} = scalar.shrui %hx{n}_{h}, %s_i : i32")
    e(f"    %wz0_{n} = scalar.addf %Mq{n}_0, %Mq{n}_1 : f32")
    e(f"    %wz1_{n} = scalar.fmaf %Tp{n}_0, %fm128, %wz0_{n} : f32")
    e(f"    %wzb{n} = scalar.fmaf %Tp{n}_1, %fm128, %wz1_{n} : f32")
    ws = []
    for j in range(8):
        m = f"{n}_{j}"
        o = 8 * (j % 4)
        e(f"    %q{m} = scalar.bitfield.extractu %qy{n}_{j // 4} {{offset = {o}, width = 4}} : i32 -> i32")
        if fmt == "Q5_K":
            e(f"    %h{m} = scalar.bitfield.extractu %hy{n}_{j // 4} {{offset = {o}, width = 1}} : i32 -> i32")
            e(f"    %qh{m} = scalar.fmai %h{m}, %i16, %q{m} : i32")
            q = f"%qh{m}"
        else:
            q = f"%q{m}"
        e(f"    %xi{m} = scalar.addi {q}, %i128 : i32")
        e(f"    %X{m} = scalar.sitofp %xi{m} : i32 to f32")
        e(f"    %wt{m} = scalar.fmaf %Tp{n}_0, %X{m}, %wzb{n} : f32")
        e(f"    %wv{m} = scalar.fmaf %Tp{n}_1, %X{m}, %wt{m} : f32")
        ws.append(f"%wv{m}")
    bfp_tail(e, src, n, ws)


def bfp_tail(e, src, n, ws):
    """Row n's 8 f32 values ws -> its E source and 8 mantissa sources (npu_dec_emit.bfp_hw), appended to src."""
    # E: the exponent of max |w|; the bump: the largest value rounds to 128 (only a positive one can leave int8)
    am, pm = None, None
    for j, w in enumerate(ws):
        e(f"    %aw{n}_{j} = scalar.absf {w} : f32")
        if j:
            e(f"    %am{n}_{j} = scalar.maxnumf {am}, %aw{n}_{j} : f32")
            e(f"    %px{n}_{j} = scalar.maxnumf {pm}, {w} : f32")
            am, pm = f"%am{n}_{j}", f"%px{n}_{j}"
        else:
            am, pm = f"%aw{n}_0", w
    e(f"    %mb{n} = scalar.bitcast {am} : f32 to i32")
    e(f"    %E{n} = scalar.bitfield.extractu %mb{n} {{offset = 23, width = 8}} : i32 -> i32")
    e(f"    %ie{n} = scalar.subi %i260, %E{n} : i32")
    e(f"    %ib{n} = scalar.shli %ie{n}, %i23 : i32")
    e(f"    %iq{n} = scalar.bitcast %ib{n} : i32 to f32")          # 2^(133 - E)
    e(f"    %ps{n} = scalar.mulf {pm}, %iq{n} : f32")
    e(f"    %pr{n} = scalar.roundevenf %ps{n} : f32")
    e(f"    %bu{n} = scalar.cmpf ogt, %pr{n}, %f127 : f32")
    e(f"    %Ep{n} = scalar.addi %E{n}, %i1 : i32")
    e(f"    %E1_{n} = scf.select %bu{n}, %Ep{n}, %E{n} : i32")
    e(f"    %je{n} = scalar.subi %i260, %E1_{n} : i32")
    e(f"    %jb{n} = scalar.shli %je{n}, %i23 : i32")
    e(f"    %jq{n} = scalar.bitcast %jb{n} : i32 to f32")          # 2^(133 - E')
    src.append(f"%E1_{n}")
    for j, w in enumerate(ws):   # m = roundeven(w 2^(133 - E')): exact scaling, one rounding
        e(f"    %y{n}_{j} = scalar.fmaf {w}, %jq{n}, %magic : f32")
        e(f"    %yb{n}_{j} = scalar.bitcast %y{n}_{j} : f32 to i32")
        src.append(f"%yb{n}_{j}")


def row_iq3s(e, src, r):
    """IQ3_S row r: its block at %blk{r}; k-block kbl of the super-block: d @0, qs bytes 2 + 2 kbl (two grid words),
    qh byte 66 + kbl / 4 (bits 2 (kbl % 4), + 1), sign byte 74 + kbl (bit j: value j), scale byte 106 + kbl / 8."""
    n = f"{r}"
    e(f"    %dv{n} = vector.load %wv[%blk{n}] : view<[%nin]xi8> -> vector<2xi8>")
    e(f"    %dw{n} = vector.bitcast %dv{n} : vector<2xi8> to vector<1xi16>")
    e(f"    %d16_{n} = vector.extract %dw{n}[0] : vector<1xi16> -> i16")
    e(f"    %dh{n} = scalar.bitcast %d16_{n} : i16 to f16")
    e(f"    %d{n} = scalar.extf %dh{n} : f16 to f32")
    e(f"    %qa{n} = index.add %blk{n}, %qso : index")
    e(f"    %qv{n} = vector.load %wv[%qa{n}] : view<[%nin]xi8> -> vector<2xi8>")
    e(f"    %qw{n} = vector.bitcast %qv{n} : vector<2xi8> to vector<1xi16>")
    e(f"    %q16_{n} = vector.extract %qw{n}[0] : vector<1xi16> -> i16")
    e(f"    %q32_{n} = scalar.extui %q16_{n} : i16 to i32")
    for nm, off in (("qh", "%qho"), ("sg", "%sgo"), ("sc", "%sco")):
        e(f"    %{nm}a{n} = index.add %blk{n}, {off} : index")
        e(f"    %{nm}b{n} = view.load %wv[%{nm}a{n}] : view<[%nin]xi8> -> i8")
        e(f"    %{nm}{n} = scalar.extui %{nm}b{n} : i8 to i32")
    e(f"    %scs{n} = scalar.shrui %sc{n}, %nsh : i32")
    e(f"    %scn{n} = scalar.andi %scs{n}, %i15 : i32")
    e(f"    %sc2_{n} = scalar.shli %scn{n}, %i1 : i32")
    e(f"    %sc1_{n} = scalar.addi %sc2_{n}, %i1 : i32")
    e(f"    %scf{n} = scalar.sitofp %sc1_{n} : i32 to f32")
    e(f"    %s{n} = scalar.mulf %d{n}, %scf{n} : f32")          # d (1 + 2 sc), exact (11 x 5 bits)
    e(f"    %qhs{n} = scalar.shrui %qh{n}, %hsh : i32")
    gws = []
    for h in range(2):
        e(f"    %gl{n}_{h} = scalar.bitfield.extractu %q32_{n} {{offset = {8 * h}, width = 8}} : i32 -> i32")
        e(f"    %gh{n}_{h} = scalar.bitfield.extractu %qhs{n} {{offset = {h}, width = 1}} : i32 -> i32")
        e(f"    %gi{n}_{h} = scalar.fmai %gh{n}_{h}, %i256, %gl{n}_{h} : i32")
        e(f"    %gq{n}_{h} = index.cast %gi{n}_{h} : i32 to index")
        e(f"    %gd{n}_{h} = index.assume %gq{n}_{h} [range(%gq{n}_{h}, 0, 511)] : index")
        e(f"    %gw{n}_{h} = view.load %gv[%gd{n}_{h}] : view<512xi32> -> i32")
        gws.append(f"%gw{n}_{h}")
    ws = []
    for j in range(8):
        m = f"{n}_{j}"
        e(f"    %g{m} = scalar.bitfield.extractu {gws[j // 4]} {{offset = {8 * (j % 4)}, width = 8}} : i32 -> i32")
        e(f"    %sb{m} = scalar.bitfield.extractu %sg{n} {{offset = {j}, width = 1}} : i32 -> i32")
        e(f"    %sn{m} = scalar.subi %i0, %sb{m} : i32")
        e(f"    %gx{m} = scalar.xori %g{m}, %sn{m} : i32")
        e(f"    %gs{m} = scalar.addi %gx{m}, %sb{m} : i32")      # (-1)^sign g
        e(f"    %gf{m} = scalar.sitofp %gs{m} : i32 to f32")
        e(f"    %wv{m} = scalar.mulf %s{n}, %gf{m} : f32")        # exact (16 x 8 bits)
        ws.append(f"%wv{m}")
    bfp_tail(e, src, n, ws)


def body_iq3s(rows, K, stream=None):
    rb = K // 256 * 110
    L = []
    e = L.append
    I.prologue(e, rows, K, rb, 0, stream, blk=110)
    e("    %sb = index.div %kbi, %c32 : index")
    e("    %kbl = index.rem %kbi, %c32 : index")
    e("    %kq = index.rem %kbl, %c4 : index")
    e("    %k4 = index.div %kbl, %c4 : index")
    e("    %k8 = index.div %kbl, %c8 : index")
    e("    %k4h = index.rem %k4, %c2 : index")
    for nm, v in (("c66", 66), ("c74", 74), ("c106", 106)):
        e(f"    %{nm} = index.constant {v} : index")
    e("    %kbl2 = index.mul %kbl, %c2 : index")
    e("    %qso = index.add %kbl2, %c2 : index")
    e("    %qho = index.add %k4, %c66 : index")
    e("    %sgo = index.add %kbl, %c74 : index")
    e("    %sco = index.add %k8, %c106 : index")
    e("    %sbo = index.mul %sb, %c136 : index")      # (c136: the block size, prologue's blk)
    e("    %row0 = index.mul %g8, %c8 : index")
    e("    %rb0 = index.mul %row0, %crb : index")
    e("    %blkb = index.add %rb0, %sbo : index")
    e("    %kq_i = index.cast %kq : index to i32")
    e("    %k4h_i = index.cast %k4h : index to i32")
    for nm, v in (("i0", 0), ("i1", 1), ("i2", 2), ("i15", 15), ("i23", 23), ("i256", 256), ("i260", 260)):
        e(f"    %{nm} = scalar.constant {v} : i32")
    e("    %hsh = scalar.shli %kq_i, %i1 : i32")       # qh bits 2 (kbl % 4), + 1
    e("    %nsh = scalar.shli %k4h_i, %i2 : i32")      # the scale nibble: 4 ((kbl / 4) % 2)
    e("    %f127 = scalar.constant 127.0 : f32")
    e("    %magic = scalar.constant 12582912.0 : f32")
    src = []
    for r in range(8):
        e(f"    %ro{r} = index.constant {r * rb} : index")
        e(f"    %blk{r} = index.add %blkb, %ro{r} : index")
        row_iq3s(e, src, r)
    store(e, src)
    e("  }")
    return L


def row_q3k(e, src, r):
    """Q3_K row r: its block at %blk{r}; k-block kbl: hmask 8 B at 8 (kbl % 4) (bit %hbs), qs 8 B at 32 + 32 (kbl / 16)
    + 8 (kbl % 4) (crumb %qcs), sub-block i = kbl / 2: scale bytes 96 + i % 8 (nibble 4 (i / 8)) and 104 + i % 4
    (crumb 2 (i / 4)), d @108."""
    n = f"{r}"
    e(f"    %da{n} = index.add %blk{n}, %c108 : index")
    e(f"    %dv{n} = vector.load %wv[%da{n}] : view<[%nin]xi8> -> vector<2xi8>")
    e(f"    %dw{n} = vector.bitcast %dv{n} : vector<2xi8> to vector<1xi16>")
    e(f"    %d16_{n} = vector.extract %dw{n}[0] : vector<1xi16> -> i16")
    e(f"    %dh{n} = scalar.bitcast %d16_{n} : i16 to f16")
    e(f"    %d{n} = scalar.extf %dh{n} : f16 to f32")
    for nm, off in (("sl", "%slo"), ("sh", "%sho")):
        e(f"    %{nm}a{n} = index.add %blk{n}, {off} : index")
        e(f"    %{nm}b{n} = view.load %wv[%{nm}a{n}] : view<[%nin]xi8> -> i8")
        e(f"    %{nm}{n} = scalar.extui %{nm}b{n} : i8 to i32")
    e(f"    %sls{n} = scalar.shrui %sl{n}, %lsh : i32")
    e(f"    %sln{n} = scalar.andi %sls{n}, %i15 : i32")
    e(f"    %shs{n} = scalar.shrui %sh{n}, %hsh2 : i32")
    e(f"    %shn{n} = scalar.andi %shs{n}, %i3 : i32")
    e(f"    %scv{n} = scalar.fmai %shn{n}, %i16, %sln{n} : i32")
    e(f"    %scm{n} = scalar.subi %scv{n}, %i32 : i32")
    e(f"    %scf{n} = scalar.sitofp %scm{n} : i32 to f32")
    e(f"    %s{n} = scalar.mulf %d{n}, %scf{n} : f32")          # d (sc - 32), exact (11 x 6 bits)
    words = {}
    for nm, off, sh in (("hm", "%hmo", "%hbs"), ("qs", "%qso", "%qcs")):
        e(f"    %{nm}a{n} = index.add %blk{n}, {off} : index")
        e(f"    %{nm}v{n} = vector.load %wv[%{nm}a{n}] : view<[%nin]xi8> -> vector<8xi8>")
        e(f"    %{nm}w{n} = vector.bitcast %{nm}v{n} : vector<8xi8> to vector<2xi32>")
        for h in range(2):
            e(f"    %{nm}x{n}_{h} = vector.extract %{nm}w{n}[{h}] : vector<2xi32> -> i32")
            e(f"    %{nm}y{n}_{h} = scalar.shrui %{nm}x{n}_{h}, {sh} : i32")
        words[nm] = [f"%{nm}y{n}_{h}" for h in range(2)]
    ws = []
    for j in range(8):
        m = f"{n}_{j}"
        o = 8 * (j % 4)
        e(f"    %cr{m} = scalar.bitfield.extractu {words['qs'][j // 4]} {{offset = {o}, width = 2}} : i32 -> i32")
        e(f"    %hb{m} = scalar.bitfield.extractu {words['hm'][j // 4]} {{offset = {o}, width = 1}} : i32 -> i32")
        e(f"    %qq{m} = scalar.fmai %hb{m}, %i4, %cr{m} : i32")
        e(f"    %qm{m} = scalar.subi %qq{m}, %i4 : i32")
        e(f"    %qf{m} = scalar.sitofp %qm{m} : i32 to f32")
        e(f"    %wv{m} = scalar.mulf %s{n}, %qf{m} : f32")        # exact (17 x 3 bits)
        ws.append(f"%wv{m}")
    bfp_tail(e, src, n, ws)


def body_q3k(rows, K, stream=None):
    rb = K // 256 * 110
    L = []
    e = L.append
    I.prologue(e, rows, K, rb, 0, stream, blk=110)
    e("    %sb = index.div %kbi, %c32 : index")
    e("    %kbl = index.rem %kbi, %c32 : index")
    for nm, v in (("c96", 96), ("c104", 104), ("c108", 108), ("c16i", 16)):
        e(f"    %{nm} = index.constant {v} : index")
    e("    %kq = index.rem %kbl, %c4 : index")
    e("    %kh = index.div %kbl, %c16i : index")     # value half (e / 128)
    e("    %k16 = index.rem %kbl, %c16i : index")
    e("    %kc = index.div %k16, %c4 : index")       # crumb (e % 128) / 32
    e("    %si = index.div %kbl, %c2 : index")       # sub-block of 16
    e("    %si8 = index.rem %si, %c8 : index")
    e("    %siq = index.div %si, %c8 : index")
    e("    %si4 = index.rem %si, %c4 : index")
    e("    %sid = index.div %si, %c4 : index")
    e("    %kqo = index.mul %kq, %c8 : index")
    e("    %hmo = index.add %kqo, %c0i : index")
    e("    %kho = index.mul %kh, %c32 : index")
    e("    %qs0 = index.add %kho, %kqo : index")
    e("    %qso = index.add %qs0, %c32 : index")
    e("    %slo = index.add %si8, %c96 : index")
    e("    %sho = index.add %si4, %c104 : index")
    e("    %sbo = index.mul %sb, %c136 : index")      # (c136: the block size, prologue's blk)
    e("    %row0 = index.mul %g8, %c8 : index")
    e("    %rb0 = index.mul %row0, %crb : index")
    e("    %blkb = index.add %rb0, %sbo : index")
    for nm in ("kh", "kc", "siq", "sid"):
        e(f"    %{nm}_i = index.cast %{nm} : index to i32")
    for nm, v in (("i0", 0), ("i1", 1), ("i2", 2), ("i3", 3), ("i4", 4), ("i15", 15), ("i16", 16), ("i23", 23),
                  ("i32", 32), ("i260", 260)):
        e(f"    %{nm} = scalar.constant {v} : i32")
    e("    %kh4 = scalar.shli %kh_i, %i2 : i32")
    e("    %hbs = scalar.addi %kh4, %kc_i : i32")       # hmask bit 4 (e / 128) + (e % 128) / 32
    e("    %qcs = scalar.shli %kc_i, %i1 : i32")        # crumb shift 2 ((e % 128) / 32)
    e("    %lsh = scalar.shli %siq_i, %i2 : i32")       # scale nibble 4 (i / 8)
    e("    %hsh2 = scalar.shli %sid_i, %i1 : i32")      # scale crumb 2 (i / 4)
    e("    %f127 = scalar.constant 127.0 : f32")
    e("    %magic = scalar.constant 12582912.0 : f32")
    src = []
    for r in range(8):
        e(f"    %ro{r} = index.constant {r * rb} : index")
        e(f"    %blk{r} = index.add %blkb, %ro{r} : index")
        row_q3k(e, src, r)
    store(e, src)
    e("  }")
    return L


def ld16(e, n, nm, off):
    """The u16 at %blk{n} + off -> %{nm}{n} (i32)."""
    e(f"    %{nm}a{n} = index.add %blk{n}, {off} : index")
    e(f"    %{nm}v{n} = vector.load %wv[%{nm}a{n}] : view<[%nin]xi8> -> vector<2xi8>")
    e(f"    %{nm}w{n} = vector.bitcast %{nm}v{n} : vector<2xi8> to vector<1xi16>")
    e(f"    %{nm}h{n} = vector.extract %{nm}w{n}[0] : vector<1xi16> -> i16")
    e(f"    %{nm}{n} = scalar.extui %{nm}h{n} : i16 to i32")


def ld8(e, n, nm, off):
    e(f"    %{nm}a{n} = index.add %blk{n}, {off} : index")
    e(f"    %{nm}b{n} = view.load %wv[%{nm}a{n}] : view<[%nin]xi8> -> i8")
    e(f"    %{nm}{n} = scalar.extui %{nm}b{n} : i8 to i32")


def gload(e, n, nm, idx, words):
    """Grid word idx (i32 SSA, < words) -> %{nm}{n} (i32)."""
    e(f"    %{nm}x{n} = index.cast {idx} : i32 to index")
    e(f"    %{nm}d{n} = index.assume %{nm}x{n} [range(%{nm}x{n}, 0, {words - 1})] : index")
    e(f"    %{nm}{n} = view.load %gv[%{nm}d{n}] : view<{words}xi32> -> i32")


def ksign(e, n, f):
    """7-bit field f -> %ks{n} = f | parity(f) << 7."""
    e(f"    %kpa{n} = scalar.shrui {f}, %i4 : i32")
    e(f"    %kpb{n} = scalar.xori {f}, %kpa{n} : i32")
    e(f"    %kpc{n} = scalar.shrui %kpb{n}, %i2 : i32")
    e(f"    %kpd{n} = scalar.xori %kpb{n}, %kpc{n} : i32")
    e(f"    %kpe{n} = scalar.shrui %kpd{n}, %i1 : i32")
    e(f"    %kpf{n} = scalar.xori %kpd{n}, %kpe{n} : i32")
    e(f"    %kpg{n} = scalar.andi %kpf{n}, %i1 : i32")
    e(f"    %kph{n} = scalar.shli %kpg{n}, %i7 : i32")
    e(f"    %ks{n} = scalar.ori {f}, %kph{n} : i32")


def row_g2(e, src, fmt, r):
    """IQ3_XXS / IQ2_XS / IQ2_S row r (its block at %blk{r}), k-block kbl (offsets from body_g2)."""
    n = f"{r}"
    W = GRIDW[fmt]
    e(f"    %dv{n} = vector.load %wv[%blk{n}] : view<[%nin]xi8> -> vector<2xi8>")
    e(f"    %dw{n} = vector.bitcast %dv{n} : vector<2xi8> to vector<1xi16>")
    e(f"    %d16_{n} = vector.extract %dw{n}[0] : vector<1xi16> -> i16")
    e(f"    %dh{n} = scalar.bitcast %d16_{n} : i16 to f16")
    e(f"    %d{n} = scalar.extf %dh{n} : f16 to f32")
    if fmt == "IQ3_XXS":   # qs u16 at 2 + 2 kbl (two grid indices), aux word 66 + 4 (kbl / 4): s = aux >> 28
        ld16(e, n, "q", "%qso")
        e(f"    %axa{n} = index.add %blk{n}, %axo : index")
        e(f"    %axv{n} = vector.load %wv[%axa{n}] : view<[%nin]xi8> -> vector<4xi8>")
        e(f"    %axw{n} = vector.bitcast %axv{n} : vector<4xi8> to vector<1xi32>")
        e(f"    %ax{n} = vector.extract %axw{n}[0] : vector<1xi32> -> i32")
        e(f"    %scn{n} = scalar.shrui %ax{n}, %i28 : i32")
        e(f"    %fs{n} = scalar.shrui %ax{n}, %fsh : i32")
        e(f"    %f{n} = scalar.andi %fs{n}, %i127 : i32")
        ksign(e, n, f"%f{n}")
        sgn = f"%ks{n}"
        e(f"    %gi0_{n} = scalar.andi %q{n}, %i255 : i32")
        e(f"    %gi1_{n} = scalar.shrui %q{n}, %i8 : i32")
        gload(e, n, "gwa", f"%gi0_{n}", W)
        gload(e, n, "gwb", f"%gi1_{n}", W)
        fold = "%f0p25"
    else:
        if fmt == "IQ2_XS":   # q u16 at 2 + 2 kbl: grid entry q & 511, sign field q >> 9
            ld16(e, n, "q", "%qso")
            e(f"    %gi{n} = scalar.andi %q{n}, %i511 : i32")
            e(f"    %f{n} = scalar.shrui %q{n}, %i9 : i32")
            ksign(e, n, f"%f{n}")
            sgn = f"%ks{n}"
        else:                 # IQ2_S: qs byte 2 + kbl, qh crumb, sign byte 34 + kbl
            ld8(e, n, "qs", "%qso")
            ld8(e, n, "qh", "%qho")
            ld8(e, n, "sg", "%sgo")
            e(f"    %qhs{n} = scalar.shrui %qh{n}, %hsh : i32")
            e(f"    %qh2_{n} = scalar.andi %qhs{n}, %i3 : i32")
            e(f"    %gi{n} = scalar.fmai %qh2_{n}, %i256, %qs{n} : i32")
            sgn = f"%sg{n}"
        ld8(e, n, "sc", "%sco")   # the scale byte; nibble 4 ((kbl / 2) % 2)
        e(f"    %scs{n} = scalar.shrui %sc{n}, %nsh : i32")
        e(f"    %scn{n} = scalar.andi %scs{n}, %i15 : i32")
        e(f"    %gw2_{n} = scalar.shli %gi{n}, %i1 : i32")   # an entry is 2 words (8 values)
        e(f"    %gw3_{n} = scalar.addi %gw2_{n}, %i1 : i32")
        gload(e, n, "gwa", f"%gw2_{n}", W)
        gload(e, n, "gwb", f"%gw3_{n}", W)
        fold = "%f0p125"
    e(f"    %sc2_{n} = scalar.shli %scn{n}, %i1 : i32")
    e(f"    %sc1_{n} = scalar.addi %sc2_{n}, %i1 : i32")
    e(f"    %scf{n} = scalar.sitofp %sc1_{n} : i32 to f32")
    e(f"    %s0_{n} = scalar.mulf %d{n}, %scf{n} : f32")        # d (1 + 2 s), exact
    e(f"    %s{n} = scalar.mulf %s0_{n}, {fold} : f32")        # / 4 or / 8, exact
    gws = [f"%gwa{n}", f"%gwb{n}"]
    ws = []
    for j in range(8):
        m = f"{n}_{j}"
        e(f"    %g{m} = scalar.bitfield.extractu {gws[j // 4]} {{offset = {8 * (j % 4)}, width = 8}} : i32 -> i32")
        e(f"    %sb{m} = scalar.bitfield.extractu {sgn} {{offset = {j}, width = 1}} : i32 -> i32")
        e(f"    %sn{m} = scalar.subi %i0, %sb{m} : i32")
        e(f"    %gx{m} = scalar.xori %g{m}, %sn{m} : i32")
        e(f"    %gs{m} = scalar.addi %gx{m}, %sb{m} : i32")
        e(f"    %gf{m} = scalar.sitofp %gs{m} : i32 to f32")
        e(f"    %wv{m} = scalar.mulf %s{n}, %gf{m} : f32")
        ws.append(f"%wv{m}")
    bfp_tail(e, src, n, ws)


def body_g2(fmt, rows, K, stream=None):
    blk = BLK[fmt]
    rb = K // 256 * blk
    L = []
    e = L.append
    I.prologue(e, rows, K, rb, 0, stream, blk=blk)
    e("    %sb = index.div %kbi, %c32 : index")
    e("    %kbl = index.rem %kbi, %c32 : index")
    e("    %kq = index.rem %kbl, %c4 : index")
    e("    %k4 = index.div %kbl, %c4 : index")
    e("    %k2 = index.div %kbl, %c2 : index")
    e("    %k2h = index.rem %k2, %c2 : index")
    for nm, v in (("c34", 34), ("c66", 66), ("c74", 74)):
        e(f"    %{nm} = index.constant {v} : index")
    if fmt == "IQ2_S":
        e("    %qso = index.add %kbl, %c2 : index")
        e("    %qho = index.add %k4, %c66 : index")
        e("    %sgo = index.add %kbl, %c34 : index")
        e("    %sco = index.add %k4, %c74 : index")
    else:
        e("    %kbl2 = index.mul %kbl, %c2 : index")
        e("    %qso = index.add %kbl2, %c2 : index")
        if fmt == "IQ3_XXS":
            e("    %k44 = index.mul %k4, %c4 : index")
            e("    %axo = index.add %k44, %c66 : index")
        else:
            e("    %sco = index.add %k4, %c66 : index")
    e("    %sbo = index.mul %sb, %c136 : index")      # (c136: the block size, prologue's blk)
    e("    %row0 = index.mul %g8, %c8 : index")
    e("    %rb0 = index.mul %row0, %crb : index")
    e("    %blkb = index.add %rb0, %sbo : index")
    e("    %kq_i = index.cast %kq : index to i32")
    e("    %k2h_i = index.cast %k2h : index to i32")
    for nm, v in (("i0", 0), ("i1", 1), ("i2", 2), ("i3", 3), ("i4", 4), ("i7", 7), ("i8", 8), ("i9", 9),
                  ("i15", 15), ("i23", 23), ("i28", 28), ("i127", 127), ("i255", 255), ("i256", 256),
                  ("i260", 260), ("i511", 511)):
        e(f"    %{nm} = scalar.constant {v} : i32")
    e("    %hsh = scalar.shli %kq_i, %i1 : i32")       # IQ2_S qh crumb 2 (kbl % 4)
    e("    %fsh = scalar.muli %kq_i, %i7 : i32")       # IQ3_XXS sign field 7 (kbl % 4)
    e("    %nsh = scalar.shli %k2h_i, %i2 : i32")      # scale nibble 4 ((kbl / 2) % 2)
    e("    %f127 = scalar.constant 127.0 : f32")
    e("    %f0p25 = scalar.constant 0.25 : f32")
    e("    %f0p125 = scalar.constant 0.125 : f32")
    e("    %magic = scalar.constant 12582912.0 : f32")
    src = []
    for r in range(8):
        e(f"    %ro{r} = index.constant {r * rb} : index")
        e(f"    %blk{r} = index.add %blkb, %ro{r} : index")
        row_g2(e, src, fmt, r)
    store(e, src)
    e("  }")
    return L


def body(fmt, rows, K, stream=None):
    if fmt in ("IQ3_XXS", "IQ2_XS", "IQ2_S"):
        return body_g2(fmt, rows, K, stream)
    if fmt == "Q3_K":
        return body_q3k(rows, K, stream)
    if fmt == "IQ3_S":
        return body_iq3s(rows, K, stream)
    rb = K // 256 * BLK[fmt]
    L = []
    e = L.append
    I.prologue(e, rows, K, rb, 0, stream, blk=BLK[fmt])
    # k-block kbi: super-block kbi / 32; sub-block s = (kbi % 32) / 4 (32 values), its quarter kq = kbi % 4;
    # qs bytes 32 (s / 2) + 8 kq (nibble half s % 2); Q5_K: qh bytes 8 kq, bit s; scale bytes s % 4
    e("    %sb = index.div %kbi, %c32 : index")
    e("    %kbl = index.rem %kbi, %c32 : index")
    e("    %s = index.div %kbl, %c4 : index")
    e("    %kq = index.rem %kbl, %c4 : index")
    e("    %sj = index.div %s, %c2 : index")
    e("    %shf = index.rem %s, %c2 : index")
    e("    %sa = index.rem %s, %c4 : index")
    e("    %sg = index.div %s, %c4 : index")
    e(f"    %cqs = index.constant {QS[fmt]} : index")
    e("    %sbo = index.mul %sb, %c136 : index")      # (c136: the block size, prologue's blk)
    e("    %sjo = index.mul %sj, %c32 : index")
    e("    %kqo = index.mul %kq, %c8 : index")
    e("    %qs0 = index.add %sjo, %kqo : index")
    e("    %qso = index.add %qs0, %cqs : index")
    if fmt == "Q5_K":
        e("    %qho = index.add %kqo, %c16 : index")
    e("    %row0 = index.mul %g8, %c8 : index")
    e("    %rb0 = index.mul %row0, %crb : index")
    e("    %blkb = index.add %rb0, %sbo : index")
    e("    %s_i = index.cast %s : index to i32")
    e("    %shf_i = index.cast %shf : index to i32")
    e("    %sa_i = index.cast %sa : index to i32")
    e("    %sg_i = index.cast %sg : index to i32")
    for nm, v in (("i0", 0), ("i1", 1), ("i2", 2), ("i3", 3), ("i4", 4), ("i6", 6), ("i15", 15), ("i16", 16),
                  ("i23", 23), ("i63", 63), ("i128", 128), ("i255", 255), ("i260", 260), ("i7fff", 0x7FFF),
                  ("ihi", -65536)):
        e(f"    %{nm} = scalar.constant {v} : i32")
    e("    %sh8a = scalar.shli %sa_i, %i3 : i32")      # 8 (s % 4)
    e("    %nsh = scalar.shli %shf_i, %i2 : i32")      # 0 (low nibbles) or 4 (high)
    e("    %selm = scalar.subi %i0, %sg_i : i32")      # all ones for s >= 4
    e("    %f127 = scalar.constant 127.0 : f32")
    e("    %fm128 = scalar.constant -128.0 : f32")
    e("    %magic = scalar.constant 12582912.0 : f32")   # 1.5 2^23: x + magic rounds x to even, in the low bits
    src = []
    for r in range(8):
        e(f"    %ro{r} = index.constant {r * rb} : index")
        e(f"    %blk{r} = index.add %blkb, %ro{r} : index")
        row(e, src, fmt, r)
    store(e, src)
    e("  }")
    return L


