#!/usr/bin/env python3
"""Emit the GPU Q4_K / Q5_K -> NPU bfp16ebs8 weight decoder: the NPU decoder's exact values and rounding, on the GPU
(row 5 swap: the GPU decodes a pair layer's gate / up into the swap's weight stream).

Input: rows [rows][K / 256][144 B] (block_q4_K) or [176 B] (block_q5_K). Output: as gen_iq4xs_bfp (fragments of 8 rows
x 8 k, per row [E u8][8 x int8 m]; row-major, or the swap's stream).
Values: gen_npu_dec.weights() of the gather-free path (Q4_K's "GF" order, the pair layers' form, and Q5_K): per
sub-block T = d sc and M = -dmin m, each split into two bf16 parts (RNE, then the RNE of the remainder); X = 128 + q
(q = nibble + 16 h, h = 0 for Q4_K); in f32, in the NPU kernel's order: w = M0 + M1, + T0 (-128), + T1 (-128), + T0 X,
+ T1 X. Every product is exact (8-bit T part times a <= 8-bit X), so a fused multiply-add rounds as the kernel does.
E / m: npu_dec_emit.bfp_hw, as gen_iq4xs_bfp (the exponent of max |w|, + 1 when the largest value rounds to 128).
"""
import sys

import gen_iq4xs_bfp as I

WG = I.WG
BLK = {"Q4_K": 144, "Q5_K": 176}
QS = {"Q4_K": 16, "Q5_K": 48}   # the qs bytes' offset in a block (Q5_K: qh 32 B at 16 first)


def out_bytes(rows, K, stream=None):
    return I.out_bytes(rows, K, stream)


def items(rows, K):
    return I.items(rows, K)


def gen(fmt, rows, K, stream=None):
    assert fmt in BLK and rows % 8 == 0 and K % 256 == 0
    rb = K // 256 * BLK[fmt]
    n = items(rows, K)
    nin, nout = rows * rb, out_bytes(rows, K, stream)
    L = []
    e = L.append
    e(f"// GENERATED by tools/gen_kq_bfp.py ({fmt} rows={rows} K={K}" + (f" stream={stream}" if stream else "")
      + ") -- edit the generator.")
    e("amdgpu.target<gfx1151> @yah_wave32 {subgroup_size = 32}")
    e("")
    e("kernel.def target(@yah_wave32) @yah_kq_bfp() {")
    e("  %unit = index.constant 1 : index")
    e(f"  %wgs = index.constant {(n + WG - 1) // WG} : index")
    e(f"  %wgsz = index.constant {WG} : index")
    e("  kernel.launch.config workgroups(%wgs, %unit, %unit) workgroup_size(%wgsz, %unit, %unit) : index")
    e("} launch(%w: buffer, %out: buffer) {")
    e("  %base = index.constant 0 : offset")
    e(f"  %nin = index.constant {nin} : index")
    e(f"  %nout = index.constant {nout} : index")
    e("  %w_na, %out_na = buffer.assume.noalias %w, %out : buffer, buffer")
    e("  %wv = buffer.view %w_na[%base] : buffer -> view<[%nin]xi8>")
    e("  %ov = buffer.view %out_na[%base] : buffer -> view<[%nout]xi8>")
    e("  %wg = kernel.workgroup.id<x> : index")
    e("  %tid = kernel.workitem.id<x> : index")
    e(f"  %cwg = index.constant {WG} : index")
    e("  %item0 = index.mul %wg, %cwg : index")
    e("  %item = index.add %item0, %tid : index")
    L += body(fmt, rows, K, stream)
    e("  kernel.return")
    e("}")
    return "\n".join(L) + "\n"


def rne(e, n, x):
    """f32 x -> its nearest-even bf16 as f32 (npu_dec_emit.bf16_rne), named %{n}."""
    e(f"    %{n}_u = scalar.bitcast {x} : f32 to i32")
    e(f"    %{n}_l = scalar.shrui %{n}_u, %i16 : i32")
    e(f"    %{n}_o = scalar.andi %{n}_l, %i1 : i32")
    e(f"    %{n}_a = scalar.addi %{n}_u, %i7fff : i32")
    e(f"    %{n}_b = scalar.addi %{n}_a, %{n}_o : i32")
    e(f"    %{n}_c = scalar.andi %{n}_b, %ihi : i32")
    e(f"    %{n} = scalar.bitcast %{n}_c : i32 to f32")


def parts2(e, n, x):
    """f32 x -> %{n}0, %{n}1 (gen_npu_dec.parts2: the RNE, then the RNE of the exact remainder)."""
    rne(e, f"{n}0", x)
    e(f"    %{n}r = scalar.subf {x}, %{n}0 : f32")
    rne(e, f"{n}1", f"%{n}r")


def row(e, src, fmt, r):
    """Row r of the fragment: its block at %blk{r}; 1 E source and 8 mantissa sources appended to src."""
    n = f"{r}"
    e(f"    %hdr{n} = vector.load %wv[%blk{n}] : view<[%nin]xi8> -> vector<16xi8>")
    e(f"    %hdw{n} = vector.bitcast %hdr{n} : vector<16xi8> to vector<4xi32>")
    for h in range(4):
        e(f"    %hw{h}_{n} = vector.extract %hdw{n}[{h}] : vector<4xi32> -> i32")
    e(f"    %d16_{n} = scalar.trunci %hw0_{n} : i32 to i16")
    e(f"    %dh{n} = scalar.bitcast %d16_{n} : i16 to f16")
    e(f"    %d{n} = scalar.extf %dh{n} : f16 to f32")
    e(f"    %dmw{n} = scalar.shrui %hw0_{n}, %i16 : i32")
    e(f"    %dm16_{n} = scalar.trunci %dmw{n} : i32 to i16")
    e(f"    %dmh{n} = scalar.bitcast %dm16_{n} : i16 to f16")
    e(f"    %dm{n} = scalar.extf %dmh{n} : f16 to f32")
    # scale bytes s % 4 of words 1..3 (bytes 4 + a, 8 + a, 12 + a); sub-block s < 4: sc = b1 & 63, m = b2 & 63;
    # s >= 4: sc = b3 & 15 | (b1 >> 6) << 4, m = b3 >> 4 | (b2 >> 6) << 4 (picked by the mask %selm: s >= 4)
    for h in (1, 2, 3):
        e(f"    %bs{h}_{n} = scalar.shrui %hw{h}_{n}, %sh8a : i32")
        e(f"    %b{h}_{n} = scalar.andi %bs{h}_{n}, %i255 : i32")
    e(f"    %scl{n} = scalar.andi %b1_{n}, %i63 : i32")
    e(f"    %mnl{n} = scalar.andi %b2_{n}, %i63 : i32")
    e(f"    %t1_{n} = scalar.shrui %b1_{n}, %i6 : i32")
    e(f"    %t1s{n} = scalar.shli %t1_{n}, %i4 : i32")
    e(f"    %b3l{n} = scalar.andi %b3_{n}, %i15 : i32")
    e(f"    %sch{n} = scalar.ori %b3l{n}, %t1s{n} : i32")
    e(f"    %t2_{n} = scalar.shrui %b2_{n}, %i6 : i32")
    e(f"    %t2s{n} = scalar.shli %t2_{n}, %i4 : i32")
    e(f"    %b3h{n} = scalar.shrui %b3_{n}, %i4 : i32")
    e(f"    %mnh{n} = scalar.ori %b3h{n}, %t2s{n} : i32")
    for v in ("sc", "mn"):
        e(f"    %{v}x{n} = scalar.xori %{v}l{n}, %{v}h{n} : i32")
        e(f"    %{v}y{n} = scalar.andi %{v}x{n}, %selm : i32")
        e(f"    %{v}{n} = scalar.xori %{v}l{n}, %{v}y{n} : i32")
    e(f"    %scf{n} = scalar.sitofp %sc{n} : i32 to f32")
    e(f"    %mnf{n} = scalar.sitofp %mn{n} : i32 to f32")
    e(f"    %T{n} = scalar.mulf %d{n}, %scf{n} : f32")         # d sc, exact (11 x 6 bits)
    e(f"    %Mp{n} = scalar.mulf %dm{n}, %mnf{n} : f32")
    e(f"    %M{n} = scalar.negf %Mp{n} : f32")                 # -dmin m, exact
    parts2(e, f"Tp{n}_", f"%T{n}")
    parts2(e, f"Mq{n}_", f"%M{n}")
    e(f"    %qa{n} = index.add %blk{n}, %qso : index")
    e(f"    %qb{n} = vector.load %wv[%qa{n}] : view<[%nin]xi8> -> vector<8xi8>")
    e(f"    %qw{n} = vector.bitcast %qb{n} : vector<8xi8> to vector<2xi32>")
    if fmt == "Q5_K":
        e(f"    %ha{n} = index.add %blk{n}, %qho : index")
        e(f"    %hb{n} = vector.load %wv[%ha{n}] : view<[%nin]xi8> -> vector<8xi8>")
        e(f"    %qhw{n} = vector.bitcast %hb{n} : vector<8xi8> to vector<2xi32>")
    for h in range(2):
        e(f"    %qx{n}_{h} = vector.extract %qw{n}[{h}] : vector<2xi32> -> i32")
        e(f"    %qy{n}_{h} = scalar.shrui %qx{n}_{h}, %nsh : i32")
        if fmt == "Q5_K":
            e(f"    %hx{n}_{h} = vector.extract %qhw{n}[{h}] : vector<2xi32> -> i32")
            e(f"    %hy{n}_{h} = scalar.shrui %hx{n}_{h}, %s_i : i32")
    e(f"    %wz0_{n} = scalar.addf %Mq{n}_0, %Mq{n}_1 : f32")
    e(f"    %wz1_{n} = scalar.fmaf %Tp{n}_0, %fm128, %wz0_{n} : f32")
    e(f"    %wzb{n} = scalar.fmaf %Tp{n}_1, %fm128, %wz1_{n} : f32")
    ws = []
    for j in range(8):
        m = f"{n}_{j}"
        o = 8 * (j % 4)
        e(f"    %q{m} = scalar.bitfield.extractu %qy{n}_{j // 4} {{offset = {o}, width = 4}} : i32 -> i32")
        if fmt == "Q5_K":
            e(f"    %h{m} = scalar.bitfield.extractu %hy{n}_{j // 4} {{offset = {o}, width = 1}} : i32 -> i32")
            e(f"    %qh{m} = scalar.fmai %h{m}, %i16, %q{m} : i32")
            q = f"%qh{m}"
        else:
            q = f"%q{m}"
        e(f"    %xi{m} = scalar.addi {q}, %i128 : i32")
        e(f"    %X{m} = scalar.sitofp %xi{m} : i32 to f32")
        e(f"    %wt{m} = scalar.fmaf %Tp{n}_0, %X{m}, %wzb{n} : f32")
        e(f"    %wv{m} = scalar.fmaf %Tp{n}_1, %X{m}, %wt{m} : f32")
        ws.append(f"%wv{m}")
    # E: the exponent of max |w|; the bump: the largest value rounds to 128 (only a positive one can leave int8)
    am, pm = None, None
    for j, w in enumerate(ws):
        e(f"    %aw{n}_{j} = scalar.absf {w} : f32")
        if j:
            e(f"    %am{n}_{j} = scalar.maxnumf {am}, %aw{n}_{j} : f32")
            e(f"    %px{n}_{j} = scalar.maxnumf {pm}, {w} : f32")
            am, pm = f"%am{n}_{j}", f"%px{n}_{j}"
        else:
            am, pm = f"%aw{n}_0", w
    e(f"    %mb{n} = scalar.bitcast {am} : f32 to i32")
    e(f"    %E{n} = scalar.bitfield.extractu %mb{n} {{offset = 23, width = 8}} : i32 -> i32")
    e(f"    %ie{n} = scalar.subi %i260, %E{n} : i32")
    e(f"    %ib{n} = scalar.shli %ie{n}, %i23 : i32")
    e(f"    %iq{n} = scalar.bitcast %ib{n} : i32 to f32")          # 2^(133 - E)
    e(f"    %ps{n} = scalar.mulf {pm}, %iq{n} : f32")
    e(f"    %pr{n} = scalar.roundevenf %ps{n} : f32")
    e(f"    %bu{n} = scalar.cmpf ogt, %pr{n}, %f127 : f32")
    e(f"    %Ep{n} = scalar.addi %E{n}, %i1 : i32")
    e(f"    %E1_{n} = scf.select %bu{n}, %Ep{n}, %E{n} : i32")
    e(f"    %je{n} = scalar.subi %i260, %E1_{n} : i32")
    e(f"    %jb{n} = scalar.shli %je{n}, %i23 : i32")
    e(f"    %jq{n} = scalar.bitcast %jb{n} : i32 to f32")          # 2^(133 - E')
    src.append(f"%E1_{n}")
    for j, w in enumerate(ws):   # m = roundeven(w 2^(133 - E')): exact scaling, one rounding
        e(f"    %y{n}_{j} = scalar.fmaf {w}, %jq{n}, %magic : f32")
        e(f"    %yb{n}_{j} = scalar.bitcast %y{n}_{j} : f32 to i32")
        src.append(f"%yb{n}_{j}")


def body(fmt, rows, K, stream=None):
    rb = K // 256 * BLK[fmt]
    L = []
    e = L.append
    I.prologue(e, rows, K, rb, 0, stream, blk=BLK[fmt])
    # k-block kbi: super-block kbi / 32; sub-block s = (kbi % 32) / 4 (32 values), its quarter kq = kbi % 4;
    # qs bytes 32 (s / 2) + 8 kq (nibble half s % 2); Q5_K: qh bytes 8 kq, bit s; scale bytes s % 4
    e("    %sb = index.div %kbi, %c32 : index")
    e("    %kbl = index.rem %kbi, %c32 : index")
    e("    %s = index.div %kbl, %c4 : index")
    e("    %kq = index.rem %kbl, %c4 : index")
    e("    %sj = index.div %s, %c2 : index")
    e("    %shf = index.rem %s, %c2 : index")
    e("    %sa = index.rem %s, %c4 : index")
    e("    %sg = index.div %s, %c4 : index")
    e(f"    %cqs = index.constant {QS[fmt]} : index")
    e("    %sbo = index.mul %sb, %c136 : index")      # (c136: the block size, prologue's blk)
    e("    %sjo = index.mul %sj, %c32 : index")
    e("    %kqo = index.mul %kq, %c8 : index")
    e("    %qs0 = index.add %sjo, %kqo : index")
    e("    %qso = index.add %qs0, %cqs : index")
    if fmt == "Q5_K":
        e("    %qho = index.add %kqo, %c16 : index")
    e("    %row0 = index.mul %g8, %c8 : index")
    e("    %rb0 = index.mul %row0, %crb : index")
    e("    %blkb = index.add %rb0, %sbo : index")
    e("    %s_i = index.cast %s : index to i32")
    e("    %shf_i = index.cast %shf : index to i32")
    e("    %sa_i = index.cast %sa : index to i32")
    e("    %sg_i = index.cast %sg : index to i32")
    for nm, v in (("i0", 0), ("i1", 1), ("i2", 2), ("i3", 3), ("i4", 4), ("i6", 6), ("i15", 15), ("i16", 16),
                  ("i23", 23), ("i63", 63), ("i128", 128), ("i255", 255), ("i260", 260), ("i7fff", 0x7FFF),
                  ("ihi", -65536)):
        e(f"    %{nm} = scalar.constant {v} : i32")
    e("    %sh8a = scalar.shli %sa_i, %i3 : i32")      # 8 (s % 4)
    e("    %nsh = scalar.shli %shf_i, %i2 : i32")      # 0 (low nibbles) or 4 (high)
    e("    %selm = scalar.subi %i0, %sg_i : i32")      # all ones for s >= 4
    e("    %f127 = scalar.constant 127.0 : f32")
    e("    %fm128 = scalar.constant -128.0 : f32")
    e("    %magic = scalar.constant 12582912.0 : f32")   # 1.5 2^23: x + magic rounds x to even, in the low bits
    src = []
    for r in range(8):
        e(f"    %ro{r} = index.constant {r * rb} : index")
        e(f"    %blk{r} = index.add %blkb, %ro{r} : index")
        row(e, src, fmt, r)
    I.st(e, I.pack(e, src), "%frag")
    e("  }")
    return L


def main():
    if len(sys.argv) != 4:
        sys.exit("usage: gen_kq_bfp.py <Q4_K|Q5_K> <rows> <K>")
    sys.stdout.write(gen(sys.argv[1], int(sys.argv[2]), int(sys.argv[3])))


if __name__ == "__main__":
    main()
