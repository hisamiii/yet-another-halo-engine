#!/usr/bin/env python3
"""Tile GEMM yah_iu4_gemm[_swiglu|_kres|_kqg]: MQ4G256 weights x int4 activations (the A4 path) on v_wmma_i32_16x16x16_iu4.

Weights: MQ4G256 rows (136 B per 256 K: f16 scale0, zero0, scale1, zero1, 128 B of nibbles), the loader's signed codes, so
w = code * scale per 128 K. Activations: gen_rot.gen_q's int4 rows (aq, [tokens][K / 2] bytes) and f32 scales (ad, one per
128 values of each token).
Workgroup: BM rows x BN tokens over WM x WN wave32 waves, TM x TN each. Per 128-K phase the workgroup stages the weight
nibbles, the phase's weight scales and the activation nibbles in LDS (double-buffered, one barrier per phase); each wave
runs 8 k steps of i32 WMMAs into zeroed accumulators, then folds them into its f32 accumulators:
acc += f32(c) * (weight scale * activation scale).
The iu4 C layout (wave32): element i of lane l is row 2 i + l / 16, token l % 16, so the weight scale is a per-element
vector (LDS holds each 16-row tile's scales in that order) and the activation scale is one value per lane.
Epilogues: gen_gemm_tile.lds_epilogue (kstore, kres, swiglu, kqg); the 48-row tile (TM 16) stores its f32 fragments.
Bindings: weight, aq, ad, then kstore: output; kres: resid, output; swiglu: gate, output (f16); kqg: output (q), gate_out.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen_gemm_tile as TG  # noqa: E402

KP = 128        # K per phase: one weight scale group
WP = 18         # LDS dwords per staged row: 16 of nibbles + 2 of pad
V8 = "vector<8xf32>"
VI = "vector<8xi32>"
V2 = "vector<2xi32>"


def tile(M):
    """The workgroup geometry (BM, BN, WM, WN) for M rows."""
    return (128, 256, 4, 4) if M % 128 == 0 else (48, 256, 3, 4)


def sym(kind):
    return "yah_iu4_gemm" + {"swiglu": "_swiglu", "kres": "_kres", "kqg": "_kqg"}.get(kind, "")


def gen(kind, M, out16=False):
    """out16: kstore stores f16 (gen_gemm_tile.OUT16)."""
    BM, BN, WM, WN = tile(M)
    t = TG.Tile(bm=BM, bn=BN, wm=WM, wn=WN)
    TM, TN = t.tm, t.tn
    FM, FN, NWAVE = TM // 16, TN // 16, WM * WN
    LANES = 32 * NWAVE
    assert TM % 16 == 0 and TN % 16 == 0 and (kind != "kqg" or TM == 32)
    s = sym(kind)
    bufs = ["weight", "aq", "ad"] + {"kstore": ["output"], "kres": ["resid", "output"], "swiglu": ["gate", "output"],
                                     "kqg": ["output", "gate_out"]}[kind]
    WB, AB = BM * WP, BN * WP          # dwords of one staged weight / activation tile
    SB = 2 * (WB + AB) + 2 * BM        # dwords: two weight tiles, two activation tiles, two scale tiles
    epi = NWAVE * (TM + TG.EPAD) * 16  # f32 of the epilogue slabs (alias the tiles)
    LDSW = max(SB, epi)
    L = []
    e = L.append
    e(f"// GENERATED by tools/gen_gemm_iu4.py {kind} -- edit the generator.")
    e(f"amdgpu.target<gfx1151> @yah_iu4_w32 {{subgroup_size = 32}}")
    e("")
    for c in ("m_tiles", "k_blocks", "token_tiles"):
        e(f"config.decl @{s}.{c} : %value: index where [range(%value, 1, 4096)]")
    e("")
    e(f"kernel.def target(@yah_iu4_w32) @{s}() {{")
    e("  %unit = index.constant 1 : index")
    e(f"  %m_tiles = config.get @{s}.m_tiles : index")
    e(f"  %token_tiles = config.get @{s}.token_tiles : index")
    e(f"  %wgs = index.constant {LANES} : index")
    e(f"  %rowgrp = index.constant {BM // 16} : index")
    e("  %m_groups = index.div %m_tiles, %rowgrp : index")
    e("  kernel.launch.config workgroups(%m_groups, %token_tiles, %unit) workgroup_size(%wgs, %unit, %unit) : index")
    e("} launch(" + ", ".join(f"%{b}: buffer" for b in bufs) + ") {")
    e("  %base = index.constant 0 : offset")
    for v in sorted({0, 1, 2, 4, 8, 16, 32, 64, 256, WP, BM, BN, LANES}):
        e(f"  %c{v} = index.constant {v} : index")
    e("  %m = index.constant 16 : index")
    e("  %n = index.constant 16 : index")
    e("  %k = index.constant 16 : index")
    e(f"  %m_tiles = config.get @{s}.m_tiles : index")
    e(f"  %k_blocks = config.get @{s}.k_blocks : index")
    e(f"  %token_tiles = config.get @{s}.token_tiles : index")
    e(f"  %cwtok = index.constant {BN} : index")
    e("  %tokens = index.mul %token_tiles, %cwtok : index")
    e("  %m_rows = index.mul %m_tiles, %c16 : index")
    e("  %out_total = index.mul %m_rows, %tokens : index")
    e("  %c136 = index.constant 136 : index")
    e("  %ktot = index.mul %k_blocks, %c256 : index")
    e("  %kphases = index.mul %k_blocks, %c2 : index")
    e("  %plast = index.sub %kphases, %c1 : index")
    e("  %bpr = index.mul %k_blocks, %c136 : index")              # weight bytes per row
    e("  %w_bytes = index.mul %m_rows, %bpr : index")
    e("  %w_dw = index.div %w_bytes, %c4 : index")
    e("  %w_h = index.div %w_bytes, %c2 : index")
    e("  %a_rowdw = index.div %ktot, %c8 : index")                # activation dwords per token
    e("  %a_dw = index.mul %tokens, %a_rowdw : index")
    e("  %d_tot = index.mul %tokens, %kphases : index")
    e("  " + ", ".join(f"%{b}_na" for b in bufs) + " = buffer.assume.noalias " + ", ".join(f"%{b}" for b in bufs)
      + " : " + ", ".join(["buffer"] * len(bufs)))
    e("  %wv = buffer.view %weight_na[%base] : buffer -> view<[%w_dw]xi32>")
    e("  %whv = buffer.view %weight_na[%base] : buffer -> view<[%w_h]xf16>")
    e("  %aqv = buffer.view %aq_na[%base] : buffer -> view<[%a_dw]xi32>")
    e("  %adv = buffer.view %ad_na[%base] : buffer -> view<[%d_tot]xf32>")
    e(f"  %al_bytes = index.constant {LDSW * 4} : offset")
    e("  %al = buffer.alloca<workgroup> align(16) %al_bytes : buffer")
    e(f"  %lv = buffer.view %al[%base] : buffer -> view<{LDSW}xi32>")
    e(f"  %lf = buffer.view %al[%base] : buffer -> view<{LDSW}xf32>")
    e("  %wg_x = kernel.workgroup.id<x> : index")
    e("  %wg_y = kernel.workgroup.id<y> : index")
    e("  %tid = kernel.workitem.id<x> : index")
    e("  %wave = index.div %tid, %c32 : index")
    e("  %lane = index.rem %tid, %c32 : index")
    e("  %l16 = index.rem %lane, %c16 : index")
    e("  %lh = index.div %lane, %c16 : index")
    e(f"  %cwn = index.constant {WN} : index")
    e("  %wr = index.div %wave, %cwn : index")
    e("  %wt = index.rem %wave, %cwn : index")
    e(f"  %cbm = index.constant {BM} : index")
    e("  %wg_row = index.mul %wg_x, %cbm : index")
    e("  %wtb = index.mul %wg_y, %cwtok : index")
    e(f"  %ctm = index.constant {TM} : index")
    e(f"  %ctn = index.constant {TN} : index")
    e("  %wr_off = index.mul %wr, %ctm : index")
    e("  %wt_off = index.mul %wt, %ctn : index")
    e("  %m_origin = index.add %wg_row, %wr_off : index")
    e("  %token_base = index.add %wtb, %wt_off : index")
    # staging map: chunk c = tid + LANES * r (16 bytes: weight row c / 4 or token c / 4, quarter c % 4 of its 64 bytes)
    nwc, nac = -(-BM * 4 // LANES), -(-BN * 4 // LANES)
    e(f"  %w_clast = index.constant {BM * 4 - 1} : index")
    e(f"  %a_clast = index.constant {BN * 4 - 1} : index")
    e("  %w_dlim = index.sub %w_dw, %c4 : index")
    e("  %a_dlim = index.sub %a_dw, %c4 : index")
    e("  %w_hlim = index.sub %w_h, %c1 : index")
    for nm, n, last in (("w", nwc, "%w_clast"), ("a", nac, "%a_clast")):
        for r in range(n):
            p = f"%{nm}s{r}"
            e(f"  {p}o = index.constant {LANES * r} : index")
            e(f"  {p}c0 = index.add %tid, {p}o : index")
            e(f"  {p}live = index.cmp ule, {p}c0, {last} : index")   # past the tile: the store is skipped
            e(f"  {p}c = index.min {p}c0, {last} : index")
            e(f"  {p}row = index.div {p}c, %c4 : index")
            e(f"  {p}q = index.rem {p}c, %c4 : index")
            e(f"  {p}q4 = index.mul {p}q, %c4 : index")
            e(f"  {p}lr = index.mul {p}row, %c{WP} : index")
            e(f"  {p}lo = index.add {p}lr, {p}q4 : index")             # LDS dword within the tile
            if nm == "w":
                e(f"  {p}gr = index.add %wg_row, {p}row : index")
                e(f"  {p}gb = index.mul {p}gr, %bpr : index")
                e(f"  {p}qb = index.mul {p}q, %c16 : index")
                e(f"  {p}gbq = index.add {p}gb, {p}qb : index")         # + 136 * block + 8 + 64 * half per phase
            else:
                e(f"  {p}gt = index.add %wtb, {p}row : index")
                e(f"  {p}gb = index.mul {p}gt, %a_rowdw : index")
                e(f"  {p}gbq = index.add {p}gb, {p}q4 : index")        # + 16 * phase dwords
    # scales: lane tid < BM loads row tid's f16 scale, stores it at its C-layout slot: tile r / 16, half r % 2, i (r % 16) / 2
    e("  %sc_live = index.cmp ult, %tid, %cbm : index")
    e(f"  %sc_last = index.constant {BM - 1} : index")
    e("  %sc_r = index.min %tid, %sc_last : index")
    e("  %sc_gr = index.add %wg_row, %sc_r : index")
    e("  %sc_gb = index.mul %sc_gr, %bpr : index")
    e("  %sc_t = index.div %sc_r, %c16 : index")
    e("  %sc_rr = index.rem %sc_r, %c16 : index")
    e("  %sc_h = index.rem %sc_rr, %c2 : index")
    e("  %sc_i = index.div %sc_rr, %c2 : index")
    e("  %sc_t16 = index.mul %sc_t, %c16 : index")
    e("  %sc_h8 = index.mul %sc_h, %c8 : index")
    e("  %sc_o0 = index.add %sc_t16, %sc_h8 : index")
    e(f"  %sc_base = index.constant {2 * (WB + AB)} : index")
    e("  %sc_o1 = index.add %sc_o0, %sc_i : index")
    e("  %sc_lo = index.add %sc_o1, %sc_base : index")

    def loads(pfx, kp):
        """The global loads of phase kp into registers; returns [(kind, value, lds offset, live)]."""
        e(f"  %{pfx}kb = index.div {kp}, %c2 : index")
        e(f"  %{pfx}hf = index.rem {kp}, %c2 : index")
        e(f"  %{pfx}kb136 = index.mul %{pfx}kb, %c136 : index")
        e(f"  %{pfx}hf64 = index.mul %{pfx}hf, %c64 : index")
        e(f"  %{pfx}wo0 = index.add %{pfx}kb136, %{pfx}hf64 : index")
        e(f"  %{pfx}wo = index.add %{pfx}wo0, %c8 : index")            # nibble bytes of the phase within the row
        e(f"  %{pfx}ao = index.mul {kp}, %c16 : index")                  # activation dwords of the phase within the row
        out = []
        for nm, n in (("w", nwc), ("a", nac)):
            for r in range(n):
                p = f"%{nm}s{r}"
                if nm == "w":
                    e(f"  %{pfx}w{r}b = index.add {p}gbq, %{pfx}wo : index")
                    e(f"  %{pfx}w{r}d0 = index.div %{pfx}w{r}b, %c4 : index")
                    e(f"  %{pfx}w{r}d = index.min %{pfx}w{r}d0, %w_dlim : index")
                    e(f"  %{pfx}w{r} = vector.load %wv[%{pfx}w{r}d] : view<[%w_dw]xi32> -> vector<4xi32>")
                else:
                    e(f"  %{pfx}a{r}d0 = index.add {p}gbq, %{pfx}ao : index")
                    e(f"  %{pfx}a{r}d = index.min %{pfx}a{r}d0, %a_dlim : index")
                    e(f"  %{pfx}a{r} = vector.load %aqv[%{pfx}a{r}d] : view<[%a_dw]xi32> -> vector<4xi32>")
                out.append((nm, f"%{pfx}{nm}{r}", f"{p}lo", f"{p}live"))
        e(f"  %{pfx}hf4 = index.mul %{pfx}hf, %c4 : index")
        e(f"  %{pfx}sb0 = index.add %sc_gb, %{pfx}kb136 : index")
        e(f"  %{pfx}sb = index.add %{pfx}sb0, %{pfx}hf4 : index")
        e(f"  %{pfx}sh0 = index.div %{pfx}sb, %c2 : index")
        e(f"  %{pfx}sh = index.min %{pfx}sh0, %w_hlim : index")
        e(f"  %{pfx}sc = view.load %whv[%{pfx}sh] : view<[%w_h]xf16> -> f16")
        out.append(("s", f"%{pfx}sc", "%sc_lo", "%sc_live"))
        return out

    def stores(pfx, regs, buf):
        """Store the registers of loads() into LDS buffer buf (an index value: 0 or 1)."""
        e(f"  %{pfx}cwb = index.constant {WB} : index")
        e(f"  %{pfx}cab = index.constant {AB} : index")
        e(f"  %{pfx}wbo = index.mul {buf}, %{pfx}cwb : index")
        e(f"  %{pfx}abo0 = index.mul {buf}, %{pfx}cab : index")
        e(f"  %{pfx}cwb2 = index.constant {2 * WB} : index")
        e(f"  %{pfx}abo = index.add %{pfx}abo0, %{pfx}cwb2 : index")
        e(f"  %{pfx}sbo = index.mul {buf}, %cbm : index")
        for x, (nm, v, lo, live) in enumerate(regs):
            off = {"w": f"%{pfx}wbo", "a": f"%{pfx}abo", "s": f"%{pfx}sbo"}[nm]
            e(f"  %{pfx}st{x} = index.add {lo}, {off} : index")
            e(f"  scf.if {live} {{")
            if nm == "s":
                e(f"    %{pfx}sf = scalar.extf {v} : f16 to f32")
                e(f"    view.store %{pfx}sf, %lf[%{pfx}st{x}] : f32, view<{LDSW}xf32>")
            else:
                e(f"    vector.store {v}, %lv[%{pfx}st{x}] : vector<4xi32>, view<{LDSW}xi32>")
            e("  }")

    # prologue: phase 0 into buffer 0
    stores("p0_", loads("p0_", "%c0"), "%c0")
    e("  kernel.barrier<workgroup> scope(workgroup) ordering(acq_rel)")
    # per-lane fragment offsets within a tile: weight row m0 + 16 i + l16, token n0 + 16 j + l16
    for i in range(FM):
        e(f"  %fr{i}c = index.constant {16 * i} : index")
        e(f"  %fr{i}0 = index.add %wr_off, %fr{i}c : index")
        e(f"  %fr{i}1 = index.add %fr{i}0, %l16 : index")
        e(f"  %fr{i} = index.mul %fr{i}1, %c{WP} : index")
        e(f"  %fs{i}t = index.div %fr{i}0, %c16 : index")                  # scale slot: tile * 16 + half * 8
        e(f"  %fs{i}t16 = index.mul %fs{i}t, %c16 : index")
        e(f"  %fs{i}h = index.mul %lh, %c8 : index")
        e(f"  %fs{i}0 = index.add %fs{i}t16, %fs{i}h : index")
        e(f"  %fs{i} = index.add %fs{i}0, %sc_base : index")
    for j in range(FN):
        e(f"  %ft{j}c = index.constant {16 * j} : index")
        e(f"  %ft{j}0 = index.add %wt_off, %ft{j}c : index")
        e(f"  %ft{j}1 = index.add %ft{j}0, %l16 : index")
        e(f"  %ft{j}2 = index.mul %ft{j}1, %c{WP} : index")
        e(f"  %ft{j}cw = index.constant {2 * WB} : index")
        e(f"  %ft{j} = index.add %ft{j}2, %ft{j}cw : index")
        # this lane's token (activation scale)
        e(f"  %tk{j}0 = index.add %token_base, %ft{j}c : index")
        e(f"  %tk{j} = index.add %tk{j}0, %l16 : index")
        e(f"  %tkd{j} = index.mul %tk{j}, %kphases : index")
    e("  %schema = encoding.define #encoding.operand<element_format=i4, payload_elements=16, payload_registers=2> : encoding<schema>")
    e("  %zi = scalar.constant 0 : i32")
    e(f"  %zv = vector.splat %zi : {VI}")
    e("  %zf = scalar.constant 0.0 : f32")
    e(f"  %zfv = vector.splat %zf : {V8}")
    NA = FM * FN
    ca = ", ".join(f"%a{x} = %zfv : {V8}" for x in range(NA))
    e("  " + ", ".join(f"%acc{x}" for x in range(NA)) + f" = scf.for %kp = [%c0 to %kphases step %c1]({ca}) -> ("
      + ", ".join([V8] * NA) + ") {")
    e("    %buf = index.rem %kp, %c2 : index")
    e("    %nbuf = index.sub %c1, %buf : index")
    e("    %kn0 = index.add %kp, %c1 : index")
    e("    %kn = index.min %kn0, %plast : index")
    regs = loads("n_", "%kn")
    e(f"    %cwbk = index.constant {WB} : index")
    e(f"    %cabk = index.constant {AB} : index")
    e("    %wbk = index.mul %buf, %cwbk : index")
    e("    %abk = index.mul %buf, %cabk : index")
    e("    %sbk = index.mul %buf, %cbm : index")
    for j in range(FN):
        e(f"    %dti{j} = index.add %tkd{j}, %kp : index")
        e(f"    %dt{j} = view.load %adv[%dti{j}] : view<[%d_tot]xf32> -> f32")
        e(f"    %dtv{j} = vector.splat %dt{j} : {V8}")
    c = {(i, j): "%zv" for i in range(FM) for j in range(FN)}
    for st in range(KP // 16):
        for i in range(FM):
            e(f"    %la{st}_{i}0 = index.add %fr{i}, %wbk : index")
            e(f"    %la{st}_{i}c = index.constant {2 * st} : index")
            e(f"    %la{st}_{i} = index.add %la{st}_{i}0, %la{st}_{i}c : index")
            e(f"    %wd{st}_{i} = vector.load %lv[%la{st}_{i}] : view<{LDSW}xi32> -> {V2}")
            e(f"    %lhs{st}_{i} = vector.fragment<lhs> %wd{st}_{i} shape [%m, %k] using {{schema = %schema : encoding<schema>}} : {V2}")
        for j in range(FN):
            e(f"    %lb{st}_{j}0 = index.add %ft{j}, %abk : index")
            e(f"    %lb{st}_{j}c = index.constant {2 * st} : index")
            e(f"    %lb{st}_{j} = index.add %lb{st}_{j}0, %lb{st}_{j}c : index")
            e(f"    %ad{st}_{j} = vector.load %lv[%lb{st}_{j}] : view<{LDSW}xi32> -> {V2}")
            e(f"    %rhs{st}_{j} = vector.fragment<rhs> %ad{st}_{j} shape [%k, %n] using {{schema = %schema : encoding<schema>}} : {V2}")
        for i in range(FM):
            for j in range(FN):
                if st == 0:
                    e(f"    %init{i}_{j} = vector.fragment<init> %zv shape [%m, %n] : {VI}")
                    c[i, j] = f"%init{i}_{j}"
                e(f"    %c{st}_{i}_{j} = vector.mma %lhs{st}_{i}, %rhs{st}_{j}, {c[i, j]} : {V2}, {V2}, {VI}")
                c[i, j] = f"%c{st}_{i}_{j}"
    # fold: acc += f32(c) * weight scale (per element) * activation scale (per lane)
    for i in range(FM):
        e(f"    %wsi{i} = index.add %fs{i}, %sbk : index")
        e(f"    %ws{i} = vector.load %lf[%wsi{i}] : view<{LDSW}xf32> -> {V8}")
        for j in range(FN):
            x = i * FN + j
            e(f"    %cf{x} = vector.sitofp {c[i, j]} : {VI} to {V8}")
            e(f"    %sc{x} = vector.mulf %ws{i}, %dtv{j} : {V8}")
            e(f"    %f{x} = vector.fmaf %cf{x}, %sc{x}, %a{x} : {V8}")
    stores("n_", regs, "%nbuf")
    e("    kernel.barrier<workgroup> scope(workgroup) ordering(acq_rel)")
    e("    scf.yield " + ", ".join(f"%f{x}" for x in range(NA)) + " : " + ", ".join([V8] * NA))
    e("  }")
    if TM != 32:
        # lds_epilogue reads 32-row slabs: other tiles store the result fragments directly (f32 kstore)
        assert kind == "kstore" and not out16
        e("  %out_layout = encoding.layout.strided [%c1, %m_rows] : encoding<layout>")
        OV = "view<[%m_rows]x[%tokens]xf32, %out_layout>"
        e(f"  %out_t_view = buffer.view %output_na[%base] : buffer -> {OV}")
        for i in range(FM):
            for j in range(FN):
                e(f"  %or{i}_{j} = index.add %m_origin, %fr{i}c : index")
                e(f"  %ot{i}_{j} = index.add %token_base, %ft{j}c : index")
                e(f"  vector.fragment.store<result> %acc{i * FN + j}, %out_t_view[%or{i}_{j}, %ot{i}_{j}] shape [%m, %n] : {V8}, {OV}")
    else:
        TG.OUT16, TG.OSTRIDE = out16, 0
        try:
            TG.lds_epilogue(e, t, kind == "kres", V8, sw=kind == "swiglu", qg=kind == "kqg")
        finally:
            TG.OUT16 = False
    e("  kernel.return")
    e("}")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    print(gen(sys.argv[1], int(sys.argv[2])), end="")
