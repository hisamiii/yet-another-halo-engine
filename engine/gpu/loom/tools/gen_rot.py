    e(f"  %xv = buffer.view %x_na[%base] : buffer -> view<{total}xf32>")
    e(f"  %wv = buffer.view %weight_na[%base] : buffer -> view<{K}xf32>")
    e(f"  %av = buffer.view %awq_na[%base] : buffer -> view<{K}xf32>")
    e("  %sv = buffer.view %sg_na[%base] : buffer -> view<512xf32>")
    # one LDS region: the row (f32 [K]) for the norm chains, then the rotation slabs (all values are in registers by then)
    assert ng * 16 * PITCH >= K
    e(f"  %lb = index.constant {ng * 16 * PITCH * 4} : offset")
    e("  %lds = buffer.alloca<workgroup> align(16) %lb : buffer")
    e(f"  %lv = buffer.view %lds[%base] : buffer -> {LV}")
    e(f"  %xrow = buffer.view %lds[%base] : buffer -> view<{K}xf32>")
    e("  %ib = index.constant 16 : offset")
    e("  %ilds = buffer.alloca<workgroup> align(16) %ib : buffer")
    e("  %iview = buffer.view %ilds[%base] : buffer -> view<4xf32>")
    e("  %lane = kernel.workitem.id<x> : index")
    e("  %row = kernel.workgroup.id<x> : index")
    e("  %gl = index.div %lane, %c16 : index")
    e("  %a = index.rem %lane, %c16 : index")
    e("  %rb = index.mul %row, %ck : index")
    e("  %gk = index.mul %gl, %c256 : index")
    e("  %a16 = index.mul %a, %c16 : index")
    e("  %kk = index.add %gk, %a16 : index")
    e("  %xi = index.add %rb, %kk : index")
    e(f"  %x16 = vector.load %xv[%xi] : view<{total}xf32> -> vector<16xf32>")
    e(f"  vector.store %x16, %xrow[%kk] : vector<16xf32>, view<{K}xf32>")
    e("  kernel.barrier<workgroup> scope(workgroup) ordering(acq_rel)")
    e("  %w0 = index.cmp ult, %lane, %c32 : index")
    e("  scf.if %w0 {")
    e("    %zero = scalar.constant 0.0 : f32")
    e("    %one = scalar.constant 1.0 : f32")
    e(f"    %eps = scalar.constant {eps!r} : f32")
    n = K // 32
    prev = "%zero"
    for k in range(n):   # load, square, add per value: all 160 loads hoisted would set the kernel's VGPRs
        e(f"    %no{k} = index.constant {32 * k} : index")
        e(f"    %na{k} = index.add %lane, %no{k} : index")
        e(f"    %nx{k} = view.load %xrow[%na{k}] : view<{K}xf32> -> f32")
        e(f"    %nq{k} = scalar.mulf %nx{k}, %nx{k} : f32")
        e(f"    %ns{k} = scalar.addf {prev}, %nq{k} : f32")
        prev = f"%ns{k}"
    e(f"    %sum_sq = kernel.subgroup.reduce<addf> {prev} : f32")
    e(f"    %dim_i = scalar.constant {K} : i32")
    e("    %dim_f = scalar.sitofp %dim_i : i32 to f32")
    e("    %mean = scalar.divf %sum_sq, %dim_f : f32")
    e("    %shifted = scalar.addf %mean, %eps : f32")
    e("    %root = scalar.sqrtf %shifted : f32")
    e("    %inv0 = scalar.divf %one, %root : f32")
    e("    %l0 = index.cmp eq, %lane, %c0 : index")
    e("    scf.if %l0 {")
    e("      view.store %inv0, %iview[%c0] : f32, view<4xf32>")
    e("    }")
    e("  }")
    e("  kernel.barrier<workgroup> scope(workgroup) ordering(acq_rel)")
    e("  %inv = view.load %iview[%c0] : view<4xf32> -> f32")
    e("  %invv = vector.splat %inv : vector<16xf32>")
    e(f"  %w16 = vector.load %wv[%kk] : view<{K}xf32> -> vector<16xf32>")
    e("  %nm = vector.mulf %x16, %invv : vector<16xf32>")
    e("  %wt = vector.mulf %nm, %w16 : vector<16xf32>")
    e("  %xh = vector.fptrunc %wt : vector<16xf32> to vector<16xf16>")
    e("  %xf = vector.extf %xh : vector<16xf16> to vector<16xf32>")
    _core(e, K, total, True, "f16", ("q", "d"), LV)
    _quant(e, total, span, LV)
    e("  kernel.return")
    e("}")
    return "\n".join(L) + "\n"


