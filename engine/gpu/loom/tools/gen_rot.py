#!/usr/bin/env python3
"""yah_rot256: the input rotation of MQ4G256 (HFQ) GEMMs, per 256-wide group of each f16 row:
  out = f16(s2 / 16 * H256(s1 * x / awq)), H256 the natural-order Walsh-Hadamard matrix, s1 / s2 the +-1 sign vectors.
The weights are stored in this basis, so W x = W_rot rot(x). H256 = H16 (x) H16: 16 lanes per group each run one H16
over 16 contiguous values in registers, the transpose goes through LDS, then each lane runs the other H16.
Workgroup: 64 lanes = 4 groups of one row; grid (K / 1024, rows).
Bindings: x (in place) or src + dst (heads: dst in HF value-head order), awq (f32 [K], absent with awq=False),
signs (f32 [512]: s1, then s2 / 16; signs() writes it).
"""
import struct

SEEDS = (42, 1042)


def sign_vec(seed, n=256):
    """hipfire's sign vector: state = state * 1103515245 + 12345 mod 2^31, bit 16 set -> +1."""
    s, out = seed, []
    for _ in range(n):
        s = (s * 1103515245 + 12345) & 0x7FFFFFFF
        out.append(1.0 if (s >> 16) & 1 else -1.0)
    return out


def signs():
    """The signs binding: s1, then s2 / 16, f32."""
    s1, s2 = (sign_vec(s) for s in SEEDS)
    return struct.pack("<512f", *(s1 + [v / 16 for v in s2]))


def gen(K, rows, awq=True, heads=None, ty="f16"):
    """ty: the element type of x / src / dst (f32: the output head's norm row).
    heads = (value heads, key heads, head dim): src holds the value heads in GGUF order (value head i uses key head
    i mod key heads), dst gets them in HF order (grouped by key head): HF head h is GGUF head (h % r) * key heads + h / r."""
    assert K % 1024 == 0
    PITCH = 17   # f32 per LDS row: pitch 16 would put a group's 16 transposed reads in one bank
    L = []
    e = L.append
    e("// GENERATED by tools/gen_rot.py -- edit the generator.")
    e("amdgpu.target<gfx1151> @dm32 {subgroup_size = 32}")
    e("kernel.def target(@dm32) @yah_rot256() {")
    e("  %u1 = index.constant 1 : index")
    e("  %c64 = index.constant 64 : index")
    e(f"  %gx = index.constant {K // 1024} : index")
    e(f"  %gy = index.constant {rows} : index")
    e("  kernel.launch.config workgroups(%gx, %gy, %u1) workgroup_size(%c64, %u1, %u1) : index")
    binds = (["%src: buffer"] if heads else ["%x: buffer"]) + (["%awq: buffer"] if awq else []) + ["%sg: buffer"]
    binds += ["%dst: buffer"] if heads else []
    e("} launch(" + ", ".join(binds) + ") {")
    e("  %base = index.constant 0 : offset")
    for v in (0, 1, 16, 128, 256, PITCH, 16 * PITCH):
        e(f"  %c{v} = index.constant {v} : index")
    e(f"  %ck = index.constant {K} : index")
    names = [b.split(":")[0] for b in binds]
    e("  " + ", ".join(n + "_na" for n in names) + " = buffer.assume.noalias " + ", ".join(names) + " : "
      + ", ".join(["buffer"] * len(names)))
    total = K * rows
    src = "%src_na" if heads else "%x_na"
    e(f"  %xv = buffer.view {src}[%base] : buffer -> view<{total}x{ty}>")
    e(f"  %ov = buffer.view {'%dst_na' if heads else '%x_na'}[%base] : buffer -> view<{total}x{ty}>")
    if awq:
        e(f"  %av = buffer.view %awq_na[%base] : buffer -> view<{K}xf32>")
    e("  %sv = buffer.view %sg_na[%base] : buffer -> view<512xf32>")
    e(f"  %lb = index.constant {4 * 16 * PITCH * 4} : offset")
    e("  %lds = buffer.alloca<workgroup> align(16) %lb : buffer")
    e(f"  %lv = buffer.view %lds[%base] : buffer -> view<{4 * 16 * PITCH}xf32>")
    e("  %lane = kernel.workitem.id<x> : index")
    e("  %wx = kernel.workgroup.id<x> : index")
    e("  %row = kernel.workgroup.id<y> : index")
    e("  %gl = index.div %lane, %c16 : index")   # group within the workgroup
    e("  %a = index.rem %lane, %c16 : index")
    e("  %c4 = index.constant 4 : index")
    e("  %g0 = index.mul %wx, %c4 : index")
    e("  %g = index.add %g0, %gl : index")
    e("  %rb = index.mul %row, %ck : index")
    e("  %gk = index.mul %g, %c256 : index")
    e("  %a16 = index.mul %a, %c16 : index")
    e("  %kk = index.add %gk, %a16 : index")   # this lane's 16 values: k = 256 g + 16 a .. + 15 (HF order)
    if heads:
        nv, nk, hd = heads
        r = nv // nk
        assert hd % 16 == 0 and 256 % hd == 0
        e(f"  %chd = index.constant {hd} : index")
        e(f"  %cr = index.constant {r} : index")
        e(f"  %cnk = index.constant {nk} : index")
        e("  %hh = index.div %kk, %chd : index")
        e("  %ho = index.rem %kk, %chd : index")
        e("  %hm = index.rem %hh, %cr : index")
        e("  %hq = index.div %hh, %cr : index")
        e("  %hg0 = index.mul %hm, %cnk : index")
        e("  %hg = index.add %hg0, %hq : index")
        e("  %hgo = index.mul %hg, %chd : index")
        e("  %ki = index.add %hgo, %ho : index")
    else:
        e("  %ki = index.add %kk, %c0 : index")
    e("  %xi0 = index.add %rb, %ki : index")
    e(f"  %xlim = index.constant {total - 16} : index")
    e("  %xi = index.min %xi0, %xlim : index")
    if ty == "f16":
        e(f"  %xh = vector.load %xv[%xi] : view<{total}xf16> -> vector<16xf16>")
        e("  %xf = vector.extf %xh : vector<16xf16> to vector<16xf32>")
    else:
        e(f"  %xf = vector.load %xv[%xi] : view<{total}xf32> -> vector<16xf32>")
    e("  %s1 = vector.load %sv[%a16] : view<512xf32> -> vector<16xf32>")
    if awq:
        e(f"  %aw = vector.load %av[%kk] : view<{K}xf32> -> vector<16xf32>")
        e("  %xd = vector.divf %xf, %aw : vector<16xf32>")
        e("  %xs = vector.mulf %xd, %s1 : vector<16xf32>")
    else:
        e("  %xs = vector.mulf %xf, %s1 : vector<16xf32>")
    v = []
    for i in range(16):
        e(f"  %p0_{i} = vector.extract %xs[{i}] : vector<16xf32> -> f32")
        v.append(f"%p0_{i}")

    def h16(v, tag):
        h, n = 1, 0
        while h < 16:
            w = list(v)
            for i in range(16):
                if i & h == 0:
                    e(f"  %{tag}{n}_{i} = scalar.addf {v[i]}, {v[i + h]} : f32")
                    e(f"  %{tag}{n}_{i + h} = scalar.subf {v[i]}, {v[i + h]} : f32")
                    w[i], w[i + h] = f"%{tag}{n}_{i}", f"%{tag}{n}_{i + h}"
            v, h, n = w, h * 2, n + 1
        return v
    y = h16(v, "b")
    # LDS [group][a][b] (pitch PITCH): lane (gl, a) writes its row a
    e(f"  %lg = index.mul %gl, %c{16 * PITCH} : index")
    e("  %la0 = index.mul %a, %c17 : index")
    e("  %la = index.add %lg, %la0 : index")
    for i in range(16):
        e(f"  %lw{i} = index.constant {i} : index")
        e(f"  %lwi{i} = index.add %la, %lw{i} : index")
        e(f"  view.store {y[i]}, %lv[%lwi{i}] : f32, view<{4 * 16 * PITCH}xf32>")
    e("  kernel.barrier<workgroup> scope(workgroup) ordering(acq_rel)")
    # lane (gl, b) reads column b over a, runs H16 over a; out k = 256 g + 16 a + b
    z = []
    for i in range(16):
        e(f"  %lr{i} = index.constant {i * PITCH} : index")
        e(f"  %lri{i}a = index.add %lg, %lr{i} : index")
        e(f"  %lri{i} = index.add %lri{i}a, %a : index")
        e(f"  %q{i} = view.load %lv[%lri{i}] : view<{4 * 16 * PITCH}xf32> -> f32")
        z.append(f"%q{i}")
    o = h16(z, "c")
    e("  %ob = index.add %rb, %gk : index")
    e("  %ob1 = index.add %ob, %a : index")
    e("  %s2b = index.add %c256, %a : index")
    for i in range(16):
        e(f"  %so{i} = index.constant {16 * i} : index")
        e(f"  %s2i{i} = index.add %s2b, %so{i} : index")
        e(f"  %s2_{i} = view.load %sv[%s2i{i}] : view<512xf32> -> f32")
        e(f"  %r{i} = scalar.mulf {o[i]}, %s2_{i} : f32")
        e(f"  %oi{i} = index.add %ob1, %so{i} : index")
        if ty == "f16":
            e(f"  %rh{i} = scalar.fptrunc %r{i} : f32 to f16")
            e(f"  view.store %rh{i}, %ov[%oi{i}] : f16, view<{total}xf16>")
        else:
            e(f"  view.store %r{i}, %ov[%oi{i}] : f32, view<{total}xf32>")
    e("  kernel.return")
    e("}")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    import sys
    print(gen(int(sys.argv[1]), int(sys.argv[2])), end="")
