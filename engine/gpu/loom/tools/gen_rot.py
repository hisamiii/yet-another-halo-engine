#!/usr/bin/env python3
"""yah_rot256: the input rotation of MQ4G256 (HFQ) GEMMs, per 256-wide group of each f16 row:
  out = f16(s2 / 16 * H256(s1 * x / awq)), H256 the natural-order Walsh-Hadamard matrix, s1 / s2 the +-1 sign vectors.
The weights are stored in this basis, so W x = W_rot rot(x). H256 = H16 (x) H16: 16 lanes per group each run one H16
over 16 contiguous values in registers, the transpose goes through LDS, then each lane runs the other H16.
Workgroup: 64 lanes = 4 groups of one row; grid (K / 1024, rows).
Bindings: x (in place) or src + dst (heads: dst in HF value-head order), awq (f32 [K], absent with awq=False),
signs (f32 [512]: s1, then s2 / 16; signs() writes it).

yah_rotq256 (gen_q): the same rotation of f16 rows, then int4 quantization for the iu4 GEMMs (the A4 path) instead of
the f16 store: one scale per span values of a row, hipfire's recipe (amax, the best of 8 candidate scales
(amax / 7) * (1 + j / 7) / 2 by squared error, round to nearest even, clamp to [-8, 7]). Writes q (row-major nibbles,
value 2j in the low nibble of byte j) and d times 2^26 (f32 [rows][K / span], the iu4 GEMMs' fold scale). Workgroup and
grid as yah_rot256.
"""
import struct

SEEDS = (42, 1042)
PITCH = 17   # f32 per LDS row: pitch 16 would put a group's 16 transposed reads in one bank


def sign_vec(seed, n=256):
    """hipfire's sign vector: state = state * 1103515245 + 12345 mod 2^31, bit 16 set -> +1."""
    s, out = seed, []
    for _ in range(n):
        s = (s * 1103515245 + 12345) & 0x7FFFFFFF
        out.append(1.0 if (s >> 16) & 1 else -1.0)
    return out


def signs():
    """The signs binding: s1, then s2 / 16, f32."""
    s1, s2 = (sign_vec(s) for s in SEEDS)
    return struct.pack("<512f", *(s1 + [v / 16 for v in s2]))


def _body(e, sym, K, rows, awq, heads, ty, outs, hot=False, flag=0, oflag=False):
    """Kernel head, both H16 passes and the s2 product: %r<i> is the rotated value k = 256 g + 16 i + a of lane (gl, a).
    outs: the output bindings (none: x in place, or dst with heads).
    hot: the workgroups walk the 1024-value chunks from the last one, tokens fastest (gen_q hot).
    flag: binding cnt after the outputs; the workgroup waits until cnt[chunk token tiles + token / 128] reaches flag
    (gen_q flag), and the chunks run n - 2 .. 0, then n - 1. oflag: binding ocnt after that (gen_q oflag)."""
    assert K % 1024 == 0
    LV = f"view<{4 * 16 * PITCH}xf32>"
    e("// GENERATED by tools/gen_rot.py -- edit the generator.")
    e("amdgpu.target<gfx1151> @dm32 {subgroup_size = 32}")
    e(f"kernel.def target(@dm32) @{sym}() {{")
    e("  %u1 = index.constant 1 : index")
    e("  %c64 = index.constant 64 : index")
    e(f"  %gx = index.constant {K // 1024} : index")
    e(f"  %gy = index.constant {rows} : index")
    e("  kernel.launch.config workgroups(%gx, %gy, %u1) workgroup_size(%c64, %u1, %u1) : index")
    binds = (["%src: buffer"] if heads or outs else ["%x: buffer"]) + (["%awq: buffer"] if awq else []) + ["%sg: buffer"]
    binds += [f"%{o}: buffer" for o in outs] if outs else ["%dst: buffer"] if heads else []
    binds += ["%cnt: buffer"] if flag else []
    binds += ["%ocnt: buffer"] if oflag else []
    e("} launch(" + ", ".join(binds) + ") {")
    e("  %base = index.constant 0 : offset")
    for v in (0, 1, 16, 128, 256, PITCH, 16 * PITCH):
        e(f"  %c{v} = index.constant {v} : index")
    e(f"  %ck = index.constant {K} : index")
    names = [b.split(":")[0] for b in binds]
    e("  " + ", ".join(n + "_na" for n in names) + " = buffer.assume.noalias " + ", ".join(names) + " : "
      + ", ".join(["buffer"] * len(names)))
    total = K * rows
    src = "%src_na" if heads or outs else "%x_na"
    e(f"  %xv = buffer.view {src}[%base] : buffer -> view<{total}x{ty}>")
    if not outs:
        e(f"  %ov = buffer.view {'%dst_na' if heads else '%x_na'}[%base] : buffer -> view<{total}x{ty}>")
    if awq:
        e(f"  %av = buffer.view %awq_na[%base] : buffer -> view<{K}xf32>")
    e("  %sv = buffer.view %sg_na[%base] : buffer -> view<512xf32>")
    e(f"  %lb = index.constant {4 * 16 * PITCH * 4} : offset")
    e("  %lds = buffer.alloca<workgroup> align(16) %lb : buffer")
    e(f"  %lv = buffer.view %lds[%base] : buffer -> {LV}")
    e("  %lane = kernel.workitem.id<x> : index")
    if hot or flag:
        e("  %hx = kernel.workgroup.id<x> : index")
        e("  %hy = kernel.workgroup.id<y> : index")
        e(f"  %hgx = index.constant {K // 1024} : index")
        e(f"  %hgy = index.constant {rows} : index")
        e("  %hl0 = index.mul %hy, %hgx : index")
        e("  %hl = index.add %hl0, %hx : index")
        e("  %hq0 = index.div %hl, %hgy : index")
        e(f"  %hlast = index.constant {K // 1024 - 1} : index")
        e("  %hq = index.min %hq0, %hlast : index")   # bound proof (never clamps)
        if flag:   # the last chunk (the producer's last bands) after the others, which finish first
            e(f"  %htop = index.constant {2 * (K // 1024) - 2} : index")
            e("  %hw = index.sub %htop, %hq : index")
            e("  %wx = index.rem %hw, %hgx : index")
        else:
            e("  %wx = index.sub %hlast, %hq : index")
        e("  %row = index.rem %hl, %hgy : index")
    else:
        e("  %wx = kernel.workgroup.id<x> : index")
        e("  %row = kernel.workgroup.id<y> : index")
    if flag:
        tt = rows // 128
        FV = f"view<{K // 1024 * tt}xi32>"
        e(f"  %fl_ctt = index.constant {tt} : index")
        e("  %fl_c128 = index.constant 128 : index")
        e("  %fl_t = index.div %row, %fl_c128 : index")
        e("  %fl_i0 = index.mul %wx, %fl_ctt : index")
        e("  %fl_i = index.add %fl_i0, %fl_t : index")
        e(f"  %fl_cv = buffer.view %cnt_na[%base] : buffer -> {FV}")
        flag_wait(e, "%fl_cv", FV, ["%fl_i"], flag, "%lane")
    e("  %gl = index.div %lane, %c16 : index")   # group within the workgroup
    e("  %a = index.rem %lane, %c16 : index")
    e("  %c4 = index.constant 4 : index")
    e("  %g0 = index.mul %wx, %c4 : index")
    e("  %g = index.add %g0, %gl : index")
    e("  %rb = index.mul %row, %ck : index")
    e("  %gk = index.mul %g, %c256 : index")
    e("  %a16 = index.mul %a, %c16 : index")
    e("  %kk = index.add %gk, %a16 : index")   # this lane's 16 values: k = 256 g + 16 a .. + 15 (HF order)
    if heads:
        nv, nk, hd = heads
        r = nv // nk
        assert hd % 16 == 0 and 256 % hd == 0
        e(f"  %chd = index.constant {hd} : index")
        e(f"  %cr = index.constant {r} : index")
        e(f"  %cnk = index.constant {nk} : index")
        e("  %hh = index.div %kk, %chd : index")
        e("  %ho = index.rem %kk, %chd : index")
        e("  %hm = index.rem %hh, %cr : index")
        e("  %hq = index.div %hh, %cr : index")
        e("  %hg0 = index.mul %hm, %cnk : index")
        e("  %hg = index.add %hg0, %hq : index")
        e("  %hgo = index.mul %hg, %chd : index")
        e("  %ki = index.add %hgo, %ho : index")
    else:
        e("  %ki = index.add %kk, %c0 : index")
    e("  %xi0 = index.add %rb, %ki : index")
    e(f"  %xlim = index.constant {total - 16} : index")
    e("  %xi = index.min %xi0, %xlim : index")
    if ty == "f16":
        e(f"  %xh = vector.load %xv[%xi] : view<{total}xf16> -> vector<16xf16>")
        e("  %xf = vector.extf %xh : vector<16xf16> to vector<16xf32>")
    else:
        e(f"  %xf = vector.load %xv[%xi] : view<{total}xf32> -> vector<16xf32>")
    return _core(e, K, total, awq, ty, outs, LV)


def _core_loads(e, K, awq):
    """_core's global loads (s1, awq, s2): issued up front, they share one memory latency with the kernel's own loads
    instead of waiting behind its barriers."""
    e("  %s1 = vector.load %sv[%a16] : view<512xf32> -> vector<16xf32>")
    if awq:
        e(f"  %aw = vector.load %av[%kk] : view<{K}xf32> -> vector<16xf32>")
    e("  %s2b = index.add %c256, %a : index")
    for i in range(16):
        e(f"  %so{i} = index.constant {16 * i} : index")
        e(f"  %s2i{i} = index.add %s2b, %so{i} : index")
        e(f"  %s2_{i} = view.load %sv[%s2i{i}] : view<512xf32> -> f32")


def _awrcp(e):
    """_core's rotq divide constants from %aw: %awn = -awq, %awy = v_rcp + one Newton step."""
    e("  %awone = scalar.constant 1.0 : f32")
    e("  %awonev = vector.splat %awone : vector<16xf32>")
    e("  %awr0 = vector.divf<nnan|ninf|nsz|arcp> %awonev, %aw : vector<16xf32>")
    e("  %awn = vector.negf %aw : vector<16xf32>")
    e("  %awer = vector.fmaf %awn, %awr0, %awonev : vector<16xf32>")
    e("  %awy = vector.fmaf %awer, %awr0, %awr0 : vector<16xf32>")


def _core(e, K, total, awq, ty, outs, LV, loaded=False):
    """From the lane's 16 f32 values %xf (k = %kk + i): the awq divide, s1, both H16 passes through LDS view %lv (LV,
    group %gl's slab at %gl 16 PITCH) and the s2 product into %r<i>; without outs the f16 / f32 store to %ov.
    loaded: the kernel already ran _core_loads."""
    if not loaded:
        _core_loads(e, K, awq)
    if awq:
        if outs:
            if loaded == "hoist":   # %awn / %awy computed once by the caller (its chunk is loop-invariant)
                e("  %awq0 = vector.mulf %xf, %awy : vector<16xf32>")
                e("  %awrr = vector.fmaf %awq0, %awn, %xf : vector<16xf32>")
                e("  %xd = vector.fmaf %awrr, %awy, %awq0 : vector<16xf32>")
                e("  %xs = vector.mulf %xd, %s1 : vector<16xf32>")
                return _core_tail(e, total, ty, outs, LV)
            # rotq: x / awq as Markstein's q0 + (x - q0 awq) y with y = v_rcp + one Newton step, which is the IEEE 1 / awq
            # for every normal awq (exhaustive over the mantissas): the IEEE quotient up to the sign of a zero
            _awrcp(e)
            e("  %awq0 = vector.mulf %xf, %awy : vector<16xf32>")
            e("  %awrr = vector.fmaf %awq0, %awn, %xf : vector<16xf32>")
            e("  %xd = vector.fmaf %awrr, %awy, %awq0 : vector<16xf32>")
        else:
            e("  %xd = vector.divf %xf, %aw : vector<16xf32>")
        e("  %xs = vector.mulf %xd, %s1 : vector<16xf32>")
    else:
        e("  %xs = vector.mulf %xf, %s1 : vector<16xf32>")
    return _core_tail(e, total, ty, outs, LV)


def _core_tail(e, total, ty, outs, LV):
    """_core from the scaled values %xs."""
    v = []
    for i in range(16):
        e(f"  %p0_{i} = vector.extract %xs[{i}] : vector<16xf32> -> f32")
        v.append(f"%p0_{i}")

    def h16(v, tag):
        h, n = 1, 0
        while h < 16:
            w = list(v)
            for i in range(16):
                if i & h == 0:
                    e(f"  %{tag}{n}_{i} = scalar.addf {v[i]}, {v[i + h]} : f32")
                    e(f"  %{tag}{n}_{i + h} = scalar.subf {v[i]}, {v[i + h]} : f32")
                    w[i], w[i + h] = f"%{tag}{n}_{i}", f"%{tag}{n}_{i + h}"
            v, h, n = w, h * 2, n + 1
        return v
    y = h16(v, "b")
    # LDS [group][a][b] (pitch PITCH): lane (gl, a) writes its row a
    e(f"  %lg = index.mul %gl, %c{16 * PITCH} : index")
    e("  %la0 = index.mul %a, %c17 : index")
    e("  %la = index.add %lg, %la0 : index")
    for i in range(16):
        e(f"  %lw{i} = index.constant {i} : index")
        e(f"  %lwi{i} = index.add %la, %lw{i} : index")
        e(f"  view.store {y[i]}, %lv[%lwi{i}] : f32, {LV}")
    e("  kernel.barrier<workgroup> scope(workgroup) ordering(acq_rel)")
    # lane (gl, b) reads column b over a, runs H16 over a; out k = 256 g + 16 a + b
    z = []
    for i in range(16):
        e(f"  %lr{i} = index.constant {i * PITCH} : index")
        e(f"  %lri{i}a = index.add %lg, %lr{i} : index")
        e(f"  %lri{i} = index.add %lri{i}a, %a : index")
        e(f"  %q{i} = view.load %lv[%lri{i}] : {LV} -> f32")
        z.append(f"%q{i}")
    o = h16(z, "c")
    if not outs:
        e("  %ob = index.add %rb, %gk : index")
        e("  %ob1 = index.add %ob, %a : index")
    for i in range(16):
        e(f"  %r{i} = scalar.mulf {o[i]}, %s2_{i} : f32")
        if outs:
            continue
        e(f"  %oi{i} = index.add %ob1, %so{i} : index")
        if ty == "f16":
            e(f"  %rh{i} = scalar.fptrunc %r{i} : f32 to f16")
            e(f"  view.store %rh{i}, %ov[%oi{i}] : f16, view<{total}xf16>")
        else:
            e(f"  view.store %r{i}, %ov[%oi{i}] : f32, view<{total}xf32>")
    return total


def gen(K, rows, awq=True, heads=None, ty="f16"):
    """ty: the element type of x / src / dst (f32: the output head's norm row).
    heads = (value heads, key heads, head dim): src holds the value heads in GGUF order (value head i uses key head
    i mod key heads), dst gets them in HF order (grouped by key head): HF head h is GGUF head (h % r) * key heads + h / r."""
    L = []
    e = L.append
    _body(e, "yah_rot256", K, rows, awq, heads, ty, ())
    e("  kernel.return")
    e("}")
    return "\n".join(L) + "\n"


def q_flag_count(K):
    """What gen_q oflag adds to a token tile's counter: one per wave of its FLAG_TT rows' K / 1024 workgroups."""
    return FLAG_TT * K // 1024 * 2


def emit_oflag(e, nt, row, lane):
    """A flag-producing kernel's end: lane 0 of each wave adds 1 to ocnt[row / FLAG_TT] once the wave's stores are
    visible (device scope), ocnt i32 [nt]."""
    OV = f"view<{nt}xi32>"
    e("  %of_one = scalar.constant 1 : i32")
    e(f"  %of_tt = index.constant {FLAG_TT} : index")
    e(f"  %of_tile = index.div {row}, %of_tt : index")
    e(f"  %of_cv = buffer.view %ocnt_na[%base] : buffer -> {OV}")
    e("  %of_c32 = index.constant 32 : index")
    e("  %of_c0 = index.constant 0 : index")
    e(f"  %of_l = index.rem {lane}, %of_c32 : index")
    e("  %of_l0 = index.cmp eq, %of_l, %of_c0 : index")
    e("  scf.if %of_l0 {")
    e(f"    view.atomic.reduce<addi> %of_one, %of_cv[%of_tile] {{ordering = release, scope = device}} : i32, {OV}")
    e("  }")


def gen_q(K, rows, span, awq=True, heads=None, hot=False, flag=0, oflag=False):
    """f16 x -> rotated int4 q + scales d, one scale per span values (128, 256 or 512: the lanes of a span reduce with
    shuffles inside their wave). Bindings: src, awq, signs, q, d.
    hot: chunks from the last one, tokens fastest: the gu GEMM writes x band by band (gen_gemm_iu4.group_of), so the
    last ~32 MB of it are still in the MALL; the default order's misses evict them first (rotq_17408 -8%).
    flag (gen_gemm_iu4.gu_flag_count): binding cnt after d, the flagged gu's counters (zero before it); each workgroup
    waits for its chunk and token tile, so the gu GEMM runs without a graph barrier before this kernel.
    oflag: binding ocnt after them, i32 [rows / FLAG_TT] (zero before), q_flag_count per token tile (emit_oflag), so a
    flag-waiting GEMM (gen_gemm_iu4.gen wait) runs without a graph barrier after this kernel."""
    assert span in (128, 256, 512) and (not oflag or rows % FLAG_TT == 0)
    LV = f"view<{4 * 16 * PITCH}xf32>"
    L = []
    e = L.append
    total = _body(e, "yah_rotq256", K, rows, awq, heads, "f16", ("q", "d"), hot, flag, oflag)
    _quant(e, total, span, LV)
    if oflag:
        emit_oflag(e, rows // FLAG_TT, "%row", "%lane")
    e("  kernel.return")
    e("}")
    return "\n".join(L) + "\n"


# gen_qp's issue priority: its VALU chains share the SIMDs with the waiting kres's WMMA waves; at 0 they lose the
# arbitration (rotq 1.35 ms past the gu instead of 0.3)
QP_PRIO = 3


# gen_qp / gen_pnqp: chunk-fastest items when P allows (the awq divide out of the item loop): pnqp (P 120) VALU -5%;
# rotqp at P 170 / rotqop at 162 flat (138 -> 163 VGPRs), so RQP / RQOP stay 160 (not multiples: rows fastest)
QP_CM = True


def gen_qp(K, rows, span, P, flag, plow=False):
    """gen_q flag + oflag as P persistent workgroups (rotqp): the grid of K / 1024 x rows workgroups queues the waiting
    GEMM after it behind ~35K workgroups, so it starts only in their last wave. Each token tile's items (chunk c, row r:
    1024 values) are split over the workgroups (item j = 128 c + r, workgroup w takes j = w, w + P, ..); a workgroup
    polls the tile's K / 1024 producer counters once, prefetches its next item's values while it rotates and
    quantizes the current one, then adds its item count to the tile's ocnt (per wave: q_flag_count in all). Tiles in
    order, so the waiting GEMM's first token tiles start in this kernel's tail. flag 0: no producer counters (gen_q
    oflag alone, a graph barrier orders the producer). Same values as gen_q.
    plow: priority 0 while a tile's counters are polled (QP_PRIO after), so polling beside a producer that runs at
    its normal priority does not take its issue slots.
    P a multiple of K / 1024: items chunk fastest (j = c + K / 1024 r), so a workgroup keeps one chunk and loads its awq
    and reciprocal once."""
    assert rows % FLAG_TT == 0 and K % 1024 == 0
    nch, tt = K // 1024, rows // FLAG_TT
    per = nch * FLAG_TT
    assert P <= per
    cm = QP_CM and P % nch == 0
    LV = f"view<{4 * 16 * PITCH}xf32>"
    total = K * rows
    FV = f"view<{nch * tt}xi32>"
    OV = f"view<{tt}xi32>"
    XV = f"view<{total}xf16>"
    L = []
    e = L.append
    e("// GENERATED by tools/gen_rot.py -- edit the generator.")
    e("amdgpu.target<gfx1151> @dm32 {subgroup_size = 32}")
    e("kernel.def target(@dm32) @yah_rotq256() {")
    e("  %u1 = index.constant 1 : index")
    e("  %c64 = index.constant 64 : index")
    e(f"  %gx = index.constant {P} : index")
    e("  kernel.launch.config workgroups(%gx, %u1, %u1) workgroup_size(%c64, %u1, %u1) : index")
    names = ["src", "awq", "sg", "q", "d"] + (["cnt"] if flag else []) + ["ocnt"]
    e("} launch(" + ", ".join(f"%{n}: buffer" for n in names) + ") {")
    e("  %base = index.constant 0 : offset")
    for v in (0, 1, 16, 128, 256, PITCH, 16 * PITCH):
        e(f"  %c{v} = index.constant {v} : index")
    e(f"  %ck = index.constant {K} : index")
    e("  " + ", ".join("%" + n + "_na" for n in names) + " = buffer.assume.noalias " + ", ".join("%" + n for n in names) + " : "
      + ", ".join(["buffer"] * len(names)))
    e(f"  %xv = buffer.view %src_na[%base] : buffer -> {XV}")
    e(f"  %av = buffer.view %awq_na[%base] : buffer -> view<{K}xf32>")
    e("  %sv = buffer.view %sg_na[%base] : buffer -> view<512xf32>")
    if flag:
        e(f"  %fl_cv = buffer.view %cnt_na[%base] : buffer -> {FV}")
    e(f"  %of_cv = buffer.view %ocnt_na[%base] : buffer -> {OV}")
    e(f"  %lb = index.constant {4 * 16 * PITCH * 4} : offset")
    e("  %lds = buffer.alloca<workgroup> align(16) %lb : buffer")
    e(f"  %lv = buffer.view %lds[%base] : buffer -> {LV}")
    e("  %lane = kernel.workitem.id<x> : index")
    e(f"  kernel.priority {{level = {QP_PRIO}}}")
    e("  %pw = kernel.workgroup.id<x> : index")
    e(f"  %pP = index.constant {P} : index")
    e(f"  %pT = index.constant {per} : index")
    e(f"  %pTm = index.constant {per - 1} : index")
    e(f"  %pct = index.constant {tt} : index")
    e("  %pc32 = index.constant 32 : index")
    e("  %gl = index.div %lane, %c16 : index")   # group within the workgroup
    e("  %a = index.rem %lane, %c16 : index")
    e("  %c4 = index.constant 4 : index")
    e("  %a16 = index.mul %a, %c16 : index")
    # s1, s2: loop-invariant
    e("  %s1 = vector.load %sv[%a16] : view<512xf32> -> vector<16xf32>")
    e("  %s2b = index.add %c256, %a : index")
    for i in range(16):
        e(f"  %so{i} = index.constant {16 * i} : index")
        e(f"  %s2i{i} = index.add %s2b, %so{i} : index")
        e(f"  %s2_{i} = view.load %sv[%s2i{i}] : view<512xf32> -> f32")
    # this workgroup's items per tile, per wave added to the tile's ocnt
    e("  %pn0 = index.sub %pT, %pw : index")
    e("  %pn1 = index.add %pn0, %pP : index")
    e("  %pn2 = index.sub %pn1, %c1 : index")
    e("  %pn = index.div %pn2, %pP : index")
    e("  %pni = index.cast %pn : index to i32")
    e(f"  %pneed = scalar.constant {flag} : i32")
    e(f"  %plimit = scalar.constant {FLAG_POLLS} : i32")
    e("  %pzero = scalar.constant 0 : i32")
    e("  %pone = scalar.constant 1 : i32")
    e("  %pw0 = index.cmp ult, %lane, %pc32 : index")
    e("  %of_l = index.rem %lane, %pc32 : index")
    e("  %of_l0 = index.cmp eq, %of_l, %c0 : index")

    e(f"  %cnch = index.constant {nch} : index")

    def addr(p, j, row0):
        """Item j (chunk j / 128, row row0 + j % 128; cm: chunk j % nch, row row0 + j / nch): the lane's value index
        %{p}xi and awq index %{p}kk."""
        if cm:
            e(f"  %{p}wx = index.rem {j}, %cnch : index")
            e(f"  %{p}r = index.div {j}, %cnch : index")
        else:
            e(f"  %{p}wx = index.div {j}, %c128 : index")
            e(f"  %{p}r = index.rem {j}, %c128 : index")
        e(f"  %{p}row = index.add {row0}, %{p}r : index")
        e(f"  %{p}g0 = index.mul %{p}wx, %c4 : index")
        e(f"  %{p}g = index.add %{p}g0, %gl : index")
        e(f"  %{p}rb = index.mul %{p}row, %ck : index")
        e(f"  %{p}gk = index.mul %{p}g, %c256 : index")
        e(f"  %{p}kk = index.add %{p}gk, %a16 : index")
        e(f"  %{p}xi0 = index.add %{p}rb, %{p}kk : index")
        e(f"  %{p}xlim = index.constant {total - 16} : index")
        e(f"  %{p}xi = index.min %{p}xi0, %{p}xlim : index")

    def load(p):
        e(f"  %{p}xh = vector.load %xv[%{p}xi] : {XV} -> vector<16xf16>")
        if not cm:
            e(f"  %{p}aw = vector.load %av[%{p}kk] : view<{K}xf32> -> vector<16xf32>")

    if cm:   # the workgroup's chunk: its awq and the reciprocal (_core's Markstein divide) once
        addr("h_", "%pw", "%c0")
        e(f"  %aw = vector.load %av[%h_kk] : view<{K}xf32> -> vector<16xf32>")
        _awrcp(e)

    e("  scf.for %ptt = [%c0 to %pct step %c1] {")
    e("  %prow0 = index.mul %ptt, %c128 : index")
    # the tile's producer counters (chunk c's at c tt + tile), lane c of wave 0 polls chunk min(c, nch - 1)'s: one
    # round trip per poll; relaxed polls (an acquire load invalidates the WGP's L0 and its array's L1 at every poll),
    # the barrier's global acquire after them
    if flag:
        if plow:
            e("  kernel.priority {level = 0}")
        e(f"  %plc = index.constant {nch - 1} : index")
        e("  %pl0 = index.min %lane, %plc : index")
        e("  %pl1 = index.mul %pl0, %pct : index")
        e("  %plk = index.add %pl1, %ptt : index")
        e("  scf.if %pw0 {")
        e("    %pfn = scf.while(%pfi = %pzero : i32) -> (i32) {")
        e(f"      %pfx = view.atomic.load %fl_cv[%plk] {{ordering = relaxed, scope = device}} : {FV} -> i32")
        e("      %pfe = scalar.cmpi slt, %pfx, %pneed : i32")
        e("      %pfa = kernel.subgroup.vote.any %pfe : i1")
        e("      %pfl = scalar.cmpi ult, %pfi, %plimit : i32")
        e("      %pfg = scalar.andi %pfa, %pfl : i1")
        e("      scf.condition %pfg, %pfi : i1, i32")
        e("    } do(%pfj: i32) {")
        e("      %pfj1 = scalar.addi %pfj, %pone : i32")
        e("      scf.yield %pfj1 : i32")
        e("    }")
        e("  }")
        e("  kernel.barrier<global> scope(workgroup) ordering(acquire)")
        if plow:
            e(f"  kernel.priority {{level = {QP_PRIO}}}")
    addr("f_", "%pw", "%prow0")
    load("f_")
    if cm:
        e("  %pxe = scf.for %pj = [%pw to %pT step %pP](%pxc = %f_xh : vector<16xf16>) -> (vector<16xf16>) {")
    else:
        e("  %pxe, %pae = scf.for %pj = [%pw to %pT step %pP](%pxc = %f_xh : vector<16xf16>, %aw = %f_aw : vector<16xf32>) -> (vector<16xf16>, vector<16xf32>) {")
    e("  %pj1 = index.add %pj, %pP : index")
    e("  %pjn = index.min %pj1, %pTm : index")   # the last item's prefetch: a harmless reload
    addr("n_", "%pjn", "%prow0")
    load("n_")
    e("  kernel.barrier<workgroup> scope(workgroup) ordering(acq_rel)")   # the last item's LDS reads before these writes
    addr("", "%pj", "%prow0")
    e("  %xf = vector.extf %pxc : vector<16xf16> to vector<16xf32>")
    _core(e, K, total, True, "f16", ("q", "d"), LV, loaded="hoist" if cm else True)
    _quant(e, total, span, LV)
    if cm:
        e("  scf.yield %n_xh : vector<16xf16>")
    else:
        e("  scf.yield %n_xh, %n_aw : vector<16xf16>, vector<16xf32>")
    e("  }")
    # this workgroup's items of the tile are stored: each wave counts them (device-scope release)
    e("  %of_tile = index.add %ptt, %c0 : index")
    e("  scf.if %of_l0 {")
    e(f"    view.atomic.reduce<addi> %pni, %of_cv[%of_tile] {{ordering = release, scope = device}} : i32, {OV}")
    e("  }")
    e("  }")
    e("  kernel.return")
    e("}")
    return "\n".join(L) + "\n"


# The scale candidates searched (j of d = (amax / 7)(1 + j / 7) / 2). hipfire's 0 .. 7 keep its exact search (the fast
# search with a bound-checked exact fallback); any other set runs the fast search alone: its winner is the first minimum
# of the fast errors, codes clamp(rne(x RN(1 / d))). 3 .. 6: j 0 .. 2 and 7 win ~1% of spans (MSE x1.0004 on Gaussian
# spans, the same scale as 0 .. 7 in 98.9% of real ones), half the search's VALU. The exact search's scf.if with results
# also miscompiled at 4 candidates (all-zero codes).
QCANDS = (3, 4, 5, 6)


def _quant(e, total, span, LV):
    """gen_q's int4 quantization of %r<i> (after _core): q nibbles and the span's scale times 2^26."""
    nc = len(QCANDS)
    exact = QCANDS == tuple(range(8))
    nl = span // 16    # lanes per span
    # back through LDS so each lane holds 16 contiguous values: [gl][i][a] is k = 256 g + 16 i + a, which this lane
    # read itself (no other lane touches it), then lane (gl, a) reads its row a
    for i in range(16):
        e(f"  %tw{i} = index.add %lri{i}, %c0 : index")
        e(f"  view.store %r{i}, %lv[%tw{i}] : f32, {LV}")
    e("  kernel.barrier<workgroup> scope(workgroup) ordering(acq_rel)")
    vals = []
    for i in range(16):
        e(f"  %t{i} = view.load %lv[%lwi{i}] : {LV} -> f32")
        vals.append(f"%t{i}")
    e("  %xq = vector.from_elements " + ", ".join(vals) + " : vector<16xf32>")
    e("  %fz = scalar.constant 0.0 : f32")
    e("  %x32 = scalar.constant 32 : i32")

    def reduce(x, ty, op, tag, ind="  "):
        """op of x over the span's lanes (xor shuffles)."""
        p = f"%{tag}_"
        for k in (16, 8, 4, 2, 1):
            if k >= nl:
                continue
            e(f"{ind}{p}k{k} = scalar.constant {k} : i32")
            if ty == "f32":
                e(f"{ind}{p}b{k} = scalar.bitcast {x} : f32 to i32")
                e(f"{ind}{p}s{k}, {p}v{k} = kernel.subgroup.shuffle<xor> {p}b{k}, {p}k{k}, %x32 : i32, i32, i32")
                e(f"{ind}{p}f{k} = scalar.bitcast {p}s{k} : i32 to f32")
                e(f"{ind}{p}m{k} = scalar.{op} {x}, {p}f{k} : f32")
            else:
                e(f"{ind}{p}f{k}, {p}v{k} = kernel.subgroup.shuffle<xor> {x}, {p}k{k}, %x32 : {ty}, i32, i32")
                e(f"{ind}{p}m{k} = vector.{op} {x}, {p}f{k} : {ty}")
            x = f"{p}m{k}"
        return x
    e("  %xa = vector.absf %xq : vector<16xf32>")
    e("  %am0 = vector.reduce<maxnumf> %xa, %fz : vector<16xf32>, f32")
    amax = reduce("%am0", "f32", "maxnumf", "am")
    e("  %f7 = scalar.constant 7.0 : f32")
    e("  %fone = scalar.constant 1.0 : f32")
    e("  %fhalf = scalar.constant 0.5 : f32")
    # the clamp bounds as lane * 0 + c: folded to literals, the clamp's max / min never dual-issue (-8.2% rotq_heads)
    e("  %oq_i = index.cast %lane : index to i32")
    e("  %oq_f = scalar.sitofp %oq_i : i32 to f32")
    e("  %oq_0 = scalar.mulf %oq_f, %fz : f32")
    e("  %fl8c = scalar.constant -8.0 : f32")
    e("  %fl8 = scalar.addf %oq_0, %fl8c : f32")
    e("  %f7o = scalar.addf %oq_0, %f7 : f32")
    e("  %fl8v = vector.splat %fl8 : vector<16xf32>")
    e("  %fh7v = vector.splat %f7o : vector<16xf32>")
    # nnan on every max / min: no NaN reaches them, and without it LLVM canonicalizes both operands (v_max x, x) first
    # codes in the magic domain: RN(y + 1.5 2^23) = 1.5 2^23 + rne(y) for |y| < 2^22 (ties to even: 1.5 2^23 is even),
    # two dual-issue adds instead of a single-issue v_rndne; clamped there, and its bits & 15 are the nibble
    e("  %fmgc = scalar.constant 12582912.0 : f32")
    e("  %fmg = scalar.addf %oq_0, %fmgc : f32")
    e("  %fmlc = scalar.constant 12582904.0 : f32")
    e("  %fml = scalar.addf %oq_0, %fmlc : f32")
    e("  %fmhc = scalar.constant 12582919.0 : f32")
    e("  %fmh = scalar.addf %oq_0, %fmhc : f32")
    e("  %fmgv = vector.splat %fmg : vector<16xf32>")
    e("  %fmlv = vector.splat %fml : vector<16xf32>")
    e("  %fmhv = vector.splat %fmh : vector<16xf32>")
    # amax / 7 as Markstein with RN(1 / 7): the IEEE quotient (exhaustive over the mantissas)
    e("  %y7 = scalar.constant 0.142857142857142857 : f32")
    e("  %n7 = scalar.constant -7.0 : f32")
    e(f"  %am7q = scalar.mulf {amax}, %y7 : f32")
    e(f"  %am7r = scalar.fmaf %am7q, %n7, {amax} : f32")
    e("  %am7 = scalar.fmaf %am7r, %y7, %am7q : f32")
    e("  %anz = scalar.cmpf ogt, %am7, %fz : f32")
    e("  %am7s = scf.select %anz, %am7, %fone : f32")   # all zero: any scale, q = 0
    e("  %amh = scalar.mulf %am7s, %fhalf : f32")
    # scale candidates d = (amax / 7)(1 + j / 7) / 2
    for j in QCANDS:
        e(f"  %cj{j} = scalar.constant {1.0 + j / 7.0!r} : f32")
        e(f"  %dj{j} = scalar.mulf %amh, %cj{j} : f32")
        e(f"  %djv{j} = vector.splat %dj{j} : vector<16xf32>")
        # x / d as Markstein's q0 + (x - q0 d) y: rounds once, so equals divf, given y = RN(1 / d), which v_rcp + one
        # Newton step is for every normal d (exhaustive over the mantissas)
        e(f"  %nd{j} = scalar.negf %dj{j} : f32")
        e(f"  %ij0{j} = scalar.divf<nnan|ninf|nsz|arcp> %fone, %dj{j} : f32")
        e(f"  %ije{j} = scalar.fmaf %nd{j}, %ij0{j}, %fone : f32")
        e(f"  %ij{j} = scalar.fmaf %ije{j}, %ij0{j}, %ij0{j} : f32")
        e(f"  %ijv{j} = vector.splat %ij{j} : vector<16xf32>")
        e(f"  %ndv{j} = vector.splat %nd{j} : vector<16xf32>")

    def exact_search():
        """hipfire's search: per candidate the exact codes clamp(rne(x / d)), errors x - RN(q d) squared, summed in
        order; the first minimum wins. Returns the winner's d, RN(1 / d), -d."""
        errs = []
        for j in QCANDS:
            e(f"    %q0{j} = vector.mulf %xq, %ijv{j} : vector<16xf32>")
            e(f"    %rr{j} = vector.fmaf %q0{j}, %ndv{j}, %xq : vector<16xf32>")
            e(f"    %qd{j} = vector.fmaf %rr{j}, %ijv{j}, %q0{j} : vector<16xf32>")
            e(f"    %qr{j} = vector.roundevenf %qd{j} : vector<16xf32>")
            e(f"    %ql{j} = vector.maxnumf<nnan> %qr{j}, %fl8v : vector<16xf32>")
            e(f"    %qc{j} = vector.minnumf<nnan> %ql{j}, %fh7v : vector<16xf32>")
            e(f"    %qm{j} = vector.mulf %qc{j}, %djv{j} : vector<16xf32>")
            e(f"    %er{j} = vector.subf %xq, %qm{j} : vector<16xf32>")
            e(f"    %e2{j} = vector.mulf %er{j}, %er{j} : vector<16xf32>")
            # vector.reduce's chain ((0 + e0) + e1) + .. without the 0 + (e0 = er^2 is never -0): an unpaired literal add
            acc = f"%e2{j}_0"
            e(f"    {acc} = vector.extract %e2{j}[0] : vector<16xf32> -> f32")
            for t in range(1, 16):
                e(f"    %e2{j}_{t} = vector.extract %e2{j}[{t}] : vector<16xf32> -> f32")
                nxt = f"%ms{j}" if t == 15 else f"%es{j}_{t}"
                e(f"    {nxt} = scalar.addf {acc}, %e2{j}_{t} : f32")
                acc = nxt
            errs.append(f"%ms{j}")
        e("    %msv = vector.from_elements " + ", ".join(errs) + f" : vector<{nc}xf32>")
        msr = reduce("%msv", f"vector<{nc}xf32>", "addf", "ms", "    ")
        j0 = QCANDS[0]
        best, bi, bn, bm = f"%dj{j0}", f"%ij{j0}", f"%nd{j0}", f"%mr{j0}"
        for n, j in enumerate(QCANDS):
            e(f"    %mr{j} = vector.extract {msr}[{n}] : vector<{nc}xf32> -> f32")
            if n:
                e(f"    %lt{j} = scalar.cmpf olt, %mr{j}, {bm} : f32")   # the first minimum wins, as hipfire
                e(f"    %bm{j} = scf.select %lt{j}, %mr{j}, {bm} : f32")
                e(f"    %bd{j} = scf.select %lt{j}, %dj{j}, {best} : f32")
                e(f"    %bi{j} = scf.select %lt{j}, %ij{j}, {bi} : f32")
                e(f"    %bn{j} = scf.select %lt{j}, %nd{j}, {bn} : f32")
                best, bi, bn, bm = f"%bd{j}", f"%bi{j}", f"%bn{j}", f"%bm{j}"
        return best, bi, bn

    # The fast search: codes clamp(rne(x RN(1 / d))), errors fma(-q, d, x), squares accumulated by fma. Against the
    # exact search, per candidate: the error terms and sums move by <= u (2 sqrt(X2 E) + 261 E) + u^2 X2 (u = 2^-24,
    # X2 = sum x^2, Cauchy-Schwarz), and a code can differ only where x / d is within 2^-19 of a half-integer, where
    # both codes' squared errors are ~d^2 / 4 and differ by <= 2^-18 d^2: <= 2^-15.9 E. So with
    # B(E) = 2^-14 E + 2^-21 sqrt(X2 E) + 2^-46 X2 + 2^-115, a best E' (first minimum) below every other E' - B by
    # more than its own B is the exact search's winner. Otherwise (near ties; amax in (0, 2^-30)) the whole wave runs
    # the exact search; amax = 0 gives all E = 0 in both, winner 0.
    if exact:
        acc = "%fz"
        for t in range(16):
            e(f"  %xx{t} = vector.extract %xq[{t}] : vector<16xf32> -> f32")
            e(f"  %x2c{t} = scalar.fmaf %xx{t}, %xx{t}, {acc} : f32")
            acc = f"%x2c{t}"
        x2 = reduce(acc, "f32", "addf", "x2")
    errs = []
    for j in QCANDS:
        e(f"  %cqr{j} = vector.mulf %xq, %ijv{j} : vector<16xf32>")
        e(f"  %cqx{j} = vector.addf %cqr{j}, %fmgv : vector<16xf32>")
        e(f"  %cql{j} = vector.maxnumf<nnan> %cqx{j}, %fmlv : vector<16xf32>")
        e(f"  %cqm{j} = vector.minnumf<nnan> %cql{j}, %fmhv : vector<16xf32>")
        e(f"  %cqc{j} = vector.subf %cqm{j}, %fmgv : vector<16xf32>")
        e(f"  %cer{j} = vector.fmaf %cqc{j}, %ndv{j}, %xq : vector<16xf32>")
        acc = "%fz"
        for t in range(16):
            e(f"  %cee{j}_{t} = vector.extract %cer{j}[{t}] : vector<16xf32> -> f32")
            nxt = f"%cms{j}" if t == 15 else f"%ces{j}_{t}"
            e(f"  {nxt} = scalar.fmaf %cee{j}_{t}, %cee{j}_{t}, {acc} : f32")
            acc = nxt
        errs.append(f"%cms{j}")
    e("  %cmsv = vector.from_elements " + ", ".join(errs) + f" : vector<{nc}xf32>")
    msr = reduce("%cmsv", f"vector<{nc}xf32>", "addf", "cms")
    e("  %cbig = scalar.constant 3.0e38 : f32")
    j0 = QCANDS[0]
    best, bi, bn, bm, sm = f"%dj{j0}", f"%ij{j0}", f"%nd{j0}", f"%cmr{j0}", "%cbig"
    for n, j in enumerate(QCANDS):
        e(f"  %cmr{j} = vector.extract {msr}[{n}] : vector<{nc}xf32> -> f32")
        if n:
            e(f"  %clt{j} = scalar.cmpf olt, %cmr{j}, {bm} : f32")
            if exact:
                e(f"  %csn{j} = scalar.minnumf<nnan> {sm}, %cmr{j} : f32")
                e(f"  %csm{j} = scf.select %clt{j}, {bm}, %csn{j} : f32")   # the runner-up: ties land here
            e(f"  %cbm{j} = scf.select %clt{j}, %cmr{j}, {bm} : f32")
            e(f"  %cbd{j} = scf.select %clt{j}, %dj{j}, {best} : f32")
            e(f"  %cbi{j} = scf.select %clt{j}, %ij{j}, {bi} : f32")
            e(f"  %cbn{j} = scf.select %clt{j}, %nd{j}, {bn} : f32")
            best, bi, bn, bm, sm = f"%cbd{j}", f"%cbi{j}", f"%cbn{j}", f"%cbm{j}", f"%csm{j}"
    if exact:
        best, bi, bn = _fallback(e, exact_search, x2, amax, best, bi, bn, bm, sm)
        # the winner's clamped codes again, by its candidate pass's ops: selecting the 8 candidates' codes instead costs
        # 112 v_cndmask and keeps them all live (192 vs 96 VGPRs, +6% cycles)
        e(f"  %wiv = vector.splat {bi} : vector<16xf32>")
        e(f"  %wnv = vector.splat {bn} : vector<16xf32>")
        e("  %wq0 = vector.mulf %xq, %wiv : vector<16xf32>")
        e("  %wrr = vector.fmaf %wq0, %wnv, %xq : vector<16xf32>")
        e("  %wqd = vector.fmaf %wrr, %wiv, %wq0 : vector<16xf32>")
        e("  %wqr = vector.roundevenf %wqd : vector<16xf32>")
        e("  %wql = vector.maxnumf<nnan> %wqr, %fl8v : vector<16xf32>")
        e("  %wqc = vector.minnumf<nnan> %wql, %fh7v : vector<16xf32>")
        _pack(e, total, span, "%wqc", best)
    else:
        e(f"  %wiv = vector.splat {bi} : vector<16xf32>")
        e("  %wqd = vector.mulf %xq, %wiv : vector<16xf32>")
        e("  %wqr = vector.addf %wqd, %fmgv : vector<16xf32>")
        e("  %wql = vector.maxnumf<nnan> %wqr, %fmlv : vector<16xf32>")
        e("  %wqc = vector.minnumf<nnan> %wql, %fmhv : vector<16xf32>")
        _pack(e, total, span, "%wqc", best, magic=True)


def _fallback(e, exact_search, x2, amax, best, bi, bn, bm, sm):
    """The fast search's bound check: near ties run the exact search (see _quant); returns the winner's d, RN(1 / d), -d."""
    e("  %bk14 = scalar.constant 6.103515625e-05 : f32")   # 2^-14
    e("  %bk21 = scalar.constant 4.76837158203125e-07 : f32")   # 2^-21
    e("  %bk46 = scalar.constant 1.4210854715202004e-14 : f32")   # 2^-46
    e("  %bk115 = scalar.constant 2.407412430484045e-35 : f32")   # 2^-115
    for nm, v in (("bb", bm), ("bs", sm)):
        e(f"  %{nm}p = scalar.mulf {x2}, {v} : f32")
        e(f"  %{nm}r = scalar.sqrtf %{nm}p : f32")
        e(f"  %{nm}1 = scalar.mulf {v}, %bk14 : f32")
        e(f"  %{nm}2 = scalar.fmaf %{nm}r, %bk21, %{nm}1 : f32")
        e(f"  %{nm}3 = scalar.fmaf {x2}, %bk46, %{nm}2 : f32")
        e(f"  %{nm} = scalar.addf %{nm}3, %bk115 : f32")
    e(f"  %bhi = scalar.addf {bm}, %bb : f32")
    e(f"  %slo = scalar.subf {sm}, %bs : f32")
    e("  %cok = scalar.cmpf ogt, %slo, %bhi : f32")
    e("  %cbad0 = scf.select %cok, %fz, %fone : f32")
    e("  %ctiny = scalar.constant 9.313225746154785e-10 : f32")   # 2^-30
    e(f"  %catn = scalar.cmpf olt, {amax}, %ctiny : f32")
    e("  %cbad1 = scf.select %catn, %fone, %cbad0 : f32")
    e(f"  %caz = scalar.cmpf oeq, {amax}, %fz : f32")
    e("  %cbad = scf.select %caz, %fz, %cbad1 : f32")
    e("  %cnbad = kernel.subgroup.reduce<addf> %cbad : f32")
    e("  %canyb = scalar.cmpf ogt, %cnbad, %fz : f32")
    e("  %wd, %wi, %wn = scf.if %canyb -> (f32, f32, f32) {")
    xb = exact_search()
    e(f"    scf.yield {xb[0]}, {xb[1]}, {xb[2]} : f32, f32, f32")
    e("  } else {")
    e(f"    scf.yield {best}, {bi}, {bn} : f32, f32, f32")
    e("  }")
    return "%wd", "%wi", "%wn"


def _pack(e, total, span, fc, best, magic=False):
    """Store the clamped codes fc (vector<16xf32>; magic: 1.5 2^23 + code, whose low bits are the code's two's
    complement) as nibbles and the span's scale best times 2^26."""
    e("  %m15 = scalar.constant 15 : i32")
    words = []
    for w in range(2):
        acc = None
        for j in range(8):
            i = 8 * w + j
            e(f"  %ne{i} = vector.extract {fc}[{i}] : vector<16xf32> -> f32")
            if magic:
                e(f"  %ni{i} = scalar.bitcast %ne{i} : f32 to i32")
            else:
                e(f"  %ni{i} = scalar.fptosi %ne{i} : f32 to i32")
            e(f"  %nn{i} = scalar.andi %ni{i}, %m15 : i32")
            cur = f"%nn{i}"
            if j:
                e(f"  %nsc{i} = scalar.constant {4 * j} : i32")
                e(f"  %ns{i} = scalar.shli %nn{i}, %nsc{i} : i32")
                cur = f"%ns{i}"
                e(f"  %no{i} = scalar.ori {acc}, {cur} : i32")
                cur = f"%no{i}"
            acc = cur
        words.append(acc)
    e(f"  %qw = vector.from_elements {words[0]}, {words[1]} : vector<2xi32>")
    e(f"  %qv = buffer.view %q_na[%base] : buffer -> view<{total // 8}xi32>")
    e("  %qk0 = index.add %rb, %kk : index")
    e("  %c8q = index.constant 8 : index")
    e("  %qk = index.div %qk0, %c8q : index")
    e(f"  vector.store %qw, %qv[%qk] : vector<2xi32>, view<{total // 8}xi32>")
    # the span's first lane stores the scale
    e(f"  %cspan = index.constant {span} : index")
    e(f"  %dview = buffer.view %d_na[%base] : buffer -> view<{total // span}xf32>")
    e("  %sk = index.rem %kk, %cspan : index")
    e("  %first = index.cmp eq, %sk, %c0 : index")
    e("  %di = index.div %qk0, %cspan : index")
    e("  scf.if %first {")   # stored times 2^26 (exact): the iu4 GEMM fold reads its integers as c * 2^-26
    e("    %d2p26 = scalar.constant 67108864.0 : f32")
    e(f"    %dst = scalar.mulf {best}, %d2p26 : f32")
    e(f"    view.store %dst, %dview[%di] : f32, view<{total // span}xf32>")
    e("  }")

# Polls before a flag-waiting kernel gives up (~0.2 s; a real wait is one producer workgroup, ~0.5 ms): a lost producer
# flag costs one bound per workgroup, not a hang or a ring timeout.
FLAG_POLLS = 200_000
FLAG_TT = 128   # tokens of a producer token tile


def flag_wait(e, cv, fv, tiles, need, lane, pre="fl"):
    """A flag-waiting kernel's start: wave 0 polls the counter cv[t] (view type fv) of each token tile t in tiles (SSA
    indices) until it reaches need (the producer's gen_gemm_iu4.flag_count; FLAG_POLLS bounds each), the other waves
    wait at the barrier; then the workgroup acquires (device scope), so the producer's stores are visible."""
    e(f"  %{pre}_need = scalar.constant {need} : i32")
    e(f"  %{pre}_zero = scalar.constant 0 : i32")
    e(f"  %{pre}_one = scalar.constant 1 : i32")
    e(f"  %{pre}_limit = scalar.constant {FLAG_POLLS} : i32")
    # one L2 request per round trip per workgroup, all on the counters' line
    e(f"  %{pre}_c32 = index.constant 32 : index")
    e(f"  %{pre}_w0 = index.cmp ult, {lane}, %{pre}_c32 : index")
    e(f"  scf.if %{pre}_w0 {{")
    for j, t in enumerate(tiles):
        q = f"%{pre}{j}"
        e(f"    {q}_n, {q}_v = scf.while({q}_i = %{pre}_zero : i32, {q}_p = %{pre}_zero : i32) -> (i32, i32) {{")
        e(f"      {q}_x = view.atomic.load {cv}[{t}] {{ordering = acquire, scope = device}} : {fv} -> i32")
        e(f"      {q}_early = scalar.cmpi slt, {q}_x, %{pre}_need : i32")
        e(f"      {q}_lt = scalar.cmpi ult, {q}_i, %{pre}_limit : i32")
        e(f"      {q}_go = scalar.andi {q}_early, {q}_lt : i1")
        e(f"      scf.condition {q}_go, {q}_i, {q}_x : i1, i32, i32")
        e(f"    }} do({q}_j: i32, {q}_w: i32) {{")
        e(f"      {q}_j1 = scalar.addi {q}_j, %{pre}_one : i32")
        e(f"      scf.yield {q}_j1, {q}_w : i32, i32")
        e("    }")
    e("  }")
    e("  kernel.barrier<global> scope(workgroup) ordering(acquire)")


def nq_flag_count(K):
    """What gen_nq oflag adds to a token tile's counter: one per wave of its FLAG_TT rows (emit_oflag)."""
    return FLAG_TT * (16 * K // 256) // 32


# gen_nq persist: what the row loop hoists (None, "rcp": the awq divide constants, "all": also signs and norm weights).
# "all": normqfo 113 -> 192 VGPRs, +25% cycles beside its GEMM; "rcp": 144 VGPRs, VALU -7% but +8% cycles (matched clock).
NQ_HOIST = None


def gen_nq(K, rows, span, eps=1e-6, flag=0, oflag=False, persist=0):
    """yah_normq: gen_half_norm's RMS norm of f32 x rows fused with gen_q (the norm-fed A4 sites): the f16 norm output
    never leaves the workgroup. One row per workgroup of 16 K / 256 lanes, lane (gl, a) the rotation lane of group gl.
    The lanes load their 16 values into LDS; wave 0 runs gen_half_norm's per-lane chains (lane l: ((0 + x_l x_l) +
    x_{l+32} x_{l+32}) + ..., mulf then addf) and its subgroup reduction, so inv has the norm's bits; each lane then forms
    f16((x inv) w) as the norm did and runs gen_q's rotation and quantization. Bindings: x, weight, awq, signs, q, d.
    flag (the producer's count per token tile, gen_gemm_iu4.flag_count): binding cnt after d, i32 [rows / FLAG_TT]
    (zero before the producer); the row waits until cnt[token tile] reaches flag (flag_wait), so the producer
    (gen_gemm_iu4.gen flag) runs without a graph barrier before this kernel.
    oflag: binding ocnt after them, i32 [rows / FLAG_TT] (zero before), nq_flag_count per token tile (emit_oflag), so a
    flag-waiting GEMM (gen_gemm_iu4.gen wait) runs without a graph barrier after this kernel.
    persist: grid (persist) instead of (rows), workgroup g does rows g, g + persist, ... in order: all workgroups are
    dispatched at once, so the queue reaches the flag-waiting GEMM behind it while the rows still run."""
    assert K % 256 == 0 and K % 32 == 0 and (not oflag or rows % FLAG_TT == 0) and (not persist or rows % persist == 0)
    ng = K // 256
    nth = 16 * ng
    total = K * rows
    LV = f"view<{ng * 16 * PITCH}xf32>"
    L = []
    e = L.append
    e("// GENERATED by tools/gen_rot.py gen_nq -- edit the generator.")
    e("amdgpu.target<gfx1151> @dm32 {subgroup_size = 32}")
    e("kernel.def target(@dm32) @yah_normq() {")
    e("  %u1 = index.constant 1 : index")
    e(f"  %cnth = index.constant {nth} : index")
    e(f"  %gy = index.constant {persist or rows} : index")
    e("  kernel.launch.config workgroups(%gy, %u1, %u1) workgroup_size(%cnth, %u1, %u1) : index")
    nt = rows // FLAG_TT
    e("} launch(%x: buffer, %weight: buffer, %awq: buffer, %sg: buffer, %q: buffer, %d: buffer"
      + (", %cnt: buffer" if flag else "") + (", %ocnt: buffer" if oflag else "") + ") {")
    e("  %base = index.constant 0 : offset")
    for v in (0, 1, 16, 32, 128, 256, PITCH, 16 * PITCH):
        e(f"  %c{v} = index.constant {v} : index")
    e(f"  %ck = index.constant {K} : index")
    nb = ["x", "weight", "awq", "sg", "q", "d"] + (["cnt"] if flag else []) + (["ocnt"] if oflag else [])
    e("  " + ", ".join(f"%{b}_na" for b in nb) + " = buffer.assume.noalias " + ", ".join(f"%{b}" for b in nb)
      + " : " + ", ".join(["buffer"] * len(nb)))
    e(f"  %xv = buffer.view %x_na[%base] : buffer -> view<{total}xf32>")
    e(f"  %wv = buffer.view %weight_na[%base] : buffer -> view<{K}xf32>")
    e(f"  %av = buffer.view %awq_na[%base] : buffer -> view<{K}xf32>")
    e("  %sv = buffer.view %sg_na[%base] : buffer -> view<512xf32>")
    # one LDS region: the row (f32 [K]) for the norm chains, then the rotation slabs (all values are in registers by then)
    assert ng * 16 * PITCH >= K
    e(f"  %lb = index.constant {ng * 16 * PITCH * 4} : offset")
    e("  %lds = buffer.alloca<workgroup> align(16) %lb : buffer")
    e(f"  %lv = buffer.view %lds[%base] : buffer -> {LV}")
    e(f"  %xrow = buffer.view %lds[%base] : buffer -> view<{K}xf32>")
    e("  %ib = index.constant 16 : offset")
    e("  %ilds = buffer.alloca<workgroup> align(16) %ib : buffer")
    e("  %iview = buffer.view %ilds[%base] : buffer -> view<4xf32>")
    e("  %lane = kernel.workitem.id<x> : index")

    def kslice():
        e("  %gl = index.div %lane, %c16 : index")
        e("  %a = index.rem %lane, %c16 : index")
        e("  %gk = index.mul %gl, %c256 : index")
        e("  %a16 = index.mul %a, %c16 : index")
        e("  %kk = index.add %gk, %a16 : index")
    hoist = persist and NQ_HOIST
    if hoist:   # the lane's k slice and awq divide constants once ("all": its signs and norm weights too)
        kslice()
        if NQ_HOIST == "all":
            _core_loads(e, K, True)
            e(f"  %w16 = vector.load %wv[%kk] : view<{K}xf32> -> vector<16xf32>")
        else:
            e(f"  %aw = vector.load %av[%kk] : view<{K}xf32> -> vector<16xf32>")
        _awrcp(e)
    if persist:
        e("  %wg = kernel.workgroup.id<x> : index")
        e(f"  %np = index.constant {rows // persist} : index")
        e(f"  %cp = index.constant {persist} : index")
        e("  scf.for %it = [%c0 to %np step %c1] {")
        e("  %row0 = index.mul %it, %cp : index")
        e("  %row1 = index.add %row0, %wg : index")
        e(f"  %row = index.assume %row1 [range(%row1, 0, {rows - 1})] : index")
    else:
        e("  %row = kernel.workgroup.id<x> : index")
    if flag:
        FV = f"view<{nt}xi32>"
        e(f"  %fl_tt = index.constant {FLAG_TT} : index")
        e("  %fl_tile = index.div %row, %fl_tt : index")
        e(f"  %fl_cv = buffer.view %cnt_na[%base] : buffer -> {FV}")
        flag_wait(e, "%fl_cv", FV, ["%fl_tile"], flag, "%lane")
    if not hoist:
        kslice()
    e("  %rb = index.mul %row, %ck : index")
    e("  %xi = index.add %rb, %kk : index")
    e(f"  %x16 = vector.load %xv[%xi] : view<{total}xf32> -> vector<16xf32>")
    e(f"  vector.store %x16, %xrow[%kk] : vector<16xf32>, view<{K}xf32>")
    e("  kernel.barrier<workgroup> scope(workgroup) ordering(acq_rel)")
    e("  %w0 = index.cmp ult, %lane, %c32 : index")
    e("  scf.if %w0 {")
    e("    %zero = scalar.constant 0.0 : f32")
    e("    %one = scalar.constant 1.0 : f32")
    e(f"    %eps = scalar.constant {eps!r} : f32")
    n = K // 32
    prev = "%zero"
    for k in range(n):   # load, square, add per value: all 160 loads hoisted would set the kernel's VGPRs
        e(f"    %no{k} = index.constant {32 * k} : index")
        e(f"    %na{k} = index.add %lane, %no{k} : index")
        e(f"    %nx{k} = view.load %xrow[%na{k}] : view<{K}xf32> -> f32")
        e(f"    %nq{k} = scalar.mulf %nx{k}, %nx{k} : f32")
        e(f"    %ns{k} = scalar.addf {prev}, %nq{k} : f32")
        prev = f"%ns{k}"
    e(f"    %sum_sq = kernel.subgroup.reduce<addf> {prev} : f32")
    e(f"    %dim_i = scalar.constant {K} : i32")
    e("    %dim_f = scalar.sitofp %dim_i : i32 to f32")
    e("    %mean = scalar.divf %sum_sq, %dim_f : f32")
    e("    %shifted = scalar.addf %mean, %eps : f32")
    e("    %root = scalar.sqrtf %shifted : f32")
    e("    %inv0 = scalar.divf %one, %root : f32")
    e("    %l0 = index.cmp eq, %lane, %c0 : index")
    e("    scf.if %l0 {")
    e("      view.store %inv0, %iview[%c0] : f32, view<4xf32>")
    e("    }")
    e("  }")
    e("  kernel.barrier<workgroup> scope(workgroup) ordering(acq_rel)")
    e("  %inv = view.load %iview[%c0] : view<4xf32> -> f32")
    e("  %invv = vector.splat %inv : vector<16xf32>")
    if not (hoist and NQ_HOIST == "all"):
        e(f"  %w16 = vector.load %wv[%kk] : view<{K}xf32> -> vector<16xf32>")
    e("  %nm = vector.mulf %x16, %invv : vector<16xf32>")
    e("  %wt = vector.mulf %nm, %w16 : vector<16xf32>")
    e("  %xh = vector.fptrunc %wt : vector<16xf32> to vector<16xf16>")
    e("  %xf = vector.extf %xh : vector<16xf16> to vector<16xf32>")
    if hoist and NQ_HOIST != "all":
        _core_loads(e, K, False)
    _core(e, K, total, True, "f16", ("q", "d"), LV, loaded="hoist" if hoist else False)
    _quant(e, total, span, LV)
    if oflag:
        emit_oflag(e, nt, "%row", "%lane")
    if persist:   # the next row reuses the LDS
        e("  kernel.barrier<workgroup> scope(workgroup) ordering(acq_rel)")
        e("  }")
    e("  kernel.return")
    e("}")
    return "\n".join(L) + "\n"


PN_HEADS = (48, 16, 128)   # DeltaNet value heads, key heads, head dim (rotq_heads)


PN_BGROUPS = 4   # the rotq groups of DeltaNet's second part (A4 sets: its heads are pn_heads("b"))


def pn_gguf(h):
    """the GGUF head of HF value head h (rotq_heads order: grouped by key head)"""
    nv, nk, _ = PN_HEADS
    return (h % (nv // nk)) * nk + h // (nv // nk)


def pnq_groups(part):
    """The rotq groups (256 HF values = HF heads 2g, 2g + 1) of gen_pnq part "b" (0 .. PN_BGROUPS - 1, after DeltaNet's
    second part) and "a" (the rest, beside it)."""
    ng = PN_HEADS[0] // 2
    return {"b": list(range(PN_BGROUPS)), "a": list(range(PN_BGROUPS, ng)), "ab": list(range(ng))}[part]


def pn_heads(part):
    """the GGUF heads of DeltaNet part a / b in A4 sets, in HF order: the heads of pnq_groups(part), so each pnq part
    reads one DeltaNet part's compact output"""
    return [pn_gguf(h) for g in pnq_groups(part) for h in (2 * g, 2 * g + 1)]


def _pn_values(e):
    """gen_pnq's postnorm of the lane's 16 raw values %xr (f32), its norm weights %w16 and gate %gh16: the workgroup's
    8 heads through LDS (%hrow, %iview), each wave's reduction for four of them, then the per-element ops into %xh
    (f16)."""
    # the workgroup's 8 heads in LDS (local head lh at lh 128, aliasing the rotation slabs: all reads end at the barrier)
    e("  %lk0 = index.mul %gl, %c256 : index")
    e("  %lk = index.add %lk0, %a16 : index")
    e("  vector.store %xr, %hrow[%lk] : vector<16xf32>, view<1024xf32>")
    e("  kernel.barrier<workgroup> scope(workgroup) ordering(acq_rel)")
    # the postnorm's reduction: wave w the local heads 4 w .. 4 w + 3, lane l ((0 + x_l^2) + x_{l+32}^2) + .., one
    # subgroup sum, then its inv
    e("  %pw = index.div %lane, %c32 : index")
    e("  %pl = index.rem %lane, %c32 : index")
    e("  %pzero = scalar.constant 0.0 : f32")
    e("  %pone = scalar.constant 1.0 : f32")
    e("  %pnegone = scalar.constant -1.0 : f32")
    e("  %peps = scalar.constant 0.000001 : f32")
    e("  %pinvdim = scalar.constant 0.0078125 : f32")
    e("  %pw2 = index.add %pw, %pw : index")
    e("  %pw4 = index.add %pw2, %pw2 : index")
    e("  %pl0 = index.cmp eq, %pl, %c0 : index")
    for j in range(4):
        e(f"  %plh{j} = index.add %pw4, %c{j} : index")
        e(f"  %pb0{j} = index.mul %plh{j}, %c128 : index")
        e(f"  %pb{j} = index.add %pb0{j}, %pl : index")
        acc = "%pzero"
        for t in range(4):
            e(f"  %po{j}_{t} = index.constant {32 * t} : index")
            e(f"  %pa{j}_{t} = index.add %pb{j}, %po{j}_{t} : index")
            e(f"  %pv{j}_{t} = view.load %hrow[%pa{j}_{t}] : view<1024xf32> -> f32")
            e(f"  %pq{j}_{t} = scalar.mulf %pv{j}_{t}, %pv{j}_{t} : f32")
            e(f"  %ps{j}_{t} = scalar.addf {acc}, %pq{j}_{t} : f32")
            acc = f"%ps{j}_{t}"
        e(f"  %ptot{j} = kernel.subgroup.reduce<addf> {acc} : f32")
        e(f"  %pscl{j} = scalar.mulf %ptot{j}, %pinvdim : f32")
        e(f"  %psh{j} = scalar.addf %pscl{j}, %peps : f32")
        e(f"  %prt{j} = scalar.sqrtf %psh{j} : f32")
        e(f"  %pinv{j} = scalar.divf %pone, %prt{j} : f32")
        e("  scf.if %pl0 {")
        e(f"    view.store %pinv{j}, %iview[%plh{j}] : f32, view<8xf32>")
        e("  }")
    e("  kernel.barrier<workgroup> scope(workgroup) ordering(acq_rel)")
    e("  %ah = index.div %a, %c8 : index")
    e("  %gl2 = index.add %gl, %gl : index")
    e("  %lh = index.add %gl2, %ah : index")
    e("  %inv = view.load %iview[%lh] : view<8xf32> -> f32")
    vals = []
    for i in range(16):
        e(f"  %ev{i} = vector.extract %xr[{i}] : vector<16xf32> -> f32")
        e(f"  %ew{i} = vector.extract %w16[{i}] : vector<16xf32> -> f32")
        e(f"  %egh{i} = vector.extract %gh16[{i}] : vector<16xf16> -> f16")
        e(f"  %eg{i} = scalar.extf %egh{i} : f16 to f32")
        e(f"  %enm{i} = scalar.mulf %ev{i}, %inv : f32")
        e(f"  %ewt{i} = scalar.mulf %enm{i}, %ew{i} : f32")
        e(f"  %eng{i} = scalar.mulf %eg{i}, %pnegone : f32")
        e(f"  %eex{i} = scalar.expf<afn> %eng{i} : f32")
        e(f"  %eden{i} = scalar.addf %pone, %eex{i} : f32")
        e(f"  %esig{i} = scalar.divf %pone, %eden{i} : f32")
        e(f"  %egt{i} = scalar.mulf %eg{i}, %esig{i} : f32")
        e(f"  %ers{i} = scalar.mulf %ewt{i}, %egt{i} : f32")
        e(f"  %eh{i} = scalar.fptrunc %ers{i} : f32 to f16")
        vals.append(f"%eh{i}")
    e("  %xh = vector.from_elements " + ", ".join(vals) + " : vector<16xf16>")


def gen_pnq(rows, span, part, o16=False, flag=0, dflag=0, oflag=False):
    """yah_pnq: the DeltaNet postnorm (yah_ssm_postnorm_gate_f16 with the f16 gate: per GGUF head, inv = 1 / sqrt(sum
    raw^2 / 128 + 1e-6), out = f16((raw inv) w (g sigmoid(g)))) fused with rotq_heads (gen_q with PN_HEADS): the f16
    postnorm output never leaves the workgroup. Part p takes pnq_groups(p), whose heads are DeltaNet part p's
    (pn_heads), read from that part's output raw: "a" runs beside DeltaNet's second part, "b" after it. Four groups per
    workgroup, grid (groups / 4, rows). Each lane loads its 16 raw values once into LDS; each wave runs the postnorm's
    own reduction for four of the workgroup's 8 heads from there (lane l chains raw[l + 32 j]^2 over j, then one subgroup
    sum: the postnorm's bits); each lane then forms its 16 values with the postnorm's per-element ops and runs gen_q's
    rotation and quantization.
    raw holds only this part's heads, in HF order (pn_heads(part)), 128 values each, so a token row of raw is the part's
    groups contiguous (its DeltaNet part writes it so), and the gate is in HF head order (the kstoreh GEMM): each part
    reads contiguous rows (heads spread over 48-head rows read 3-5x slower, DRAM bank conflicts).
    o16: raw is f16 O 2^O16_EXP (gen_gdn_chunk o16), scaled back here.
    flag (the gate GEMM's gen_gemm_iu4.flag_count): binding cnt after d (flag_wait on the row's token tile), so the
    gate GEMM runs without a graph barrier before this kernel.
    Part "ab": both parts in one grid (workgroup x 0 part b, 1.. part a), raw both compact outputs: part b's rows
    (rows x 1024), then part a's, so part b never waits behind part a's dispatch. dflag (DeltaNet part b's
    gen_gdn_ss.done_count): binding dcnt after cnt, also waited on, so raw needs no graph barrier behind part b (which
    runs beside the gate GEMM; part a is ordered before it).
    oflag: binding ocnt last, i32 [rows / FLAG_TT] (zero before): each wave counts itself in its row's token tile
    (emit_oflag; "ab": gen_q's q_flag_count of the 6144 values), so the kres after it waits instead of a graph barrier.
    Bindings: raw, weight [128], gate (f16), awq, signs, q, d."""
    nv, nk, hd = PN_HEADS
    r = nv // nk
    K = nv * hd
    groups = pnq_groups(part)
    ng = len(groups)
    assert ng % 4 == 0 and groups == list(range(groups[0], groups[0] + ng))
    total = K * rows
    LV = f"view<{4 * 16 * PITCH}xf32>"
    L = []
    e = L.append
    e("// GENERATED by tools/gen_rot.py gen_pnq -- edit the generator.")
    e("amdgpu.target<gfx1151> @dm32 {subgroup_size = 32}")
    e("kernel.def target(@dm32) @yah_pnq() {")
    e("  %u1 = index.constant 1 : index")
    e("  %c64 = index.constant 64 : index")
    e(f"  %gx = index.constant {ng // 4} : index")
    e(f"  %gy = index.constant {rows} : index")
    e("  kernel.launch.config workgroups(%gx, %gy, %u1) workgroup_size(%c64, %u1, %u1) : index")
    names = (["raw", "nw", "gate", "awq", "sg", "q", "d"] + (["cnt"] if flag else []) + (["dcnt"] if dflag else [])
             + (["ocnt"] if oflag else []))
    e("} launch(" + ", ".join(f"%{n}: buffer" for n in names) + ") {")
    e("  %base = index.constant 0 : offset")
    for v in (0, 1, 2, 3, 8, 16, 32, 128, 256, PITCH, 16 * PITCH):
        e(f"  %c{v} = index.constant {v} : index")
    e(f"  %ck = index.constant {K} : index")
    e(f"  %cg0 = index.constant {groups[0]} : index")
    e("  " + ", ".join(f"%{n}_na" for n in names) + " = buffer.assume.noalias " + ", ".join(f"%{n}" for n in names)
      + " : " + ", ".join(["buffer"] * len(names)))
    rtotal = ng * 256 * rows
    e(f"  %xv = buffer.view %raw_na[%base] : buffer -> view<{rtotal}x{'f16' if o16 else 'f32'}>")
    e(f"  %wv = buffer.view %nw_na[%base] : buffer -> view<{hd}xf32>")
    e(f"  %gv = buffer.view %gate_na[%base] : buffer -> view<{total}xf16>")
    e(f"  %av = buffer.view %awq_na[%base] : buffer -> view<{K}xf32>")
    e("  %sv = buffer.view %sg_na[%base] : buffer -> view<512xf32>")
    e(f"  %lb = index.constant {4 * 16 * PITCH * 4} : offset")
    e("  %lds = buffer.alloca<workgroup> align(16) %lb : buffer")
    e(f"  %lv = buffer.view %lds[%base] : buffer -> {LV}")
    e("  %hrow = buffer.view %lds[%base] : buffer -> view<1024xf32>")
    e("  %ib = index.constant 32 : offset")
    e("  %ilds = buffer.alloca<workgroup> align(16) %ib : buffer")
    e("  %iview = buffer.view %ilds[%base] : buffer -> view<8xf32>")
    e("  %lane = kernel.workitem.id<x> : index")
    e("  %wx = kernel.workgroup.id<x> : index")
    e("  %row = kernel.workgroup.id<y> : index")
    if flag:
        FV = f"view<{rows // FLAG_TT}xi32>"
        e(f"  %fl_tt = index.constant {FLAG_TT} : index")
        e("  %fl_tile = index.div %row, %fl_tt : index")
        e(f"  %fl_cv = buffer.view %cnt_na[%base] : buffer -> {FV}")
        flag_wait(e, "%fl_cv", FV, ["%fl_tile"], flag, "%lane")
    if dflag:
        e("  %dn_cv = buffer.view %dcnt_na[%base] : buffer -> view<1xi32>")
        flag_wait(e, "%dn_cv", "view<1xi32>", ["%c0"], dflag, "%lane", "dn")
    e("  %gl = index.div %lane, %c16 : index")
    e("  %a = index.rem %lane, %c16 : index")
    e("  %rb = index.mul %row, %ck : index")
    e("  %c4 = index.constant 4 : index")
    e("  %gx4 = index.mul %wx, %c4 : index")

    def group(gidx, tag):
        """the rotq group of workgroup-local index gidx"""
        e(f"  %{tag} = index.add {gidx}, %cg0 : index")
        return f"%{tag}"

    # this lane: group gl, 16 HF values k = 256 g + 16 a .. (local head lh = 2 gl + a / 8, offset ho in its head)
    e("  %gi = index.add %gx4, %gl : index")
    g = group("%gi", "g")
    e("  %gk = index.mul %g, %c256 : index")
    e("  %a16 = index.mul %a, %c16 : index")
    e("  %kk = index.add %gk, %a16 : index")
    e("  %ho = index.rem %kk, %c128 : index")
    e("  %xi0 = index.add %rb, %kk : index")   # the gate's HF index
    e(f"  %xlim = index.constant {total - 16} : index")
    e("  %xi = index.min %xi0, %xlim : index")   # bound proofs for the 16-wide loads (never clamps)
    e(f"  %holim = index.constant {hd - 16} : index")
    e("  %hoc = index.min %ho, %holim : index")
    e(f"  %w16 = vector.load %wv[%hoc] : view<{hd}xf32> -> vector<16xf32>")
    e(f"  %gh16 = vector.load %gv[%xi] : view<{total}xf16> -> vector<16xf16>")
    _core_loads(e, K, True)
    if part == "ab":   # workgroup 0 part b's compact row, the others part a's (after part b's rows, groups from nb)
        nb = len(pnq_groups("b"))
        e("  %ppa = index.min %wx, %c1 : index")
        e(f"  %crwa = index.constant {(ng - 2 * nb) * 256} : index")
        e(f"  %crwb = index.constant {nb * 256} : index")
        e("  %crwd = index.mul %ppa, %crwa : index")
        e("  %crw = index.add %crwb, %crwd : index")   # nb 256, or (ng - nb) 256 for part a
        e("  %kl0 = index.add %gx4, %gl : index")
        # part a: rows nb 256 + row (ng - nb) 256 + (g - nb) 256 = (rows - 1) nb 256 + row crw + g 256
        e(f"  %cpbo = index.constant {(rows - 1) * nb * 256} : index")
        e("  %pbo = index.mul %ppa, %cpbo : index")
    else:
        e(f"  %crw = index.constant {ng * 256} : index")   # this lane's 16 values in its compact raw row
        e("  %kl0 = index.add %gx4, %gl : index")
    e("  %kl1 = index.mul %kl0, %c256 : index")
    e("  %kl = index.add %kl1, %a16 : index")
    e("  %rr0 = index.mul %row, %crw : index")
    if part == "ab":
        e("  %rr1 = index.add %rr0, %pbo : index")
        e("  %ri0 = index.add %rr1, %kl : index")
    else:
        e("  %ri0 = index.add %rr0, %kl : index")
    e(f"  %rlim = index.constant {rtotal - 16} : index")
    e("  %ri = index.min %ri0, %rlim : index")   # bound proof (never clamps)
    if o16:
        import gen_gdn_chunk
        e(f"  %xrh = vector.load %xv[%ri] : view<{rtotal}xf16> -> vector<16xf16>")
        e("  %xre = vector.extf %xrh : vector<16xf16> to vector<16xf32>")
        e(f"  %xrs = scalar.constant {2.0 ** -gen_gdn_chunk.O16_EXP!r} : f32")
        e("  %xrsv = vector.splat %xrs : vector<16xf32>")
        e("  %xr = vector.mulf %xre, %xrsv : vector<16xf32>")   # exact: a power of 2
    else:
        e(f"  %xr = vector.load %xv[%ri] : view<{rtotal}xf32> -> vector<16xf32>")
    _pn_values(e)
    e("  %xf = vector.extf %xh : vector<16xf16> to vector<16xf32>")
    _core(e, K, total, True, "f16", ("q", "d"), LV, loaded=True)
    _quant(e, total, span, LV)
    if oflag:
        emit_oflag(e, rows // FLAG_TT, "%row", "%lane")
    e("  kernel.return")
    e("}")
    return "\n".join(L) + "\n"


def gen_pnqp(rows, span, P, flag, dflag):
    """gen_pnq "ab" (o16, flag, dflag, oflag) as P persistent workgroups (pnqp), like gen_qp: the grid's 12288
    workgroups queue ssm_out's kres behind them. Each token tile's items (workgroup x of gen_pnq's grid, row r: item
    j = 128 x + r) are split over the workgroups; a workgroup waits for dcnt once, polls the tile's gate counter once,
    prefetches its next item's gate and raw values while it computes the current one, then adds its item count to the tile's ocnt
    (per wave: q_flag_count in all). Same values as gen_pnq.
    P a multiple of the gen_pnq grid's x: items x fastest (j = x + nx r), so a workgroup keeps one x and loads its awq
    and reciprocal once."""
    import gen_gdn_chunk
    nv, nk, hd = PN_HEADS
    K = nv * hd
    groups = pnq_groups("ab")
    ng = len(groups)
    nb = len(pnq_groups("b"))
    assert ng % 4 == 0 and groups == list(range(groups[0], groups[0] + ng)) and rows % FLAG_TT == 0
    tt = rows // FLAG_TT
    nx = ng // 4
    per = nx * FLAG_TT
    assert P <= per
    cm = QP_CM and P % nx == 0
    total = K * rows
    rtotal = ng * 256 * rows
    LV = f"view<{4 * 16 * PITCH}xf32>"
    OV = f"view<{tt}xi32>"
    FV = f"view<{tt}xi32>"
    RV = f"view<{rtotal}xf16>"
    GV = f"view<{total}xf16>"
    L = []
    e = L.append
    e("// GENERATED by tools/gen_rot.py gen_pnqp -- edit the generator.")
    e("amdgpu.target<gfx1151> @dm32 {subgroup_size = 32}")
    e("kernel.def target(@dm32) @yah_pnq() {")
    e("  %u1 = index.constant 1 : index")
    e("  %c64 = index.constant 64 : index")
    e(f"  %gx = index.constant {P} : index")
    e("  kernel.launch.config workgroups(%gx, %u1, %u1) workgroup_size(%c64, %u1, %u1) : index")
    names = ["raw", "nw", "gate", "awq", "sg", "q", "d", "cnt", "dcnt", "ocnt"]
    e("} launch(" + ", ".join(f"%{n}: buffer" for n in names) + ") {")
    e("  %base = index.constant 0 : offset")
    for v in (0, 1, 2, 3, 8, 16, 32, 128, 256, PITCH, 16 * PITCH):
        e(f"  %c{v} = index.constant {v} : index")
    e(f"  %ck = index.constant {K} : index")
    e(f"  %cg0 = index.constant {groups[0]} : index")
    e("  " + ", ".join(f"%{n}_na" for n in names) + " = buffer.assume.noalias " + ", ".join(f"%{n}" for n in names)
      + " : " + ", ".join(["buffer"] * len(names)))
    e(f"  %xv = buffer.view %raw_na[%base] : buffer -> {RV}")
    e(f"  %wv = buffer.view %nw_na[%base] : buffer -> view<{hd}xf32>")
    e(f"  %gv = buffer.view %gate_na[%base] : buffer -> {GV}")
    e(f"  %av = buffer.view %awq_na[%base] : buffer -> view<{K}xf32>")
    e("  %sv = buffer.view %sg_na[%base] : buffer -> view<512xf32>")
    e(f"  %fl_cv = buffer.view %cnt_na[%base] : buffer -> {FV}")
    e(f"  %of_cv = buffer.view %ocnt_na[%base] : buffer -> {OV}")
    e(f"  %lb = index.constant {4 * 16 * PITCH * 4} : offset")
    e("  %lds = buffer.alloca<workgroup> align(16) %lb : buffer")
    e(f"  %lv = buffer.view %lds[%base] : buffer -> {LV}")
    e("  %hrow = buffer.view %lds[%base] : buffer -> view<1024xf32>")
    e("  %ib = index.constant 32 : offset")
    e("  %ilds = buffer.alloca<workgroup> align(16) %ib : buffer")
    e("  %iview = buffer.view %ilds[%base] : buffer -> view<8xf32>")
    e("  %lane = kernel.workitem.id<x> : index")
    e(f"  kernel.priority {{level = {QP_PRIO}}}")
    e("  %dn_cv = buffer.view %dcnt_na[%base] : buffer -> view<1xi32>")
    flag_wait(e, "%dn_cv", "view<1xi32>", ["%c0"], dflag, "%lane", "dn")
    e("  %gl = index.div %lane, %c16 : index")
    e("  %a = index.rem %lane, %c16 : index")
    e("  %c4 = index.constant 4 : index")
    e("  %a16 = index.mul %a, %c16 : index")
    e("  %s1 = vector.load %sv[%a16] : view<512xf32> -> vector<16xf32>")
    e("  %s2b = index.add %c256, %a : index")
    for i in range(16):
        e(f"  %so{i} = index.constant {16 * i} : index")
        e(f"  %s2i{i} = index.add %s2b, %so{i} : index")
        e(f"  %s2_{i} = view.load %sv[%s2i{i}] : view<512xf32> -> f32")
    e("  %qw = kernel.workgroup.id<x> : index")
    e(f"  %qP = index.constant {P} : index")
    e(f"  %qT = index.constant {per} : index")
    e(f"  %qTm = index.constant {per - 1} : index")
    e(f"  %qct = index.constant {tt} : index")
    e("  %qn0 = index.sub %qT, %qw : index")
    e("  %qn1 = index.add %qn0, %qP : index")
    e("  %qn2 = index.sub %qn1, %c1 : index")
    e("  %qn = index.div %qn2, %qP : index")
    e("  %qni = index.cast %qn : index to i32")
    e(f"  %qneed = scalar.constant {flag} : i32")
    e(f"  %qlimit = scalar.constant {FLAG_POLLS} : i32")
    e("  %qzero = scalar.constant 0 : i32")
    e("  %qone = scalar.constant 1 : i32")
    e("  %qw0 = index.cmp ult, %lane, %c32 : index")
    e("  %of_l = index.rem %lane, %c32 : index")
    e("  %of_l0 = index.cmp eq, %of_l, %c0 : index")
    e(f"  %xlim = index.constant {total - 16} : index")
    e(f"  %holim = index.constant {hd - 16} : index")
    e(f"  %rlim = index.constant {rtotal - 16} : index")
    e(f"  %crwa = index.constant {(ng - 2 * nb) * 256} : index")
    e(f"  %crwb = index.constant {nb * 256} : index")
    e(f"  %cpbo = index.constant {(rows - 1) * nb * 256} : index")
    # the norm weights: offset 16 a in every head (256 g + 16 a mod 128), loop-invariant
    e("  %ho = index.rem %a16, %c128 : index")
    e("  %hoc = index.min %ho, %holim : index")
    e(f"  %w16 = vector.load %wv[%hoc] : view<{hd}xf32> -> vector<16xf32>")

    def addr(p, j, row0, loads):
        """Item j (gen_pnq workgroup x = j / 128, row row0 + j % 128; cm: x = j % nx, row row0 + j / nx): the lane's
        indices (%{p}rb, %{p}kk, ..) and, with loads, its gate and raw values %{p}gh16, %{p}xrh."""
        if cm:
            e(f"  %{p}wx = index.rem {j}, %cnx : index")
            e(f"  %{p}r = index.div {j}, %cnx : index")
        else:
            e(f"  %{p}wx = index.div {j}, %c128 : index")
            e(f"  %{p}r = index.rem {j}, %c128 : index")
        e(f"  %{p}row = index.add {row0}, %{p}r : index")
        e(f"  %{p}rb = index.mul %{p}row, %ck : index")
        e(f"  %{p}gx4 = index.mul %{p}wx, %c4 : index")
        e(f"  %{p}gi = index.add %{p}gx4, %gl : index")
        e(f"  %{p}g = index.add %{p}gi, %cg0 : index")
        e(f"  %{p}gk = index.mul %{p}g, %c256 : index")
        e(f"  %{p}kk = index.add %{p}gk, %a16 : index")
        if not loads:
            return
        e(f"  %{p}xi0 = index.add %{p}rb, %{p}kk : index")
        e(f"  %{p}xi = index.min %{p}xi0, %xlim : index")
        e(f"  %{p}gh16 = vector.load %gv[%{p}xi] : {GV} -> vector<16xf16>")
        # workgroup x 0: part b's compact row, the others part a's (gen_pnq "ab")
        e(f"  %{p}ppa = index.min %{p}wx, %c1 : index")
        e(f"  %{p}crwd = index.mul %{p}ppa, %crwa : index")
        e(f"  %{p}crw = index.add %crwb, %{p}crwd : index")
        e(f"  %{p}pbo = index.mul %{p}ppa, %cpbo : index")
        e(f"  %{p}kl1 = index.mul %{p}gi, %c256 : index")
        e(f"  %{p}kl = index.add %{p}kl1, %a16 : index")
        e(f"  %{p}rr0 = index.mul %{p}row, %{p}crw : index")
        e(f"  %{p}rr1 = index.add %{p}rr0, %{p}pbo : index")
        e(f"  %{p}ri0 = index.add %{p}rr1, %{p}kl : index")
        e(f"  %{p}ri = index.min %{p}ri0, %rlim : index")
        e(f"  %{p}xrh = vector.load %xv[%{p}ri] : {RV} -> vector<16xf16>")

    V16H, V16F = "vector<16xf16>", "vector<16xf32>"
    if cm:   # the workgroup's x: its awq and the reciprocal (_core's Markstein divide) once
        e(f"  %cnx = index.constant {nx} : index")
        addr("h_", "%qw", "%c0", False)
        e(f"  %aw = vector.load %av[%h_kk] : view<{K}xf32> -> vector<16xf32>")
        _awrcp(e)
    e("  scf.for %qtt = [%c0 to %qct step %c1] {")
    e("  %qrow0 = index.mul %qtt, %c128 : index")
    e("  scf.if %qw0 {")
    e("    %qfn = scf.while(%qfi = %qzero : i32) -> (i32) {")
    e(f"      %qfx = view.atomic.load %fl_cv[%qtt] {{ordering = relaxed, scope = device}} : {FV} -> i32")
    e("      %qfe = scalar.cmpi slt, %qfx, %qneed : i32")
    e("      %qfl = scalar.cmpi ult, %qfi, %qlimit : i32")
    e("      %qfg = scalar.andi %qfe, %qfl : i1")
    e("      scf.condition %qfg, %qfi : i1, i32")
    e("    } do(%qfj: i32) {")
    e("      %qfj1 = scalar.addi %qfj, %qone : i32")
    e("      scf.yield %qfj1 : i32")
    e("    }")
    e("  }")
    e("  kernel.barrier<global> scope(workgroup) ordering(acquire)")
    addr("f_", "%qw", "%qrow0", True)
    e("  %qe0, %qe1 = scf.for %qj = [%qw to %qT step %qP](%qxrh = %f_xrh : " + V16H + ", %gh16 = %f_gh16 : " + V16H
      + ") -> (" + V16H + ", " + V16H + ") {")
    e("  %qj1 = index.add %qj, %qP : index")
    e("  %qjn = index.min %qj1, %qTm : index")   # the last item's prefetch: a harmless reload
    addr("n_", "%qjn", "%qrow0", True)
    e("  kernel.barrier<workgroup> scope(workgroup) ordering(acq_rel)")   # the last item's LDS reads before these writes
    addr("", "%qj", "%qrow0", False)
    if not cm:
        e(f"  %aw = vector.load %av[%kk] : view<{K}xf32> -> vector<16xf32>")   # L2-resident: not prefetched
    e("  %xre = vector.extf %qxrh : vector<16xf16> to vector<16xf32>")
    e(f"  %xrs = scalar.constant {2.0 ** -gen_gdn_chunk.O16_EXP!r} : f32")
    e("  %xrsv = vector.splat %xrs : vector<16xf32>")
    e("  %xr = vector.mulf %xre, %xrsv : vector<16xf32>")   # exact: a power of 2
    _pn_values(e)
    e("  %xf = vector.extf %xh : vector<16xf16> to vector<16xf32>")
    _core(e, K, total, True, "f16", ("q", "d"), LV, loaded="hoist" if cm else True)
    _quant(e, total, span, LV)
    e("  scf.yield %n_xrh, %n_gh16 : " + V16H + ", " + V16H)
    e("  }")
    # this workgroup's items of the tile are stored: each wave counts them (device-scope release)
    e("  %of_tile = index.add %qtt, %c0 : index")
    e("  scf.if %of_l0 {")
    e(f"    view.atomic.reduce<addi> %qni, %of_cv[%of_tile] {{ordering = release, scope = device}} : i32, {OV}")
    e("  }")
    e("  }")
    e("  kernel.return")
    e("}")
    return "\n".join(L) + "\n"


