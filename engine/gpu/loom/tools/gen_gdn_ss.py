#!/usr/bin/env python3
"""Generate the state-stationary chunked Gated DeltaNet prefill kernel: gen_gdn_chunk's math and bits, one workgroup per
head, the state in registers.

usage: gen_gdn_ss.py [out.loom]

Same ABI as gen_gdn_chunk.gen(heads=..., vconv=True, o16=True) (bindings conv, x, conv_weights, conv_state, alpha, beta,
ssm_a, ssm_dt, valid, state, out), grid (1, len(heads)) x THREADS = 288 threads (9 wave32 waves; dispatch.txt
"dnthreads").

gen_gdn_chunk splits a head's 128 value rows over two workgroups, so both run the head's v-independent work (KK^T, QK^T,
the solve, W) and stage the f16 state in LDS for the X / O1 fragment loads each chunk. Here wave w owns value rows
16 w .. +15 over all 128 keys, as S^T [key][row]: 8 f32 accumulator tiles (tile j: keys 16 j .. +15). KS = K S^T and
O1 = Q S^T take S^T's f16 rhs fragments straight from the accumulators (vector.fragment.repack: fptrunc, one half-wave
exchange and one v_perm per register), and so do Y, P Vn and the update K^T Vn'; KS, V, Y, Vn, Vn' and O never leave
the wave.

Waves 0-7 (the row waves) own the value rows; wave 8 (the solver) runs a loop of its own one chunk ahead: while the
row waves work on chunk c it solves chunk c + 1 (T2 into T buffer (c + 1) % 2) and computes chunk c + 2's gates
(GA buffer (c + 2) % 3) and A = K K^T (K fragments from the conv buffer), spread over the row waves' phases where
its SIMD has issue slots to spare. Each role loop runs the same 3 workgroup barriers per chunk under one wave-uniform
branch (HRX patch 0037). Per chunk, rows:
    P1  K, Q -> LDS (Kt transposed), this chunk's v conv taps and next chunk's K, Q loads, the previous chunk's O stores
    P2  P = QK^T (waves 5-7, one lower tile each), KS = K S^T, O1 = Q S^T
    P5  V = the v conv of the wave's 16 channels in the accumulator layout, Y = V - 2^G KS, Vn = T2 Y,
        Vn' = 2^(G_C - G) Vn, O = 2^G O1 + P Vn, S^T <- 2^G_C S^T + K^T Vn'
Vn = T2 (V - 2^G KS) reassociates gen_gdn_chunk's T2 V - (T1 K) S^T (T1 = T2 2^G; one f16 rounding of Y instead of V
and W) and the v conv taps are fma_mix with a plain rcp: not bit-identical to it.
"""
import sys

from gen_gdn_chunk import O16_EXP, TPRE

C, D = 32, 128
THREADS = 288
S1 = 10   # the solver's solve steps in the row waves' phase 1
V8 = "vector<8xf32>"
V4 = "vector<4xf32>"
V16H = "vector<16xf16>"
V8H = "vector<8xf16>"
V4H = "vector<4xf16>"
# LDS regions (bytes): K|Q rows, Kt [key][tok] (key k at row k + k / 16: the transposed stores' 8 key segments
# land on distinct banks), -A^T (f32, the solver's), P, T2 (2 buffers), gates (3 buffers), conv weights [128][4] and
# conv ring x[-3..-1] [128][3] (f32)
KQ, KT, AF, PP, T2, GA, CW, CS = 0, 17408, 28288, 32896, 35456, 40576, 42880, 44928
POOL = CS + 128 * 3 * 4
assert POOL <= 65536


def gen(heads):
    L = []
    e = L.append
    nh = len(heads)
    e("// GENERATED by tools/gen_gdn_ss.py -- edit the generator.")
    e("// State-stationary chunked (WY) Gated DeltaNet, C = 32; ABI of yah_deltanet (vconv, o16).")
    e("amdgpu.target<gfx1151> @gdn_w32 {subgroup_size = 32}")
    e("")
    e("config.decl @yah_deltanet.batch : %value: index where [range(%value, 32, 1048576)]")
    e("config.decl @yah_deltanet.qkv_size : %value: index where [range(%value, 128, 1048576)]")
    e("config.decl @yah_deltanet.inner_size : %value: index where [range(%value, 128, 1048576)]")
    e("config.decl @yah_deltanet.num_key_heads : %value: index where [range(%value, 1, 4096)]")
    e("config.decl @yah_deltanet.num_heads : %value: index where [range(%value, 1, 4096)]")
    e("")
    e("kernel.def target(@gdn_w32) @yah_deltanet() {")
    e("  %unit = index.constant 1 : index")
    e(f"  %nthreads = index.constant {THREADS} : index")
    e(f"  %launch_heads = index.constant {nh} : index")
    e("  kernel.launch.config workgroups(%unit, %launch_heads, %unit) workgroup_size(%nthreads, %unit, %unit) : index")
    e("} launch(%conv: buffer, %x: buffer, %cw: buffer, %cst: buffer, %alpha: buffer, %beta: buffer, %ssm_a: buffer, "
      "%ssm_dt: buffer, %valid: buffer, %state: buffer, %out: buffer) {")
    e("  %base = index.constant 0 : offset")
    for v in (0, 1, 2, 3, 4, 5, 6, 7, 8, 16, 31, 32, 40, 48, 64, 127, 128, 255, 16384):
        e(f"  %c{v} = index.constant {v} : index")
    e("  %zero = scalar.constant 0.0 : f32")
    e("  %one = scalar.constant 1.0 : f32")
    e("  %zh = scalar.constant 0.0 : f16")
    e("  %negone = scalar.constant -1.0 : f32")
    e(f"  %zeros8 = vector.constant 0.0 : {V8}")
    e("  %m = index.constant 16 : index")
    e("  %n = index.constant 16 : index")
    e("  %k = index.constant 16 : index")
    e(f"  %zs = vector.fragment<init> %zeros8 shape [%m, %n] : {V8}")
    e("  %batch = config.get @yah_deltanet.batch : index")
    e("  %qkv_size = config.get @yah_deltanet.qkv_size : index")
    e("  %inner_size = config.get @yah_deltanet.inner_size : index")
    e("  %num_key_heads = config.get @yah_deltanet.num_key_heads : index")
    e("  %num_heads = config.get @yah_deltanet.num_heads : index")
    e("  %conv_total = index.mul %batch, %qkv_size : index")
    e("  %state_total = index.mul %num_heads, %c16384 : index")
    e("  %out_total = index.mul %batch, %inner_size : index")
    e("  %ra_total = index.mul %batch, %num_heads : index")
    e("  %cw_total = index.mul %qkv_size, %c4 : index")
    e("  %cv_na, %x_na, %cw_na, %cst_na, %al_na, %be_na, %sa_na, %sdt_na, %st_na, %out_na = buffer.assume.noalias %conv, "
      "%x, %cw, %cst, %alpha, %beta, %ssm_a, %ssm_dt, %state, %out : buffer, buffer, buffer, buffer, buffer, buffer, "
      "buffer, buffer, buffer, buffer")
    e("  %conv_view = buffer.view %cv_na[%base] : buffer -> view<[%conv_total]xf16>")
    e("  %x_view = buffer.view %x_na[%base] : buffer -> view<[%conv_total]xf16>")
    e("  %cw_view = buffer.view %cw_na[%base] : buffer -> view<[%cw_total]xf32>")
    e("  %cst_view = buffer.view %cst_na[%base] : buffer -> view<[%cw_total]xf32>")
    e("  %al_view = buffer.view %al_na[%base] : buffer -> view<[%ra_total]xf32>")
    e("  %be_view = buffer.view %be_na[%base] : buffer -> view<[%ra_total]xf32>")
    e("  %sa_view = buffer.view %sa_na[%base] : buffer -> view<[%num_heads]xf32>")
    e("  %sdt_view = buffer.view %sdt_na[%base] : buffer -> view<[%num_heads]xf32>")
    e("  %valid_view = buffer.view %valid[%base] : buffer -> view<1xi32>")
    e("  %state_view = buffer.view %st_na[%base] : buffer -> view<[%state_total]xf32>")
    e("  %out_view = buffer.view %out_na[%base] : buffer -> view<[%out_total]xf16>")
    e(f"  %o16_sc = scalar.constant {float(2 ** O16_EXP)!r} : f32")
    e("  %o16_hi = scalar.constant 65504.0 : f32")
    e("  %o16_lo = scalar.constant -65504.0 : f32")
    e(f"  %pool_bytes = index.constant {POOL} : offset")
    e("  %pool = buffer.alloca<workgroup> align(16) %pool_bytes : buffer")

    def region(name, off):
        e(f"  %{name}_o = index.constant {off} : offset")
        return f"%{name}_o"

    def lay(name, pitch):
        e(f"  %{name}_lay = encoding.layout.strided [1, {pitch}] : encoding<layout>")
        return f"%{name}_lay"
    o = region("kr", KQ)
    e(f"  %kq_l = buffer.view %pool[{o}] : buffer -> view<64x136xf16>")          # rows 0-31 K (later W), 32-63 Q
    l_ = lay("kr", 136)
    e(f"  %kr_r = buffer.view %pool[{o}] : buffer -> view<128x32xf16, {l_}>")      # B[key][tok] from K[tok][key]
    o = region("kt", KT)
    e(f"  %kt_w = buffer.view %pool[{o}] : buffer -> view<136x40xf16>")              # Kt[key][tok]; lhs A[key][tok]
    o = region("af", AF)
    e(f"  %a_v = buffer.view %pool[{o}] : buffer -> view<32x36xf32>")
    o = region("pp", PP)
    e(f"  %p_v = buffer.view %pool[{o}] : buffer -> view<32x40xf16>")
    o = region("t2", T2)
    e(f"  %t2_v = buffer.view %pool[{o}] : buffer -> view<64x40xf16>")
    o = region("ga", GA)
    e(f"  %ga = buffer.view %pool[{o}] : buffer -> view<18x32xf32>")
    o = region("cw", CW)
    e(f"  %cws = buffer.view %pool[{o}] : buffer -> view<128x4xf32>")
    o = region("cs", CS)
    e(f"  %css = buffer.view %pool[{o}] : buffer -> view<128x3xf32>")
    for i, nm in enumerate(("LG", "G2", "BETA", "BG", "GC", "GG")):
        e(f"  %ga{nm} = index.constant {i} : index")

    # head: heads[workgroup y], a select chain (scalar, once)
    e("  %h_rel = kernel.workgroup.id<y> : index")
    cur = f"%ht_c{heads[0]}"
    e(f"  {cur} = index.constant {heads[0]} : index")
    if len(heads) == 1:
        e(f"  %h = index.add {cur}, %c0 : index")
    for i, hv in enumerate(heads[1:], 1):
        e(f"  %ht_i{i} = index.constant {i} : index")
        e(f"  %ht_v{i} = index.constant {hv} : index")
        e(f"  %ht_e{i} = index.cmp eq, %h_rel, %ht_i{i} : index")
        nxt = "%h" if i == len(heads) - 1 else f"%ht_s{i}"
        e(f"  {nxt} = scf.select %ht_e{i}, %ht_v{i}, {cur} : index")
        cur = nxt
    e("  %tid = kernel.workitem.id<x> : index")
    e("  %sg = kernel.subgroup.id : index")
    e("  %lane = index.rem %tid, %c32 : index")
    e("  %sub = index.rem %lane, %c16 : index")
    e("  %half = index.div %lane, %c16 : index")
    e("  %kh = index.rem %h, %num_key_heads : index")
    e("  %q_rel = index.mul %kh, %c128 : index")
    e("  %k_head = index.add %num_key_heads, %kh : index")
    e("  %k_rel = index.mul %k_head, %c128 : index")
    # K [tok][key] of this head straight from the conv buffer (the solver's K K^T)
    e("  %kg_offi = index.mul %k_rel, %c2 : index")
    e("  %kg_off = index.cast %kg_offi : index to offset")
    e("  %kg_lay = encoding.layout.strided [%qkv_size, %c1] : encoding<layout>")
    e("  %kg = buffer.view %cv_na[%kg_off] : buffer -> view<[%batch]x128xf16, %kg_lay>")
    e("  %v_heads = index.mul %num_key_heads, %c2 : index")
    e("  %v_head = index.add %v_heads, %h : index")
    e("  %v_rel = index.mul %v_head, %c128 : index")
    e("  %o_rel = index.mul %h_rel, %c128 : index")
    e("  %s_head = index.mul %h, %c16384 : index")
    # wave roles: wave 8 the solver; row waves: value rows 16 sg .. +15 (the solver's row-wave values are clamped
    # copies of wave 7's: computed, never used)
    e("  %issv = index.cmp eq, %sg, %c8 : index")
    e("  %sgc = index.min %sg, %c7 : index")
    e("  %row0 = index.mul %sgc, %c16 : index")
    e("  %row = index.add %row0, %sub : index")         # accumulator column (S^T, U, Vn, O): value row
    e("  %orow = index.add %o_rel, %row : index")

    # ---- initial state: S^T tile j element i = S[row][16 j + 2 i + half]; each lane loads keys 16 j + 8 half .. +7
    # (two b128) and trades the other parity with its xor-16 partner (one shuffle per tile)
    e("  %srow = index.mul %row, %c128 : index")
    e("  %sb0 = index.add %s_head, %srow : index")
    e("  %sb8h = index.mul %half, %c8 : index")
    e("  %sbq = index.add %sb0, %sb8h : index")
    e("  %shi = index.cmp eq, %half, %c1 : index")
    e("  %ssx16 = scalar.constant 16 : i32")
    e("  %ssx32 = scalar.constant 32 : i32")

    def swap_halves(ind, p, send):
        """the xor-16 partner's values of send (4 f32)"""
        e(f"{ind}%{p}s4 = vector.from_elements {', '.join(send)} : {V4}")
        e(f"{ind}%{p}p4, %{p}pv = kernel.subgroup.shuffle<xor> %{p}s4, %ssx16, %ssx32 : {V4}, i32, i32")
        out = []
        for k in range(4):
            e(f"{ind}%{p}p{k} = vector.extract %{p}p4[{k}] : {V4} -> f32")
            out.append(f"%{p}p{k}")
        return out
    st = []
    for j in range(8):
        e(f"  %sq{j}c = index.constant {16 * j} : index")
        e(f"  %sq{j}a = index.add %sbq, %sq{j}c : index")
        e(f"  %sq{j}b = index.add %sq{j}a, %c4 : index")
        lv = []
        for hlf in "ab":
            e(f"  %sl{j}{hlf} = vector.load %state_view[%sq{j}{hlf}] : view<[%state_total]xf32> -> {V4}")
            for k in range(4):
                e(f"  %sl{j}{hlf}{k} = vector.extract %sl{j}{hlf}[{k}] : {V4} -> f32")
                lv.append(f"%sl{j}{hlf}{k}")
        # half 0 holds keys 0 .. 7 (keeps the even ones), half 1 keys 8 .. 15 (keeps the odd ones)
        send = []
        for k in range(4):
            e(f"  %ss{j}_{k} = scf.select %shi, {lv[2 * k]}, {lv[2 * k + 1]} : f32")
            send.append(f"%ss{j}_{k}")
        pk = swap_halves("  ", f"si{j}", send)
        els = [None] * 8
        for k in range(4):
            e(f"  %sv{j}_{k} = scf.select %shi, {pk[k]}, {lv[2 * k]} : f32")
            e(f"  %sv{j}_{4 + k} = scf.select %shi, {lv[2 * k + 1]}, {pk[k]} : f32")
            els[k], els[4 + k] = f"%sv{j}_{k}", f"%sv{j}_{4 + k}"
        e(f"  %si{j} = vector.from_elements {', '.join(els)} : {V8}")
        st.append(f"%si{j}")
    # ---- v conv weights and ring (channel tid < 128)
    e("  %vc_cl = index.min %tid, %c127 : index")
    e("  %vc_ch = index.add %v_rel, %vc_cl : index")
    e("  %vc_wa = index.mul %vc_ch, %c4 : index")
    e(f"  %vc_w = vector.load %cw_view[%vc_wa] : view<[%cw_total]xf32> -> {V4}")
    e(f"  %vc_s = vector.load %cst_view[%vc_wa] : view<[%cw_total]xf32> -> {V4}")
    e("  %vc_own = index.cmp ult, %tid, %c128 : index")
    e("  scf.if %vc_own {")
    e(f"    vector.store %vc_w, %cws[%tid, %c0] : {V4}, view<128x4xf32>")
    for j in (1, 2, 3):
        e(f"    %vc_s{j} = vector.extract %vc_s[{j}] : {V4} -> f32")
        e(f"    %vc_s{j}c = index.constant {j - 1} : index")
        e(f"    view.store %vc_s{j}, %css[%tid, %vc_s{j}c] : f32, view<128x3xf32>")
    e("  }")
    e("  kernel.barrier<workgroup> scope(workgroup) ordering(acq_rel)")
    e("  %ab_dt = view.load %sdt_view[%h] : view<[%num_heads]xf32> -> f32")
    e("  %ab_a = view.load %sa_view[%h] : view<[%num_heads]xf32> -> f32")
    e("  %ab_vraw = view.load %valid_view[%c0] : view<1xi32> -> i32")
    e("  %ab_vi = index.cast %ab_vraw : i32 to index")
    e("  %ab_vlo = index.max %ab_vi, %c1 : index")
    e("  %ab_vld = index.min %ab_vlo, %batch : index")
    e("  %vc_c = index.add %v_rel, %row : index")       # this lane's v channel
    e("  %nchunks = index.div %batch, %c32 : index")
    e("  %lastc = index.sub %nchunks, %c1 : index")
    # per-thread fetch map: token lt = tid / 8; K/Q dims (tid % 8) * 16 .. +15
    e("  %tidc = index.min %tid, %c255 : index")
    e("  %lt = index.div %tidc, %c8 : index")
    e("  %seg8 = index.rem %tidc, %c8 : index")
    e("  %dseg = index.mul %seg8, %c16 : index")
    e("  %qrow = index.add %lt, %c32 : index")
    e("  %kseg = index.add %dseg, %seg8 : index")         # Kt row of key dseg

    def fetch_rows(cidx, p, ind, kq=True):
        """the row waves' loads of chunk cidx: K, Q (normalized f16) or the v conv taps"""
        e(f"{ind}%{p}t0 = index.mul {cidx}, %c32 : index")
        e(f"{ind}%{p}tok = index.add %{p}t0, %lt : index")
        e(f"{ind}%{p}crow = index.mul %{p}tok, %qkv_size : index")
        names, vx = [], []
        for nm, rel in (("k", "%k_rel"), ("q", "%q_rel")) if kq else ():
            e(f"{ind}%{p}{nm}base0 = index.add %{p}crow, {rel} : index")
            e(f"{ind}%{p}{nm}base = index.add %{p}{nm}base0, %dseg : index")
            for g in range(4):
                e(f"{ind}%{p}{nm}a{g}c = index.constant {4 * g} : index")
                e(f"{ind}%{p}{nm}a{g} = index.add %{p}{nm}base, %{p}{nm}a{g}c : index")
                e(f"{ind}%{p}{nm}v{g} = vector.load %conv_view[%{p}{nm}a{g}] : view<[%conv_total]xf16> -> {V4H}")
                names.append(f"%{p}{nm}v{g}")
        # v conv taps (this lane's channel %row, tokens t0 + half + k - 3, k = 0 .. 33; k < 3 clamped at token 0)
        e(f"{ind}%{p}vb = index.add %{p}t0, %half : index")
        for k in range(0 if kq else 34):
            if k < 3:
                e(f"{ind}%{p}vt{k}m = index.max %{p}vb, %c{3 - k} : index")
                e(f"{ind}%{p}vt{k} = index.sub %{p}vt{k}m, %c{3 - k} : index")
            else:
                e(f"{ind}%{p}vt{k}c = index.constant {k - 3} : index")
                e(f"{ind}%{p}vt{k} = index.add %{p}vb, %{p}vt{k}c : index")
            e(f"{ind}%{p}vr{k} = index.mul %{p}vt{k}, %qkv_size : index")
            e(f"{ind}%{p}vo{k} = index.add %{p}vr{k}, %vc_c : index")
            e(f"{ind}%{p}vx{k} = view.load %x_view[%{p}vo{k}] : view<[%conv_total]xf16> -> f16")
            vx.append(f"%{p}vx{k}")
        return names if kq else vx

    def fetch_gates(cidx, p, ind):
        """the solver's loads of chunk cidx: raw alpha, beta of token t0 + lane"""
        e(f"{ind}%{p}t0 = index.mul {cidx}, %c32 : index")
        e(f"{ind}%{p}abt = index.add %{p}t0, %lane : index")
        e(f"{ind}%{p}ab0 = index.mul %{p}abt, %num_heads : index")
        e(f"{ind}%{p}ab1 = index.add %{p}ab0, %h : index")
        e(f"{ind}%{p}al = view.load %al_view[%{p}ab1] : view<[%ra_total]xf32> -> f32")
        e(f"{ind}%{p}be = view.load %be_view[%{p}ab1] : view<[%ra_total]xf32> -> f32")
        return [f"%{p}al", f"%{p}be"]

    def ostore(ind, t0, acc, t, p):
        """O tile t (tokens 16 t + half + 2 i of the chunk at t0, row) -> out, f16(clamp(O 2^O16_EXP))"""
        for i in range(8):
            e(f"{ind}%{p}e{i} = vector.extract {acc}[{i}] : {V8} -> f32")
            e(f"{ind}%{p}t{i}c = index.constant {16 * t + 2 * i} : index")
            e(f"{ind}%{p}t{i}0 = index.add {t0}, %half : index")
            e(f"{ind}%{p}t{i}1 = index.add %{p}t{i}0, %{p}t{i}c : index")
            e(f"{ind}%{p}t{i}2 = index.mul %{p}t{i}1, %inner_size : index")
            e(f"{ind}%{p}t{i} = index.add %{p}t{i}2, %orow : index")
            e(f"{ind}%{p}s{i} = scalar.mulf %{p}e{i}, %o16_sc : f32")
            e(f"{ind}%{p}l{i} = scalar.minnumf<nnan> %{p}s{i}, %o16_hi : f32")
            e(f"{ind}%{p}c{i} = scalar.maxnumf<nnan> %{p}l{i}, %o16_lo : f32")
            e(f"{ind}%{p}h{i} = scalar.fptrunc %{p}c{i} : f32 to f16")
            e(f"{ind}view.store %{p}h{i}, %out_view[%{p}t{i}] : f16, view<[%out_total]xf16>")

    def repack(ind, src, nm):
        """f32 accumulator tile [m][n] -> f16 rhs fragment [k = m][n], in registers (value i in the low half of
        register i: the f16-accumulator layout the repack takes)"""
        els = []
        for i in range(8):
            e(f"{ind}%{nm}f{i} = vector.extract {src}[{i}] : {V8} -> f32")
            e(f"{ind}%{nm}e{i} = scalar.fptrunc %{nm}f{i} : f32 to f16")
            els += [f"%{nm}e{i}", "%zh"]
        e(f"{ind}%{nm}w = vector.from_elements {', '.join(els)} : {V16H}")
        e(f"{ind}%{nm}r = vector.fragment<result> %{nm}w shape [%m, %n] : {V16H}")
        e(f"{ind}%{nm} = vector.fragment.repack<rhs> %{nm}r shape [%k, %n] : {V16H} -> {V16H}")
        return f"%{nm}"

    barrier = "kernel.barrier<workgroup> scope(workgroup) ordering(acq_rel)"

    def solver():
        """wave 8, one chunk ahead of the row waves: in iteration c it computes chunk c + 1's gates (-> GA buffer
        (c + 1) % 2), A = K K^T from the conv buffer, the solve, and T2 (-> T buffers (c + 1) % 2); the prologue
        does chunk 0. The same 3 barriers per chunk as the row waves split its work over their phases; its values are
        named %sv_*, the row loop's names live in the sibling region"""
        for i in range(C):
            e(f"    %sv_ti{i}c = index.constant {i} : index")

        def gates(v, I, t0, al, be, gb):
            """yah_deltanet_prep_ab of tokens t0 + lane -> GA rows gb .. +5; padding tokens (>= valid) get (1, 0)"""
            e(f"{I}{v}ab_b = scalar.addf {al}, %ab_dt : f32")
            e(f"{I}{v}ab_20 = scalar.constant 20.0 : f32")
            e(f"{I}{v}ab_over = scalar.cmpf ogt, {v}ab_b, {v}ab_20 : f32")
            e(f"{I}{v}ab_ex = scalar.expf<afn> {v}ab_b : f32")
            e(f"{I}{v}ab_op = scalar.addf %one, {v}ab_ex : f32")
            e(f"{I}{v}ab_lg = scalar.logf<afn> {v}ab_op : f32")
            e(f"{I}{v}ab_sp = scf.select {v}ab_over, {v}ab_b, {v}ab_lg : f32")
            e(f"{I}{v}ab_sc = scalar.mulf {v}ab_sp, %ab_a : f32")
            e(f"{I}{v}ab_ao = scalar.expf<afn> {v}ab_sc : f32")
            e(f"{I}{v}ab_nb = scalar.mulf {be}, %negone : f32")
            e(f"{I}{v}ab_bx = scalar.expf<afn> {v}ab_nb : f32")
            e(f"{I}{v}ab_dn = scalar.addf %one, {v}ab_bx : f32")
            e(f"{I}{v}ab_bo = scalar.divf %one, {v}ab_dn : f32")
            e(f"{I}{v}ab_tok = index.add {t0}, %lane : index")
            e(f"{I}{v}ab_real = index.cmp ult, {v}ab_tok, %ab_vld : index")
            e(f"{I}{v}alpha = scf.select {v}ab_real, {v}ab_ao, %one : f32")
            e(f"{I}{v}beta = scf.select {v}ab_real, {v}ab_bo, %zero : f32")
            # decay: G2 = inclusive scan of log2 alpha; alpha can underflow to 0: log2 gives -inf, -inf - -inf = NaN in
            # the decay differences; clamp at 2^-100
            e(f"{I}{v}lg0 = scalar.log2f<afn> {v}alpha : f32")
            e(f"{I}{v}lgmin = scalar.constant -100.0 : f32")
            e(f"{I}{v}lg = scalar.maxnumf {v}lg0, {v}lgmin : f32")
            e(f"{I}{v}g2 = kernel.subgroup.scan<addf> {v}lg {{mode = inclusive, direction = forward}} : f32")
            e(f"{I}{v}c31i = scalar.constant 31 : i32")
            e(f"{I}{v}gtot = kernel.subgroup.broadcast {v}g2 from {v}c31i : f32, i32")
            e(f"{I}{v}gg = scalar.exp2f<afn> {v}g2 : f32")
            e(f"{I}{v}bg = scalar.mulf {v}beta, {v}gg : f32")
            e(f"{I}{v}gcd = scalar.subf {v}gtot, {v}g2 : f32")
            e(f"{I}{v}gc = scalar.exp2f<afn> {v}gcd : f32")
            for nm, val in (("G2", "g2"), ("BETA", "beta"), ("GG", "gg"), ("BG", "bg"), ("GC", "gc")):
                e(f"{I}{v}gr{nm} = index.add {gb}, %ga{nm} : index")
                e(f"{I}view.store {v}{val}, %ga[{v}gr{nm}, %lane] : f32, view<18x32xf32>")

        def kload(v, I, t0):
            """K fragments of the chunk at t0 from the conv buffer (the lhs fragment of a token tile is its rhs
            fragment too)"""
            fr = {}
            for ks in range(8):
                e(f"{I}{v}kk{ks} = index.constant {16 * ks} : index")
                for mi in range(2):
                    e(f"{I}{v}kr{mi}_{ks} = index.add {t0}, %c{16 * mi} : index")
                    e(f"{I}{v}ka{mi}_{ks} = vector.fragment.load<lhs> %kg[{v}kr{mi}_{ks}, {v}kk{ks}] shape [%m, %k] : "
                      f"view<[%batch]x128xf16, %kg_lay> -> {V16H}")
                    e(f"{I}{v}kb{mi}_{ks} = vector.fragment<rhs> {v}ka{mi}_{ks} shape [%k, %n] : {V16H}")
                    fr[(mi, ks)] = (f"{v}ka{mi}_{ks}", f"{v}kb{mi}_{ks}")
            return fr

        def kkt(v, I, fr):
            """-A^T -> a_v: A = K K^T scaled as gen_gdn_chunk phase 2 (gates of this chunk in GA rows {v}gr*), tiles
            (0, 0), (1, 0), (1, 1) (the strictly upper one is never read)"""
            for mi, nj in ((0, 0), (1, 0), (1, 1)):
                p = f"{v}a{mi}{nj}"
                acc = "%zs"
                for ks in range(8):
                    e(f"{I}{p}c{ks} = vector.mma {fr[(mi, ks)][0]}, {fr[(nj, ks)][1]}, {acc} : {V16H}, {V16H}, {V8}")
                    acc = f"{p}c{ks}"
                # element i: (m = 16 mi + half + 2 i, n = 16 nj + sub)
                e(f"{I}{p}mr = index.add %half, %c{16 * mi} : index")
                e(f"{I}{p}n = index.add %sub, %c{16 * nj} : index")
                e(f"{I}{p}gn = view.load %ga[{v}grG2, {p}n] : view<18x32xf32> -> f32")
                gms, bms, ms = [], [], []
                for i in range(8):
                    e(f"{I}{p}e{i}c = index.constant {2 * i} : index")
                    e(f"{I}{p}e{i} = index.add {p}mr, {p}e{i}c : index")
                    e(f"{I}{p}gm{i} = view.load %ga[{v}grG2, {p}e{i}] : view<18x32xf32> -> f32")
                    e(f"{I}{p}bm{i} = view.load %ga[{v}grBETA, {p}e{i}] : view<18x32xf32> -> f32")
                    gms.append(f"{p}gm{i}"); bms.append(f"{p}bm{i}"); ms.append(f"{p}e{i}")
                e(f"{I}{p}gm8 = vector.from_elements {', '.join(gms)} : {V8}")
                e(f"{I}{p}bm8 = vector.from_elements {', '.join(bms)} : {V8}")
                e(f"{I}{p}gn8 = vector.splat {p}gn : {V8}")
                e(f"{I}{p}gd8 = vector.subf {p}gm8, {p}gn8 : {V8}")
                e(f"{I}{p}gd8c = vector.minnumf {p}gd8, %zeros8 : {V8}")
                e(f"{I}{p}ed8 = vector.exp2f<afn> {p}gd8c : {V8}")
                e(f"{I}{p}sd8 = vector.mulf {acc}, {p}ed8 : {V8}")
                e(f"{I}{p}ad8 = vector.mulf {p}sd8, {p}bm8 : {V8}")
                # A is stored negated: the solve takes -A[i][j] t_j terms (negf is exact)
                e(f"{I}{p}adn8 = vector.negf {p}ad8 : {V8}")
                for i in range(8):
                    e(f"{I}{p}gt{i} = index.cmp ugt, {ms[i]}, {p}n : index")
                    e(f"{I}{p}ae{i} = vector.extract {p}adn8[{i}] : {V8} -> f32")
                    e(f"{I}{p}av{i} = scf.select {p}gt{i}, {p}ae{i}, %zero : f32")
                    e(f"{I}view.store {p}av{i}, %a_v[{p}n, {ms[i]}] : f32, view<32x36xf32>")   # -A^T

        def solve(v, I, tb, gv, split=None):
            """T = (I + A)^-1 by forward substitution, lane = column (right-looking); T2 = T diag(b) (gates in GA rows {gv}gr*) -> T rows tb .. +31. split: {step: callback} run before that
            step (steps >= C: after the substitution)"""
            split = split or {}
            accs = []
            for i in range(C):
                e(f"{I}{v}tie{i} = index.cmp eq, %sv_ti{i}c, %lane : index")
                e(f"{I}{v}td{i} = scf.select {v}tie{i}, %one, %zero : f32")
                accs.append(f"{v}td{i}")
            t = []

            def col_loads(j):
                for q in range((j + 1) // 4, 8):
                    e(f"{I}{v}tc{j}_{q}c = index.constant {4 * q} : index")
                    e(f"{I}{v}tc{j}_{q} = vector.load %a_v[%sv_ti{j}c, {v}tc{j}_{q}c] : view<32x36xf32> -> {V4}")
            for j in range(min(TPRE, C - 1)):
                col_loads(j)
            for j in range(C):
                if j in split:
                    split[j]()
                t.append(accs[j])
                if j == C - 1:
                    continue
                if TPRE:
                    if j + TPRE < C - 1:
                        col_loads(j + TPRE)
                    e(f"{I}scf.schedule.fence")
                else:
                    col_loads(j)
                for i in range(j + 1, C):
                    q = i // 4
                    e(f"{I}{v}tx{j}_{i} = vector.extract {v}tc{j}_{q}[{i % 4}] : {V4} -> f32")
                    e(f"{I}{v}tf{j}_{i} = scalar.fmaf {v}tx{j}_{i}, {t[j]}, {accs[i]} : f32")
                    accs[i] = f"{v}tf{j}_{i}"
            for j in sorted(k for k in split if k >= C):
                split[j]()
            e(f"{I}{v}tbe = view.load %ga[{gv}grBETA, %lane] : view<18x32xf32> -> f32")
            for i in range(C):
                e(f"{I}{v}tw2_{i} = scalar.mulf {t[i]}, {v}tbe : f32")
                e(f"{I}{v}th2_{i} = scalar.fptrunc {v}tw2_{i} : f32 to f16")
                e(f"{I}{v}tr{i} = index.add {tb}, %sv_ti{i}c : index")
                e(f"{I}view.store {v}th2_{i}, %t2_v[{v}tr{i}, %lane] : f16, view<64x40xf16>")

        def grows(v, I, gb):
            for nm in ("G2", "BETA", "BG"):
                e(f"{I}{v}gr{nm} = index.add {gb}, %ga{nm} : index")

        # prologue: chunk 0 (GA buffer 0, T buffer 0) solved, chunk 1 (GA buffer 1) gates and A
        J = "    "
        pre = fetch_gates("%c0", "sv_f0_", J)
        gates("%sv_p0_", J, "%sv_f0_t0", pre[0], pre[1], "%c0")
        fr = kload("%sv_p0_", J, "%sv_f0_t0")
        kkt("%sv_p0_", J, fr)
        solve("%sv_p0_", J, "%c0", "%sv_p0_")
        e(f"{J}%sv_c1 = index.min %c1, %lastc : index")
        pre = fetch_gates("%sv_c1", "sv_f1_", J)
        gates("%sv_p1_", J, "%sv_f1_t0", pre[0], pre[1], "%c6")
        fr = kload("%sv_p1_", J, "%sv_f1_t0")
        kkt("%sv_p1_", J, fr)
        v = "%sv_"
        e(f"{J}scf.for {v}ci = [%c0 to %nchunks step %c1] {{")
        I = "      "
        # solve chunk ci + 1 (GA buffer (ci + 1) % 3, T buffer (ci + 1) % 2); gates and A of chunk ci + 2 (clamped; GA
        # buffer (ci + 2) % 3): the last iterations' extra chunks land in buffers the rows no longer read
        e(f"{I}{v}cu1 = index.add {v}ci, %c1 : index")
        e(f"{I}{v}par = index.rem {v}cu1, %c2 : index")
        e(f"{I}{v}tb = index.mul {v}par, %c32 : index")
        e(f"{I}{v}g1 = index.rem {v}cu1, %c3 : index")
        e(f"{I}{v}gb1 = index.mul {v}g1, %c6 : index")
        grows(f"{v}s_", I, f"{v}gb1")
        e(f"{I}{v}cu2 = index.add {v}ci, %c2 : index")
        e(f"{I}{v}cn2 = index.min {v}cu2, %lastc : index")
        e(f"{I}{v}g2b = index.rem {v}cu2, %c3 : index")
        e(f"{I}{v}gb2 = index.mul {v}g2b, %c6 : index")
        nxt = fetch_gates(f"{v}cn2", "sv_nx_", I)
        # windows (the row waves' phases): P1 = the first S1 solve steps; P2 = the rest, the next K loads (in flight
        # over the T stores, the gates and the wait at b2), the T stores, the gates; P5 = A
        fr = []
        solve(v, I, f"{v}tb", f"{v}s_", {S1: lambda: e(f"{I}{barrier}"),
                                         C: lambda: fr.append(kload(v, I, "%sv_nx_t0"))})
        gates(v, I, "%sv_nx_t0", nxt[0], nxt[1], f"{v}gb2")
        e(f"{I}{barrier}")
        kkt(v, I, fr[0])
        e(f"{I}{barrier}")
        e("    }")

    def rows():
        """waves 0-7: value rows 16 sg .. +15, the state as S^T accumulators"""
        ftypes = [V4H] * 8
        fnames = [f"%kv{g}" for g in range(4)] + [f"%qv{g}" for g in range(4)]
        pre = fetch_rows("%c0", "f0_", "    ")
        carried = ", ".join(f"%s{j} = {st[j]} : {V8}" for j in range(8))
        carried += ", " + ", ".join(f"{nm} = {x} : {t}" for nm, x, t in zip(fnames, pre, ftypes))
        carried += f", %opv0 = %zeros8 : {V8}, %opv1 = %zeros8 : {V8}"      # the previous chunk's O, stored next iteration
        res = ", ".join(f"%sf{j}" for j in range(8)) + ", " + ", ".join(f"%ff{i}" for i in range(len(fnames)))
        res += ", %opf0, %opf1"
        alltypes = ", ".join([V8] * 8 + ftypes + [V8, V8])
        e(f"    {res} = scf.for %ci = [%c0 to %nchunks step %c1]({carried}) -> ({alltypes}) {{")
        I = "      "
        e(f"{I}%t0 = index.mul %ci, %c32 : index")
        e(f"{I}%par = index.rem %ci, %c2 : index")      # the solver's buffers of this chunk
        e(f"{I}%gpar = index.rem %ci, %c3 : index")
        e(f"{I}%gb = index.mul %gpar, %c6 : index")
        e(f"{I}%tb = index.mul %par, %c32 : index")
        for nm in ("G2", "GG", "GC"):
            e(f"{I}%gr{nm} = index.add %gb, %ga{nm} : index")
        # ---- phase 1: K, Q -> K|Q rows, Kt
        for nm, row in (("k", "%lt"), ("q", "%qrow")):
            hs = [f"%{nm}v{g}" for g in range(4)]
            for p in range(2):
                e(f"{I}%{nm}c{p} = vector.concat<0> {hs[2 * p]}, {hs[2 * p + 1]} : {V4H}, {V4H} -> {V8H}")
                e(f"{I}%{nm}d{p} = index.add %dseg, %c{8 * p} : index")
                e(f"{I}vector.store %{nm}c{p}, %kq_l[{row}, %{nm}d{p}] : {V8H}, view<64x136xf16>")
            if nm == "k":   # transposed copy Kt[key][tok]
                for g in range(4):
                    for i in range(4):
                        e(f"{I}%kt{g}{i}e = vector.extract {hs[g]}[{i}] : {V4H} -> f16")
                        e(f"{I}%kt{g}{i}c = index.constant {4 * g + i} : index")
                        e(f"{I}%kt{g}{i}r = index.add %kseg, %kt{g}{i}c : index")
                        e(f"{I}view.store %kt{g}{i}e, %kt_w[%kt{g}{i}r, %lt] : f16, view<136x40xf16>")
        # this chunk's v conv taps: in flight during phases 1-2, the conv runs in phase 5
        vx = fetch_rows("%ci", "v_", I, kq=False)
        # next chunk's inputs (clamped): in flight during phases 2-5
        e(f"{I}%cn0 = index.add %ci, %c1 : index")
        e(f"{I}%cn = index.min %cn0, %lastc : index")
        nxt = fetch_rows("%cn", "nx_", I)
        # the previous chunk's O, unconditionally (a branch's join drains the loads just issued): at chunk 0 it stores zeros
        # to chunk 0's rows, which chunk 1 then overwrites with the real O (same wave, same addresses, in order)
        e(f"{I}%opc0 = index.max %ci, %c1 : index")
        e(f"{I}%opc = index.sub %opc0, %c1 : index")
        e(f"{I}%opt0 = index.mul %opc, %c32 : index")
        for t in range(2):
            ostore(I, "%opt0", f"%opv{t}", t, f"ox{t}")
        e(f"{I}{barrier}")
        # ---- phase 2: P = QK^T (f16), its 3 lower tiles on waves 5-7 (the strictly upper one is zero: never computed,
        # its P Vn product skipped)
        e(f"{I}%hasp = index.cmp uge, %sg, %c5 : index")
        e(f"{I}scf.if %hasp {{")
        J = I + "  "
        e(f"{J}%p2t = index.sub %sg, %c5 : index")
        e(f"{J}%p2mi = index.min %p2t, %c1 : index")
        e(f"{J}%p2nj = index.div %p2t, %c2 : index")
        e(f"{J}%p2m0 = index.mul %p2mi, %c16 : index")
        e(f"{J}%p2n0 = index.mul %p2nj, %c16 : index")
        e(f"{J}%p2r = index.add %p2m0, %c32 : index")        # Q rows of the 64-row K|Q view
        acc = "%zs"
        for c in range(8):
            e(f"{J}%p2k{c} = index.constant {16 * c} : index")
            e(f"{J}%p2a{c} = vector.fragment.load<lhs> %kq_l[%p2r, %p2k{c}] shape [%m, %k] : view<64x136xf16> -> {V16H}")
            e(f"{J}%p2b{c} = vector.fragment.load<rhs> %kr_r[%p2k{c}, %p2n0] shape [%k, %n] : view<128x32xf16, %kr_lay> -> {V16H}")
            e(f"{J}%p2c{c} = vector.mma %p2a{c}, %p2b{c}, {acc} : {V16H}, {V16H}, {V8}")
            acc = f"%p2c{c}"
        # element i: (m = p2m0 + half + 2 i, n = p2n0 + sub)
        e(f"{J}%p2mr = index.add %p2m0, %half : index")
        e(f"{J}%p2n = index.add %p2n0, %sub : index")
        e(f"{J}%gn = view.load %ga[%grG2, %p2n] : view<18x32xf32> -> f32")
        gms = []
        for i in range(8):
            e(f"{J}%p2e{i}c = index.constant {2 * i} : index")
            e(f"{J}%p2e{i} = index.add %p2mr, %p2e{i}c : index")
            e(f"{J}%gmx{i} = view.load %ga[%grG2, %p2e{i}] : view<18x32xf32> -> f32")
            gms.append(f"%gmx{i}")
        e(f"{J}%gm8 = vector.from_elements {', '.join(gms)} : {V8}")
        e(f"{J}%gn8 = vector.splat %gn : {V8}")
        e(f"{J}%gd8 = vector.subf %gm8, %gn8 : {V8}")
        e(f"{J}%gd8c = vector.minnumf %gd8, %zeros8 : {V8}")
        e(f"{J}%ed8 = vector.exp2f<afn> %gd8c : {V8}")
        e(f"{J}%sd8 = vector.mulf {acc}, %ed8 : {V8}")
        for i in range(8):
            e(f"{J}%pge{i} = index.cmp uge, %p2e{i}, %p2n : index")
            e(f"{J}%pe{i} = vector.extract %sd8[{i}] : {V8} -> f32")
            e(f"{J}%pv{i} = scf.select %pge{i}, %pe{i}, %zero : f32")
            e(f"{J}%ph{i} = scalar.fptrunc %pv{i} : f32 to f16")
            e(f"{J}view.store %ph{i}, %p_v[%p2e{i}, %p2n] : f16, view<32x40xf16>")
        e(f"{I}}}")
        # ---- phase 2 (all row waves): KS = K S^T, O1 = Q S^T (S^T repacked once per tile)
        for j in range(8):
            e(f"{I}%xk{j} = index.constant {16 * j} : index")
            e(f"{I}%ktr{j} = index.constant {17 * j} : index")
        ka, oa = ["%zs", "%zs"], ["%zs", "%zs"]
        for j in range(8):
            b = repack(I, f"%s{j}", f"sb{j}")
            for tt in range(2):
                e(f"{I}%xt{tt}_{j} = index.constant {16 * tt} : index")
                e(f"{I}%xa{tt}_{j} = vector.fragment.load<lhs> %kq_l[%xt{tt}_{j}, %xk{j}] shape [%m, %k] : view<64x136xf16> -> {V16H}")
                e(f"{I}%xc{tt}_{j} = vector.mma %xa{tt}_{j}, {b}, {ka[tt]} : {V16H}, {V16H}, {V8}")
                ka[tt] = f"%xc{tt}_{j}"
                e(f"{I}%oq{tt}_{j} = index.constant {32 + 16 * tt} : index")
                e(f"{I}%oa{tt}_{j} = vector.fragment.load<lhs> %kq_l[%oq{tt}_{j}, %xk{j}] shape [%m, %k] : view<64x136xf16> -> {V16H}")
                e(f"{I}%oc{tt}_{j} = vector.mma %oa{tt}_{j}, {b}, {oa[tt]} : {V16H}, {V16H}, {V8}")
                oa[tt] = f"%oc{tt}_{j}"
        e(f"{I}{barrier}")
        # ---- phase 5: the v conv in the accumulator layout (lane: channel %row; tile tt element i: token
        # 16 tt + half + 2 i), Y = V - 2^G KS, Vn = U = T2 Y; Vn' = 2^(G_C - G) Vn, O1 2^G
        for c in range(2):
            e(f"{I}%uk{c} = index.constant {16 * c} : index")
        gt8, gc8 = [], []
        for tt in range(2):
            e(f"{I}%ut{tt} = index.constant {16 * tt} : index")
            e(f"{I}%utb{tt} = index.add %tb, %ut{tt} : index")
            gts, gcs = [], []
            for i in range(8):
                e(f"{I}%ux{tt}{i}c = index.constant {16 * tt + 2 * i} : index")
                e(f"{I}%ux{tt}{i} = index.add %half, %ux{tt}{i}c : index")
                e(f"{I}%gtx{tt}{i} = view.load %ga[%grGG, %ux{tt}{i}] : view<18x32xf32> -> f32")
                e(f"{I}%gcx{tt}{i} = view.load %ga[%grGC, %ux{tt}{i}] : view<18x32xf32> -> f32")
                gts.append(f"%gtx{tt}{i}"); gcs.append(f"%gcx{tt}{i}")
            e(f"{I}%gt8_{tt} = vector.from_elements {', '.join(gts)} : {V8}")
            e(f"{I}%gc8_{tt} = vector.from_elements {', '.join(gcs)} : {V8}")
            gt8.append(f"%gt8_{tt}"); gc8.append(f"%gc8_{tt}")
        # v conv (gen_conv_kq.conv_steps per channel: s0 .. s3 = x[t-3] .. x[t]); taps before token 0: ring slot half + k
        e(f"{I}%vc_w = vector.load %cws[%row, %c0] : view<128x4xf32> -> {V4}")
        w = []
        for k in range(4):
            e(f"{I}%vc_w{k} = vector.extract %vc_w[{k}] : {V4} -> f32")
            w.append(f"%vc_w{k}")
        e(f"{I}%nl2e = scalar.constant -1.4426950408889634 : f32")
        xs = []
        for k in range(34):
            e(f"{I}%vc_e{k} = scalar.extf {vx[k]} : f16 to f32")
            if k < 3:
                e(f"{I}%vc_rk{k} = index.add %half, %c{k} : index")
                e(f"{I}%vc_rs{k} = index.min %vc_rk{k}, %c2 : index")
                e(f"{I}%vc_st{k} = view.load %css[%row, %vc_rs{k}] : view<128x3xf32> -> f32")
                e(f"{I}%vc_neg{k} = index.cmp ult, %v_vb, %c{3 - k} : index")
                e(f"{I}%vc_x{k} = scf.select %vc_neg{k}, %vc_st{k}, %vc_e{k} : f32")
                xs.append(f"%vc_x{k}")
            else:
                xs.append(f"%vc_e{k}")
        vt = []
        for tt in range(2):
            hs = []
            for i in range(8):
                u = 8 * tt + i
                q = f"%vc{tt}_{i}"
                s0, s1, s2, s3 = xs[2 * u], xs[2 * u + 1], xs[2 * u + 2], xs[2 * u + 3]
                # taps as fma_mix on the f16 inputs
                e(f"{I}{q}d0 = scalar.mulf {s0}, {w[0]} : f32")
                e(f"{I}{q}d1 = scalar.fmaf {s1}, {w[1]}, {q}d0 : f32")
                e(f"{I}{q}d2 = scalar.fmaf {s2}, {w[2]}, {q}d1 : f32")
                e(f"{I}{q}dot = scalar.fmaf {s3}, {w[3]}, {q}d2 : f32")
                e(f"{I}{q}ng = scalar.mulf {q}dot, %nl2e : f32")
                e(f"{I}{q}ex = scalar.exp2f<afn> {q}ng : f32")
                e(f"{I}{q}dn = scalar.addf %one, {q}ex : f32")
                e(f"{I}{q}sg = scalar.divf<nnan|ninf|nsz|arcp> %one, {q}dn : f32")   # v_rcp: rcp(inf) = 0
                e(f"{I}{q}r = scalar.mulf {q}dot, {q}sg : f32")
                hs.append(f"{q}r")
            e(f"{I}%vv{tt} = vector.from_elements {', '.join(hs)} : {V8}")
            vt.append(f"%vv{tt}")
        by = []
        for tt in range(2):
            e(f"{I}%ngt{tt} = vector.negf {gt8[tt]} : {V8}")
            e(f"{I}%yv{tt} = vector.fmaf %ngt{tt}, {ka[tt]}, {vt[tt]} : {V8}")
            by.append(repack(I, f"%yv{tt}", f"by{tt}"))
        bvn, bvp, o1s = [], [], []
        for tt in range(2):
            acc = "%zs"
            for c in range(2):
                e(f"{I}%ua{tt}{c} = vector.fragment.load<lhs> %t2_v[%utb{tt}, %uk{c}] shape [%m, %k] : view<64x40xf16> -> {V16H}")
                e(f"{I}%uc{tt}{c} = vector.mma %ua{tt}{c}, {by[c]}, {acc} : {V16H}, {V16H}, {V8}")
                acc = f"%uc{tt}{c}"
            e(f"{I}%o18_{tt} = vector.mulf {oa[tt]}, {gt8[tt]} : {V8}")
            e(f"{I}%vnp{tt} = vector.mulf {acc}, {gc8[tt]} : {V8}")
            bvn.append(repack(I, acc, f"bvn{tt}"))
            bvp.append(repack(I, f"%vnp{tt}", f"bvp{tt}"))
            o1s.append(f"%o18_{tt}")
        # O = O1 + P Vn (stored next iteration)
        oacc = []
        for tt in range(2):
            e(f"{I}%o1f{tt} = vector.fragment<init> {o1s[tt]} shape [%m, %n] : {V8}")
            acc = f"%o1f{tt}"
            for c in range(tt + 1):
                e(f"{I}%pa{tt}{c} = vector.fragment.load<lhs> %p_v[%ut{tt}, %uk{c}] shape [%m, %k] : view<32x40xf16> -> {V16H}")
                e(f"{I}%pc{tt}{c} = vector.mma %pa{tt}{c}, {bvn[c]}, {acc} : {V16H}, {V16H}, {V8}")
                acc = f"%pc{tt}{c}"
            oacc.append(acc)
        # S^T <- 2^G_C S^T + K^T Vn'
        e(f"{I}%gtot = view.load %ga[%grGC, %c0] : view<18x32xf32> -> f32")   # 2^(G_31 - G_0)
        e(f"{I}%gg0 = view.load %ga[%grGG, %c0] : view<18x32xf32> -> f32")
        e(f"{I}%gall = scalar.mulf %gtot, %gg0 : f32")                       # 2^G_31
        e(f"{I}%gall8 = vector.splat %gall : {V8}")
        new = []
        for j in range(8):
            e(f"{I}%sd{j} = vector.mulf %s{j}, %gall8 : {V8}")
            e(f"{I}%sdf{j} = vector.fragment<init> %sd{j} shape [%m, %n] : {V8}")
            acc = f"%sdf{j}"
            for c in range(2):
                e(f"{I}%ka{j}{c} = vector.fragment.load<lhs> %kt_w[%ktr{j}, %uk{c}] shape [%m, %k] : view<136x40xf16> -> {V16H}")
                e(f"{I}%kc{j}{c} = vector.mma %ka{j}{c}, {bvp[c]}, {acc} : {V16H}, {V16H}, {V8}")
                acc = f"%kc{j}{c}"
            new.append(acc)
        e(f"{I}{barrier}")
        e(f"{I}scf.yield {', '.join(new + nxt + oacc)} : {alltypes}")
        e("    }")
        # the last chunk's O
        e("    %oplast = index.mul %lastc, %c32 : index")
        for tt in range(2):
            ostore("    ", "%oplast", f"%opf{tt}", tt, f"ol{tt}")
        # ---- final state: the initial load's exchange in reverse, two b128 stores per tile
        for j in range(8):
            fe = []
            for i in range(8):
                e(f"    %fe{j}_{i} = vector.extract %sf{j}[{i}] : {V8} -> f32")
                fe.append(f"%fe{j}_{i}")
            send = []
            for k in range(4):
                e(f"    %fs{j}_{k} = scf.select %shi, {fe[k]}, {fe[4 + k]} : f32")
                send.append(f"%fs{j}_{k}")
            pk = swap_halves("    ", f"so{j}", send)
            ov = []
            for k in range(4):
                e(f"    %fo{j}_{2 * k} = scf.select %shi, {pk[k]}, {fe[k]} : f32")
                e(f"    %fo{j}_{2 * k + 1} = scf.select %shi, {fe[4 + k]}, {pk[k]} : f32")
                ov += [f"%fo{j}_{2 * k}", f"%fo{j}_{2 * k + 1}"]
            for hi, hlf in enumerate("ab"):
                e(f"    %fv{j}{hlf} = vector.from_elements {', '.join(ov[4 * hi:4 * hi + 4])} : {V4}")
                e(f"    vector.store %fv{j}{hlf}, %state_view[%sq{j}{hlf}] : {V4}, view<[%state_total]xf32>")

    # wave-uniform role branch: every barrier inside has a matching barrier in the other region (HRX patch 0037)
    e("  scf.if %issv {")
    solver()
    e("  } else {")
    rows()
    e("  }")
    e("  kernel.return")
    e("}")
    return "\n".join(L) + "\n"

