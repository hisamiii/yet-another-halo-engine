def gen_vqt(bits):
    """yah_vq4 / yah_vq8: V^T quantized per channel per 16-token tile around
    the tile's midrange c with step s (per-channel per-tile range: attention
    error 3.5e-2 -> 2.1e-2 vs per-channel over the prompt at 4 bits).
      4 bits: u = rne((v - c) / s) + 7 in [0, 14], s = range / 14; in each of
        the lane's 2 dwords nibble p holds key 2p (p < 4) or 2(p - 4) + 1, so
        (w >> 4k ...) & 0x03c003c0 | 0x3c003c00 are f16 1 + u/16 for keys 2k,
        2k + 1; stats (S, C') = (16 s, c - 23 s).
      8 bits: u = rne((v - c) / s) + 128 in [1, 255], s = range / 254; each of
        the lane's 4 dwords holds keys (k0, k2, k1, k3) of its 4, so (w << 2,
        w >> 6) & 0x03fc03fc | 0x3c003c00 are f16 1 + u/256 for keys (k0, k1),
        (k2, k3); stats (S, C') = (256 s, c - 384 s).
    Either way the attention dequantizes with one fma f * S + C' while staging.
    Output [kv head][tile][256 dims] x (2 or 4) dwords, stats [kv head][tile][256]
    f16 pairs. Chunked prefill: src is the chunk's token_count rows of f16 V
    (a slice of the cache), written at tiles start_pos / 16 + tile of a cache of
    cache_capacity tokens. Tokens past token_count repeat the last one (keys
    the softmax masks). grid (4, ceil(token_count / 16)) x 256 (lane = dim)."""
    nw = 2 if bits == 4 else 4
    lv = 14 if bits == 4 else 254              # range / s
    off = 7 if bits == 4 else 128              # u offset
    umax = 14 if bits == 4 else 255
    smul, cmul = (16.0, -23.0) if bits == 4 else (256.0, -384.0)
    L = []
    e = L.append
    e(f"// GENERATED by tools/gen_kvq.py (vq{bits}) -- edit the generator.")
    e("amdgpu.target<gfx1151> @kvq_w32 {subgroup_size = 32}")
    e("config.decl @yah_kvq.token_count : %value: index where [range(%value, 1, 1048576)]")
    e("config.decl @yah_kvq.cache_capacity : %value: index where [range(%value, 1, 1048576)]")
    e("config.decl @yah_kvq.start_pos : %value: index where [range(%value, 0, 1048576)]")
    e("")
    e(f"kernel.def target(@kvq_w32) @yah_vq{bits}() {{")
    e("  %ntk = config.get @yah_kvq.token_count : index")
    e("  %c1 = index.constant 1 : index")
    e("  %c4 = index.constant 4 : index")
    e("  %c15 = index.constant 15 : index")
    e("  %c16 = index.constant 16 : index")
    e("  %c256 = index.constant 256 : index")
    e("  %t0 = index.add %ntk, %c15 : index")
    e("  %tiles = index.div %t0, %c16 : index")
    e("  kernel.launch.config workgroups(%c4, %tiles, %c1) workgroup_size(%c256, %c1, %c1) : index")
    e("} launch(%src: buffer, %dst: buffer, %stat: buffer" + (", %ptab: buffer" if PAGED else "") + ") {")
    e("  %base = index.constant 0 : offset")
    for v in (0, 1, 2, 4, 15, 16, 256, 1024):
        e(f"  %c{v} = index.constant {v} : index")
    e("  %ntok = config.get @yah_kvq.token_count : index")
    e("  %cap = config.get @yah_kvq.cache_capacity : index")
    e("  %start = config.get @yah_kvq.start_pos : index")
    e("  %p15 = index.add %cap, %c15 : index")
    e("  %tiles = index.div %p15, %c16 : index")          # tiles of the whole cache
    e("  %stot = index.mul %ntok, %c1024 : index")         # the chunk's rows
    e("  %ttot0 = index.mul %tiles, %c1024 : index")      # 4 heads x 256 dims per tile
    e(f"  %dtot = index.mul %ttot0, %c{nw} : index")
    e("  %s_na, %d_na, %t_na = buffer.assume.noalias %src, %dst, %stat : buffer, buffer, buffer")
    e("  %s_flat = buffer.view %s_na[%base] : buffer -> view<[%stot]xf16>")
    e("  %d_flat = buffer.view %d_na[%base] : buffer -> view<[%dtot]xi32>")
    e("  %t_flat = buffer.view %t_na[%base] : buffer -> view<[%ttot0]xi32>")
    e("  %head = kernel.workgroup.id<x> : index")
    e("  %ltile = kernel.workgroup.id<y> : index")
    e("  %d = kernel.workitem.id<x> : index")
    e("  %st16 = index.div %start, %c16 : index")
    if PAGED:   # physical tile = ptab[tile / 16] * 16 + tile % 16
        e("  %c255g = index.constant 255 : index")
        e("  %npg0 = index.add %cap, %c255g : index")
        e("  %npages = index.div %npg0, %c256 : index")
        e("  %pt_flat = buffer.view %ptab[%base] : buffer -> view<[%npages]xi32>")
        e("  %ltl = index.add %st16, %ltile : index")
        e("  %ltp = index.div %ltl, %c16 : index")
        e("  %ltg0 = view.load %pt_flat[%ltp] : view<[%npages]xi32> -> i32")
        e("  %ltgu = index.cast %ltg0 : i32 to index")
        e("  %ltnpm = index.sub %npages, %c1 : index")
        e("  %ltgr = index.min %ltgu, %ltnpm : index")              # clamp into the pool
        e("  %ltg = index.assume %ltgr [range(%ltgr, 0, 65535), lt(%ltgr, %npages)] : index")
        e("  %ltb = index.mul %ltg, %c16 : index")
        e("  %lto = index.rem %ltl, %c16 : index")
        e("  %tile = index.add %ltb, %lto : index")
    else:
        e("  %tile = index.add %st16, %ltile : index")
    e("  %hb = index.mul %head, %c256 : index")
    e("  %col = index.add %hb, %d : index")
    e("  %t16 = index.mul %ltile, %c16 : index")
    e("  %ntok1 = index.sub %ntok, %c1 : index")
    vals = []
    for j in range(16):
        e(f"  %tk{j}c = index.constant {j} : index")
        e(f"  %tk{j} = index.add %t16, %tk{j}c : index")
        e(f"  %tl{j} = index.min %tk{j}, %ntok1 : index")      # past the chunk: repeat its last token
        e(f"  %tm{j} = index.mul %tl{j}, %c1024 : index")
        e(f"  %ta{j} = index.add %tm{j}, %col : index")
        e(f"  %vh{j} = view.load %s_flat[%ta{j}] : view<[%stot]xf16> -> f16")
        e(f"  %v{j} = scalar.extf %vh{j} : f16 to f32")
        vals.append(f"%v{j}")
    mx, mn = vals[0], vals[0]
    for j in range(1, 16):
        e(f"  %mx{j} = scalar.maxnumf {mx}, {vals[j]} : f32")
        e(f"  %mn{j} = scalar.minnumf {mn}, {vals[j]} : f32")
        mx, mn = f"%mx{j}", f"%mn{j}"
    e("  %half = scalar.constant 0.5 : f32")
    e(f"  %rlv = scalar.constant {float(lv)} : f32")
    e("  %one = scalar.constant 1.0 : f32")
    e("  %zero = scalar.constant 0.0 : f32")
    e(f"  %sm = scalar.addf {mx}, {mn} : f32")
    e("  %cen = scalar.mulf %sm, %half : f32")
    e(f"  %rg = scalar.subf {mx}, {mn} : f32")
    e("  %s0 = scalar.divf %rg, %rlv : f32")
    e("  %spos = scalar.cmpf ogt, %s0, %zero : f32")
    e("  %s = scf.select %spos, %s0, %one : f32")
    # round the stats to f16 first: the attention dequantizes with the f16 values
    e("  %sh = scalar.fptrunc %s : f32 to f16")
    e("  %ch = scalar.fptrunc %cen : f32 to f16")
    e("  %sf = scalar.extf %sh : f16 to f32")
    e("  %cf = scalar.extf %ch : f16 to f32")
    e("  %inv = scalar.divf %one, %sf : f32")
    e(f"  %roff = scalar.constant {float(off)} : f32")
    e("  %r0 = scalar.constant 0.0 : f32")
    e(f"  %rmax = scalar.constant {float(umax)} : f32")
    us = []
    for j in range(16):
        e(f"  %xc{j} = scalar.subf {vals[j]}, %cf : f32")
        e(f"  %xs{j} = scalar.mulf %xc{j}, %inv : f32")
        e(f"  %xr{j} = scalar.roundevenf %xs{j} : f32")
        e(f"  %xo{j} = scalar.addf %xr{j}, %roff : f32")
        e(f"  %xl{j} = scalar.maxnumf %xo{j}, %r0 : f32")
        e(f"  %xm{j} = scalar.minnumf %xl{j}, %rmax : f32")
        e(f"  %xu{j} = scalar.fptosi %xm{j} : f32 to i32")
        us.append(f"%xu{j}")
    words = []
    for w in range(nw):
        acc = None
        slots = 8 if bits == 4 else 4
        for p in range(slots):
            if bits == 4:
                key = 8 * w + (2 * p if p < 4 else 2 * (p - 4) + 1)
                sh = 4 * p
            else:
                key = 4 * w + (0, 2, 1, 3)[p]
                sh = 8 * p
            e(f"  %np{w}{p}c = scalar.constant {sh} : i32")
            e(f"  %np{w}{p} = scalar.shli {us[key]}, %np{w}{p}c : i32")
            if acc is None:
                acc = f"%np{w}{p}"
            else:
                e(f"  %na{w}{p} = scalar.ori {acc}, %np{w}{p} : i32")
                acc = f"%na{w}{p}"
        words.append(acc)
    e("  %ti0 = index.mul %head, %tiles : index")
    e("  %ti1 = index.add %ti0, %tile : index")
    e("  %ti2 = index.mul %ti1, %c256 : index")
    e("  %ti = index.add %ti2, %d : index")             # [head][tile][dim]
    e(f"  %da0 = index.mul %ti, %c{nw} : index")
    for w in range(nw):
        e(f"  %daw{w}c = index.constant {w} : index")
        e(f"  %daw{w} = index.add %da0, %daw{w}c : index")
        e(f"  view.store {words[w]}, %d_flat[%daw{w}] : i32, view<[%dtot]xi32>")
    e(f"  %rS = scalar.constant {smul} : f32")
    e(f"  %rC = scalar.constant {cmul} : f32")
    e("  %S = scalar.mulf %sf, %rS : f32")
    e("  %Cp = scalar.fmaf %sf, %rC, %cf : f32")
    e("  %Sh = scalar.fptrunc %S : f32 to f16")
    e("  %Cph = scalar.fptrunc %Cp : f32 to f16")
    e("  %pk = vector.from_elements %Sh, %Cph : vector<2xf16>")
    e("  %pkw = vector.bitcast %pk : vector<2xf16> to vector<1xi32>")
    e("  %pkd = vector.extract %pkw[0] : vector<1xi32> -> i32")
    e("  view.store %pkd, %t_flat[%ti] : i32, view<[%ttot0]xi32>")
    e("  kernel.return")
    e("}")
    return "\n".join(L) + "\n"


