ZPAD_WG = 64   # (gen_zpad) threads a workgroup: 9 x 8 words each, one 18432-byte unit


def gen_zpad(nb, pads, hbytes):
    """yah_npu_zpad: zeros into H's pad units (emit_prefill_pp ffnblk_pads: [(first unit, units apart)], a unit 18432
    bytes of C, one a 64-token M block each): workgroup w zeroes pad w / nb of M block w % nb. One binding: C's first
    hbytes (H)."""
    nw = 18432 // 4
    assert nw == ZPAD_WG * 9 * 8 and pads and hbytes % 4 == 0
    consts, e = {}, []

    def ci(v):
        consts.setdefault(v, f"%k{v}")
        return consts[v]
    e.append("  %wg = kernel.workgroup.id<x> : index")
    e.append("  %tid = kernel.workitem.id<x> : index")
    e.append(f"  %mb = index.rem %wg, {ci(nb)} : index")
    e.append(f"  %pk = index.div %wg, {ci(nb)} : index")
    base, stride = ci(pads[0][0]), ci(pads[0][1])
    for k, (b0, st) in enumerate(pads[1:], 1):   # (the pad's (first unit, units apart) by compares)
        e.append(f"  %pi{k} = index.cmp uge, %pk, {ci(k)} : index")
        e.append(f"  %pb{k} = scf.select %pi{k}, {ci(b0)}, {base} : index")
        e.append(f"  %ps{k} = scf.select %pi{k}, {ci(st)}, {stride} : index")
        base, stride = f"%pb{k}", f"%ps{k}"
    e.append(f"  %um = index.mul %mb, {stride} : index")
    e.append(f"  %u = index.add %um, {base} : index")
    e.append(f"  %w0 = index.mul %u, {ci(nw)} : index")
    e.append(f"  %t8 = index.mul %tid, {ci(8)} : index")
    e.append("  %w1 = index.add %w0, %t8 : index")
    e.append("  %z = vector.splat %zi : vector<8xi32>")
    for i in range(9):
        e.append(f"  %a{i} = index.add %w1, {ci(i * ZPAD_WG * 8)} : index")
        e.append(f"  vector.store %z, %cv[%a{i}] : vector<8xi32>, view<{hbytes // 4}xi32>")
    decl = "\n".join(f"  {n} = index.constant {v} : index" for v, n in consts.items())
    body = "\n".join(e)
    return f"""// GENERATED by tools/gen_npu_unpack.py gen_zpad -- edit the generator.
amdgpu.target<gfx1151> @yah_wave32 {{subgroup_size = 32}}

kernel.def target(@yah_wave32) @yah_npu_zpad() {{
  %unit = index.constant 1 : index
  %nwg = index.constant {nb * len(pads)} : index
  %nthr = index.constant {ZPAD_WG} : index
  kernel.launch.config workgroups(%nwg, %unit, %unit) workgroup_size(%nthr, %unit, %unit) : index
}} launch(%c: buffer) {{
  %base = index.constant 0 : offset
  %c_na = buffer.assume.noalias %c : buffer
  %cv = buffer.view %c_na[%base] : buffer -> view<{hbytes // 4}xi32>
  %zi = scalar.constant 0 : i32
{decl}
{body}
  kernel.return
}}
"""
