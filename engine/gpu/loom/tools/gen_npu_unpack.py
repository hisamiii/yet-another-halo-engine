#!/usr/bin/env python3
"""Emit yah_npu_unpack: the NPU GEMM's C into the GPU output's column slice.

C (gen_npu_gemm): [col][M block][mp][np][chain mh, nh][8 rows][8 cols] bf16, 64 x TN per (col, M block).
out: f32 [tokens][stride], or f16 with out16 (rounded as the f16-output GEMMs round, emit_prefill_pp.O16_MT); C column j
goes to out column off + j.
One work item per 8 consecutive C columns of one token: a 32-byte read and a 32-byte write.
A run of NJ = TN / 8 items takes one token's TN columns of an NPU column (TN * 4 contiguous bytes); each chunk's 4 tokens
read 128 contiguous bytes of C.
The next waves take the next columns, so 4 output rows fill left to right (DRAM-page friendly).
"""
import sys

import gen_bfp16_encode as GE
import gen_gemm_tile as TG
import gen_npu_gemm as GN



CG = len(GE.GROUPS)   # C partials per NPU call, one per replay group, summed here


def wg(cols):
    """Workgroup size of an unpack over cols NPU columns: 8 tokens x 32 column chunks, 16, 8 or 4 where 32 do not divide
    them (7-column calls: gen_npu_gemm dcol 2; the FFN block's 70)."""
    nch = cols * GN.TN // 8
    return 8 * next(c for c in (32, 16, 8, 4) if nch % c == 0)


def gen(tokens, cols, stride, off, out16=False, resid=False, parts=1, swiglu=False, tiled=False, qg=False, rem=False,
        bfp=None, last8=False, dup=None, remres=False, swap=None):
    """resid: out = resid + C (f32; bindings c, resid, out), the kres GEMMs. parts: C is that many consecutive partial C
    blocks (the K chunks of one GEMM), summed in order. swiglu: C is the gate block then the up block; out =
    f16(silu(gate) * up) with the swiglu epilogue's scalar ops. tiled: f16 out fragment-major ([token / 16][column / 16]
    [token % 16][column % 16], an afrag GEMM's input). qg: the attention q projection's rows (heads x [256 q | 256
    gate], off = first NPU head * 512): C column j goes to q or gate (f32 [token][stride], bindings c, q, gate) at
    head * 256 + j % 256. rem (with resid): the GPU's f32 [token][TN * cols] partial over the rest of K (the NPU split's K
    remainder) is added to the C chunks before the residual (bindings c, resid, rem, out). bfp = (ks, passes, chunk_k,
    chunks) with swiglu: also the NPU's BFP16 activation stream of the next GEMM (ffn_down, whose input columns these are) for
    the columns in its K chunks (chunk_k columns each, gen_bfp16_encode "act" layout, one stream per chunk back to back;
    binding a after out): an item's 8 columns of one token are one bfp16ebs8 row block, encoded from the f16 values
    (stage_bfp: a workgroup takes 8 tokens x its column chunks, so each chunk's row blocks are one stream fragment).
    last8: only the last 8 tokens (the conv ring of a qkv split whose conv reads C itself, gen_conv_kq.gen_c).
    dup = (col0, base) with resid and rem (the NPU's FFN block, whose down calls cover all rows): C columns from col0 on
    (the last call, which overlaps the one before it) go to out column base + (col - col0) * TN + 8 j (the overlapped
    columns are written twice with equal values), and rem is the GPU's f32 [token][stride] partial over the other K.
    remres (with resid and rem): rem already holds resid + the GPU's partial (its GEMM's residual epilogue): out = rem +
    the C chunks' sum (bindings c, rem, out), a summation order of its own.
    swap = R (out16 or qg, one part): C is a swap-form site image's (R rows, swapc_base, one value an element)."""
    assert not swap or ((out16 or qg) and parts == 1 and not (resid or rem or swiglu or tiled or bfp or dup)
                        and tokens % 512 == 0 and cols * GN.TN <= swap)
    assert not remres or (resid and rem)
    assert not (resid and (swiglu or tiled or out16)) and not (swiglu and parts > 1) and (resid or not rem)
    assert not bfp or swiglu
    assert not qg or not (resid or swiglu or tiled or out16)
    out16 = out16 or swiglu or tiled
    TN, NJ = GN.TN, GN.TN // 8
    assert not dup or (resid and rem and off == 0 and dup[0] <= cols < 2 * dup[0] and dup[1] + (cols - dup[0]) * TN == stride)
    assert tokens % 64 == 0 and (dup or off + TN * cols <= (2 if qg else 1) * stride)
    items = (8 if last8 else tokens) * cols * NJ
    c_elems = tokens * cols * TN * CG   # one call's C: per column [group][M block][...]
    L = []
    e = L.append
    flags = "".join(f" {k}" for k, v in (("resid", resid), ("rem", rem), ("swiglu", swiglu), ("tiled", tiled), ("qg", qg),
                                          ("bfp", bool(bfp))) if v) + (f" parts={parts}" if parts > 1 else "")
    e(f"// GENERATED by tools/gen_npu_unpack.py (tokens={tokens} cols={cols} stride={stride} off={off} out16={int(out16)}{flags})"
      " -- edit the generator.")
    e("amdgpu.target<gfx1151> @yah_wave32 {subgroup_size = 32}")
    e("")
    e("kernel.def target(@yah_wave32) @yah_npu_unpack() {")
    e("  %unit = index.constant 1 : index")
    WG = wg(cols)
    NCH = WG // 8
    assert items % WG == 0 and tokens % 8 == 0
    e(f"  %wgs = index.constant {items // WG} : index")
    e(f"  %wgsz = index.constant {WG} : index")
    e("  kernel.launch.config workgroups(%wgs, %unit, %unit) workgroup_size(%wgsz, %unit, %unit) : index")
    nblk = parts * (2 if swiglu else 1)
    if remres:
        e("} launch(%c: buffer, %rem: buffer, %out: buffer) {")
    elif resid and rem:
        e("} launch(%c: buffer, %resid: buffer, %rem: buffer, %out: buffer) {")
    elif resid:
        e("} launch(%c: buffer, %resid: buffer, %out: buffer) {")
    elif qg:
        e("} launch(%c: buffer, %out: buffer, %gate: buffer) {")
    elif bfp:
        e("} launch(%c: buffer, %out: buffer, %ab: buffer) {")
    else:
        e("} launch(%c: buffer, %out: buffer) {")
    e("  %base = index.constant 0 : offset")
    e(f"  %nc = index.constant {tokens * swap // 2 if swap else c_elems * nblk // 2} : index")   # bf16 pairs
    e(f"  %no = index.constant {tokens * stride} : index")
    if remres:
        e("  %c_na, %rem_na, %out_na = buffer.assume.noalias %c, %rem, %out : buffer, buffer, buffer")
        e(f"  %nrem = index.constant {tokens * (stride if dup else cols * TN)} : index")
        e("  %remv = buffer.view %rem_na[%base] : buffer -> view<[%nrem]xf32>")
    elif resid and rem:
        e("  %c_na, %res_na, %rem_na, %out_na = buffer.assume.noalias %c, %resid, %rem, %out : buffer, buffer, buffer, buffer")
        e("  %rv = buffer.view %res_na[%base] : buffer -> view<[%no]xf32>")
        e(f"  %nrem = index.constant {tokens * (stride if dup else cols * TN)} : index")
        e("  %remv = buffer.view %rem_na[%base] : buffer -> view<[%nrem]xf32>")
    elif resid:
        e("  %c_na, %res_na, %out_na = buffer.assume.noalias %c, %resid, %out : buffer, buffer, buffer")
        e("  %rv = buffer.view %res_na[%base] : buffer -> view<[%no]xf32>")
    elif qg:
        e("  %c_na, %out_na, %gate_na = buffer.assume.noalias %c, %out, %gate : buffer, buffer, buffer")
        e("  %gv = buffer.view %gate_na[%base] : buffer -> view<[%no]xf32>")
    elif bfp:
        bks, bpasses, bck, bnck = bfp
        bcb = GE.layout_bytes("act", tokens, bks, bpasses)
        e("  %c_na, %out_na, %ab_na = buffer.assume.noalias %c, %out, %ab : buffer, buffer, buffer")
        e(f"  %nab = index.constant {bcb * bnck} : index")
        e("  %abv = buffer.view %ab_na[%base] : buffer -> view<[%nab]xi8>")
        e(f"  %bs_bytes = index.constant {72 * wg(cols) // 8} : offset")   # column chunks x 8 tokens x 9 bytes
        e("  %bs_buf = buffer.alloca<workgroup> align(16) %bs_bytes : buffer")
        e(f"  %bs_view = buffer.view %bs_buf[%base] : buffer -> view<{72 * wg(cols) // 8}xi8>")
    else:
        e("  %c_na, %out_na = buffer.assume.noalias %c, %out : buffer, buffer")
    e("  %cv = buffer.view %c_na[%base] : buffer -> view<[%nc]xi32>")
    e("  %c16i = scalar.constant 16 : i32")
    e("  %chii = scalar.constant -65536 : i32")
    ot = "f16" if out16 else "f32"
    e(f"  %ov = buffer.view %out_na[%base] : buffer -> view<[%no]x{ot}>")
    e("  %wg = kernel.workgroup.id<x> : index")
    e("  %tid = kernel.workitem.id<x> : index")
    for nm, v in (("c8", 8), ("c2", 2), ("c4", 4), ("c16", 16), ("c64", 64), ("cnj", NJ), ("cnp", GN.NP),
                  ("ctn", TN), ("ctile", 64 * TN), ("cmb", tokens // 64 * CG), ("ccols", cols), ("cstride", stride), ("coff", off)):
        e(f"  %{nm} = index.constant {v} : index")
    if tiled:
        e("  %c256t = index.constant 256 : index")
    if qg:
        e("  %c512q = index.constant 512 : index")
        e("  %c256q = index.constant 256 : index")
    # a workgroup takes 8 tokens x NCH column chunks, token fastest: a wave reads whole 256-byte C blocks (8 tokens x 8
    # columns), and for bfp each chunk's 8 row blocks are one stream fragment
    e(f"  %cnq = index.constant {cols * NJ // NCH} : index")
    e(f"  %cnch = index.constant {NCH} : index")
    e("  %tr = index.rem %tid, %c8 : index")
    e("  %cl = index.div %tid, %c8 : index")
    e("  %wq = index.rem %wg, %cnq : index")
    if last8:
        e("  %wp0 = index.div %wg, %cnq : index")
        e(f"  %cwpl = index.constant {tokens // 8 - 1} : index")
        e("  %wp = index.add %wp0, %cwpl : index")
    else:
        e("  %wp = index.div %wg, %cnq : index")
    e("  %tg8 = index.mul %wp, %c8 : index")
    e("  %tokg = index.add %tg8, %tr : index")
    e("  %jq = index.mul %wq, %cnch : index")
    e("  %jg = index.add %jq, %cl : index")
    e("  %col = index.div %jg, %cnj : index")
    e("  %j = index.rem %jg, %cnj : index")
    e("  %blk = index.div %tokg, %c64 : index")
    e("  %r = index.rem %tokg, %c64 : index")
    e("  %tc = index.mul %col, %cmb : index")
    e("  %tile = index.add %tc, %blk : index")
    e("  %mpi = index.div %r, %c16 : index")
    e("  %r16 = index.rem %r, %c16 : index")
    e("  %mh = index.div %r16, %c8 : index")
    e("  %row = index.rem %r, %c8 : index")
    e("  %npi = index.div %j, %c2 : index")
    e("  %nh = index.rem %j, %c2 : index")
    # C element (group 0): tile * 64 * TN + ((mp * NP + np) * 4 + mh * 2 + nh) * 64 + row * 8
    e("  %a0 = index.mul %mpi, %cnp : index")
    e("  %a1 = index.add %a0, %npi : index")
    e("  %a2 = index.mul %a1, %c4 : index")
    e("  %a3 = index.mul %mh, %c2 : index")
    e("  %a4 = index.add %a2, %a3 : index")
    e("  %a5 = index.add %a4, %nh : index")
    e("  %a6 = index.mul %a5, %c64 : index")
    e("  %a7 = index.mul %row, %c8 : index")
    e("  %a8 = index.add %a6, %a7 : index")
    e("  %a9 = index.mul %tile, %ctile : index")
    # out: token blk * 64 + r, column col * TN + 8 * j + off
    e("  %t0 = index.mul %blk, %c64 : index")
    e("  %tok = index.add %t0, %r : index")
    e("  %j0 = index.mul %col, %ctn : index")
    e("  %j1 = index.mul %j, %c8 : index")
    e("  %j2 = index.add %j0, %j1 : index")
    if dup:   # col < col0: col * TN + 8 j; else base + (col - col0) * TN + 8 j
        e(f"  %cdup0 = index.constant {dup[0]} : index")
        e(f"  %cdupb = index.constant {dup[1]} : index")
        e("  %dupi = index.div %col, %cdup0 : index")
        e("  %dupc = index.rem %col, %cdup0 : index")
        e("  %dupj0 = index.mul %dupc, %ctn : index")
        e("  %dupj1 = index.add %dupj0, %j1 : index")
        e("  %dupb = index.mul %dupi, %cdupb : index")
        e("  %jo0 = index.add %dupj1, %dupb : index")
        e(f"  %cjlast = index.constant {stride - 8} : index")
        e("  %jo = index.min %jo0, %cjlast : index")   # always in range; for the bound proof
    else:
        e("  %jo = index.add %j2, %coff : index")
    if tiled:   # 8 columns of one 16-column tile: contiguous inside the tile
        e(f"  %ctc = index.constant {stride // 16} : index")
        e("  %ot0 = index.div %tok, %c16 : index")
        e("  %otr = index.rem %tok, %c16 : index")
        e("  %oj0 = index.div %jo, %c16 : index")
        e("  %ojr = index.rem %jo, %c16 : index")
        e("  %ot1 = index.mul %ot0, %ctc : index")
        e("  %ot2 = index.add %ot1, %oj0 : index")
        e("  %ot3 = index.mul %ot2, %c256t : index")
        e("  %ot4 = index.mul %otr, %c16 : index")
        e("  %ot5 = index.add %ot3, %ot4 : index")
        e("  %oa0 = index.add %ot5, %ojr : index")
        e(f"  %olast = index.constant {tokens * stride - 8} : index")
        e("  %oa = index.min %oa0, %olast : index")   # always in range; for the bound proof
    elif qg:   # j -> head jo / 512, half (jo / 256) % 2, d = jo % 256
        e("  %qh = index.div %jo, %c512q : index")
        e("  %qw = index.rem %jo, %c512q : index")
        e("  %qd = index.rem %qw, %c256q : index")
        e("  %qisq = index.cmp ult, %qw, %c256q : index")
        e("  %qc0 = index.mul %qh, %c256q : index")
        e("  %qc = index.add %qc0, %qd : index")
        e("  %tb = index.mul %tok, %cstride : index")
        e("  %oa0 = index.add %tb, %qc : index")
        e(f"  %olast = index.constant {tokens * stride - 8} : index")
        e("  %oa = index.min %oa0, %olast : index")   # always in range; for the bound proof
    else:
        e("  %tb = index.mul %tok, %cstride : index")
        e("  %oa = index.add %tb, %jo : index")
    if swap:   # (swap form) one value per element: the item's feature 8 jg, its base clamped for the bound proof
        e("  %fe = index.mul %jg, %c8 : index")
        sb = swapc_base(e, "sw_", "%fe", "%tokg", swap)
        e(f"  %calast = index.constant {swapc_last(tokens, cols * TN, swap)} : index")
        e(f"  %ca = index.min {sb}, %calast : index")
        load_c(e, "%v", "%ca")
    else:
        e("  %ca = index.add %a9, %a8 : index")
        e(f"  %cgs = index.constant {tokens * TN} : index")   # group stride inside a column
        load_cg(e, "%v", "%ca")
    val = "%v"
    for p in range(1, parts):   # the K chunks' partial sums
        e(f"  %cpo{p} = index.constant {p * c_elems} : index")
        e(f"  %cpa{p} = index.add %ca, %cpo{p} : index")
        load_cg(e, f"%cp{p}", f"%cpa{p}")
        e(f"  %cs{p} = vector.addf {val}, %cp{p} : vector<8xf32>")
        val = f"%cs{p}"
    if rem:   # token tok, NPU column j2 of the [tokens][TN * cols] partial (dup: output column jo of [tokens][stride])
        e(f"  %cremw = index.constant {stride if dup else cols * TN} : index")
        e("  %rmb = index.mul %tok, %cremw : index")
        e(f"  %rma = index.add %rmb, {'%jo' if dup else '%j2'} : index")
        e("  %rmv = vector.load %remv[%rma] : view<[%nrem]xf32> -> vector<8xf32>")
        e(f"  %rms = vector.addf {val}, %rmv : vector<8xf32>")
        val = "%rms"
    if resid and not remres:
        e("  %rsv = vector.load %rv[%oa] : view<[%no]xf32> -> vector<8xf32>")
        e(f"  %rs = vector.addf %rsv, {val} : vector<8xf32>")
        val = "%rs"
    if swiglu:   # silu(gate) * up per element, the swiglu epilogue's ops (gen_gemm_tile)
        e(f"  %cuo = index.constant {c_elems} : index")
        e("  %cua = index.add %ca, %cuo : index")
        load_cg(e, "%vu", "%cua")
        e("  %one = scalar.constant 1.0 : f32")
        e("  %negone = scalar.constant -1.0 : f32")
        TG.rcp_consts(e)
        hs = []
        for x in range(8):
            e(f"  %g_{x} = vector.extract %v[{x}] : vector<8xf32> -> f32")
            e(f"  %u_{x} = vector.extract %vu[{x}] : vector<8xf32> -> f32")
            e(f"  %ng_{x} = scalar.mulf %g_{x}, %negone : f32")
            e(f"  %ex_{x} = scalar.expf<afn> %ng_{x} : f32")
            e(f"  %dn_{x} = scalar.addf %one, %ex_{x} : f32")
            TG.recip1(e, f"%iv_{x}", f"%dn_{x}")
            e(f"  %sg_{x} = scalar.mulf %g_{x}, %iv_{x} : f32")
            e(f"  %ac_{x} = scalar.mulf %sg_{x}, %u_{x} : f32")
            e(f"  %h_{x} = scalar.fptrunc %ac_{x} : f32 to f16")
            hs.append(f"%h_{x}")
        e(f"  %vh = vector.from_elements {', '.join(hs)} : vector<8xf16>")
        e("  vector.store %vh, %ov[%oa] : vector<8xf16>, view<[%no]xf16>")
        if bfp:
            stage_bfp(e, hs, tokens, bfp, NCH)
    elif qg:
        e("  scf.if %qisq {")
        e(f"    vector.store {val}, %ov[%oa] : vector<8xf32>, view<[%no]xf32>")
        e("  } else {")
        e(f"    vector.store {val}, %gv[%oa] : vector<8xf32>, view<[%no]xf32>")
        e("  }")
    elif out16:
        e(f"  %vh = vector.fptrunc {val} : vector<8xf32> to vector<8xf16>")
        e("  vector.store %vh, %ov[%oa] : vector<8xf16>, view<[%no]xf16>")
    else:
        e(f"  vector.store {val}, %ov[%oa] : vector<8xf32>, view<[%no]xf32>")
    e("  kernel.return")
    e("}")
    return "\n".join(L) + "\n"


# Polls before yah_npu_flag_wait gives up (~0.2 us each: ~2 s, far beyond any NPU job; a timeout sets the status word).
FLAG_WAIT_POLLS = 10_000_000


WAIT_LOOP = """  %low = scalar.constant 2147483647 : i32
  %n, %last = scf.while(%i = %zero : i32, %p = %zero : i32) -> (i32, i32) {
    %v = view.atomic.load %dv[%c0] {ordering = acquire, scope = system} : view<1xi32> -> i32
    %seq = scalar.andi %v, %low : i32
    %early = scalar.cmpi ult, %seq, %want : i32
    %ok = scalar.cmpi eq, %seq, %v : i32
    %more = scalar.andi %early, %ok : i1
    %lt = scalar.cmpi ult, %i, %limit : i32
    %s = view.atomic.load %sv[%c0] {ordering = acquire, scope = system} : view<1xi32> -> i32
    %calm = scalar.cmpi eq, %s, %zero : i32
    %live = scalar.andi %lt, %calm : i1
    %go = scalar.andi %more, %live : i1
    scf.condition %go, %i, %v : i1, i32, i32
  } do(%j: i32, %w: i32) {
    %j1 = scalar.addi %j, %one : i32
    scf.yield %j1, %w : i32, i32
  }
  %timeout = scalar.cmpi uge, %n, %limit : i32
  %lseq = scalar.andi %last, %low : i32
  %gaveup = scalar.cmpi ne, %lseq, %last : i32
  %bad = scalar.ori %timeout, %gaveup : i1
  scf.if %bad {
    view.store %one, %sv[%c0] : i32, view<1xi32>
  }"""


# YAH_CLK_PROBE (diag, mem 11-21: clock-free GPU work counts without the dispatch profiler). CLK_DEF: one Low helper
# that reads REALTIME (s_sendmsg_rtn message 131, 100 MHz constant, low 32 bits: wraps after 42 s) and SHADER_CYCLES
# (s_getreg_b32 HW_REG_SHADER_CYCLES = 29, 20 bits: the SQ clock, wraps after ~0.4 ms at 2.6 GHz).
CLK_SPIN = 2000   # yah_clk_probe's window in REALTIME ticks (20 us: ~52k cycles at 2.6 GHz < 2^20; +-1 tick = 0.05%)
CLK_DEF = """amdgpu.target<gfx1151> @yah_clk_target
low.func.def target<amdgpu.rdna3_5.core>(@yah_clk_target) @yah_clk() -> (reg<amdgpu.sgpr>, reg<amdgpu.sgpr>) asm {
  %t = s_sendmsg_rtn_b32 {message = 131}
  %c = s_getreg_b32 {hwreg = 38941}
  return %t, %c
}
"""


def gen_clk_probe():
    """yah_clk_probe (YAH_CLK_PROBE): one wave reads (REALTIME, SHADER_CYCLES), spins until REALTIME has moved CLK_SPIN
    ticks, reads both again and stores t0, t1, c0, c1 (4 words) to its binding: the GPU clock there is
    ((c1 - c0) mod 2^20) / (t1 - t0) x 100 MHz. The host reads the slots after the run (LoomPrefill::ReportClk)."""
    return f"""// GENERATED by tools/gen_npu_unpack.py gen_clk_probe -- edit the generator.
amdgpu.target<gfx1151> @yah_wave32 {{subgroup_size = 32}}

kernel.def target(@yah_wave32) @yah_clk_probe() {{
  %unit = index.constant 1 : index
  %c32 = index.constant 32 : index
  kernel.launch.config workgroups(%unit, %unit, %unit) workgroup_size(%c32, %unit, %unit) : index
}} launch(%out: buffer) {{
  %base = index.constant 0 : offset
  %c0 = index.constant 0 : index
  %c1 = index.constant 1 : index
  %c2 = index.constant 2 : index
  %c3 = index.constant 3 : index
  %o_na = buffer.assume.noalias %out : buffer
  %ov = buffer.view %o_na[%base] : buffer -> view<4xi32>
  %spin = scalar.constant {CLK_SPIN} : i32
  %t0, %k0 = low.invoke @yah_clk() : () -> (i32, i32)
  %t1, %k1 = scf.while(%a = %t0 : i32, %b = %k0 : i32) -> (i32, i32) {{
    %d = scalar.subi %a, %t0 : i32
    %go = scalar.cmpi ult, %d, %spin : i32
    scf.condition %go, %a, %b : i1, i32, i32
  }} do(%x: i32, %y: i32) {{
    %tn, %kn = low.invoke @yah_clk() : () -> (i32, i32)
    scf.yield %tn, %kn : i32, i32
  }}
  view.store %t0, %ov[%c0] : i32, view<4xi32>
  view.store %t1, %ov[%c1] : i32, view<4xi32>
  view.store %k0, %ov[%c2] : i32, view<4xi32>
  view.store %k1, %ov[%c3] : i32, view<4xi32>
  kernel.return
}}

{CLK_DEF}"""


def gen_flag_wait(log=False, stamp=False):
    """yah_npu_flag_wait: one wave polls word done (system scope, acquire) until it reaches word ready, the job's gate
    value the same graph stored there before the NPU job (gen_npu_gemm GATE; bindings done, ready, status: 4 bytes each,
    host memory). The NPU may write done for a later job sharing the word: the wait ends once done's low 31 bits reach
    ready. gen_npu_gemm.GATE_FAILED in done (the NPU gave up, or the host saw the job fail) stores 1 to status.
    Bounded: after FLAG_WAIT_POLLS it stores 1 to status and returns, so a lost NPU job cannot hang the GPU.
    Status is sticky: once set, every later wait returns at once, so one lost job costs one bound, not one per job.
    log (YAH_NPU_WAITLOG, npu_flag_wait_log.hal): a fourth binding, one word that gets the wait's poll count.
    stamp (YAH_CLK_PROBE, npu_flag_wait_stamp.hal): a fourth binding of 2 words, REALTIME (100 MHz) at the wait's entry and
    exit (yah_clk, CLK_DEF): the GPU's time waiting on the NPU without the dispatch profiler."""
    assert not (log and stamp)
    lb = ", %log: buffer" if log else ", %stamp: buffer" if stamp else ""
    ls = ("\n  %l_na = buffer.assume.noalias %log : buffer\n  %lv = buffer.view %l_na[%base] : buffer -> view<1xi32>\n"
          "  view.store %n, %lv[%c0] : i32, view<1xi32>") if log else ""
    pre = "\n  %te, %ke = low.invoke @yah_clk() : () -> (i32, i32)" if stamp else ""
    if stamp:
        ls = ("\n  %tx, %kx = low.invoke @yah_clk() : () -> (i32, i32)\n  %c1s = index.constant 1 : index\n"
              "  %st_na = buffer.assume.noalias %stamp : buffer\n  %stv = buffer.view %st_na[%base] : buffer -> view<2xi32>\n"
              "  view.store %te, %stv[%c0] : i32, view<2xi32>\n  view.store %tx, %stv[%c1s] : i32, view<2xi32>")
    return f"""// GENERATED by tools/gen_npu_unpack.py gen_flag_wait -- edit the generator.
amdgpu.target<gfx1151> @yah_wave32 {{subgroup_size = 32}}

kernel.def target(@yah_wave32) @yah_npu_flag_wait() {{
  %unit = index.constant 1 : index
  %c32 = index.constant 32 : index
  kernel.launch.config workgroups(%unit, %unit, %unit) workgroup_size(%c32, %unit, %unit) : index
}} launch(%done: buffer, %ready: buffer, %status: buffer{lb}) {{
  %base = index.constant 0 : offset
  %c0 = index.constant 0 : index
  %d_na, %r_na, %s_na = buffer.assume.noalias %done, %ready, %status : buffer, buffer, buffer
  %dv = buffer.view %d_na[%base] : buffer -> view<1xi32>
  %rv = buffer.view %r_na[%base] : buffer -> view<1xi32>
  %sv = buffer.view %s_na[%base] : buffer -> view<1xi32>
  %want = view.atomic.load %rv[%c0] {{ordering = acquire, scope = system}} : view<1xi32> -> i32
  %zero = scalar.constant 0 : i32
  %one = scalar.constant 1 : i32
  %limit = scalar.constant {FLAG_WAIT_POLLS} : i32{pre}
{WAIT_LOOP}{ls}
  kernel.return
}}
""" + ("\n" + CLK_DEF if stamp else "")


def c_lane(e, p, nc, tokens):
    """Column part of the group-0 C element of NPU output column nc (0 .. cols * TN - 1), gen's layout split as
    element = c_lane(nc) + c_tok(token): col * (tokens * TN * CG) + (np * 4 + nh) * 64 + jj, with q = nc % TN,
    item j = q / 8 = 2 np + nh, jj = q % 8. Returns its SSA name."""
    for nm, v in (("tn", GN.TN), ("c8", 8), ("c2", 2), ("c4", 4), ("c64", 64), ("cs", tokens * GN.TN * CG)):
        e(f"  %{p}{nm} = index.constant {v} : index")
    e(f"  %{p}col = index.div {nc}, %{p}tn : index")
    e(f"  %{p}q = index.rem {nc}, %{p}tn : index")
    e(f"  %{p}j = index.div %{p}q, %{p}c8 : index")
    e(f"  %{p}jj = index.rem %{p}q, %{p}c8 : index")
    e(f"  %{p}npi = index.div %{p}j, %{p}c2 : index")
    e(f"  %{p}nh = index.rem %{p}j, %{p}c2 : index")
    e(f"  %{p}a0 = index.mul %{p}col, %{p}cs : index")
    e(f"  %{p}a1 = index.mul %{p}npi, %{p}c4 : index")
    e(f"  %{p}a2 = index.add %{p}a1, %{p}nh : index")
    e(f"  %{p}a3 = index.mul %{p}a2, %{p}c64 : index")
    e(f"  %{p}a4 = index.add %{p}a0, %{p}a3 : index")
    e(f"  %{p}la = index.add %{p}a4, %{p}jj : index")
    return f"%{p}la"


def c_tok(e, p, tok):
    """Token part of a C element (see c_lane): blk * 64 * TN + (mp * NP * 4 + mh * 2) * 64 + row * 8, with blk = tok / 64,
    r = tok % 64, mp = r / 16, mh = (r % 16) / 8, row = r % 8. Returns its SSA name."""
    for nm, v in (("c8", 8), ("c16", 16), ("c64", 64), ("cbs", 64 * GN.TN), ("cmp", GN.NP * 4 * 64), ("c128", 128)):
        e(f"  %{p}{nm} = index.constant {v} : index")
    e(f"  %{p}blk = index.div {tok}, %{p}c64 : index")
    e(f"  %{p}r = index.rem {tok}, %{p}c64 : index")
    e(f"  %{p}mp = index.div %{p}r, %{p}c16 : index")
    e(f"  %{p}r16 = index.rem %{p}r, %{p}c16 : index")
    e(f"  %{p}mh = index.div %{p}r16, %{p}c8 : index")
    e(f"  %{p}row = index.rem %{p}r, %{p}c8 : index")
    e(f"  %{p}b0 = index.mul %{p}blk, %{p}cbs : index")
    e(f"  %{p}b1 = index.mul %{p}mp, %{p}cmp : index")
    e(f"  %{p}b2 = index.mul %{p}mh, %{p}c128 : index")
    e(f"  %{p}b3 = index.mul %{p}row, %{p}c8 : index")
    e(f"  %{p}b4 = index.add %{p}b0, %{p}b1 : index")
    e(f"  %{p}b5 = index.add %{p}b4, %{p}b2 : index")
    e(f"  %{p}tb = index.add %{p}b5, %{p}b3 : index")
    return f"%{p}tb"


def swapc_base(e, p, nc, tok, R):
    """(swap-form site image, npu_swsite, R = nb * 64 rows) the C element of feature nc (a multiple of 8) and token tok:
    panel P = tok / 512 at P R 512; in it 64 [c R + (rb / 2) 16 + (t8 / 2) 4 + (rb % 2) 2 + t8 % 2] + (tok % 8) 8 + f % 8,
    c = (tok % 512) / 64, t8 = (tok % 64) / 8, rb = f / 8. Blocks are [8 tokens][8 features] as dcol's (npu MEASURED on
    the image's output, sg60): a token's 8 features are contiguous, load_c reads them. Returns its SSA."""
    for nm, v in (("c8", 8), ("c2", 2), ("c512", 512), ("c64", 64), ("c1024", 1024), ("c128", 128), ("c256", 256),
                  ("cP", R * 512), ("cC", R * 64)):
        e(f"  %{p}{nm} = index.constant {v} : index")
    e(f"  %{p}rb = index.div {nc}, %{p}c8 : index")
    e(f"  %{p}rh = index.div %{p}rb, %{p}c2 : index")
    e(f"  %{p}rl = index.rem %{p}rb, %{p}c2 : index")
    e(f"  %{p}f0 = index.mul %{p}rh, %{p}c1024 : index")
    e(f"  %{p}f1 = index.mul %{p}rl, %{p}c128 : index")
    e(f"  %{p}pp = index.div {tok}, %{p}c512 : index")
    e(f"  %{p}r512 = index.rem {tok}, %{p}c512 : index")
    e(f"  %{p}cc = index.div %{p}r512, %{p}c64 : index")
    e(f"  %{p}r64 = index.rem {tok}, %{p}c64 : index")
    e(f"  %{p}t8 = index.div %{p}r64, %{p}c8 : index")
    e(f"  %{p}tr = index.rem {tok}, %{p}c8 : index")
    e(f"  %{p}th = index.div %{p}t8, %{p}c2 : index")
    e(f"  %{p}tl = index.rem %{p}t8, %{p}c2 : index")
    e(f"  %{p}a0 = index.mul %{p}pp, %{p}cP : index")
    e(f"  %{p}a1 = index.mul %{p}cc, %{p}cC : index")
    e(f"  %{p}a2 = index.mul %{p}th, %{p}c256 : index")
    e(f"  %{p}a3 = index.mul %{p}tl, %{p}c64 : index")
    e(f"  %{p}s0 = index.add %{p}a0, %{p}a1 : index")
    e(f"  %{p}s1 = index.add %{p}s0, %{p}a2 : index")
    e(f"  %{p}s2 = index.add %{p}s1, %{p}a3 : index")
    e(f"  %{p}tr8 = index.mul %{p}tr, %{p}c8 : index")
    e(f"  %{p}s3 = index.add %{p}s2, %{p}tr8 : index")
    e(f"  %{p}s4 = index.add %{p}s3, %{p}f0 : index")
    e(f"  %{p}base = index.add %{p}s4, %{p}f1 : index")
    return f"%{p}base"


def swapc_last(B, n, R):
    """The largest swapc_base over features 0, 8, .., n - 8 and tokens 0 .. B - 1 (its 8 elements stay in B R)."""
    import numpy as np
    f = np.arange(0, n, 8)[:, None]
    t = np.arange(B)[None, :]
    rb, c, t8 = f // 8, (t % 512) // 64, (t % 64) // 8
    b = t // 512 * R * 512 + 64 * (c * R + (rb // 2) * 16 + (t8 // 2) * 4 + (rb % 2) * 2 + t8 % 2) + t % 8 * 8
    m = int(b.max())
    assert m + 8 <= B * R, (m, B, R)
    return m


def swap_rows(n):
    """The swap-form site image's rows R for n real NPU rows (emit_prefill_pp SWSITE: nb = ceil(n / 256) 4, R = 64 nb)."""
    return -(-n // 256) * 256


def load_cg(e, dst, idx):
    """The 8 C values at element idx of a call's group 0 plus the same values of its other groups (%cgs apart)."""
    if CG == 1:
        load_c(e, dst, idx)
        return
    n = dst[1:]
    load_c(e, f"%{n}g0", idx)
    acc = f"%{n}g0"
    for g in range(1, CG):
        e(f"  %{n}gi{g} = index.add {idx if g == 1 else f'%{n}gi{g - 1}'}, %cgs : index")
        load_c(e, f"%{n}g{g}", f"%{n}gi{g}")
        nxt = dst if g == CG - 1 else f"%{n}gs{g}"
        e(f"  {nxt} = vector.addf {acc}, %{n}g{g} : vector<8xf32>")
        acc = nxt


def load_c(e, dst, idx):
    """The 8 C values from element idx (a multiple of 8) as vector<8xf32>: 4 words of bf16 pairs, the low half first."""
    n = dst[1:]
    e(f"  %{n}_w = index.div {idx}, %c2 : index")
    e(f"  %{n}_v = vector.load %cv[%{n}_w] : view<[%nc]xi32> -> vector<4xi32>")
    vals = []
    for w in range(4):
        e(f"  %{n}_e{w} = vector.extract %{n}_v[{w}] : vector<4xi32> -> i32")
        e(f"  %{n}_l{w} = scalar.shli %{n}_e{w}, %c16i : i32")
        e(f"  %{n}_h{w} = scalar.andi %{n}_e{w}, %chii : i32")
        e(f"  %{n}_lf{w} = scalar.bitcast %{n}_l{w} : i32 to f32")
        e(f"  %{n}_hf{w} = scalar.bitcast %{n}_h{w} : i32 to f32")
        vals += [f"%{n}_lf{w}", f"%{n}_hf{w}"]
    e(f"  {dst} = vector.from_elements {', '.join(vals)} : vector<8xf32>")


def stage_bfp(e, hs, tokens, bfp, nch):
    """The bfp form's row blocks (the item's 8 f16 values of token %tokg, column %jo..) staged in LDS as
    [chunk %cl][token %tr][9 bytes]; after a barrier the workgroup copies each live chunk's fragment (8 tokens, 72 bytes)
    into the stream as 8-byte stores (one stream offset per fragment)."""
    bks, bpasses, bck, bnck = bfp
    bcb = GE.layout_bytes("act", tokens, bks, bpasses)
    for nm, v in (("ck", bck), ("nck", bnck), ("cb", bcb), ("c9", 9), ("c72", 72)):
        e(f"  %bs_{nm} = index.constant {v} : index")
    e("  %bs_ci = index.div %jo, %bs_ck : index")
    e("  %bs_live = index.cmp ult, %bs_ci, %bs_nck : index")
    e("  scf.if %bs_live {")
    e("    %bs_r0 = index.mul %cl, %c8 : index")
    e("    %bs_r1 = index.add %bs_r0, %tr : index")
    e("    %bs_sb = index.mul %bs_r1, %bs_c9 : index")

    def store(x, v):
        a = "%bs_sb"
        if x:
            e(f"    %bs_so{x} = index.constant {x} : index")
            e(f"    %bs_sa{x} = index.add %bs_sb, %bs_so{x} : index")
            a = f"%bs_sa{x}"
        e(f"    view.store {v}, %bs_view[{a}] : i8, view<{72 * nch}xi8>")
    bfp_block(e, hs, "bq_", store)
    e("  }")
    e("  kernel.barrier<workgroup> scope(workgroup) ordering(acq_rel)")
    for i in range(2):   # nch fragments x 9 words over 8 nch lanes
        q = f"bc{i}_"
        e(f"  %{q}d0 = index.constant {8 * nch * i} : index")
        e(f"  %{q}d = index.add %tid, %{q}d0 : index")
        e(f"  %{q}n = index.constant {9 * nch} : index")
        e(f"  %{q}in = index.cmp ult, %{q}d, %{q}n : index")
        e(f"  scf.if %{q}in {{")
        e(f"    %{q}cl = index.div %{q}d, %bs_c9 : index")
        e(f"    %{q}w = index.rem %{q}d, %bs_c9 : index")
        e(f"    %{q}jg = index.add %jq, %{q}cl : index")
        e(f"    %{q}jo0 = index.mul %{q}jg, %c8 : index")
        e(f"    %{q}jo = index.add %{q}jo0, %coff : index")   # TN = 8 NJ: the chunk's first output column
        e(f"    %{q}ci = index.div %{q}jo, %bs_ck : index")
        e(f"    %{q}live = index.cmp ult, %{q}ci, %bs_nck : index")
        e(f"    scf.if %{q}live {{")
        for nm, v in (("c2", 2), ("c144", 144), ("c72", 72), ("csub", 4), ("cpk", sum(bks)), ("cpass", bpasses)):
            e(f"      %{q}{nm} = index.constant {v} : index")
        e(f"      %{q}kcol = index.rem %{q}jo, %bs_ck : index")
        e(f"      %{q}kbi = index.div %{q}kcol, %c8 : index")
        frag = GE.emit_offset(e, "act", tokens, list(bks), bpasses, 64, True, "%wp", f"%{q}kbi", p=q, ind="      ")
        e(f"      %{q}co = index.mul %{q}ci, %bs_cb : index")
        e(f"      %{q}wo = index.mul %{q}w, %c8 : index")
        e(f"      %{q}g0 = index.add {frag}, %{q}co : index")
        e(f"      %{q}ga = index.add %{q}g0, %{q}wo : index")
        e(f"      %{q}fb = index.mul %{q}cl, %bs_c72 : index")
        e(f"      %{q}la = index.add %{q}fb, %{q}wo : index")
        e(f"      %{q}v = vector.load %bs_view[%{q}la] : view<{72 * nch}xi8> -> vector<8xi8>")
        e(f"      vector.store %{q}v, %abv[%{q}ga] : vector<8xi8>, view<[%nab]xi8>")
        e("    }")
        e("  }")


def bfp_block(e, hs, p, store):
    """One bfp16ebs8 row block of 8 f16 values hs (gen_bfp16_encode.emit_encode's arithmetic): store(0, exponent byte),
    then store(x + 1, mantissa byte x), each right after its value."""
    for nm, v in (("i23", 23), ("i255", 255), ("i260", 260), ("i0", 0)):
        e(f"    %{p}{nm} = scalar.constant {v} : i32")
    for nm, v in (("zero", "0.0"), ("fmin", "-128.0"), ("fmax", "127.0")):
        e(f"    %{p}{nm} = scalar.constant {v} : f32")
    cur = None
    for x, h in enumerate(hs):
        e(f"    %{p}v{x} = scalar.extf {h} : f16 to f32")
        e(f"    %{p}a{x} = scalar.absf %{p}v{x} : f32")
        if cur is None:
            cur = f"%{p}a{x}"
        else:
            e(f"    %{p}mx{x} = scalar.maxnumf {cur}, %{p}a{x} : f32")
            cur = f"%{p}mx{x}"
    e(f"    %{p}mb = scalar.bitcast {cur} : f32 to i32")
    e(f"    %{p}ms = scalar.shrui %{p}mb, %{p}i23 : i32")
    e(f"    %{p}E = scalar.andi %{p}ms, %{p}i255 : i32")
    e(f"    %{p}ie = scalar.subi %{p}i260, %{p}E : i32")
    e(f"    %{p}ib = scalar.shli %{p}ie, %{p}i23 : i32")
    e(f"    %{p}iq0 = scalar.bitcast %{p}ib : i32 to f32")
    e(f"    %{p}z = scalar.cmpi eq, %{p}E, %{p}i0 : i32")
    e(f"    %{p}iq = scf.select %{p}z, %{p}zero, %{p}iq0 : f32")
    e(f"    %{p}eb = scalar.trunci %{p}E : i32 to i8")
    store(0, f"%{p}eb")
    for x in range(8):
        e(f"    %{p}s{x} = scalar.mulf %{p}v{x}, %{p}iq : f32")
        e(f"    %{p}n{x} = scalar.roundevenf %{p}s{x} : f32")
        e(f"    %{p}c0{x} = scalar.maxnumf %{p}n{x}, %{p}fmin : f32")
        e(f"    %{p}cl{x} = scalar.minnumf %{p}c0{x}, %{p}fmax : f32")
        e(f"    %{p}t{x} = scalar.fptosi %{p}cl{x} : f32 to i32")
        e(f"    %{p}m{x} = scalar.trunci %{p}t{x} : i32 to i8")
        store(x + 1, f"%{p}m{x}")


