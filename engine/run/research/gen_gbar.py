"""grid-barrier microbenchmark: G workgroups x 256, N barriers (counter: atomic add release,
spin on acquire load until (i+1) * G). Spin capped at CAP iterations: on a cap hit the
workgroup records 1 in fail[0] and stops waiting (no hang if residency is short)."""
import sys
def gen(G, N, CAP=2000000):
    L = []; e = L.append
    e("amdgpu.target<gfx1151> @gb {subgroup_size = 32}")
    e("kernel.def target(@gb) @gbar() {")
    e(f"  %u1 = index.constant 1 : index\n  %g = index.constant {G} : index\n  %t = index.constant 256 : index")
    e("  kernel.launch.config workgroups(%g, %u1, %u1) workgroup_size(%t, %u1, %u1) : index")
    e("} launch(%cnt: buffer, %fail: buffer) {")
    e("  %base = index.constant 0 : offset")
    e("  %c0 = index.constant 0 : index\n  %c1 = index.constant 1 : index")
    e(f"  %cn = index.constant {N} : index")
    e("  %w1 = scalar.constant 1 : i32\n  %w0 = scalar.constant 0 : i32")
    e(f"  %wg = scalar.constant {G} : i32\n  %wcap = scalar.constant {CAP} : i32")
    e("  %cg = buffer.assume.memory_space<global> %cnt : buffer")
    e("  %fg = buffer.assume.memory_space<global> %fail : buffer")
    e("  %cv = buffer.view %cg[%base] : buffer -> view<1xi32>")
    e("  %fv = buffer.view %fg[%base] : buffer -> view<1xi32>")
    e("  %tid = kernel.workitem.id<x> : index")
    e("  %t0 = index.cmp eq, %tid, %c0 : index")
    e("  %sink = scf.for %i = [%c0 to %cn step %c1](%s = %c0 : index) -> (index) {")
    e("    kernel.barrier<workgroup> scope(workgroup) ordering(acq_rel)")
    e("    scf.if %t0 {")
    e("      view.atomic.reduce<addi> %w1, %cv[%c0] {ordering = release, scope = device} : i32, view<1xi32>")
    e("      %ii = index.cast %i : index to i32")
    e("      %i1 = scalar.addi %ii, %w1 : i32")
    e("      %target = scalar.muli %i1, %wg : i32")
    e("      %spins = scf.while(%k = %w0 : i32) -> (i32) {")
    e("        %v = view.atomic.load %cv[%c0] {ordering = acquire, scope = device} : view<1xi32> -> i32")
    e("        %notyet = scalar.cmpi slt, %v, %target : i32")
    e("        %undercap = scalar.cmpi slt, %k, %wcap : i32")
    e("        %more = scalar.andi %notyet, %undercap : i1")
    e("        scf.condition %more, %k : i1, i32")
    e("      } do(%kk: i32) {")
    e("        %kn = scalar.addi %kk, %w1 : i32")
    e("        scf.yield %kn : i32")
    e("      }")
    e("      %hit = scalar.cmpi sge, %spins, %wcap : i32")
    e("      scf.if %hit {")
    e("        view.store %w1, %fv[%c0] : i32, view<1xi32>")
    e("      }")
    e("    }")
    e("    kernel.barrier<workgroup> scope(workgroup) ordering(acq_rel)")
    e("    scf.yield %s : index")
    e("  }")
    e("  kernel.return\n}")
    return "\n".join(L) + "\n"
if __name__ == "__main__":
    open(sys.argv[3], "w").write(gen(int(sys.argv[1]), int(sys.argv[2])))
